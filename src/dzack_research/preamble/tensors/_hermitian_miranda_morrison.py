class _UnitQuotient:
    r"""A subgroup of ``(O_E/P^i)^*`` with explicit discrete logarithm and exponential.

    ``ambient`` is ``Z^k / diag(orders)`` on the PARI ideal-star generators;
    ``subgroup`` is the submodule (the whole group, or the kernel of the norm).
    """

    def __init__(self, E, P, i, kind, p, j=None):
        self.E = E
        self.P = P
        self.p = p
        if i == 0:
            self.modulus = None
            self.orders = []
            self.values = []
        else:
            self.modulus = P ** i
            bid = self.modulus.idealstar(2)
            self.orders = list(bid.gens_orders())
            self.values = list(bid.gens_values())
        k = len(self.orders)
        V = FreeModule(ZZ, k)
        W = V.span([vector(ZZ, [self.orders[a] if b == a else 0 for b in range(k)]) for a in range(k)])
        self.V = V
        self.W = W
        if kind == "split" or self.modulus is None:
            self.subspace = V
        else:
            # Relative norm into (O_K/p^j)^*, in its own ideal-star basis.
            modulus = p ** j
            target = modulus.idealstar(2)
            target_orders = list(target.gens_orders())
            images = [list(modulus.ideallog(_cm(E).norm(g))) for g in self.values]
            self.subspace = _norm_kernel(k, images, target_orders)
        self.group = self.subspace / W

    def raw_log(self, x):
        r"""The ideal-star logarithm of a ``P``-unit ``x`` integral at the primes over ``p``, cleared of denominators as in OSCAR ``dlog``."""
        if self.modulus is None:
            return vector(ZZ, [])
        d = ZZ(x.denominator())
        xabs = d * x
        dabs = self.E(d)
        for Q, _e in _primes_over(self.E, self.p):
            assert x.valuation(Q) >= 0, f"{x} is not integral at {Q}"
            api = _anti_uniformizer(Q)
            exponent = dabs.valuation(Q)
            dabs *= api ** exponent
            xabs *= api ** exponent
        return vector(ZZ, self.modulus.ideallog(xabs)) - vector(ZZ, self.modulus.ideallog(dabs))

    def log(self, x):
        v = self.raw_log(x)
        assert v in self.subspace + self.W, f"the logarithm of {x} does not lie in the subgroup"
        return v

    def exp(self, v):
        x = self.E.one()
        for value, order, c in zip(self.values, self.orders, v, strict=True):
            x *= value ** (ZZ(c) % order)
        return x


def _norm_kernel(k, images, target_orders):
    r"""The preimage in ``Z^k`` of ``0`` under the map to ``prod Z/target_orders`` with columns ``images``."""
    t = len(target_orders)
    if t == 0:
        return FreeModule(ZZ, k)
    # Solve sum_a v_a images[a] = 0 mod target_orders: kernel of [images | diag(target)] projected to v.
    M = matrix(ZZ, [list(images[a]) for a in range(k)] + [[target_orders[b] if c == b else 0 for c in range(t)] for b in range(t)])
    K = M.left_kernel()
    return FreeModule(ZZ, k).span([vector(ZZ, list(row)[:k]) for row in K.basis()])


def _local_quotient(E, p, i):
    r"""OSCAR ``_get_quotient(O, p, i)``: the factor of [BH23, Remark 6.16] at ``p``."""
    D = _primes_over(E, p)
    P = D[0][0]
    if i == 0:
        return _UnitQuotient(E, P, 0, "split", p)
    if len(D) == 2:
        return _UnitQuotient(E, P, i, "split", p)
    if D[0][1] == 1:
        return _UnitQuotient(E, P, i, "inert", p, j=i)
    e = _cm(E).relative_different.valuation(P)
    if i < e:
        return _UnitQuotient(E, P, 0, "split", p)
    t = e - 1
    jj = QQ(t) + QQ(1) / 2
    while (t + 2 * (jj - t)).ceil() != i:
        jj += QQ(1) / 2
    return _UnitQuotient(E, P, i, "ramified", p, j=jj.ceil())


class _ProductQuotient:
    r"""OSCAR ``_get_product_quotient``: the product of the local factors, with componentwise logarithms."""

    def __init__(self, E, data):
        self.E = E
        self.factors = [_local_quotient(E, p, i) for p, i in data]
        sizes = [len(f.orders) for f in self.factors]
        self.offsets = [sum(sizes[:a]) for a in range(len(sizes))]
        total = sum(sizes)
        V = FreeModule(ZZ, total)
        self.V = V
        sub_gens = []
        rel_gens = []
        for f, offset in zip(self.factors, self.offsets):
            for g in f.subspace.basis():
                sub_gens.append(_embed(g, offset, total))
            for g in f.W.basis():
                rel_gens.append(_embed(g, offset, total))
        self.W = V.span(rel_gens)
        self.subspace = V.span(sub_gens + rel_gens)
        self.group = self.subspace / self.W

    def log(self, xs):
        if len(xs) == 1:
            xs = xs * len(self.factors)
        assert len(xs) == len(self.factors)
        total = self.V.degree()
        v = vector(ZZ, [0] * total)
        for f, offset, x in zip(self.factors, self.offsets, xs):
            v += _embed(f.log(x), offset, total)
        return v

    def exp(self, v):
        return [f.exp(v[offset: offset + len(f.orders)]) for f, offset in zip(self.factors, self.offsets)]


def _embed(v, offset, total):
    return vector(ZZ, [0] * offset + list(v) + [0] * (total - offset - len(v)))


