def _centralizer_image_matrices(gram, isometry):
    r"""The image of ``Z_{O(L)}(f)`` in ``O(A_L)``, as matrices on the dual-basis classes, and its order.

    ``gram`` is the Gram matrix of ``L`` on its basis, ``isometry`` the matrix
    of ``f`` in the row convention ``v -> v F``.  Each returned matrix ``M``
    is a generator ``g`` of the image with ``g([d_i]) = [sum_j M[i, j] d_j]``
    for the dual basis ``d_i`` (the rows of ``gram^{-1}``).
    """
    gram = matrix(ZZ, gram)
    F = matrix(QQ, isometry)
    assert F * gram * F.transpose() == gram, f"{F} is not an isometry of {gram}"
    r = gram.nrows()
    assert all(gram[i, i] % 2 == 0 for i in range(r)), f"hermitian Miranda--Morrison is computed for even lattices; {gram} is odd"
    minimal = F.minpoly()
    assert minimal.is_cyclotomic() and minimal.degree() == 2, f"the minimal polynomial {minimal} of {F} must be a cyclotomic polynomial of degree two"
    assert r > minimal.degree(), f"the hermitian structure must have rank at least two, but {gram} has rank {r}"
    order = matrix(ZZ, F).multiplicative_order()

    transfer = _HermitianTransfer(gram, F, order)
    E = transfer.E

    # The discriminant group D_L and the induced D_f (Sage's finite quadratic module on L^#/L).
    qL = _discriminant_module(gram)
    from dzack_research.preamble.categories.modules.framed.formed.torsion_form_modules import _engine_orthogonal_group

    OqL = _engine_orthogonal_group(qL)
    fqL = OqL(qL.hom([qL(_ambient(g.lift()) * F) for g in qL.gens()]))
    G2 = libgap.Centralizer(OqL.gap(), fqL.gap())
    gensG2 = [OqL(x) for x in G2.GeneratorsOfGroup()]

    # The hermitian structure H of (L, f) and H2 = D_{E/Q}^{-1} H^#.
    generators = [transfer.to_E(vector(QQ, [1 if j == i else 0 for j in range(r)])) for i in range(r)]
    H = _FreeHermitianLattice(transfer, _o_e_basis(transfer, generators))
    DEQ = E.different()
    delta_generator = DEQ.gens_reduced()[0]
    H2 = H.dual().scaled(delta_generator ** -1)
    assert H2.contains(H), "H must be a sublattice of D^{-1} H^# since L is integral"
    _assert_trace_dual(transfer, H2, gram)

    S = _elementary_divisors(H, DEQ)
    N = H.norm_generator()

    Fsharp_data = []
    for p in S:
        P = _primes_over(E, p)[0][0]
        n = _ideal_valuation_of_rational(E, N, P)
        a = DEQ.valuation(P)
        Fsharp_data.append((p, n + a))
    RmodFsharp = _ProductQuotient(E, Fsharp_data)

    list_ker = []
    F_data = []
    for index, p in enumerate(S):
        if not _is_special(H, p):
            F_data.append((p, 0))
            if Fsharp_data[index][1] == 0:
                list_ker.append(p)
        else:
            P = _primes_over(E, p)[0][0]
            e = DEQ.valuation(P)
            F_data.append((p, e))
            if Fsharp_data[index][1] == e:
                list_ker.append(p)
    RmodF = _ProductQuotient(E, F_data)

    # f: R/F# -> R/F on generators, and F/F# its kernel.
    A = RmodFsharp.group
    B = RmodF.group
    images = [B(RmodF.log(RmodFsharp.exp(g.lift()))) for g in A.gens()]
    phi = A.hom(images)
    FmodFsharp = phi.kernel()

    units = E.unit_group()
    assert units.rank() == 0, f"{E} is imaginary quadratic, so its units are the roots of unity"
    norm_one = [units.torsion_generator().value()]
    FOEmodFsharp = A.submodule([A(RmodFsharp.log([x] * len(S))) for x in norm_one])
    I = (FOEmodFsharp.V().intersection(FmodFsharp.V())) / A.W()
    Q = FmodFsharp / I

    def dlog(xs):
        return Q(Q.V()(RmodFsharp.log(xs)))

    imgs = []
    order_Q = Q.cardinality()
    for g in gensG2:
        ds = []
        for p in S:
            if order_Q == 1 or p in list_ker:
                ds.append(E.one())
            else:
                P = _primes_over(E, p)[0][0]
                k = _ideal_valuation_of_rational(E, N, P)
                a = DEQ.valuation(P)
                e = DEQ.valuation(P)
                g_approx = _approximate_isometry(H, H2, g, qL, P, p, e, a, k, transfer)
                ds.append(g_approx.det())
        imgs.append(dlog(ds))

    # The image of the centralizer is the kernel of G2 -> Q.
    invariants = list(Q.invariants())
    gap_target = libgap.AbelianGroup(invariants) if invariants else libgap.TrivialGroup()
    target_generators = list(gap_target.GeneratorsOfGroup()) if invariants else []

    def to_gap(q):
        element = gap_target.Identity()
        for coordinate, generator in zip(q.vector(), target_generators):
            element = element * generator ** int(coordinate)
        return element

    hom = libgap.GroupHomomorphismByImages(G2, gap_target, [g.gap() for g in gensG2], [to_gap(q) for q in imgs])
    assert hom != libgap.fail, "the determinant images do not define a homomorphism of the centralizer"
    kernel = libgap.Kernel(hom)
    kernel_generators = [OqL(x) for x in kernel.GeneratorsOfGroup()]
    matrices = [_dual_basis_matrix(qL, g, gram) for g in kernel_generators]
    return matrices, ZZ(kernel.Size())


def _ambient(u):
    r"""The ambient rational coordinates of an element of a ``ZZ``-submodule of ``QQ^r``.

    Sage multiplies such an element by a matrix through its coordinates on the
    submodule's basis (TRAPS.md), so lifts are read off as ambient vectors first.
    """
    return vector(QQ, u.list())


def _discriminant_module(gram):
    from sage.modules.free_quadratic_module_integer_symmetric import IntegralLattice

    return IntegralLattice(gram).discriminant_group()


def _dual_basis_matrix(qL, g, gram):
    r"""The matrix ``M`` with ``g([d_i]) = [sum_j M[i, j] d_j]``, ``d_i`` the rows of ``gram^{-1}``."""
    dual_rows = gram.inverse()
    rows = []
    for i in range(gram.nrows()):
        image = _ambient(g(qL(dual_rows.row(i))).lift())
        rows.append(vector(ZZ, image * gram))
    return matrix(ZZ, rows)


def _assert_trace_dual(transfer, H2, gram):
    r"""The trace construction carries ``D^{-1} H^#`` onto ``L^#``: the ``Z``-spans agree."""
    r = gram.nrows()
    spanned = (QQ ** r).span([vector(QQ, x) for x in transfer.restrict_scalars(H2.B)], ZZ)
    dual = (QQ ** r).span(gram.inverse().rows(), ZZ)
    assert spanned == dual, "the trace dual of the hermitian structure is not L^#: the transfer convention is wrong"


def _ideal_valuation_of_rational(E, x, P):
    return Infinity if x == 0 else E(x).valuation(P)


def _elementary_divisors(H, D):
    r"""OSCAR ``_elementary_divisors(L, D)``: the rational primes ``p`` with ``(D^{-1} L^#/L)_p`` nontrivial."""
    primes = []
    minima = []
    for P, _e in D.factor():
        p = P.smallest_integer()
        minima.append(p)
        ok, a = H.is_modular(p)
        if ok and a == -D.valuation(P):
            continue
        if p not in primes:
            primes.append(p)
    for p in H.bad_primes():
        if p in primes or p in minima:
            continue
        primes.append(p)
    return primes


def _approximate_isometry(H, H2, g, qL, P, p, e, a, k, transfer):
    r"""OSCAR ``_approximate_isometry``: lift ``g`` to an isometry of ``H2`` at ``P`` up to the precision of [BH23, Theorem 6.25]."""
    E = transfer.E
    P2 = _conjugate_ideal(E, P)
    split = P2 != P
    ok, b = H.is_modular(p)
    if ok and b == -a:
        return identity_matrix(E, 1)
    Bp, Bp2, pr = _local_basis_matrix_and_projection(H2, p, a, transfer)
    Gp = Bp2 * transfer.ambient_gram * _conjugate_matrix(Bp2).transpose()
    Fp = _transfer_discriminant_isometry(transfer, g, qL, Bp, Bp2, pr)
    Rp = Gp - Fp * Gp * _conjugate_matrix(Fp).transpose()
    rho = _find_rho(E, P, p, e)
    l = 0
    while _scale_valuation(Rp, P) < k + a and (not split or _scale_valuation(Rp, P2) < k + a):
        Fp, l = _local_hermitian_lifting(Gp, Fp, rho, l, P, P2, split, a)
        Rp = Gp - Fp * Gp * _conjugate_matrix(Fp).transpose()
    return Fp


def _conjugate_ideal(E, P):
    return E.ideal([_conjugate(x) for x in P.gens()])


def _transfer_discriminant_isometry(transfer, g, qL, Bp, Bp2, pr):
    r"""OSCAR ``_transfer_discriminant_isometry``: ``g`` on the local basis of ``D^{-1}H^#``, read off along the trace construction."""
    rows = []
    for i in range(Bp.nrows()):
        x = transfer.from_E(Bp.row(i))
        moved = _ambient(g(qL(x)).lift())
        rows.append(transfer.to_E(moved) * pr)
    B2 = matrix(transfer.E, rows)
    return Bp2.solve_left(B2)
