def _is_local_norm(E, a, p):
    cm = _cm(E)
    b = cm.to_K((E.gen() - _conjugate(E.gen())) ** 2)
    return cm.K.hilbert_symbol(cm.to_K(a), b, p) == 1


def _local_genus_symbol(L, p):
    r"""Hecke ``_genus_symbol(L, p)`` with ``_get_ni_from_genus`` in the dyadic ramified case."""
    E = L.E
    blocks, grams, scales = _jordan_decomposition(L, p)
    D = _primes_over(E, p)
    ramified = D[0][1] == 2
    dyadic = p.smallest_integer() == 2
    symbol = []
    for B, G, s in zip(blocks, grams, scales):
        det_class = 1 if _is_local_norm(E, G.det(), p) else -1
        if dyadic and ramified:
            normi = _norm_valuation(G, D[0][0])
            assert normi % 2 == 0
            symbol.append((s, B.nrows(), det_class, normi // 2))
        else:
            symbol.append((s, B.nrows(), det_class, None))
    ni = None
    if dyadic and ramified:
        ni = [min(2 * max(0, symbol[i][0] - symbol[j][0]) + 2 * symbol[j][3] for j in range(len(symbol))) for i in range(len(symbol))]
    return symbol, ni, ramified, dyadic


def _local_genera_equal(E, p, first, second):
    r"""Hecke ``==(G1::HermLocalGenus, G2::HermLocalGenus)`` (Herm/Genus.jl:1017)."""
    s1, ni1, ramified, dyadic = first
    s2, ni2, _ramified, _dyadic = second
    if len(s1) != len(s2):
        return False
    t = len(s1)
    if any(s1[i][0] != s2[i][0] for i in range(t)) or any(s1[i][1] != s2[i][1] for i in range(t)):
        return False
    det1 = 1
    det2 = 1
    for i in range(t):
        det1 *= s1[i][2]
        det2 *= s2[i][2]
    if det1 != det2:
        return False
    if not ramified:
        return True
    if not dyadic:
        return all(s1[i][2] == s2[i][2] for i in range(t) if s1[i][0] % 2 == 0)
    for i in range(t):
        if (s1[i][0] == 2 * s1[i][3]) != (s2[i][0] == 2 * s2[i][3]):
            return False
    if ni1 != ni2:
        return False
    D = _primes_over(E, p)
    assert len(D) == 1 and D[0][1] == 2
    Q = D[0][0]
    e = _cm(E).relative_different.valuation(Q)
    for i in range(t - 1):
        d = 1
        for j in range(i + 1):
            d *= s1[j][2] * s2[j][2]
        if d != 1 and 2 * (e - 1) < ni1[i] + ni1[i + 1] - 2 * s1[i][0]:
            return False
    return True


def _is_special(L, p):
    r"""OSCAR ``_is_special(L::HermLat, p)`` (Kirschmer)."""
    E = L.E
    D = _primes_over(E, p)
    if D[0][1] != 2 or L.rank() % 2 != 0:
        return False
    blocks, _grams, S = _jordan_decomposition(L, p)
    if any(B.nrows() != 2 for B in blocks):
        return False
    P = D[0][0]
    e = _cm(E).relative_different.valuation(P)
    if any((e - s) % 2 != 0 for s in S):
        return False
    u = E.uniformizer(P)
    su = _conjugate(u)
    H = block_diagonal_matrix([matrix(E, 2, 2, [0, u ** s, su ** s, 0]) for s in S])
    model = _HermitianLattice(_GramTransfer(E, H), identity_matrix(E, H.nrows()))
    return _local_genera_equal(E, p, _local_genus_symbol(L, p), _local_genus_symbol(model, p))


class _GramTransfer:
    r"""The ambient hermitian space with a given Gram matrix (Hecke ``hermitian_lattice(E; gram=H)``)."""

    def __init__(self, E, gram):
        self.E = E
        self.ambient_gram = gram
        self.m = gram.nrows()


