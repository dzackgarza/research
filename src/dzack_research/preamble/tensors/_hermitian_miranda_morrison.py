def _find_rho(E, P, p, e):
    r"""OSCAR ``_find_rho``: an element of trace one, ``1/2`` away from 2, a special unit or a ramified dyadic choice at 2."""
    if p != 2:
        return E(QQ(1) / 2)
    D = _primes_over(E, p)
    if D[0][1] == 1:
        return _special_unit(E, P, p)
    nu = 2 * E(2).valuation(P) - 2 * e + 2
    r = 0
    while True:
        g = E(-(r ** 2) - 1)
        if g.valuation(P) == nu:
            d = ZZ((g + 1).denominator())
            roots = (E['t'].gen() ** 2 - (g + 1) * d ** 2).roots(multiplicities=False)
            if roots:
                rho = (1 + roots[0]) / 2
                assert rho.valuation(P) == 1 - e
                assert rho.trace() == 1
                return rho
        r += 1


def _local_hermitian_lifting(G, F, rho, l, P, P2, split, a):
    r"""[BH23, Algorithm 8] / OSCAR ``_local_hermitian_lifting``: a finer approximation of an isometry of ``G``."""
    E = G.base_ring()
    R = G - F * G * _conjugate_matrix(F).transpose()
    n = R.nrows()
    U = _mutable_matrix(E, n, n, [0] * (n * n))
    for i in range(n):
        for j in range(i + 1, n):
            U[i, j] = R[i, j]
    diagonal = R - U - _conjugate_matrix(U).transpose()
    newF = F + (U + rho * diagonal) * _conjugate_matrix(F.transpose().inverse()) * G.inverse()
    return newF, 2 * l + 1


def _local_basis_matrix_and_projection(Hv, p, a, transfer):
    r"""OSCAR ``_local_basis_matrix_and_projection``."""
    E = transfer.E
    Bv, _Gv, expsv = _jordan_decomposition(Hv, p)
    pr = identity_matrix(E, transfer.m)
    if expsv[-1] == -a:
        Bp = _block_matrix_rows(Bv[:-1])
        Bp0 = _block_matrix_rows([Bp, zero_matrix(E, Bv[-1].nrows(), Bv[-1].ncols())])
        Ball = _block_matrix_rows(Bv)
        pr = Ball.solve_right(Bp0)
    else:
        Bp = _block_matrix_rows(Bv)
    H2v = _FreeHermitianLattice(transfer, Bp)
    if not Hv.contains(H2v):
        denominator = _lcm_denominator(transfer.restrict_scalars(Hv.B) + transfer.restrict_scalars(Bp))
        Lv = (QQ ** transfer.gram.nrows()).span([denominator * vector(QQ, x) for x in transfer.restrict_scalars(Hv.B)], ZZ)
        L2 = (QQ ** transfer.gram.nrows()).span([denominator * vector(QQ, x) for x in transfer.restrict_scalars(Bp)], ZZ)
        intersection = Lv.intersection(L2)
        generators = [transfer.to_E(vector(QQ, b) / denominator) for b in intersection.basis()]
        Bp = _o_e_basis(transfer, generators)
        assert Hv.contains(_FreeHermitianLattice(transfer, Bp))
    assert Bp.rank() == (Bp * pr).rank()
    return Bp, Bp * pr, pr


def _lcm_denominator(vectors):
    d = ZZ.one()
    for x in vectors:
        for c in x:
            d = d.lcm(QQ(c).denominator())
    return d


def _block_matrix_rows(blocks):
    rows = []
    E = blocks[0].base_ring()
    ncols = blocks[0].ncols()
    for B in blocks:
        rows.extend(B.rows())
    return matrix(E, len(rows), ncols, rows)


