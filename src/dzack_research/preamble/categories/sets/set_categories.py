class NaturalNumberSets(OwnedCategory):
    r"""The owned set \(\mathbb{N}=\{0,1,2,\dots\}\)."""

    def an_object(self) -> ObjectOfCategory:
        r"""\(\mathbb{N}\)."""
        return NN

    def super_categories(self):
        from dzack_research.preamble.categories.rings.semirings import OwnedSemirings

        # The identity ranking is the chosen enumeration.  Declared by the
        # category rather than joined for the one object.
        return [
            EnumeratedSets(),
            Sets().Infinite(),
            OwnedSemirings().Commutative(),
        ]

    class ElementMethods(Element):
        r"""What a natural number is."""

        def __init__(self, parent: Parent, value: int) -> None:
            Element.__init__(self, parent)
            # The datum is a Python integer; admission of foreign data is
            # the parent's element constructor's, which is the one boundary
            # that reads it.
            assert value >= 0, f"{value} is not a natural number: it is negative"
            self._value = value

        def __int__(self) -> int:
            return self._value

        __index__ = __int__

        def __hash__(self):
            # Equality is decided on the number, not on the parent that
            # presented it, so the hash is the number's.
            return hash(self._value)

        def __eq__(self, other: Any) -> bool:
            if other not in self.parent():
                return False
            return int(self.parent()(other)) == self._value

        def __ne__(self, other):
            return not self == other

        def _semiring_operand(self, other):
            r"""Read another natural here, or defer to a larger semiring.

            NN is initial among semirings.  When the other operand already
            belongs to a different represented semiring, arithmetic belongs
            there along the unique map from NN rather than by pulling that
            element back into NN.
            """
            other_parent = element_parent(other)
            if other_parent is self.parent():
                return other
            from dzack_research.preamble.categories.rings.semirings import (
                OwnedSemirings,
            )

            if isinstance(other_parent, Parent) and other_parent in OwnedSemirings():
                return NotImplemented
            if other not in self.parent():
                return NotImplemented
            return self.parent()(other)

        def __add__(self, other):
            other = self._semiring_operand(other)
            if other is NotImplemented:
                return NotImplemented
            return self.parent()(self._value + int(other))

        __radd__ = __add__

        def __mul__(self, other):
            other = self._semiring_operand(other)
            if other is NotImplemented:
                return NotImplemented
            return self.parent()(self._value * int(other))

        __rmul__ = __mul__

        def __sub__(self, other):
            other_parent = element_parent(other)
            if isinstance(other_parent, Parent):
                from dzack_research.preamble.categories.rings.ring_foundation import (
                    OwnedRings,
                )

                if other_parent in OwnedRings():
                    return NotImplemented
            other = self.parent()(other)
            return self.parent()(self._value - int(other))

        def __rsub__(self, other):
            return self.parent()(int(other) - self._value)

        def __mod__(self, other):
            divisor = int(self.parent()(other))
            match divisor:
                case 0:
                    raise ZeroDivisionError(f"cannot compute {self} mod 0 in the natural numbers")
                case _:
                    return self.parent()(self._value % divisor)

        def _repr_(self):
            return str(self._value)

    class ParentMethods:
        def __init__(self, **rest) -> None:
            super().__init__(**rest)

        def _element_constructor_(self, value):
            r"""The natural number ``value`` names; its admission is :meth:`__contains__`."""
            match value:
                case _ if element_parent(value) is self:
                    return value
                case _ if value in self:
                    return self.element_class(self, int(value))
                case _:
                    raise ValueError(f"{value!r} is not a natural number")

        def __call__(self, value):
            r"""Construct an owned natural number without Sage coercion discovery."""
            return self._element_constructor_(value)

        def __contains__(self, value) -> bool:
            r"""Decide whether ``value`` names a natural number.

            The argument is genuinely arbitrary here, so the question is
            whether this set has a point for it: a natural number of this
            set, the Python integer literal a mathematician writes at a
            prompt, or a nonnegative owned integer, since
            \(\mathbb N\subset\mathbb Z\).  A raw engine integer is not an
            owned value and names nothing here.
            """
            match value:
                case _ if element_parent(value) is self:
                    return True
                case _ if isinstance(value, int):
                    return value >= 0
                case _ if isinstance(value, Element) and element_parent(value) in Objects() and isinstance(value, SupportsIndex):
                    return integer_index(value) >= 0
                case _:
                    return False

        @cached_method
        def ranking_map(self) -> CategoricalIsomorphism:
            r"""The identity: $\mathbb N$ is the ordinal $\omega$ that counts it."""
            return self._ranking_isomorphism(lambda value: int(self(value)), self)

        def le(self, left, right) -> bool:
            r"""The order of the ordinal $\omega$: $m \le n$ when $n = m + k$ for some $k \in \mathbb N$.

            ``EnumeratedSets`` transports an order along the ranking map, and
            here that map is the identity of $\mathbb N$, so $\mathbb N$
            states the order it transports.
            """
            return int(self(left)) <= int(self(right))

        def zero(self) -> NN.ElementType:
            return self(0)

        def one(self) -> NN.ElementType:
            return self(1)

        def submonoid(self, generators, *, description=None):
            r"""The additive submonoid of the natural numbers generated by a finite family."""
            return self.additive_submonoid(generators, description=description)

        def predicate_submonoid(self, predicate, description):
            r"""The additive submonoid of ``NN`` defined by a zero- and sum-closed predicate."""
            return self.predicate_additive_submonoid(predicate, description)

        def _repr_(self):
            return "NN = {0, 1, 2, ...}"

        def _latex_(self):
            return r"\mathbb{N}=\{0,1,2,\ldots\}"


