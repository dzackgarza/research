        def product(
            self,
            family: IndexedFamily | Iterable[Parent],
        ) -> Sets().ObjectType:
            r"""Return $\prod_{i \in I} X_i$ for an indexed family of objects.

            A product is taken over an index set, so the family carries both the
            index set and the factor at each index.  Asking the category is the
            public route (`STY-02`), and naming the index set rather than an arity
            is what `CON-14` requires. A two-factor call may pass a two-element
            family, whose canonical labels are then `Sets.Δ[1]`.

            Equal families have one product (`SET-05`).  Without that, an element
            of one never equals an element of the other and the product is
            unusable as a codomain -- a caller could not compare what an operation
            returned against a value it built.  A family's value map is a callable
            and cannot key a cache, so a finite index set is resolved to its
            factors, which compare by their own equality.

            Asking for the product constructs the object only: it stores the
            family and fixes the category (`OWN-22`).  The discrete diagram and
            the universal cone are built when ``product_construction`` asks for
            them.

            A bare sequence of factors is the family on the canonical labels, so
            the caller may hand over either.
            """
            from dzack_research.preamble.categories.abstract_categories.products import (
                _factor_family,
            )

            family = _factor_family(family, name="Product factors")
            index_set = family.index_set()
            if Sets().is_provably_finite(index_set) and index_set in EnumeratedSets():
                return self._finite_product(family)
            return _cartesian_product_of(family)

        def _categorical_product(self, left, right):
            return self._finite_product((left, right))

        def _finite_product(self, factors):
            r"""Return the product of a finite family of sets, without its universal cone."""
            from dzack_research.preamble.categories.abstract_categories.products import (
                _finite_factor_family,
            )

            family = _finite_factor_family(factors, name="Product factors")
            if any(factor not in self for factor in family):
                raise TypeError(
                    f"a product of sets needs every factor to be a set, but the factors are {family}"
                )
            return _cartesian_product_of_finite_family(family)

        def _categorical_product_construction(self, factors):
            r"""The product cone for a represented discrete set-valued diagram.

            A nonfinite diagram must retain its selected functor (or a
            constant factor). Its natural-transformation cone supplies the
            mediating map; no finite enumeration or sampled component map
            replaces that datum.
            """
            from dzack_research.preamble.categories.abstract_categories.products import (
                SelectedLimitConstruction,
                _discrete_diagram,
                _factor_family,
            )

            family = _factor_family(factors, name="Product factors")
            product = self.product(family)
            if product not in self:
                raise TypeError(
                    f"the Cartesian product {product} is not an object of {self}; "
                    "the selected subcategory does not contain this product"
                )
            diagram = _discrete_diagram(family, self)
            universal_cone = (diagram).ProductCones().cone(
                product,
                lambda index: product.projection(index.value()),
            )

            def factorizer(cone):
                finite = family.cardinality().is_finite() and family.index_set() in EnumeratedSets()
                components = (
                    (lambda label: cone.structure_morphism(diagram.domain()(label)))
                    if finite else cone.transformation()
                )
                # This is a limit in Sets. Its apex need not carry the
                # additive structure that the product's factors happen to
                # possess, so the additive-monoid/group specialization of
                # from_maps is not the universal set-map constructor.
                return CartesianProductsOfSets.ParentMethods.from_maps(
                    product,
                    cone.apex(), components,
                )

            return SelectedLimitConstruction(diagram, universal_cone, factorizer)

        def _categorical_equalizer(self, left_morphism, right_morphism):
            r"""Return the represented subset on which two set maps agree."""
            return self._categorical_equalizer_construction(
                left_morphism, right_morphism
            ).object()

        def _categorical_equalizer_construction(
            self, left_morphism, right_morphism
        ):
            r"""Return the selected equalizer cone for two parallel set maps."""
            from dzack_research.preamble.categories.abstract_categories.products import (
                SelectedLimitConstruction,
                _parallel_pair_diagram,
            )

            if (
                left_morphism.domain() is not right_morphism.domain()
                or left_morphism.codomain() is not right_morphism.codomain()
            ):
                raise ValueError(
                    f"an equalizer needs parallel maps f, g: X -> Y, but {left_morphism} is "
                    f"{left_morphism.domain()} -> {left_morphism.codomain()} and {right_morphism} is "
                    f"{right_morphism.domain()} -> {right_morphism.codomain()}"
                )
            source = left_morphism.domain()
            target = left_morphism.codomain()
            if source not in self or target not in self:
                raise TypeError(
                    f"an equalizer in the category of sets needs maps between sets, but {source} or {target} is not a set"
                )
            if not all(
                _category_accepts_morphism(self, source, target, arrow)
                for arrow in (left_morphism, right_morphism)
            ):
                raise TypeError(
                    "a set equalizer requires both parallel arrows to belong to its selected Mor category"
                )

            equalizer = self.condition_set(
                source,
                lambda element: left_morphism(element) == right_morphism(element),
            )
            inclusion = equalizer.inclusion()
            diagram = _parallel_pair_diagram(left_morphism, right_morphism, self)
            shape = diagram.domain()
            universal_cone = diagram.Cones().cone(
                equalizer,
                lambda index: (
                    inclusion
                    if index is shape.source()
                    else left_morphism * inclusion
                ),
            )

            def factorizer(cone):
                source_leg = cone.structure_morphism(shape.source())
                return self.Mor(cone.apex(), equalizer)(
                    lambda element: equalizer(source_leg(element))
                )

            return SelectedLimitConstruction(diagram, universal_cone, factorizer)

        def _finite_parallel_morphism_family(self, morphisms):
            r"""Return the data of a finite enumerable family of parallel set maps."""
            size = morphisms.cardinality()
            assert size.is_finite(), (
                f"the wide (co)equalizer of {morphisms} is computed here only for a finite family of maps, "
                f"but the family has cardinality {size}"
            )
            if size == cardinal(0):
                raise ValueError(
                    f"the wide (co)equalizer in {self} needs a nonempty family of maps to retain its common "
                    f"domain and codomain, but got {morphisms}"
                )
            index_set = morphisms.index_set()
            assert index_set in EnumeratedSets(), (
                f"the finite family {morphisms} is computed here only when its index set {index_set} carries "
                "an enumeration"
            )
            labels = tuple(index_set)
            reference = morphisms.value(labels[0])
            match reference:
                case Morphism():
                    pass
                case _:
                    raise TypeError(
                        f"a wide (co)equalizer in {self} needs morphisms of sets, but the family contains {reference}"
                    )
            source = reference.domain()
            target = reference.codomain()
            if source not in self or target not in self:
                raise TypeError(
                    f"a wide (co)equalizer in the category of sets needs maps between sets, but {source} or "
                    f"{target} is not a set"
                )
            for label in labels:
                arrow = morphisms.value(label)
                if not (
                    isinstance(arrow, Morphism)
                    and arrow.domain() is source
                    and arrow.codomain() is target
                    and _category_accepts_morphism(self, source, target, arrow)
                ):
                    raise ValueError(
                        f"a wide (co)equalizer needs a parallel family of set maps {source} -> {target}, but "
                        f"the arrow at {label!r} is {arrow}"
                    )
            return labels, reference, source, target

        def _categorical_equalizer_family(self, morphisms):
            return self._categorical_equalizer_family_construction(morphisms).object()

