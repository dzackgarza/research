class PowerSets(OwnedCategory):
    r"""The power object \(P(X)\), represented by subobjects of ``X``."""

    def an_object(self) -> ObjectOfCategory:
        r"""One object of this category."""
        return Sets.Δ[2].power_set()

    def super_categories(self):
        return [Sets()]

    def __call__(self, base_set):
        r"""Construct ``P(base_set)`` even when ``base_set`` is itself a power set."""
        return self._call_(base_set)

    def _call_(self, base_set):
        r"""Construct the power object of ``base_set``."""
        placements = [self, _cardinalities().set_power_category(Sets.Δ[1], base_set)]
        engine = None
        if Sets().is_provably_finite(base_set):
            if base_set in EnumeratedSets():
                placements.append(EnumeratedSets())
                engine = (self, _EnumeratedPowerSetEngine, None)
        return _object_of(
            owned_category_join(placements),
            _engine=engine,
            base_set=base_set,
        )

    class ParentMethods:
        def __init__(self, base_set: Parent, **rest) -> None:
            assert base_set in Sets(), (
                f"the power set P(X) needs X a set, but {base_set} is not in the category of sets"
            )
            self._base_set = base_set
            super().__init__(**rest)

        def base_set(self) -> Sets().ObjectType:
            return self._base_set

        def truth_values(self) -> Sets().ObjectType:
            return Sets.Δ[1]

        def characteristic_mor(self) -> SetMorCategory:
            return Sets().Mor(self.base_set(), self.truth_values())

        def from_predicate(
            self,
            predicate: Callable[[SourcePointT], bool | Predicate],
        ):
            r"""The subset \(\{x\in X : P(x)\}\) with its inclusion."""
            inclusion = self.base_set().condition_set(predicate).inclusion()
            base = self.base_set()
            return Sets().Subobjects(base).object(inclusion)

        def from_characteristic_morphism(
            self,
            characteristic_morphism: SetMorphism,
        ):
            r"""The subset classified by \(\chi\colon X\to\Delta[1]\): where \(\chi=1\)."""
            if not (
                isinstance(characteristic_morphism, Morphism)
                and _category_accepts_morphism(
                    Sets(), self.base_set(), self.truth_values(), characteristic_morphism
                )
            ):
                raise ValueError(
                    f"{characteristic_morphism} is not a characteristic map X -> Delta[1] of a subset of "
                    f"{self.base_set()}"
                )
            truth = self.truth_values()(1)
            return self.from_predicate(lambda member: characteristic_morphism(member) == truth)

        def _from_finite_members(self, members):
            r"""The finite subset on the stated members, as a finite ordered set with its inclusion."""
            from dzack_research.preamble.categories.sets.finite_ordered_sets import (
                finite_ordered_set,
            )

            base = self.base_set()
            normalized = []
            for member in members:
                if base.is_parent_of(member) is not True:
                    raise ValueError(
                        f"{member!r} is not proved to be an element of {base}, so its inclusion is not certified"
                    )
                normalized.append(base(member))
            # ``finite_ordered_set`` identifies equal points; identifying them
            # here as well compared every pair twice.
            subset = finite_ordered_set(tuple(normalized))
            return Sets().Subobjects(base)(Sets().Mono(subset, base)._from_subset_inclusion())

        def __call__(self, *args, **kwargs):
            r"""Construct through the owned set representation directly."""
            return self._element_constructor_(*args, **kwargs)

        def _element_constructor_(self, candidate):
            r"""Admit a subset: an inclusion into \(X\), \(X\) itself, or finitely many members."""
            subobjects = Sets().Subobjects(self.base_set())
            if candidate in subobjects:
                return candidate
            if isinstance(candidate, Morphism):
                if candidate.codomain() is not self.base_set():
                    raise ValueError(
                        f"{candidate} is a map into {candidate.codomain()}, so it is not a subset of {self.base_set()}"
                    )
                return subobjects(candidate)
            if candidate is self.base_set():
                return self.from_predicate(lambda _member: True)
            if candidate in Sets():
                assert Sets().is_provably_finite(candidate) and candidate in EnumeratedSets(), (
                    f"cannot read {candidate} as a subset of {self.base_set()}: a set is read as a subset here only "
                    "through its elements, which needs it finite and enumerated"
                )
                return self._from_finite_members(candidate)
            if isinstance(candidate, Iterable):
                return self._from_finite_members(candidate)
            raise TypeError(f"{candidate!r} does not present a subset of {self.base_set()}")

        def __contains__(self, candidate) -> bool | Predicate:
            r"""Whether ``candidate`` is a subset of \(X\): \(A\in P(X)\) exactly when \(A\subseteq X\).

            A subset is \(X\) itself, a set all of whose points lie in \(X\)
            (decided here for a finite enumerated set), or a subobject
            \(A\hookrightarrow X\), which is an arrow of ``Set`` rather than a
            set; reading that presentation off the arbitrary ``candidate`` is
            this method's whole job.  Finitely many points are data for the
            element constructor, not a subset: ``P(X)((x, y))`` builds one.
            """
            base = self.base_set()
            if candidate in Sets().Subobjects(base):
                return True
            match candidate:
                case _ if candidate is base:
                    return True
                case _ if candidate in Sets():
                    if not Sets().is_provably_finite(candidate) or candidate not in EnumeratedSets():
                        from dzack_research.preamble.logic import AtomicProposition

                        return AtomicProposition("is_subset", candidate, base)
                    from dzack_research.preamble.logic import conjunction

                    return conjunction(base.is_parent_of(point) for point in candidate)
                case _ if isinstance(candidate, Morphism):
                    return Sets().Subobjects(base).admits_arrow(candidate)
                case _:
                    return False

        # Preserve undecidable subset containment through the owned API.
        is_parent_of = __contains__

        def top(self):
            return self.from_predicate(lambda _member: True)

        def bottom(self):
            return self(())

        def inverse_image_morphism(self, morphism: SetMorphism) -> SetMorphism:
            if morphism.codomain() is not self.base_set():
                raise ValueError(
                    f"the inverse image f^-1 on P({self.base_set()}) needs f to end at {self.base_set()}, but "
                    f"{morphism} ends at {morphism.codomain()}"
                )
            target = morphism.domain().power_set()
            return Sets().Mor(self, target)(
                lambda subset: target.from_predicate(lambda member: subset.is_parent_of(morphism(member)))
            )

        def direct_image_morphism(self, morphism: SetMorphism) -> SetMorphism:
            r"""Direct image \(A\mapsto f(A)\) on subsets, as a set map \(P(X)\to P(Y)\)."""
            if morphism.domain() is not self.base_set():
                raise ValueError(
                    f"the direct image f_* on P({self.base_set()}) needs f to start at {self.base_set()}, but "
                    f"{morphism} starts at {morphism.domain()}"
                )
            target = morphism.codomain().power_set()

            def direct_image(subset):
                # The represented subobject is a Set with a chosen inclusion;
                # direct image belongs to Sets, not to the inclusion's host.
                image = subset.image_set(morphism)
                return Sets().Subobjects(morphism.codomain())(
                    Sets().Mono(image, morphism.codomain())._from_subset_inclusion()
                )

            return Sets().Mor(self, target)(direct_image)

        def cardinality_comparison(self) -> CardinalityMorphism:
            size = self.cardinality()
            return _cardinalities().Mor(size, size).identity()

        def _repr_(self) -> str:
            return f"Power set of {self.base_set()}"


def _finite_subset_ranking_map(subset_set, source) -> CategoricalIsomorphism:
    r"""Rank finite subsets of an enumerated source by their binary support."""
    source_size = cardinal(source.cardinality())
    point_at_source_rank = source.ranking_map().inverse()

    def point_at(position):
        position = int(position)
        bound = 1 << int(source_size.finite_value()) if source_size.is_finite() else None
        if position < 0 or (bound is not None and position >= bound):
            raise IndexError(
                f"position {position} is out of range for {subset_set}, which has cardinality {subset_set.cardinality()}"
            )
        members = []
        source_position = 0
        remaining_bits = position
        while remaining_bits:
            if remaining_bits & 1:
                members.append(point_at_source_rank(source_position))
            source_position += 1
            remaining_bits >>= 1
        return subset_set(tuple(members))

    def position_of(subset):
        subset = subset_set(subset)
        members = subset.domain()
        if members in EnumeratedSets() and Sets().is_provably_finite(members):
            # The selected finite member enumeration already witnesses the
            # support. Read its positions directly rather than searching the
            # ambient enumeration, including for sparse finite sources.
            position = 0
            for member in members:
                position |= 1 << int(source.ranking_map()(member))
            return position
        if source_size.is_finite() is False:
            raise ValueError(
                "ranking a finite subset of an infinite set requires its selected "
                "finite member enumeration"
            )
        position = 0
        for source_position in range(int(source_size.finite_value())):
            point = point_at_source_rank(source_position)
            decision = subset.is_parent_of(point)
            if decision is True:
                position |= 1 << source_position
            elif decision is not False:
                raise ValueError("subset ranking requires decided membership at each source point")
        return position

    return subset_set._ranking_isomorphism(position_of, point_at)


