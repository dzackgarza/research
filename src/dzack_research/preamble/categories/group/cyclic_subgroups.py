r"""Cyclic subgroups generated by live elements of owned groups."""

from sage.categories.category import Category
from sage.misc.cachefunc import cached_method
from sage.misc.unknown import Unknown
from sage.rings.integer_ring import ZZ as SageZZ
from sage.structure.parent import Parent

from dzack_research.preamble.categories.sets.finite_ordered_sets import finite_ordered_set
from dzack_research.preamble.categories.sets.cardinals import cardinal
from dzack_research.preamble.categories.group.groups import (
    GroupsWithChosenFiniteGeneratingSet,
    OwnedAbelianGroups,
    OwnedFiniteAbelianGroups,
    OwnedFiniteGroups,
    _canonical_subgroup_inclusion,
    _owned_group,
)
from dzack_research.preamble.categories.rings.ring_foundation import _own_ring


class CyclicSubgroup(Parent):
    r"""The literal subgroup ``<g> <= G`` generated by one live element.

    This is a facade of ``G``: its elements are the actual elements of the
    ambient group, not parallel residue classes in an abstract ``C_n``.  The
    chosen generator is structure on the subgroup.  Finiteness is inherited
    when the ambient group is known finite; otherwise no finite-order claim is
    made merely because the subgroup is cyclic.
    """

    def __init__(self, supergroup, generator) -> None:

        supergroup = _owned_group(supergroup)
        generator = supergroup(generator)
        self._supergroup = supergroup
        self._generator = generator
        categories = [GroupsWithChosenFiniteGeneratingSet(), OwnedAbelianGroups()]
        if supergroup in OwnedFiniteGroups():
            categories.append(OwnedFiniteAbelianGroups())
        Parent.__init__(
            self,
            facade=supergroup,
            category=Category.join(tuple(categories)),
        )

    def supergroup(self):
        return self._supergroup

    def generator(self):
        return self._generator

    @cached_method
    def group_generators(self):
        if self.generator() == self.supergroup().one():
            return finite_ordered_set(())
        return finite_ordered_set((self.generator(),))

    def number_of_group_generators(self):

        return _own_ring(SageZZ)(int(self.group_generators().cardinality()))

    def one(self):
        return self.supergroup().one()

    def inclusion(self):

        return _canonical_subgroup_inclusion(self)

    def is_finite(self):

        if self.supergroup() in OwnedFiniteGroups():
            return True
        return Unknown

    def is_abelian(self):
        return True

    @cached_method
    def _finite_elements(self):
        if self.is_finite() is not True:
            raise NotImplementedError(
                "enumerating a cyclic subgroup requires its order to be decided finite"
            )
        ambient = self.supergroup()
        identity = ambient.one()
        generator = self.generator()
        bound = ambient.order()
        elements = [identity]
        current = identity
        for _ in range(int(bound)):
            current = generator * current
            if current == identity:
                return tuple(elements)
            elements.append(current)
        raise ArithmeticError("a subgroup generator did not close within the ambient group order")

    def order(self):
        if self.is_finite() is True:
            ambient_order = self.supergroup().order()
            return ambient_order.parent()(len(self._finite_elements()))
        return self.cardinality()

    def cardinality(self):
        if self.is_finite() is True:
            return cardinal(self.order())
        return Unknown

    def __iter__(self):
        return iter(self._finite_elements())

    def __contains__(self, element):
        ambient = self.supergroup()
        try:
            if element not in ambient:
                return False
        except TypeError:
            return False
        if self.is_finite() is True:
            return any(element == candidate for candidate in self._finite_elements())
        if element == ambient.one() or element == self.generator():
            return True
        raise NotImplementedError(
            "membership in this infinite-or-undecided cyclic subgroup is not computed"
        )

    def _element_constructor_(self, datum):
        element = self.supergroup()(datum)
        if element not in self:
            raise ValueError(f"{element} is not in {self}")
        return element

    def _repr_(self):
        return f"<{self.generator()}> <= {self.supergroup()}"


def cyclic_subgroup(generator):
    r"""Return the literal cyclic subgroup generated by ``generator``."""
    ambient = generator.parent()
    return CyclicSubgroup(ambient, generator)


__all__ = ["CyclicSubgroup", "cyclic_subgroup"]
