r"""Cyclic groups: groups generated by a single chosen element."""

from inspect import getattr_static

from sage.misc.cachefunc import cached_method

from dzack_research.preamble.categories.abstract_categories.cat import Cat
from dzack_research.preamble.categories.abstract_categories.objects import (
    OwnedCategory,
)
from dzack_research.preamble.categories.group.groups import (
    FiniteAbelianGroups,
    FiniteGroups,
    Groups,
    OwnedAbelianGroups,
    OwnedGroups,
    Subgroups,
    _fix_selected_group_resolution_data,
    _owned_group,
)
from dzack_research.preamble.categories.sets.cardinals import cardinal
from dzack_research.preamble.categories.sets.finite_ordered_sets import finite_ordered_set
from dzack_research.preamble.categories.sets.set_categories import Sets
from dzack_research.preamble.logic import AtomicProposition, conjunction, negation
from dzack_research.preamble.owned_category import _object_of
from dzack_research.preamble.refine import RealizationHook


__all__ = ["CyclicGroups"]


class CyclicGroups(OwnedCategory):
    r"""Groups generated by one chosen element.

    The generator is the datum: a cyclic group is one for which such an element
    exists, and an object of this category has selected one.  Everything below
    is computed by walking that generator.
    """

    def an_object(self):
        r"""``<s> <= C_2``, generated by the nonidentity element."""
        from dzack_research.preamble.categories.group.groups import OwnedGroups

        group = OwnedGroups().C(2)
        (element,) = tuple(group.group_generators())
        return self(element)

    @classmethod
    def _repr_object_names(cls):
        return "cyclic groups"

    def super_categories(self):
        return [
            OwnedAbelianGroups(),
            OwnedGroups().FinitelyGeneratedAsMagma(),
        ]

    def _call_(self, generator, *, placements=(), **level_data):
        r"""Construct the cyclic subgroup from its selected generator.

        The generator determines both the ambient group and the subgroup
        construction.  The returned object is a facade of that ambient group,
        so its elements remain the ambient elements rather than a parallel
        abstract cyclic-group model.
        """
        supergroup = _owned_group(generator.parent())
        placement = [self, Subgroups(supergroup), *placements]
        if supergroup in FiniteGroups() or (generator == supergroup.one()) is True:
            placement.append(FiniteAbelianGroups())
        return _object_of(
            Cat().meet(placement),
            supergroup=supergroup,
            group_generator=supergroup(generator),
            **level_data,
        )

    class ParentMethods:
        def __init__(self, group_generator, **rest) -> None:
            self._group_generator = group_generator
            super().__init__(**rest)
            generators = (
                finite_ordered_set(())
                if (self.group_generator() == self.supergroup().one()) is True
                else finite_ordered_set((self.group_generator(),))
            )
            source = Groups.Free(index_set=generators)
            generator_morphism = Sets().Mor(generators, self)(lambda generator: generator)
            _fix_selected_group_resolution_data(
                self, source, generators, generator_morphism
            )

        def group_generator(self):
            r"""Return the element this group is generated by."""
            return self._group_generator

        def one(self):
            r"""The identity of this subgroup is the literal ambient identity."""
            return self.supergroup().one()

        def _finiteness_decision(self):
            r"""Ask the selected order algorithm without requiring one to construct the subgroup."""
            if self in FiniteGroups():
                return True
            size = self.group_generator()._cyclic_subgroup_cardinality_decision()
            if size is not None:
                return size.is_finite()
            return AtomicProposition("is_finite", self)

        def _cardinality_decision(self):
            r"""``|<g>|`` is the order of ``g``: finite, or ``aleph_0`` when ``<g> = ZZ``."""
            if (self.group_generator() == self.one()) is True:
                return cardinal(1)
            generator_order = self.group_generator()._cyclic_subgroup_cardinality_decision()
            if generator_order is not None:
                return generator_order
            if self.supergroup() in FiniteGroups():
                engine_subgroup = self._cyclic_engine_subgroup()
                if engine_subgroup is not None:
                    return cardinal(engine_subgroup.order())
                return cardinal(len(self._finite_elements()))
            assert False, (
                f"the cardinality of {self} is the order of {self.group_generator()}, but no "
                "order algorithm or finite ambient enumeration is supplied"
            )

        @cached_method
        def _finite_elements(self):
            r"""The powers ``1, g, g^2, ...`` of the generator up to its order."""
            assert self.is_finite() is True, (
                f"cannot list the elements of {self}: it is not known to be finite, since the "
                f"order of its generator {self.group_generator()} is not known to be finite"
            )
            ambient = self.supergroup()
            identity = ambient.one()
            generator = self.group_generator()
            if (generator == identity) is True:
                return (identity,)
            if ambient in FiniteGroups():
                bound = ambient.order()
            else:
                size = generator._cyclic_subgroup_cardinality_decision()
                assert size is not None and size.is_finite(), (
                    f"cannot enumerate {self}: no finite order of {generator} is supplied"
                )
                bound = size.finite_value()
            elements = [identity]
            current = identity
            for _ in range(int(bound)):
                current = generator * current
                equal = current == identity
                if equal is True:
                    return tuple(elements)
                assert equal is False, (
                    f"cannot enumerate {self}: equality of the power {current} with the identity "
                    "is undecided"
                )
                elements.append(current)
            raise ArithmeticError(
                f"the powers of {generator} in {ambient} did not return to the identity within "
                f"{bound} steps, although {bound} bounds the order of {generator}"
            )

        def __iter__(self):
            return iter(self._finite_elements())

        @cached_method
        def _cyclic_engine_subgroup(self):
            r"""Selected ambient engine realization of the generated subgroup, if any."""
            ambient = self.supergroup()
            supplier = getattr_static(ambient, "_engine_subgroup_from_generators", None)
            if supplier is None or isinstance(supplier, RealizationHook):
                return None
            return ambient._engine_subgroup_from_generators((self.group_generator(),))

        def is_parent_of(self, element):
            ambient = self.supergroup()
            admitted = ambient.is_parent_of(element)
            if admitted is False:
                return False
            if admitted is not True:
                return AtomicProposition("is_member", element, self)
            element = ambient(element)
            if (element == ambient.one()) is True or (element == self.group_generator()) is True:
                return True
            # Prefer the supplied engine's subgroup decision. A finite cyclic
            # group without such an engine nevertheless has a complete finite
            # power presentation: preserve its decided equality cases rather
            # than replacing their answers by an atomic proposition.
            engine_subgroup = self._cyclic_engine_subgroup()
            if engine_subgroup is not None:
                return ambient._engine_subgroup_contains(element, engine_subgroup)
            if self.is_finite() is True:
                return negation(conjunction(
                    negation(element == candidate) for candidate in self._finite_elements()
                ))
            return AtomicProposition("is_member", element, self)

        __contains__ = is_parent_of

        def _element_constructor_(self, datum):
            element = self.supergroup()(datum)
            member = self.is_parent_of(element)
            if member is False:
                raise ValueError(f"{element} is not in {self}")
            assert member is True, (
                f"cannot admit {element} into {self}: whether it is a power of "
                f"{self.group_generator()} is undecided"
            )
            return element

        def _repr_(self):
            return f"<{self.group_generator()}> <= {self.supergroup()}"
