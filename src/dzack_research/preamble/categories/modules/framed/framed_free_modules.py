def _finitely_generated_free_placement(ring, module_generating_set):
    r"""Return the owned categories of ``R^(S)``: finitely generated exactly when ``S`` is finite."""

    categories = [FramedFreeModules(ring)]
    if ring in OwnedFields():
        categories.append(VectorSpaces(ring))
    assert module_generating_set in Sets(), (
        f"cannot form the free {ring}-module on {module_generating_set!r}: "
        "a free module is generated by a set, and this is not a set"
    )
    match Cardinalities().lt(module_generating_set.cardinality(), aleph0):
        case True:
            categories.append(FramedFreeModules(ring).FinitelyGenerated())
        case False:
            pass
    categories.append(Cardinalities().finite_support_power_category(ring, module_generating_set))
    return categories


class _SparseFreeModuleElement(ModuleElement):
    """Coordinates with a selected finite containing family in ``R^(I)``.

    Stored labels contain the support; a stored coefficient need not be
    proved nonzero. Only a coefficient proved zero is discarded.
    """

    def __init__(self, parent, coefficients) -> None:
        ModuleElement.__init__(self, parent)
        ring = parent.base_ring()
        self._coefficients = {
            label: ring(coefficient)
            for label, coefficient in coefficients.items()
            if (ring(coefficient) == ring.zero()) is not True
        }

    def __call__(self, label):
        r"""The value ``a(i)`` of this finitely supported function ``a : I -> R`` at ``i``.

        An element of the free module \(R^{(I)}\) on \(I\) is a finitely
        supported function \(I\to R\), and its value at a basis label is the
        coefficient of that basis element.
        """
        labels = self.parent().module_generating_set()
        assert label in labels, f"{label!r} is not a basis label of {self.parent()}; the basis is indexed by {labels}"
        return self._coefficients.get(labels(label), self.parent().base_ring().zero())

    @cached_method
    def support(self):
        r"""The support ``{i in I : a(i) != 0}``, a finite subset of the basis with its inclusion.

        The retained finite coordinate family contains the support. Its
        nonzero predicate defines the exact subset even when a coefficient's
        equality to zero is undecided. When every retained coefficient is
        proved nonzero, keep the usual enumerated finite subset.
        """
        labels = self.parent().module_generating_set()
        possible = labels.finite_subsets()(tuple(self._coefficients))
        zero = self.parent().base_ring().zero()
        if all((coefficient == zero) is False for coefficient in self._coefficients.values()):
            return possible
        actual = possible.domain().condition_set(lambda label: negation(self(label) == zero))
        return Sets().Subobjects(labels).object(possible.inclusion() * actual.inclusion())

    def _coefficient_data(self):
        r"""Storage read for ``Modules._selected_module_coefficients``.

        The finite mapping gives all coefficients outside of which the vector
        is zero. Its keys contain the support; they do not certify nonzero
        coefficients. The selected-coefficient owner declares its consumers.
        """
        return self._coefficients

    def __iter__(self):
        r"""Iterate coordinates when the selected framing is finite and ordered."""
        labels = self.parent().module_generating_set()
        match (labels in EnumeratedSets(), labels.cardinality().is_finite()):
            case (True, True):
                zero = self.parent().base_ring().zero()
                return (self._coefficients.get(label, zero) for label in labels)
            case _:
                raise TypeError(
                    f"cannot iterate over the coordinates of {self}: its parent {self.parent()} "
                    f"has basis {labels}, which is not a finite ordered set"
                )

    def is_canonical_free_generator(self) -> bool:
        r"""Whether this is one of the chosen basis vectors, with coefficient one."""
        zero = self.parent().base_ring().zero()
        if any((coefficient == zero) is not False for coefficient in self._coefficients.values()):
            return AtomicProposition("is_canonical_free_generator", self)
        return len(self._coefficients) == 1 and next(iter(self._coefficients.values())) == self.parent().base_ring().one()

    def underlying_set_element(self):
        r"""Recover ``s`` when this is the canonical free generator ``[s]``.

        This is the inverse of the unit ``S -> U(F_R(S))`` on its image.  A
        general linear combination has no distinguished underlying element of
        ``S`` and therefore refuses rather than selecting one support label.
        """
        if self.is_canonical_free_generator() is not True:
            raise ValueError(
                f"{self} has no established single basis label in {self.parent()}"
            )
        return next(iter(self._coefficients))

    def _add_(self, other):
        ring = self.parent().base_ring()
        coefficients = dict(self._coefficients)
        for label, coefficient in other._coefficients.items():
            value = coefficients.get(label, ring.zero()) + coefficient
            if (value == ring.zero()) is True:
                coefficients.pop(label, None)
            else:
                coefficients[label] = value
        return self.parent().element_class(self.parent(), coefficients)

    def _neg_(self):
        return self.parent()._element_constructor_(
            {label: -coefficient for label, coefficient in self._coefficients.items()}
        )

    def _lmul_(self, scalar):
        return self.parent()._raw_scalar_multiple(scalar, self)

    _rmul_ = _lmul_

    def __rmul__(self, scalar):
        return self.parent().scalar_multiple(scalar, self)

    def __mul__(self, other):
        r"""Multiply in the algebra this free module underlies, else scale on the right."""
        from dzack_research.preamble.categories.algebras.algebras import Algebras

        module = self.parent()
        ring = module.base_ring()
        match other:
            case _ if element_parent(other) is module and module in Algebras(ring):
                return self._mul_(other)
            case _ if other in ring:
                return module.scalar_multiple(other, self)
            case _:
                return NotImplemented

    def _richcmp_(self, other, op):
        if op not in (op_EQ, op_NE):
            return NotImplemented
        if element_parent(other) is not self.parent():
            return NotImplemented
        if self is other:
            return op == op_EQ
        zero = self.parent().base_ring().zero()
        equal = conjunction(
            self._coefficients.get(label, zero) == other._coefficients.get(label, zero)
            for label in self._coefficients.keys() | other._coefficients.keys()
        )
        return equal if op == op_EQ else negation(equal)

    def __hash__(self):
        zero = self.parent().base_ring().zero()
        if any((coefficient == zero) is not False for coefficient in self._coefficients.values()):
            raise TypeError("a sparse vector with undecided zero coefficients has no selected canonical hash")
        return hash((id(self.parent()), frozenset(self._coefficients.items())))

    def _repr_(self):
        zero = self.parent().base_ring().zero()
        if any((coefficient == zero) is not False for coefficient in self._coefficients.values()):
            return " + ".join(f"({coefficient})*[{label}]" for label, coefficient in self._coefficients.items()) or "0"
        return repr_lincomb(
            self._coefficients.items(),
            repr_monomial=lambda label: f"[{label}]",
            strip_one=True,
        )

    def _latex_(self):
        zero = self.parent().base_ring().zero()
        if any((coefficient == zero) is not False for coefficient in self._coefficients.values()):
            return " + ".join(
                rf"\left({latex(coefficient)}\right)\left[{latex(label)}\right]"
                for label, coefficient in self._coefficients.items()
            ) or "0"
        return repr_lincomb(
            self._coefficients.items(),
            repr_monomial=lambda label: rf"\left[{latex(label)}\right]",
            is_latex=True,
            strip_one=True,
        )


class _SparseFreeModuleParent:
    """Construction methods for the owned free module on arbitrary labels."""

    def __init__(
        self,
        base_ring,
        module_generating_set,
        **rest,
    ) -> None:
        ring = _owned_ring(base_ring)
        # The free module ``F_R(S)`` is constructed on the set ``S``: that set
        # is this level's datum, and the framing it declares is the identity
        # of ``F_R(S)`` read on its basis.
        self._module_generating_set = module_generating_set
        super().__init__(
            base_ring=ring,
            module_generating_set=module_generating_set,
            module_generator_function=self._basis_element,
            framing_source=self,
            **rest,
        )

    def _basis_element(self, label):
        labels = self._module_generating_set
        assert label in labels, f"{label!r} is not a basis label of {self}; the basis is indexed by {labels}"
        return self.element_class(self, {labels(label): self.base_ring().one()})

    def __call__(self, value):
        r"""Construct a free-module element through the owned coordinate syntax."""
        return self._element_constructor_(value)

    def _element_constructor_(self, value):
        # The basis is this level's construction datum.  Reading it through
        # module_generating_set() realizes the selected resolution, whose
        # augmentation constructs elements of this module.
        labels = self._module_generating_set
        ring = self.base_ring()
        source = element_parent(value)
        match value:
            case _ if source is self:
                return value
            case _ if isinstance(source, Parent) and self._built_on_the_same_data(source):
                return self._element_on_the_same_data(source, value)
            case dict():
                coefficients = {}
                for label, coefficient in value.items():
                    if label not in labels:
                        raise ValueError(
                            f"{label!r} is not a basis label of {self}; the basis is indexed by {labels}"
                        )
                    selected_label = labels(label)
                    coefficient = ring(coefficient)
                    coefficients[selected_label] = (
                        coefficients.get(selected_label, ring.zero()) + coefficient
                    )
                return self.element_class(self, coefficients)
            case tuple() | list():
                if labels not in EnumeratedSets():
                    raise TypeError(
                        f"cannot read {value!r} as a coordinate vector in {self}: its basis "
                        f"{labels} has no order, so give the coordinates as a dict label -> coefficient"
                    )
                cardinality = labels.cardinality()
                if not cardinality.is_finite():
                    raise TypeError(
                        f"cannot read {value!r} as a coordinate vector in {self}: its basis "
                        f"{labels} is infinite, so give the finitely many nonzero coordinates "
                        "as a dict label -> coefficient"
                    )
                if len(value) != int(cardinality.finite_value()):
                    raise ValueError(
                        f"cannot read {value!r} as a coordinate vector in {self}: it has "
                        f"{len(value)} entries, but {self} has rank {cardinality}"
                    )
                coefficients = {
                    labels[position]: coefficient
                    for position, coefficient in enumerate(value)
                }
                return self.element_class(self, coefficients)
            # Sequence inputs are coordinate syntax, never candidate scalars.
            # Only after the structured ingress cases may a free module ask
            # whether the input is a scalar of its base ring.
            case _ if value in ring and (ring(value) == ring.zero()) is True:
                return self.zero()
            case _ if value in ring and labels.cardinality() == cardinal(1):
                return self.element_class(self, {labels[0]: ring(value)})
            case _ if value in labels:
                # A label is its basis element: the unit ``S -> F(S)`` of the
                # free-forgetful adjunction, as in Sage's
                # ``CombinatorialFreeModule._element_constructor_``.
                return self._basis_element(value)
            case _:
                raise TypeError(f"{value!r} does not describe an element of {self}")

    def zero(self):
        return self.element_class(self, {})

    def an_element(self):
        labels = self.module_generating_set()
        if labels.cardinality() == cardinal(0):
            return self.zero()
        return self._basis_element(labels.an_element())

    def _raw_scalar_multiple(self, scalar, element):
        ring = self.base_ring()
        scalar = ring(scalar)
        element = self._element_constructor_(element)
        return self.element_class(
            self,
            {
                label: scalar * coefficient
                for label, coefficient in element._coefficients.items()
            },
        )

    def _framing_lift(self, element):
        r"""A free module on ``I`` is its own framing source, and the framing is the identity."""
        return self._element_constructor_(element)


class FramedFreeModules(OwnedCategoryOverBaseRing):
    r"""Free modules equipped with the canonical basis map."""

    def an_object(self):
        r"""The framed free module of rank one over the base ring.

        A framed module requires no bilinear form; in particular this
        constructor must not attempt to equip an arbitrary noncommutative
        coefficient ring with the hyperbolic lattice form ``U``.
        """
        return self.base_ring().free_module(1)

    def _repr_object_names(self):
        return f"framed free modules over {self.base_ring()}"

    def super_categories(self):
        r"""The chosen free basis refines free modules over the same ring.

            sage: from dzack_research.preamble.all import ZZ, Modules
            sage: F = FramedFreeModules(ZZ).an_object()
            sage: F in Modules(ZZ).Free() and F in FramedFreeModules(ZZ)
            True
            sage: F.module_rank() == 1 and F.framing_morphism().codomain() is F
            True
        """
        from dzack_research.preamble.categories.rings.ring_foundation import OwnedCategoryOverBaseRing

        # The Free axiom belongs to Modules; use that base rather than the
        # group-algebra specialization when constructing the axiom category.
        ordinary = OwnedCategoryOverBaseRing.__classcall__(Modules, self.base_ring())
        return [ordinary.Free()]

    class ElementMethods:
        if TYPE_CHECKING:
            def __call__(self, label) -> RingElement: ...

        def order_ideal(self):
            r"""Compute the module order ideal using the chosen free basis.

            Coordinate functionals show that every coordinate belongs to
            the evaluation image. Conversely every linear functional on a
            finite-support vector is a linear combination of its nonzero
            coordinates. Thus these generate the intrinsic order ideal,
            including for an infinite basis.

            EXAMPLES::

                sage: M = ZZ**2
                sage: v = M.linear_combination({0: ZZ(-6), 1: ZZ(9)})
                sage: v.order_ideal() == ZZ.ideal(3) and v.content() == ZZ(3)
                True
                sage: M.zero().order_ideal() == ZZ.ideal(0)
                True
            """
            ring = self.parent().base_ring()
            if ring not in OwnedRings().Commutative():
                raise TypeError("the module order ideal requires a commutative scalar ring")
            coordinates = self.to_vector()
            return ring.ideal(*coordinates.parent()._selected_module_coefficients(coordinates).values())

        def primitive_part(self) -> "FramedFreeModules.ElementMethods":
            r"""Return ``v/content(v)`` for a nonzero vector over ``ZZ``.

            EXAMPLES::

                sage: M = ZZ**2
                sage: v = M.linear_combination({0: ZZ(-6), 1: ZZ(9)})
                sage: v.primitive_part() == M.linear_combination({0: ZZ(-2), 1: ZZ(3)})
                True
            """
            content = self.content()
            if not content:
                raise ValueError("the zero vector has no primitive part")
            coordinates = self.to_vector()
            return self.parent().linear_combination({
                label: coordinates(label) // content
                for label in coordinates.support().domain()
            })

        def to_vector(self) -> "FramedFreeModules.ElementMethods":
            r"""The coordinates of this element in the chosen basis ``I``.

            The finitely supported function \(a_v\colon I\to R\) with
            \(v=\sum_i a_v(i)\,e_i\): an element of \(R^{(I)}\), the free
            module on \(I\), which is the framing source of this module.  Its
            value at ``i`` is ``v.to_vector()(i)`` and its support is
            ``v.to_vector().support()``.

            Read through the module's chosen preimage, not through
            ``framing_morphism().lift``: the augmentation of a module that is
            its own framing source is its identity, whose general preimage
            solver reads coordinates.
            """
            return self.parent()._framing_lift(self)

    class ParentMethods:
        def _repr_(self):
            r"""Name the basis by its elements, printed as the basis vectors ``[i]`` print."""
            labels = self.module_generating_set()
            size = cardinal(labels.cardinality())
            match (labels in EnumeratedSets(), size.is_finite()):
                case (True, True) if int(size.finite_value()) <= 12:
                    basis = ", ".join(repr(self.module_generator(label)) for label in labels)
                    return f"Free module on {{{basis}}} over {self.base_ring()}"
                case _:
                    return f"Free module on {labels} over {self.base_ring()}"

        def _represented_cokernel_of_morphism(self, morphism):
            if morphism.codomain() is not self:
                return NotImplemented
            return ModulesWithChosenFinitePresentation(self.base_ring())(morphism)

        def _represented_annihilator_ideal(self):
            r"""Return the kernel ideal of the scalar action on a free module."""
            ring = self.base_ring()
            generator = ring.one() if self.module_rank() == 0 else ring.zero()
            return ring.ideal(generator)

        def _Hom_(self, codomain, category=None):

            if category is not None and not category.is_subcategory(Modules(self.base_ring())):
                raise TypeError(
                    f"cannot form morphisms {self} -> {codomain} in {category}: "
                    f"it is not a subcategory of {Modules(self.base_ring())}"
                )
            if not codomain.has_selected_module_resolution():
                raise TypeError(
                    f"cannot form {self}.Mor({codomain}): the target must be a "
                    f"{self.base_ring()}-module with chosen generators, but it is in {codomain.category()}"
                )

            return self.module_category().Mor(self, codomain)

        def subobject_on(self, module_generating_set):
            r"""Return the submodule spanned by the specified elements."""

            return _module_subobject_on(self, module_generating_set)

        def whole_subobject(self):
            r"""Return this free module as the full subobject of itself.

            The selected framing is already a basis, so this construction does
            not ask a private matrix computation to row-reduce it.  That distinction is essential
            over exact local PIDs, where echelon normalization can divide by a
            nonunit even though the whole-span basis is already known.
            """

            return _module_subobject_spanning(self, self.module_generators())

        def diagonal_gram(self, exceptions, default=1):
            r"""Return the diagonal type-``(0,2)`` tensor in this selected basis."""
            from dzack_research.preamble.categories._lattice import _diagonal_gram

            return _diagonal_gram(self, exceptions, default)

        def _free_biproduct_over(
            self,
            labels,
            factors,
            *,
            extra_categories=(),
            extra_construction_data=None,
        ):
            r"""Return the free biproduct realization when every factor is framed free."""
            free = FramedFreeModules(self.base_ring())
            if not all(factor in free for factor in factors):
                return NotImplemented
            return self.base_ring()._fresh_free_module_on(
                labels,
                _biproduct_factors=factors,
                _extra_categories=extra_categories,
                _extra_construction_data=extra_construction_data,
            )

        def module_rank(self):
            r"""Return the cardinality of the module generating set.

            A rank can be infinite -- \(R^{(\mathbb N)}\) has rank
            \(\aleph_0\) -- so the answer is a cardinal, not a natural
            number.  The cardinality is the generating set's own, which is
            where the doctrine puts it.
            """

            return self.module_generating_set().cardinality()

        def _torsion_freeness_decision(self) -> bool:
            r"""A free module over a domain is torsion-free.

            A basis element is killed only by a scalar killing its coefficient,
            and a domain has none nonzero.  Off a domain there is no fraction
            field and hence no torsion submodule to be zero, so the question is
            not asked rather than answered ``True``.
            """
            assert self.base_ring() in IntegralDomains(), (
                f"torsion-freeness of a module over {self.base_ring()} needs an integral-domain base"
            )
            return True

        @RealizationHook
        def _cardinality_decision(self):
            r"""Supply ``|R^(S)|`` from the represented scalar and label cardinals.

            The finite-support formula is ``|R|^|S|`` for finite ``S`` and
            ``max(|R|, |S|)`` for infinite ``S`` over a nonzero ring. A
            missing parameter cardinal supplies no exact value here.
            """

            if self.base_ring() is self:
                # A ring as the rank-one free module over itself: its
                # underlying set is the ring's, which the ring level answers.
                return super()._cardinality_decision()
            scalars = self.base_ring()._cardinality_decision()
            labels = self.module_generating_set()._cardinality_decision()
            if labels is not None and (cardinal(labels) == Cardinalities().zero()) is True:
                return Cardinalities().one()
            if scalars is not None and (cardinal(scalars) == Cardinalities().one()) is True:
                return Cardinalities().one()
            if scalars is None or labels is None:
                return None
            scalars = cardinal(scalars)
            labels = cardinal(labels)
            if not scalars.expression().is_normal_form() or not labels.expression().is_normal_form():
                return None
            if labels.is_finite():
                return scalars**labels
            return Cardinalities().supremum(scalars, labels)

        def _finiteness_decision(self):
            r"""Return whether the underlying free module is finite."""
            size = self._cardinality_decision()
            if size is None or not cardinal(size).expression().is_normal_form():
                return AtomicProposition("is_finite", self)
            return cardinal(size).is_finite()

        @cached_method
        def base_change(self, ring_map, *, _extra_construction_data=None):
            r"""Return ``S tensor_R M`` along the specified ring map ``R -> S``."""
            return _framed_free_base_change(self, ring_map, _extra_construction_data)

        @cached_method
        def vector_space(self):
            r"""Return ``M tensor_R Frac(R)`` along the canonical fraction-field map.

            This is the archived ``vector_space`` construction: rationalization
            is scalar extension, not a separately presented copy.  Structured
            refinements such as formed modules inherit this method and dispatch
            through their own ``base_change``, so the carried structure is
            transported by the same canonical ring map.
            """
            return self.base_change(self.base_ring().fraction_field_map())

    class FinitelyGenerated(CategoryWithAxiom):
        r"""Free modules framed by a finite basis."""

        def an_object(self):
            r"""The free module of rank one."""
            return self.base_ring().free_module(1)

        def extra_super_categories(self):
            return [ModulesWithChosenFinitePresentation(self.base_ring())]

        def kernel_arrow_functor(self):
            r"""Return the kernel functor on the finite-free arrow category."""
            from dzack_research.preamble.categories.functors.linear_constructions import (
                _kernel_arrow_functor,
            )

            return _kernel_arrow_functor(self.base_ring())

        class ParentMethods:
            def determinant_line(self):
                r"""The top exterior power of this finite free module."""
                from dzack_research.preamble.categories.modules.hodge import _determinant_line
                return _determinant_line(self)

            def exterior_forms(self, degree):
                r"""Exterior forms in the selected finite free framing."""
                from dzack_research.preamble.categories.modules.hodge import _exterior_forms
                return _exterior_forms(self, degree)

            def volume_trivialization(self, forward, inverse):
                from dzack_research.preamble.categories.modules.hodge import _volume_trivialization
                return _volume_trivialization(self, forward, inverse)

            def framing_volume_trivialization(self, unit=None):
                from dzack_research.preamble.categories.modules.hodge import _framing_volume_trivialization
                return _framing_volume_trivialization(self, unit=unit)

            def poincare_duality(self, volume, degree):
                from dzack_research.preamble.categories.modules.hodge import _poincare_duality
                return _poincare_duality(self, volume, degree)

            def _represented_vector_space_dimension(self):
                return self.module_rank()

            def _represented_vector_space_basis_generator_labels(self):
                return self.module_generating_set()

            def is_zero(self) -> bool:
                r"""Return whether this finite free module is the zero module.

                A finite free module is zero exactly when every vector in its
                chosen basis is the additive identity; this also handles the zero
                coefficient ring without replacing the basis by a rank heuristic.
                """
                return conjunction(generator == self.zero() for generator in self.module_generators())

            @cached_method
            def _selected_relation_morphism(self):
                r"""Return the relation morphism ``0: F(∅) -> M``: a free module has no relations."""
                relations = _fresh_free_module_on(self.base_ring(), Sets.Δ[-1])
                return relations.module_category().Mor(relations, self)(lambda label: self.zero())

            def presentation(self):
                r"""Return the chosen presentation ``0: F_1 = R^(∅) -> F_0 = M`` of this framed free module.

                A finite basis ``(e_s)_{s in S}`` is a generating epimorphism
                ``R^(S) -> M`` that is an isomorphism, so the framing is a
                length-zero free resolution, and its truncation-one extension
                has no relations: ``F_1 = 0`` (``CAT-29``).  This is the chosen
                finite presentation that places a finite framed free module in
                ``ModulesWithChosenFinitePresentation(R)``; its cokernel is ``M``
                with the identity as presentation projection.  A selected
                resolution that already reaches degree one is read as it is.
                """
                selected = self.selected_module_resolution()
                match selected.truncation():
                    case 0:
                        return self._selected_relation_morphism()
                    case _:
                        return selected.differential(1)

            @cached_method
            def base_change(self, ring_map, *, _extra_construction_data=None):
                r"""Return ``S tensor_R R^(S) = S^(S)`` on the same basis labels.

                The framing is preserved by scalar extension, so the result is
                the framed free module on the same labels.  This takes
                precedence over the transport of the chosen presentation from
                ``ModulesWithChosenFinitePresentation``, whose ``F_0`` is this
                module itself.
                """
                return _framed_free_base_change(self, ring_map, _extra_construction_data)

            def presentation_projection(self):
                r"""Return the presentation projection ``F_0 -> M``: the framing of ``M``."""
                return self.framing_morphism()

            def fitting_ideal(self, index):
                r"""Return ``Fitt_i(R^n)``: zero below the rank, the unit ideal from it on.

                A free module is presented by no relations, so its relation matrix
                has no rows and the ideal of its ``(n - i)``-minors is zero while a
                minor of positive size is asked for and the unit ideal once none
                is.  The general minor computation has no matrix to read here, so
                the same formula is stated directly.
                """
                ring = self.base_ring()
                rank = int(self.number_of_module_generators())
                return ring.ideal(ring.one() if int(index) >= rank else ring.zero())

            def _represented_kernel_of_morphism(self, morphism):
                if morphism.domain() is not self:
                    return NotImplemented
                codomain_is_zero = morphism.codomain().is_zero()
                if codomain_is_zero is True:
                    return self.whole_subobject()
                if self.base_ring() not in PrincipalIdealDomains():
                    from dzack_research.preamble.categories.modules.framed.finitely_generated.finitely_presented_modules import (
                        _selected_presentation_kernel,
                    )

                    # A kernel over a polynomial quotient need not be free.
                    # Retain its finite presentation and inclusion through
                    # the common presentation owner, not a PID span basis.
                    return _selected_presentation_kernel(morphism)
                coordinate_matrix = self.module_category().Mor(
                    self, morphism.codomain()
                )(morphism)
                from dzack_research.preamble.categories.modules.pure.modules import MatrixSpaces

                if coordinate_matrix.parent() not in MatrixSpaces(self.base_ring()):
                    return NotImplemented
                coordinate_generators = coordinate_matrix._kernel_spanning_family()

                source_labels = tuple(self.module_generating_set())
                coordinate_domain = coordinate_matrix.domain()
                coordinate_labels = tuple(coordinate_domain.module_generating_set())
                if len(source_labels) != len(coordinate_labels):
                    raise ArithmeticError(
                        f"kernel of {morphism}: its matrix has {len(coordinate_labels)} columns, "
                        f"but the domain {self} has rank {len(source_labels)}"
                    )

                def transport(coordinate_vector):
                    coordinates = coordinate_vector.to_vector()
                    return self.linear_combination(
                        {
                            source_label: coefficient
                            for source_label, coordinate_label in zip(
                                source_labels, coordinate_labels, strict=True
                            )
                            if (coefficient := coordinates(coordinate_label))
                        }
                    )

                generators = finite_indexed_family(
                    coordinate_generators.index_set(),
                    lambda index: transport(coordinate_generators[index]),
                    name=f"Kernel spanning family in {self}",
                )
                return self.subobject_on(generators)

            def _same_presentation_module(
                self,
                labels,
                *,
                _extra_categories=(),
                _extra_construction_data=None,
            ):
                return _fresh_free_module_on(self.base_ring(), 
                    labels,
                    _extra_categories=tuple(_extra_categories),
                    _extra_construction_data=_extra_construction_data,
                )

            def free_resolution(self, steps=None):
                r"""A free module is its own resolution, in degree zero alone.

                The number of steps a caller is willing to compute does not enter:
                the identity already resolves a free module, so the same resolution
                answers however far it is asked to go.
                """
                _ = steps
                return self._identity_resolution()

            @cached_method
            def _identity_resolution(self):
                zero = _fresh_free_module_on(self.base_ring(), finite_ordered_set(()))
                degrees = Sets.Δ[0]
                return FreeResolution(
                    self,
                    degrees,
                    indexed_family(degrees, lambda degree: self, name="Free resolution terms"),
                    indexed_family(
                        Sets.Δ[-1],
                        lambda degree: None,
                        name="Free resolution differentials",
                    ),
                    self.module_category().Mor(self, self).identity(),
                    zero,
                )

            def dual_basis(self):
                r"""Return the dual basis ``(e_s^*)_{s in S}`` of ``Hom_R(M, R)``.

                Let ``M`` be free over a commutative ring ``R`` with finite basis
                ``(e_s)_{s in S}``.  The dual module is the inherited
                ``M.dual_module() = Hom_R(M, R)``.  The coordinate functionals
                ``e_s^*`` with ``e_s^*(e_t) = delta_{s,t}`` form a basis of it,
                indexed by the same finite set ``S``; this is the framing of the
                dual module induced by the framing of ``M``.  Finiteness of ``S``
                is required: for infinite ``S`` the dual ``Hom_R(R^{(S)}, R) = R^S``
                is not spanned by the ``e_s^*``.
                """
                ring = self.base_ring()
                dual = self.dual_module()
                labels = self.module_generating_set()

                def coordinate_functional(label):
                    return dual(lambda other: ring.one() if other == label else ring.zero())

                return finite_indexed_family(
                    labels,
                    coordinate_functional,
                    name=f"Dual basis of {dual}",
                )


def _framed_free_base_change(module, ring_map, extra_construction_data):
    r"""Return ``S tensor_R R^(S)``, the framed free ``S``-module on the labels ``S``."""
    target_ring = _base_change_codomain(module, ring_map)
    if ring_map.is_identity() is True and not extra_construction_data:
        return module
    return target_ring._fresh_free_module_on(
        module.module_generating_set(),
        _extra_construction_data=extra_construction_data,
    )


def _new_sparse_free_module(
    ring,
    labels,
    *,
    subobject_ambient=None,
    subobject_generator_images=None,
    subobject_lift=None,
    subobject_inclusion_factory=None,
    biproduct_factors=None,
    extra_categories=(),
    extra_construction_data=None,
):
    r"""Build a sparse free module through the category constructor chain."""
    categories = _finitely_generated_free_placement(ring, labels)
    # A submodule is a module with an inclusion as additional data: the
    # categories of its objects are those of the free module, without the
    # subobject placements appended below (ARC-07, AGENTS subobjects).
    module_categories = list(categories)
    data = {
        "base_ring": ring,
        "module_generating_set": labels,
    }
    if subobject_ambient is not None or subobject_inclusion_factory is not None:
        categories.append(ModuleSubobjects(ring))
        if subobject_ambient is not None:
            categories.append(Modules(ring).Subobjects(subobject_ambient))
        data.update(
            subobject_ambient=subobject_ambient,
            subobject_generator_images=subobject_generator_images,
            subobject_lift=subobject_lift,
            subobject_inclusion_factory=subobject_inclusion_factory,
        )
    if biproduct_factors is not None:
        categories.append(BiproductModules(ring))
        data["biproduct_factors"] = biproduct_factors
    categories.extend(extra_categories)
    module_categories.extend(extra_categories)
    if biproduct_factors is not None:
        module_categories.append(BiproductModules(ring))
    if extra_construction_data is not None:
        data.update(extra_construction_data)
    return _object_of(
        Cat().meet(tuple(categories)),
        _ambient=Cat().meet(tuple(module_categories)),
        _engine=(FramedFreeModules(ring), _SparseFreeModuleParent, _SparseFreeModuleElement),
        **data,
    )



def _element_from_row(module, row):
    return module.linear_combination(
        {
            label: coefficient
            for label, coefficient in zip(
                module.module_generating_set(), row, strict=True
            )
        }
    )


def _known_finite_generator_family(module_generating_set):
    r"""Normalize one explicitly finite spanning family without guessing finiteness."""

    match module_generating_set:
        case tuple() | list() | range():
            return finite_ordered_set(module_generating_set)
        case IndexedFamily():
            # A family spans what its values span; kernels hand theirs over
            # this way, indexed by the finite set of solution vectors.
            assert module_generating_set.cardinality().is_finite(), (
                "subobject generators indexed by a family need a finite index set, but "
                f"{module_generating_set.index_set()} is not finite"
            )
            return module_generating_set
        case _:
            assert (
                module_generating_set in Sets()
                and module_generating_set.cardinality().is_finite()
            ), "subobject generators are a finite owned set or an explicit finite family"
            return module_generating_set


def _finite_support_labels(module, elements):
    r"""Return the finite union of supports without ranking the ambient framing.

    This is a private finite-coordinate boundary.  The ambient framing may be
    infinite and need not admit a ranking map; only labels that actually occur
    in the supplied finite family are retained.  A finite framing is its own
    finite window, so its labels are taken whole and no two labels are compared.
    """
    framing = module.module_generating_set()
    if cardinal(framing.cardinality()).is_finite():
        return finite_ordered_set(framing)
    support = []
    for candidate in elements:
        element = candidate if candidate.parent() is module else module(candidate)
        coordinates = element.to_vector()
        for label in coordinates.parent()._selected_module_coefficients(coordinates):
            if not any(label == known for known in support):
                support.append(label)
    return finite_ordered_set(support)


def _span_basis_elements(module, module_generating_set):
    r"""Return the canonical span basis using only the finite union of supports."""

    ring = module.base_ring()
    assert ring in PrincipalIdealDomains(), (
        f"cannot compute a basis of a submodule of {module}: the base ring {ring} "
        "must be a principal ideal domain, so that submodules of free modules are free"
    )
    assert module in FramedFreeModules(ring), (
        f"cannot compute a basis of a submodule of {module}: it must be a free "
        f"{ring}-module with a chosen basis, but it is in {module.category()}"
    )

    generators = _known_finite_generator_family(module_generating_set)
    if int(generators.cardinality()) == 1:
        generator = next(iter(generators))
        generator = generator if generator.parent() is module else module(generator)
        if generator != module.zero():
            # Over a PID, hence an integral domain, one nonzero vector is
            # automatically a basis of the cyclic submodule it generates.
            # Retain that mathematical basis instead of echelon-normalizing it;
            # p-adic backends otherwise divide through nonunit pivots.
            return finite_ordered_set((generator,))
    support_labels = _finite_support_labels(module, generators)
    support_points = tuple(support_labels)

    # Private finite backend serialization.  Only the finite support window is
    # materialized; the ambient framing itself is never enumerated.
    engine = _engine_ring(ring)
    support_count = len(support_points)
    free = _SageFreeModule(engine, support_count)
    engine_rows = []
    for candidate in generators:
        element = candidate if candidate.parent() is module else module(candidate)
        coordinates = element.to_vector()
        engine_rows.append(
            [
                _engine_element(
                    ring,
                    coordinates(support_points[position]),
                )
                for position in range(support_count)
            ]
        )
    basis = (
        free.zero_submodule().basis_matrix()
        if not engine_rows
        else free.submodule(engine_rows).basis_matrix()
    )
    positions = Sets.Δ[basis.nrows() - 1]

    def basis_element(position):
        row = basis.row(int(position))
        return module.linear_combination(
            {
                support_points[column]: _owned_engine_element(ring, row[column])
                for column in range(support_count)
                if row[column]
            }
        )

    return FiniteOrderedSets().from_indexed(
        positions,
        basis_element,
        name=f"Canonical span basis in {module}",
    )


def _module_subobject_on(module, module_generating_set):
    r"""Return the submodule spanned by one explicitly finite family.

    The finite PID backend is restricted to the union of supports of the input
    elements.  In particular, a finitely generated submodule of an infinitely
    generated free module never causes enumeration of the ambient framing.
    """
    basis = _span_basis_elements(module, module_generating_set)
    return _module_subobject_spanning(module, basis)


def _restricted_fraction_field_subobject_on(module, module_generators):
    r"""Compute a PID span in a restricted fraction-field module with Sage ``span``.

    This replaces the denominator clearing and row-module computation in
    ``sage-indefinite-port.groups.integral_structures._span_embedding``.
    Sage ``FreeModule_generic.span`` accepts fractional entries over a PID;
    the owned result retains the inclusion and its integral lift.
    """
    ring = module.base_ring()
    fractions = module.extension_ring()
    extension = module.module_over_extension()
    assert ring in PrincipalIdealDomains() and fractions is ring.fraction_field(), (
        f"finite restricted spans require a PID and its fraction field, not {ring} and {fractions}"
    )
    assert module.ring_map() == ring.fraction_field_map(), (
        f"finite restricted spans use the canonical fraction-field map, not {module.ring_map()}"
    )
    assert extension in FramedFreeModules(fractions), (
        f"finite restricted spans require a framed free module over {fractions}, not {extension}"
    )
    generators = _known_finite_generator_family(module_generators)
    underlying = tuple(module(element).underlying_element() for element in generators)
    support = _finite_support_labels(extension, underlying)
    support_points = tuple(support)
    engine_fractions = _engine_ring(fractions)
    engine_ambient = _SageFreeModule(engine_fractions, len(support_points))

    def engine_coordinates(element):
        coordinates = element.to_vector()
        return tuple(
            _engine_element(fractions, coordinates(label)) for label in support_points
        )

    engine_span = engine_ambient.span(
        tuple(engine_coordinates(element) for element in underlying),
        base_ring=_engine_ring(ring),
    )
    labels = Sets.Δ[engine_span.rank() - 1]

    def embedded(label):
        coordinates = engine_span.basis()[int(label)]
        return module(extension.linear_combination({
            point: _owned_engine_element(fractions, coordinate)
            for point, coordinate in zip(support_points, coordinates, strict=True)
            if coordinate
        }))

    def lift(source, element):
        underlying_element = module(element).underlying_element()
        coordinates = underlying_element.to_vector()
        if any(label not in support for label in coordinates.support().domain()):
            return None
        candidate = engine_ambient(engine_coordinates(underlying_element))
        if candidate not in engine_span:
            return None
        coefficients = engine_span.coordinate_vector(candidate)
        return source.linear_combination({
            label: _owned_engine_element(ring, _engine_ring(ring)(coefficient))
            for label, coefficient in zip(labels, coefficients, strict=True)
            if coefficient
        })

    return _new_sparse_free_module(
        ring,
        labels,
        subobject_ambient=module,
        subobject_generator_images=embedded,
        subobject_lift=lift,
    )


@cached_function(key=lambda module, basis: (id(module), tuple(basis)))
def _module_subobject_spanning(module, basis):
    r"""Return the subobject on its canonical owned finite span basis.

    Ambient identity is part of the subobject type.  Do not use Sage's generic
    cached-function key here: equal free-module parents need not be identical
    mathematical endpoints.
    """

    return _module_subobject_spanning_with_structure(module, basis)


def _module_subobject_spanning_with_structure(
    module,
    basis,
    *,
    extra_categories=(),
    extra_construction_data=None,
):
    r"""Construct a span, optionally in additional structural categories."""
    ring = module.base_ring()
    labels, embedded, lift_from_finite_support = _module_subobject_constructor_data(
        module,
        basis,
    )
    return _new_sparse_free_module(
        ring,
        labels,
        subobject_ambient=module,
        subobject_generator_images=embedded,
        subobject_lift=lift_from_finite_support,
        extra_categories=extra_categories,
        extra_construction_data=extra_construction_data,
    )


def _module_subobject_constructor_data(module, basis):
    r"""Return labels, generator images, and lift data for a finite span."""

    ring = module.base_ring()
    assert module in FramedFreeModules(ring), (
        f"cannot form the submodule of {module} spanned by {basis}: {module} must be a free "
        f"{ring}-module with a chosen basis, but it is in {module.category()}"
    )
    basis_elements = tuple(basis)
    labels = Sets.Δ[len(basis_elements) - 1]

    def embedded(label):
        return basis_elements[int(label)]

    support_labels = _finite_support_labels(module, basis)
    support_points = tuple(support_labels)
    source_rank = len(basis_elements)
    support_rank_count = len(support_points)
    if source_rank:
        # The map F(labels) -> F(support) sending the i-th label to the
        # coordinates of the i-th spanning element on the support.
        coordinate_space = ring.matrix_space(support_rank_count, source_rank)
        support_module = coordinate_space.codomain()
        support_module_labels = tuple(support_module.module_generating_set())
        coordinate_matrix = coordinate_space(
            tuple(
                support_module.linear_combination(
                    {
                        support_module_label: coordinates(support_point)
                        for support_module_label, support_point in zip(
                            support_module_labels, support_points, strict=True
                        )
                        if coordinates(support_point)
                    }
                )
                for coordinates in (
                    module(element).to_vector() for element in basis_elements
                )
            )
        )
    else:
        coordinate_matrix = None
    coordinate_solver = None

    def lift_from_finite_support(source, element):
        r"""The preimage of ``element`` in the span, or ``None`` when ``element`` is outside it."""
        nonlocal coordinate_solver
        element = element if element.parent() is module else module(element)
        coordinates = element.to_vector()
        if any(label not in support_labels for label in coordinates.support().domain()):
            return None
        if source_rank == 0:
            return None if coordinates else source.zero()
        if coordinate_solver is None:
            coordinate_solver = _integral_preimage_positional_solver(
                coordinate_matrix,
                ring,
            )
        solution = coordinate_solver(
            (
                coordinates(support_points[j])
                for j in range(support_rank_count)
            ),
        )
        if solution is None:
            return None
        return source.linear_combination(
            {
                labels[i]: coefficient
                for i, coefficient in enumerate(solution)
                if coefficient
            }
        )

    return labels, embedded, lift_from_finite_support




def _module_generating_set(labels):
    r"""Read the labels a free module is constructed on.

    A rank ``n``, an integer or a finite cardinal, names the ordinal ``{0, ..., n-1}``; an explicit finite
    family of labels names the ordered set of them; an owned set is its own
    label set.
    """
    integers = _owned_integers()
    match labels:
        case int() | Integer():
            rank = int(labels)
        case _ if element_parent(labels) is integers:
            rank = int(labels)
        case _ if labels in Cardinalities():
            assert labels.is_finite(), (
                f"cannot form a free module of rank {labels}: a free module of infinite rank "
                "is constructed on a set of basis labels of that cardinality, so give the set"
            )
            rank = labels.finite_value()
        case tuple() | list() | range():
            return finite_ordered_set(labels)
        case _:
            assert labels in Sets(), (
                f"cannot form a free module on {labels!r}: give a rank or a set of basis labels"
            )
            return labels
    assert rank >= 0, f"cannot form a free module of rank {rank}: a rank is nonnegative"
    return Sets.Δ[rank - 1]


@cached_function
def _owned_free_module_on(ring, module_generating_set):
    r"""Return the owned free module ``F_R(S)`` on the stated labels."""
    return _new_sparse_free_module(ring, module_generating_set)


def _matrix_space(base_ring, nrows, ncols=None):
    r"""Return ``Hom_R(F_R([n]), F_R([m]))`` for ``m=nrows``, ``n=ncols``."""
    ring = _owned_ring(base_ring)
    integers = _owned_integers()

    def dimension(value):
        result = int(integers(value))
        assert result >= 0, f"cannot form matrices with {result} rows or columns: a dimension is nonnegative"
        return result

    nrows = dimension(nrows)
    ncols = nrows if ncols is None else dimension(ncols)
    source = ring.free_module(ncols)
    target = ring.free_module(nrows)
    return _require_matrix_mor(source.module_category().Mor(source, target))


def _fresh_free_module_on(
    base_ring,
    module_generating_set,
    *,
    _subobject_ambient=None,
    _subobject_generator_images=None,
    _subobject_lift=None,
    _subobject_inclusion_factory=None,
    _biproduct_factors=None,
    _extra_categories=(),
    _extra_construction_data=None,
):
    r"""Return a new free-module parent on the specified basis labels.

    Two different actions or forms on isomorphic free modules must remain
    different structured objects, so the owned parent is not interned; the
    engine underneath may be shared, since it holds no owned data.
    """

    ring = base_ring
    if ring not in OwnedRings():
        raise TypeError(f"cannot form a free module over {ring!r}: it is not a ring of this session")
    labels = _module_generating_set(module_generating_set)
    return _new_sparse_free_module(
        ring,
        labels,
        subobject_ambient=_subobject_ambient,
        subobject_generator_images=_subobject_generator_images,
        subobject_lift=_subobject_lift,
        subobject_inclusion_factory=_subobject_inclusion_factory,
        biproduct_factors=_biproduct_factors,
        extra_categories=_extra_categories,
        extra_construction_data=_extra_construction_data,
    )
