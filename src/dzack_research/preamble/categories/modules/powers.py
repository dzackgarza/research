r"""Tensor, symmetric, exterior, and divided powers of presented modules.

The constructions use one selected module presentation.  Tensor powers are
iterated instances of the canonical categorical tensor product.  The other
three are the degree pieces of the corresponding graded algebra: for
``M = F/K`` they are the free degree piece modulo the degree part of the ideal
(or divided-power ideal) generated by ``K``.
"""

