def _gram_contraction(gram, module, left, right):
    r"""``G(x, y)``: the Gram tensor ``G`` on the framing of ``module`` contracted with the coordinates of ``x`` and ``y``."""
    lift = module.framing_morphism().lift
    ring = gram.base_ring()
    return gram.contract(
        tensor.vector(ring, tuple(lift(left))),
        tensor.vector(ring, tuple(lift(right))),
    )


def _bilinear_extension(values, module, target, left, right):
    r"""``b(x, y) = \sum_{s,t} x_s y_t\, b(s, t)``: the bilinear extension of ``values`` on pairs of framing generators.

    The values lie in a module ``target`` that is not a ring, so they form no
    tensor over the values; with values in a ring the extension is
    :func:`_gram_contraction`.
    """
    framing = module.framing_morphism()
    left_coordinates = framing.lift(left)
    right_coordinates = framing.lift(right)
    right_support = right_coordinates.support().domain()
    result = target.zero()
    for left_label in left_coordinates.support().domain():
        for right_label in right_support:
            scalar = left_coordinates(left_label) * right_coordinates(right_label)
            if scalar:
                result += target.scalar_multiple(
                    scalar,
                    _coordinate_pair(values, left_label, right_label),
                )
    return result


class QuadraticModuleMorphism:
    r"""A classifier ``Gamma^2(M) -> W``, read as the quadratic map ``M -> W``.

    Its defining datum is the classifier, given by its images on the
    generators of ``Gamma^2(M)``.  A quadratic map built from coordinates also
    keeps the chosen bilinear lift ``G`` with ``q(x) = G(x, x)``: with values
    in a ring ``W``, ``G`` is its Gram tensor in ``M^* \otimes M^*`` over
    ``W``, and ``G(x, y)`` is one contraction (`OWN-24`); with values in any
    other module, ``G`` is the family of its values ``G(s, t)`` on pairs of
    framing generators.
    """

    def __init__(self, parent, images, *, lift_gram_tensor=None, lift_coordinate_values=None) -> None:
        self._lift_gram_tensor = lift_gram_tensor
        self._lift_coordinate_values = lift_coordinate_values
        super().__init__(parent, images)

    def module(self):
        return self.domain().divided_square_source()

    def __call__(self, element):
        parent = element_parent(element)
        if parent is self.domain():
            return self._call_(element)
        module = self.module()
        if parent is not module:
            element = module(element)
        return self._call_(self.domain().quadratic(element))

    def classifying_morphism(self):
        return self

    def has_selected_bilinear_lift(self) -> bool:
        r"""Whether this quadratic classifier retains a chosen bilinear lift."""
        return self._lift_gram_tensor is not None or self._lift_coordinate_values is not None

    @validator
    def validate_symmetric_lift(self) -> None:
        r"""Check that the chosen bilinear lift is symmetric, ``G(s, t) = G(t, s)`` on framing generators."""
        match self._lift_gram_tensor, self._lift_coordinate_values:
            case None, None:
                return
            case None, values:
                labels = _finite_framing(self.module())
                for left in labels:
                    for right in labels:
                        forward = _coordinate_pair(values, left, right)
                        backward = _coordinate_pair(values, right, left)
                        if forward != backward:
                            raise ValueError(
                                f"the given values do not define a quadratic map on {self.module()}: the value "
                                f"{forward} at ({left}, {right}) differs from the value {backward} at "
                                f"({right}, {left}), but the bilinear lift must be symmetric"
                            )
            case gram, _:
                if not gram.is_symmetric():
                    raise ValueError(
                        f"the given values do not define a quadratic map on {self.module()}: the bilinear lift "
                        f"must be symmetric, but its Gram tensor {gram} is not"
                    )

    def _require_selected_bilinear_lift(self) -> None:
        if not self.has_selected_bilinear_lift():
            raise TypeError(
                f"{self} has no chosen bilinear lift: it was not constructed from a matrix of values "
                f"b(e_i, e_j) on a basis of {self.module()}"
            )

    def lift_coordinate_values(self):
        r"""The values ``G(s, t)`` of the chosen bilinear lift on pairs of framing generators."""
        self._require_selected_bilinear_lift()
        match self._lift_gram_tensor:
            case None:
                return self._lift_coordinate_values
            case gram:
                labels = _finite_framing(self.module())
                size = int(labels.cardinality())
                return _coordinate_family_from_rows(
                    labels,
                    labels,
                    self.codomain(),
                    ((gram[i, j] for j in range(size)) for i in range(size)),
                    name="Quadratic lift coordinate values",
                )

    def lift_pairing(self, left, right):
        r"""``G(x, y)`` for the chosen bilinear lift ``G``."""
        module = self.module()
        if left not in module or right not in module:
            raise TypeError(
                f"cannot evaluate the bilinear lift of {self} on ({left}, {right}): both arguments must "
                f"be elements of {module}"
            )
        self._require_selected_bilinear_lift()
        match self._lift_gram_tensor:
            case None:
                return _bilinear_extension(self._lift_coordinate_values, module, self.codomain(), left, right)
            case gram:
                return _gram_contraction(gram, module, left, right)

    def gram_tensor(self):
        r"""The Gram tensor of the chosen bilinear lift, ``G[i, j] = G(e_i, e_j)``."""
        if self.codomain() not in OwnedRings():
            raise TypeError(
                f"{self} has no Gram matrix: its values lie in {self.codomain()}, which is not a ring"
            )
        self._require_selected_bilinear_lift()
        return self._lift_gram_tensor

    def polar_form(self):

        module = self.module()
        tensor_square = Modules(module.base_ring()).tensor_product((module, module))
        return tensor_square.module_category().Mor(tensor_square, self.codomain())(
            lambda left, right: self(left + right) - self(left) - self(right)
        )

    def b(self, left, right):
        return self.polar_form()(left, right)

    def polar_coordinate_values(self):
        return self.polar_form().coordinate_values()

    def _framing_source_morphism(self, morphism):
        r"""``f: V -> M`` read between framing sources: ``F(S_V) -> F(S_M)``, ``e_s |-> lift(f(e_s))``.

        When ``V`` and ``M`` are their own framing sources, this is ``f``.
        """
        domain = morphism.domain()
        source = domain.framing_morphism().domain()
        target = self.module().framing_morphism().domain()
        match source is domain and target is self.module():
            case True:
                return morphism
            case False:
                lift = self.module().framing_morphism().lift
                return source.module_category().Mor(source, target)(
                    lambda label: lift(morphism(domain.module_generator(label)))
                )

    def pullback(self, morphism):
        r"""The quadratic map ``q \circ f``; its chosen bilinear lift is the pullback ``f^* G``."""
        if morphism.codomain() is not self.module():
            raise ValueError(
                f"cannot pull {self} back along {morphism}: its codomain {morphism.codomain()} is not "
                f"the module {self.module()} of the quadratic map"
            )
        result = self * morphism.divided_square()
        parent = result.parent()
        pullback_domain = morphism.domain()
        has_finite_framing = (
            pullback_domain.has_selected_module_resolution()
            and pullback_domain.module_generating_set().cardinality().is_finite()
        )
        match self._lift_gram_tensor, self._lift_coordinate_values, has_finite_framing:
            case _, _, False:
                return parent._from_classifying_morphism(result)
            case None, None, True:
                return parent._from_classifying_morphism(result)
            case None, values, True:
                labels = _finite_framing(pullback_domain)
                pulled_values = _coordinate_family_from_function(
                    labels,
                    labels,
                    self.codomain(),
                    lambda left_label, right_label: _bilinear_extension(
                        values,
                        self.module(),
                        self.codomain(),
                        morphism(pullback_domain.module_generator(left_label)),
                        morphism(pullback_domain.module_generator(right_label)),
                    ),
                    name="Pulled-back quadratic lift coordinate values",
                )
                return parent._from_classifying_morphism(result, lift_coordinate_values=pulled_values)
            case gram, _, True:
                return parent._from_classifying_morphism(
                    result,
                    lift_gram_tensor=gram.pullback(self._framing_source_morphism(morphism)),
                )


class QuadraticModuleMor(ModuleMor):
    r"""The ordinary Hom ``Hom_R(Gamma^2(M),W)`` with quadratic-map syntax."""

    ElementMethods = QuadraticModuleMorphism

    def _from_classifying_morphism(self, morphism, *, lift_gram_tensor=None, lift_coordinate_values=None):
        if morphism.domain() is not self.domain() or morphism.codomain() is not self.codomain():
            raise ValueError(
                f"{morphism} is not an element of {self}: it goes from {morphism.domain()} to "
                f"{morphism.codomain()}, not from {self.domain()} to {self.codomain()}"
            )
        return self.element_class(
            self,
            morphism,
            lift_gram_tensor=lift_gram_tensor,
            lift_coordinate_values=lift_coordinate_values,
        )

    def from_quadratic_map(self, quadratic, *, lift_gram_tensor=None, lift_coordinate_values=None):
        square = self.domain()
        source = square.divided_square_source()

        def generator_image(selection):
            support = selection.support()
            if int(support.cardinality()) == 1:
                label = support[0]
                return quadratic(source.module_generator(label))
            left = support[0]
            right = support[1]
            return (
                quadratic(
                    source.module_generator(left)
                    + source.module_generator(right)
                )
                - quadratic(source.module_generator(left))
                - quadratic(source.module_generator(right))
            )

        return self.element_class(
            self,
            generator_image,
            lift_gram_tensor=lift_gram_tensor,
            lift_coordinate_values=lift_coordinate_values,
        )

    def _from_coordinate_datum(self, datum):
        r"""The quadratic map ``q(x) = G(x, x)`` for the chosen bilinear lift ``G`` given by its values.

        With values in a ring the values are read once into the Gram tensor
        ``G``; otherwise ``G`` is the bilinear extension of the family of
        values.  Symmetry of ``G`` is the validator ``validate_symmetric_lift``
        (`OWN-22`).
        """
        source = self.domain().divided_square_source()
        labels = _finite_framing(source)
        codomain = self.codomain()
        values = _coordinate_family(
            labels,
            labels,
            codomain,
            datum,
            name="Quadratic lift coordinate values",
        )
        match codomain in OwnedRings():
            case True:
                size = int(labels.cardinality())
                gram = tensor(
                    codomain,
                    (),
                    (size, size),
                    tuple(
                        tuple(_coordinate_pair(values, left, right) for right in labels)
                        for left in labels
                    ),
                )
                morphism = self.from_quadratic_map(
                    lambda element: _gram_contraction(gram, source, element, element),
                    lift_gram_tensor=gram,
                )
            case False:
                morphism = self.from_quadratic_map(
                    lambda element: _bilinear_extension(values, source, codomain, element, element),
                    lift_coordinate_values=values,
                )
        morphism.validate_symmetric_lift(check=False)
        return morphism

    def _element_constructor_(self, datum):
        if isinstance(datum, ModuleMorphismMethods):
            return ModuleMor._element_constructor_(self, datum)

        if isinstance(datum, IndexedFamily) or (
            isinstance(datum, Iterable) and not isinstance(datum, (str, bytes))
        ):
            return self._from_coordinate_datum(datum)
        return ModuleMor._element_constructor_(self, datum)


class DividedSquareModules(OwnedCategoryOverBaseRing):
    r"""Degree-two divided powers, classifying quadratic maps."""

    def an_object(self):
        r"""The divided square of the free module of rank one."""
        from dzack_research.preamble.categories.modules.pure.modules import Modules

        return Modules(self.base_ring()).an_object().divided_square()

    @classmethod
    def _repr_object_names(cls):
        return "divided-square modules"

    def super_categories(self):
        return [DividedPowerModules(self.base_ring())]

    class ParentMethods:
        def _module_mor_class(self):
            return QuadraticModuleMor

        def divided_square_source(self):
            return self.power_source()

        def quadratic(self, element):
            r"""Return the universal quadratic value ``gamma_2(element)``."""
            source = self.divided_square_source()

            coordinates = source.framing_morphism().lift(element)
            support = coordinates.support().domain()
            square_labels = self.module_generating_set()
            values = {}
            for label in support:
                target_label = square_labels.from_multiplicities({label: 2})
                values[target_label] = coordinates(label) * coordinates(label)
            source_labels = source.module_generating_set()
            for left in support:
                left_position = int(source_labels.ranking_map()(left))
                for right in support:
                    if left_position >= int(source_labels.ranking_map()(right)):
                        continue
                    target_label = square_labels.from_multiplicities(
                        {left: 1, right: 1}
                    )
                    values[target_label] = coordinates(left) * coordinates(right)
            return self.linear_combination(values)

        def polar(self, left, right):
            r"""Return ``gamma_2(x+y)-gamma_2(x)-gamma_2(y)``."""
            return self.quadratic(left + right) - self.quadratic(left) - self.quadratic(right)

        def from_quadratic(self, quadratic, codomain):
            r"""Factor a quadratic map uniquely through the divided square."""
            source = self.divided_square_source()

            def generator_image(selection):
                support = selection.support()
                if int(support.cardinality()) == 1:
                    label = support[0]
                    return quadratic(source.module_generator(label))
                left = support[0]
                right = support[1]
                return (
                    quadratic(
                        source.module_generator(left)
                        + source.module_generator(right)
                    )
                    - quadratic(source.module_generator(left))
                    - quadratic(source.module_generator(right))
                )


            mor = self.module_category().Mor(self, codomain)
            return mor.from_quadratic_map(quadratic)


def _degree(degree) -> int:
    value = int(degree)
    if value < 0:
        raise ValueError(f"{degree} is not a degree: a degree must be a nonnegative integer")
    return value


def _free_degree_labels(source_labels, degree: int, flavor: str):

    if flavor in {"symmetric", "divided"}:
        return source_labels.multisets_of_size(degree)
    if flavor == "alternating":
        return source_labels.ordered_subsets_of_size(degree)
    raise ValueError(
        f"{flavor!r} is not a kind of power: expected 'symmetric', 'alternating' or 'divided'"
    )


def _relation_coordinates(relations):
    r"""Return the coordinate function of each relation ``r(e_k)`` of ``r: F_1 -> F_0``."""
    return tuple(
        relations(relations.domain().module_generator(label)).to_vector()
        for label in relations.domain().module_generating_set()
    )


def _symmetric_relations(relation_coordinates, source_labels, degree: int, generators):
    r"""Return the relations ``r(e_k) m`` of ``Sym^d``, for ``m`` a monomial of degree ``d - 1``."""
    if degree == 0:
        return ()
    ring = generators.base_ring()
    lower_labels = _free_degree_labels(source_labels, degree - 1, "symmetric")
    relations = []
    for relation in relation_coordinates:
        for monomial in lower_labels:
            coefficients = {}
            for source_label in relation.support().domain():
                target = monomial.add_label(source_label)
                coefficients[target] = coefficients.get(target, ring.zero()) + ring(relation(source_label))
            relations.append(generators.linear_combination(coefficients))
    return tuple(relation for relation in relations if relation)


def _alternating_relations(relation_coordinates, source_labels, degree: int, generators):
    r"""Return the relations ``r(e_k) wedge m`` of ``Alt^d``, for ``m`` a wedge of degree ``d - 1``."""
    if degree == 0:
        return ()
    ring = generators.base_ring()
    lower_labels = _free_degree_labels(source_labels, degree - 1, "alternating")
    singleton_labels = _free_degree_labels(source_labels, 1, "alternating")
    relations = []
    for relation in relation_coordinates:
        for monomial in lower_labels:
            coefficients = {}
            for source_label in relation.support().domain():
                singleton = singleton_labels.from_multiplicities({source_label: 1})
                wedge = monomial.wedge_with(singleton)
                if wedge is None:
                    continue
                target, sign = wedge
                coefficients[target] = coefficients.get(target, ring.zero()) + sign * ring(relation(source_label))
            relations.append(generators.linear_combination(coefficients))
    return tuple(relation for relation in relations if relation)


def _divided_product_coefficient(left, right):
    return prod(
        binomial(
            left.multiplicity(label) + right.multiplicity(label),
            left.multiplicity(label),
        )
        for label in left.support()
    )


def _divided_relations(relation_coordinates, source_labels, degree: int, generators):
    r"""Return the relations ``gamma_j(r(e_k)) m`` of ``Gamma^d``, for ``m`` of degree ``d - j``."""
    if degree == 0:
        return ()
    ring = generators.base_ring()
    relations = []
    for relation in relation_coordinates:
        for divided_degree in range(1, degree + 1):
            divided_labels = _free_degree_labels(source_labels, divided_degree, "divided")
            complementary_labels = _free_degree_labels(source_labels, degree - divided_degree, "divided")
            for monomial in complementary_labels:
                coefficients = {}
                for exponent in divided_labels:
                    coefficient = ring.one()
                    for source_label in exponent.support():
                        coefficient *= ring(relation(source_label)) ** exponent.multiplicity(source_label)
                    if not coefficient:
                        continue
                    target = exponent.merged_with(monomial)
                    coefficients[target] = coefficients.get(target, ring.zero()) + coefficient * _divided_product_coefficient(exponent, monomial)
                relations.append(generators.linear_combination(coefficients))
    return tuple(relation for relation in relations if relation)


def _presented_degree_power(
    module,
    degree: int,
    flavor: str,
    *,
    extra_categories=(),
    extra_construction_data=None,
):

    ring = _owned_ring(module.base_ring())
    if degree == 0:

        return ring.regular_module()
    if degree == 1:
        return module

    source_labels = module.module_generating_set()
    labels = _free_degree_labels(source_labels, degree, flavor)

    if module in FramedFreeModules(ring):
        if extra_categories or extra_construction_data:
            return ring._fresh_free_module_on(
                labels,
                _extra_categories=extra_categories,
                _extra_construction_data=extra_construction_data,
            )
        return ring.free_module(labels)

    assert module in ModulesWithChosenFinitePresentation(ring), (
        f"cannot compute the degree-{degree} {flavor} power of {module}: this algorithm needs a free "
        f"module or a finitely presented module with a chosen finite presentation, but {module} is in "
        f"{module.category()}"
    )


    if not source_labels.cardinality().is_finite():
        raise TypeError(
            f"cannot compute the degree-{degree} {flavor} power of {module}: its chosen generating set "
            f"{source_labels} is not finite"
        )

    relation_coordinates = _relation_coordinates(_relation_morphism(module))
    generators = ring._fresh_free_module_on(labels)
    if flavor == "symmetric":
        relations = _symmetric_relations(relation_coordinates, source_labels, degree, generators)
    elif flavor == "alternating":
        relations = _alternating_relations(relation_coordinates, source_labels, degree, generators)
    elif flavor == "divided":
        relations = _divided_relations(relation_coordinates, source_labels, degree, generators)
    else:
        raise ValueError(
            f"{flavor!r} is not a kind of power: expected 'symmetric', 'alternating' or 'divided'"
        )

    presentation = _morphism_on_elements(generators, relations)
    return ModulesWithChosenFinitePresentation(ring)(
        presentation,
        category=owned_category_join(extra_categories) if extra_categories else None,
        **(extra_construction_data or {}),
    )


@cached_function(key=lambda module: id(module))
def _divided_square(module):
    r"""Return ``Gamma^2_R(M)``, the universal target for quadratic maps."""
    return _presented_degree_power(
        module,
        2,
        "divided",
        extra_categories=(
            DividedPowerModules(module.base_ring()),
            DividedSquareModules(module.base_ring()),
        ),
        extra_construction_data={
            "power_source": module,
            "power_degree": 2,
        },
    )


def _divided_square_morphism(morphism):
    r"""Return ``Gamma^2(f)`` for a module morphism ``f``."""
    source = morphism.domain().divided_square()
    target = morphism.codomain().divided_square()
    return source.from_quadratic(
        lambda element: target.quadratic(morphism(element)),
        target,
    )


def _tensor_power(module, degree):
    r"""Return the selected iterated tensor power ``M^{\otimes degree}``."""
    degree = _degree(degree)
    if degree == 0:

        return module.base_ring().regular_module()
    if degree == 1:
        return module
    return _tensor_power_nontrivial(module, degree)


