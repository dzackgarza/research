class _PowerModuleInclusion(ModuleEmbedding):
    r"""The canonical inclusion of a homogeneous power piece into its graded algebra."""

    def __init__(self, parent, source, algebra, degree) -> None:
        self._power_source = source
        self._power_algebra = algebra
        self._power_degree = degree
        super().__init__(
            parent,
            lambda element: algebra.from_graded_piece(degree, source(element)),
            elementwise=True,
            lift=source._lift_from_ambient_power_algebra,
        )

    def _elementwise_linearity_derivation(self):
        return True

    def _injectivity_derivation(self):
        return True

    def _selected_lift_derivation(self):
        return True


class _PowerModuleParentMethods:
    def __init__(self, power_source, power_degree, **rest) -> None:
        self._power_source = power_source
        self._power_degree = int(power_degree)
        super().__init__(**rest)

    def power_source(self):
        return self._power_source

    def power_degree(self):
        return self._power_degree

    def _lift_from_ambient_power_algebra(self, element):
        r"""Read an ambient homogeneous element back in this power module."""
        algebra = self.ambient_power_algebra()
        if element_parent(element) is not algebra:
            raise TypeError(
                f"cannot read {element!r} in the degree-{self.power_degree()} piece {self}: it is not an "
                f"element of the graded algebra {algebra}"
            )
        degree = self.power_degree()
        component = algebra.homogeneous_component(element, degree)
        if algebra.from_graded_piece(degree, component) != element:
            raise ValueError(
                f"{element} is not in the degree-{degree} piece {self} of {algebra}: it has nonzero "
                f"components in other degrees"
            )
        return self(component)

    def __contains__(self, element) -> bool:
        if element_parent(element) is self:
            return True
        if element_parent(element) is self.ambient_power_algebra():
            try:
                self._lift_from_ambient_power_algebra(element)
            except (TypeError, ValueError):
                return False
            return True
        return super().__contains__(element)

    @cached_method
    def inclusion(self):
        r"""Return the canonical homogeneous-piece inclusion into its power algebra."""
        algebra = self.ambient_power_algebra()
        degree = self.power_degree()
        inclusion = _PowerModuleInclusion(
            self.Mono(algebra),
            self,
            algebra,
            degree,
        )
        self.register_conversion(
            SetMorphism(
                Sets().Mor(algebra, self),
                inclusion.lift,
            )
        )
        return inclusion


