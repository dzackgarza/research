def _exact_projectivization_map(
    sheaf_morphism,
    source_total,
    target_total,
):
    r"""Return the exact open-domain projectivization map without chart materialization."""
    from dzack_research.preamble.categories.schemes.schemes import OpenImmersions

    category = OpenImmersions(target_total)

    def inclusion(mor):
        return _RelativeProjectivizationSurjectivityOpenInclusion(
            mor,
            sheaf_morphism,
        )

    locus = _object_of(
        category,
        _engine=(category, _RelativeProjectivizationSurjectivityLocusEngine, None),
        scheme_base_ring=target_total.scheme_base_ring(),
        scheme_engine=None,
        inclusion_codomain=target_total,
        inclusion_datum=inclusion,
        projectivization_sheaf_morphism=sheaf_morphism,
    )
    induced = locus.Mor(source_total)(
        lambda mor: _RelativeProjectivizationInducedMorphism(
            mor,
            sheaf_morphism,
        )
    )
    return ProjectivizationMapOnSurjectivityLocus(
        sheaf_morphism,
        source_total,
        target_total,
        locus,
        induced,
    )


def _empty_affine_scheme_morphism(domain, codomain):
    r"""Return the unique morphism from a represented empty affine scheme."""
    match (
        domain in Schemes(domain.scheme_base_ring()).Affine(),
        codomain in Schemes(codomain.scheme_base_ring()).Affine(),
        domain.coordinate_algebra().one() == domain.coordinate_algebra().zero(),
    ):
        case (True, True, True):
            pass
        case _:
            raise ValueError(
                "the initial affine-scheme map requires an empty affine domain and affine codomain"
            )
    zero_ring = domain.coordinate_algebra()
    pullback = OwnedRings().Mor(
        codomain.coordinate_algebra(),
        zero_ring,
    ).elementwise(lambda _element: zero_ring.zero())
    return _affine_morphism_from_pullback(domain, codomain, pullback)


def _empty_projectivization_map(
    sheaf_morphism,
    source_total,
    target_total,
    source_atlas,
    target_atlas,
):
    r"""Return the projectivization map whose surjectivity locus is empty.

    If the source sheaf is zero, no quotient of the target line can be induced;
    if the target sheaf is zero, ``P_quot(target)`` is already empty.  In both
    cases the domain of definition is the open subobject obtained chartwise as
    ``D(0)``.  Maps from those empty affine charts are the unique initial maps.
    """
    from dzack_research.preamble.categories.schemes.gluing import (
        _glued_chartwise_distinguished_open,
    )

    fine_indices = target_atlas.chart_index_set()
    local_opens = {
        index: target_atlas.chart(index).distinguished_open(
            target_atlas.chart(index).coordinate_algebra().zero()
        )
        for index in fine_indices
    }
    locus = _glued_chartwise_distinguished_open(
        target_atlas,
        fine_indices,
        {index: index for index in fine_indices},
        local_opens,
        name="Empty surjectivity locus of a projectivized sheaf morphism",
    )
    source_role = next(iter(source_atlas.chart_indices()))
    source_chart = source_atlas.chart(source_role)
    locus_datum = locus.gluing_datum()
    induced = locus.Mor(source_total)(
        finite_indexed_family(
            locus_datum.chart_index_set(),
            lambda index: source_atlas.chart_embedding(source_role)
            * _empty_affine_scheme_morphism(
                locus_datum.chart(index),
                source_chart,
            ),
            name="Initial local maps of an empty projectivization domain",
        )
    )
    return ProjectivizationMapOnSurjectivityLocus(
        sheaf_morphism,
        source_total,
        target_total,
        locus,
        induced,
    )


def _projectivization_map(sheaf_morphism):
    r"""Construct the projectivization map on the locus where the induced quotient is surjective."""
    from dzack_research.preamble.categories.divisors.invertible_sheaves import (
        _ChosenTrivializationQuasiCoherentMorphism,
    )
    from dzack_research.preamble.categories.schemes.gluing import (
        FiniteAtlasModuleSheafMorphism,
        _glued_chartwise_distinguished_open,
    )
    from dzack_research.preamble.categories.schemes.ringed_spaces import (
        AffineQuasiCoherentSheafMorphism,
        QuasiCoherentSheaves,
    )

    source_sheaf = sheaf_morphism.domain()
    target_sheaf = sheaf_morphism.codomain()
    match source_sheaf.scheme() is target_sheaf.scheme():
        case True:
            pass
        case False:
            raise ValueError("projectivization of a sheaf map requires one base scheme")

    source_family = source_sheaf.projectivization()
    target_family = target_sheaf.projectivization()
    source_total = source_family.arrow().domain()
    target_total = target_family.arrow().domain()
    match (
        source_total.has_selected_finite_affine_atlas(),
        target_total.has_selected_finite_affine_atlas(),
    ):
        case (True, True):
            source_atlas = source_total.selected_finite_affine_atlas()
            target_atlas = target_total.selected_finite_affine_atlas()
        case _:
            return _exact_projectivization_map(
                sheaf_morphism,
                source_total,
                target_total,
            )
    fine_data = {}

    scheme = source_sheaf.scheme()
    match scheme in Schemes(scheme.scheme_base_ring()).Affine():
        case True:
            source_module = QuasiCoherentSheaves(scheme).global_sections(source_sheaf)
            target_module = QuasiCoherentSheaves(scheme).global_sections(target_sheaf)
            match sheaf_morphism:
                case AffineQuasiCoherentSheafMorphism():
                    local_map = sheaf_morphism.underlying_module_morphism()
                case _ChosenTrivializationQuasiCoherentMorphism():
                    local_map = sheaf_morphism.global_sections_map()
                case _:
                    raise TypeError(
                        "the represented affine projectivization map requires a quasi-coherent morphism with its module map"
                    )
            source_labels = tuple(source_module.module_generating_set())
            target_labels = tuple(target_module.module_generating_set())
            match (bool(source_labels), bool(target_labels)):
                case (False, _) | (_, False):
                    return _empty_projectivization_map(
                        sheaf_morphism,
                        source_total,
                        target_total,
                        source_atlas,
                        target_atlas,
                    )
                case (True, True):
                    pass
            for target_label in target_labels:
                for source_label in source_labels:
                    fine_key = (target_label, source_label)
                    fine_data[fine_key] = (
                        target_label,
                        source_label,
                        local_map,
                        source_module,
                        target_module,
                        source_label,
                        target_label,
                    )
        case False:
            match sheaf_morphism:
                case FiniteAtlasModuleSheafMorphism() | _ChosenTrivializationQuasiCoherentMorphism():
                    pass
                case _:
                    raise TypeError(
                        "the represented finite-atlas projectivization map requires compatible local quasi-coherent maps"
                    )
            source_datum = _finite_atlas_module_datum(source_sheaf)
            target_datum = _finite_atlas_module_datum(target_sheaf)
            match source_datum.gluing_datum() is target_datum.gluing_datum():
                case True:
                    pass
                case False:
                    raise ValueError(
                        "finite-atlas projectivization of a sheaf map requires one base atlas"
                    )
            match all(
                not tuple(target_datum.local_module(index).module_generating_set())
                for index in target_datum.chart_indices()
            ):
                case True:
                    return _empty_projectivization_map(
                        sheaf_morphism,
                        source_total,
                        target_total,
                        source_atlas,
                        target_atlas,
                    )
                case False:
                    pass
            for target_role in target_atlas.chart_indices():
                base_index, target_label = target_role
                source_module = source_datum.local_module(base_index)
                target_module = target_datum.local_module(base_index)
                source_labels = tuple(source_module.module_generating_set())
                match source_labels:
                    case ():
                        fine_key = len(fine_data)
                        fine_data[fine_key] = (
                            target_role,
                            None,
                            sheaf_morphism.local_map(base_index),
                            source_module,
                            target_module,
                            None,
                            target_label,
                        )
                    case _:
                        local_map = sheaf_morphism.local_map(base_index)
                        for source_label in source_labels:
                            source_role = (base_index, source_label)
                            fine_key = len(fine_data)
                            fine_data[fine_key] = (
                                target_role,
                                source_role,
                                local_map,
                                source_module,
                                target_module,
                                source_label,
                                target_label,
                            )

    fine_indices = finite_ordered_set(tuple(fine_data))
    local_opens = {}
    coarse_indices = {}
    for fine_index in fine_indices:
        (
            target_role,
            _source_role,
            local_map,
            source_module,
            target_module,
            source_label,
            target_label,
        ) = fine_data[fine_index]
        target_chart = target_atlas.chart(target_role)
        match source_label:
            case None:
                linear_form = target_chart.coordinate_algebra().zero()
            case _:
                linear_form = _projectivization_quotient_linear_form(
                    local_map,
                    source_module,
                    target_module,
                    target_chart,
                    target_label,
                    source_label,
                )
        coarse_indices[fine_index] = target_role
        local_opens[fine_index] = target_chart.distinguished_open(linear_form)

    locus = _glued_chartwise_distinguished_open(
        target_atlas,
        fine_indices,
        coarse_indices,
        local_opens,
        name="Surjectivity locus of a projectivized sheaf morphism",
    )

    local_maps = {}
    for fine_index in fine_indices:
        (
            target_role,
            source_role,
            local_map,
            source_module,
            target_module,
            source_label,
            target_label,
        ) = fine_data[fine_index]
        domain_chart = locus.gluing_datum().chart(fine_index)
        match source_role:
            case None:
                fallback_role = next(iter(source_atlas.chart_indices()))
                source_projective_chart = source_atlas.chart(fallback_role)
                local_maps[fine_index] = (
                    source_atlas.chart_embedding(fallback_role)
                    * _empty_affine_scheme_morphism(
                        domain_chart,
                        source_projective_chart,
                    )
                )
            case _:
                source_projective_chart = source_atlas.chart(source_role)
                target_projective_chart = target_atlas.chart(target_role)
                pullback = _projectivization_map_chart_pullback(
                    local_map,
                    source_module,
                    target_module,
                    source_projective_chart,
                    source_label,
                    target_projective_chart,
                    target_label,
                    domain_chart,
                )
                local_maps[fine_index] = (
                    source_atlas.chart_embedding(source_role)
                    * _affine_morphism_from_pullback(
                        domain_chart,
                        source_projective_chart,
                        pullback,
                    )
                )

    induced = locus.Mor(source_total)(
        finite_indexed_family(
            fine_indices,
            local_maps.__getitem__,
            name="Local maps of a projectivized sheaf morphism",
        )
    )
    return ProjectivizationMapOnSurjectivityLocus(
        sheaf_morphism,
        source_total,
        target_total,
        locus,
        induced,
    )


def _free_projectivization_projective_space_comparison(
    projectivization,
    projective_space,
):
    r"""Identify ``P_quot(R^r)`` with the represented ``P^(r-1)_R`` chartwise."""
    from dzack_research.preamble.categories.schemes.schemes import (
        ProjectiveSpaces,
        _scheme_isomorphism,
    )

    source_sheaf = projectivization.projectivization_source_sheaf()
    source_scheme = source_sheaf.scheme()
    base = source_scheme.scheme_base_ring()
    module = projectivization.projectivization_module()
    match (
        source_scheme is source_scheme.base_scheme(),
        module in FramedFreeModules(module.base_ring()),
        projective_space in ProjectiveSpaces(base),
    ):
        case (True, True, True):
            pass
        case (False, _, _):
            raise ValueError(
                "the absolute projective-space comparison starts from a free sheaf on Spec(R)"
            )
        case (_, False, _):
            raise TypeError(
                "the projective-space comparison requires a represented finite free module"
            )
        case (_, _, False):
            raise TypeError(
                "the comparison target is a represented projective space over the same base"
            )

    labels = tuple(module.module_generating_set())
    match int(projective_space.relative_dimension()) + 1 == len(labels):
        case True:
            pass
        case False:
            raise ValueError(
                "the projective-space dimension must be one less than the free-module rank"
            )
    ranking = module.module_generating_set().ranking_map()
    source_atlas = projectivization.finite_affine_atlas()
    target_atlas = projective_space.standard_affine_atlas()

    forward_local_maps = {}
    inverse_local_maps = {}
    for label in labels:
        position = int(ranking(label))
        source_chart = source_atlas.chart(label)
        target_chart = target_atlas.chart(position)
        source_algebra = source_chart.coordinate_algebra()
        target_algebra = target_chart.coordinate_algebra()

        forward_images = {}
        for numerator_position in range(len(labels)):
            match numerator_position == position:
                case True:
                    continue
                case False:
                    pass
            forward_images[
                projective_space._standard_chart_coordinate_name(
                    position, numerator_position
                )
            ] = source_algebra.algebra_generator(
                _ratio_name(module, label, labels[numerator_position])
            )
        forward_pullback = target_algebra.Mor(source_algebra)(forward_images)
        forward_local_maps[label] = target_atlas.chart_embedding(position) * _affine_morphism_from_pullback(
            source_chart,
            target_chart,
            forward_pullback,
        )

        inverse_images = {}
        for numerator_position in range(len(labels)):
            match numerator_position == position:
                case True:
                    continue
                case False:
                    pass
            inverse_images[
                _ratio_name(module, label, labels[numerator_position])
            ] = target_algebra.algebra_generator(
                projective_space._standard_chart_coordinate_name(
                    position, numerator_position
                )
            )
        inverse_pullback = source_algebra.Mor(target_algebra)(inverse_images)
        inverse_local_maps[position] = source_atlas.chart_embedding(label) * _affine_morphism_from_pullback(
            target_chart,
            source_chart,
            inverse_pullback,
        )

    forward = projectivization.Mor(projective_space)(
        finite_indexed_family(
            source_atlas.chart_index_set(),
            forward_local_maps.__getitem__,
            name="Charts of the free-module projective-space comparison",
        )
    )
    inverse = projective_space.morphism_from_finite_atlas(
        projectivization,
        finite_indexed_family(
            target_atlas.chart_index_set(),
            inverse_local_maps.__getitem__,
            name="Inverse charts of the free-module projective-space comparison",
        ),
        atlas=target_atlas,
    )
    return _scheme_isomorphism(forward, inverse)

def _symmetric_algebra_descent(module_datum):
    r"""Return the finite-atlas descent datum ``Sym(F)`` induced in degree one."""
    from dzack_research.preamble.categories.schemes.gluing import (
        FiniteAtlasAlgebraGluingData,
    )

    atlas = module_datum.gluing_datum()
    local_algebras = {
        index: module_datum.local_module(index).symmetric_algebra()
        for index in atlas.chart_indices()
    }

    def induced_images(source_index, target_index):
        source_pair = module_datum.pair_module(source_index, target_index)
        target_pair = module_datum.pair_module(target_index, source_index)
        transition = module_datum.transition(source_index, target_index).pullback()

        def images(label, _domain, codomain):
            vector = transition(target_pair.module_generator(label))
            return sum(
                (
                    codomain.scalar_multiple(
                        coefficient,
                        codomain.algebra_generator(source_label),
                    )
                    for source_label, coefficient in source_pair.framing_coefficients(
                        vector
                    ).items()
                ),
                codomain.zero(),
            )

        return images

    transitions = {
        (source_index, target_index): (
            induced_images(source_index, target_index),
            induced_images(target_index, source_index),
        )
        for source_index, target_index in atlas.transition_index_set()
    }
    return FiniteAtlasAlgebraGluingData(atlas)(local_algebras, transitions)


def _base_changed_finite_atlas_module_datum(
    module_datum,
    changed_atlas,
    ring_map,
):
    r"""Scalar-extend one finite-atlas module datum to a compatible changed atlas.

    The changed atlas is selected on the already constructed scalar base change
    of the underlying scheme.  Each chart map is the scalar extension of its
    coordinate algebra, and each semilinear transition is obtained by applying
    the corresponding overlap scalar map to its framing coefficients.  Thus no
    transition matrix is re-derived from a rank or locally-free shortcut.
    """
    from dzack_research.preamble.categories.schemes.gluing import (
        FiniteAtlasModuleGluingData,
    )

    source_atlas = module_datum.gluing_datum()
    if source_atlas.chart_index_set() != changed_atlas.chart_index_set():
        raise ValueError(
            "finite-atlas scalar base change must retain the chart index set"
        )

    chart_ring_maps = {
        index: _chart_base_change_pullback(
            source_atlas.chart(index),
            changed_atlas.chart(index),
            ring_map,
        )
        for index in source_atlas.chart_indices()
    }
    local_modules = {
        index: module_datum.local_module(index).base_change(chart_ring_maps[index])
        for index in source_atlas.chart_indices()
    }

    transitions = {}
    for source_index, target_index in source_atlas.transition_index_set():
        old_transition = module_datum.transition(source_index, target_index)
        old_source_pair = module_datum.pair_module(source_index, target_index)
        old_target_pair = module_datum.pair_module(target_index, source_index)
        source_overlap = source_atlas.overlap(source_index, target_index)
        changed_source_overlap = changed_atlas.overlap(source_index, target_index)
        source_overlap_map = source_overlap.coordinate_algebra().induced_morphism(
            changed_source_overlap.inclusion().coordinate_algebra_morphism()
            * chart_ring_maps[source_index]
        )
        target_overlap = source_atlas.overlap(target_index, source_index)
        changed_target_overlap = changed_atlas.overlap(target_index, source_index)
        target_overlap_map = target_overlap.coordinate_algebra().induced_morphism(
            changed_target_overlap.inclusion().coordinate_algebra_morphism()
            * chart_ring_maps[target_index]
        )

        def forward_images(
            label,
            _domain,
            codomain,
            old_transition=old_transition,
            old_source_pair=old_source_pair,
            old_target_pair=old_target_pair,
            source_overlap_map=source_overlap_map,
        ):
            image = old_transition.pullback()(
                old_target_pair.module_generator(label)
            )
            return codomain.linear_combination(
                {
                    target_label: source_overlap_map(coefficient)
                    for target_label, coefficient in old_source_pair.framing_coefficients(
                        image
                    ).items()
                    if source_overlap_map(coefficient) != codomain.base_ring().zero()
                }
            )

        def inverse_images(
            label,
            _domain,
            codomain,
            old_transition=old_transition,
            old_source_pair=old_source_pair,
            old_target_pair=old_target_pair,
            target_overlap_map=target_overlap_map,
        ):
            image = old_transition.inverse_pullback()(
                old_source_pair.module_generator(label)
            )
            return codomain.linear_combination(
                {
                    target_label: target_overlap_map(coefficient)
                    for target_label, coefficient in old_target_pair.framing_coefficients(
                        image
                    ).items()
                    if target_overlap_map(coefficient) != codomain.base_ring().zero()
                }
            )

        transitions[source_index, target_index] = (
            forward_images,
            inverse_images,
        )
    return FiniteAtlasModuleGluingData(changed_atlas)(local_modules, transitions)


def _projectivization_chart_family(module_datum, scheme_base_ring):
    r"""Return all standard affine Proj charts ``(i,a)`` of a finite-atlas sheaf."""
    roles = tuple(
        (index, label)
        for index in module_datum.chart_indices()
        for label in module_datum.local_module(index).module_generating_set()
    )
    if not roles:
        first_index = next(iter(module_datum.chart_indices()))
        empty = module_datum.gluing_datum().chart(first_index).closed_subscheme(
            module_datum.local_module(first_index).base_ring().one()
        )
        roles = ((first_index, "empty"),)
        return finite_indexed_family(
            finite_ordered_set(roles),
            lambda _role: empty,
            name="The empty affine atlas of a zero sheaf projectivization",
        )
    index_set = finite_ordered_set(roles)
    return finite_indexed_family(
        index_set,
        lambda role: _chart_algebra(
            module_datum.local_module(role[0]),
            role[1],
        ).affine_spectrum(base_ring=scheme_base_ring),
        name="Standard affine charts of a finite-atlas projectivization",
    )


def _projectivization_chart_transitions(
    module_datum,
    projective_charts,
    scheme_base_ring,
):
    roles = tuple(projective_charts.index_set())
    transitions = {}
    for position, source_key in enumerate(roles):
        source_index, source_label = source_key
        source_module = module_datum.local_module(source_index)
        for target_key in roles[position + 1 :]:
            target_index, target_label = target_key
            if source_label == "empty" or target_label == "empty":
                continue
            match source_index == target_index:
                case True:
                    local_charts = {
                        label: projective_charts[(source_index, label)]
                        for label in source_module.module_generating_set()
                    }
                    transitions[source_key, target_key] = _chart_transition(
                        source_module,
                        local_charts,
                        source_label,
                        target_label,
                        scheme_base_ring,
                    )
                case False:
                    transitions[source_key, target_key] = _cross_projective_transition(
                        module_datum,
                        projective_charts,
                        source_key,
                        target_key,
                        scheme_base_ring,
                    )
    return transitions


def _pulled_module_transition_images(
    module_datum,
    total_atlas,
    source_key,
    target_key,
):
    source_index, source_label = source_key
    target_index, _target_label = target_key
    if source_index == target_index:
        return lambda label, _domain, codomain: codomain.module_generator(label)
    source_local = module_datum.local_module(source_index)
    source_pair = module_datum.pair_module(source_index, target_index)
    target_pair = module_datum.pair_module(target_index, source_index)
    transition = module_datum.transition(source_index, target_index).pullback()
    projective_chart = total_atlas.chart(source_key)
    projective_open = total_atlas.overlap(source_key, target_key)
    pair_map = _pair_ring_map_to_projective_open(
        source_local,
        source_pair,
        projective_chart,
        projective_open,
    )

    def images(label, _domain, codomain):
        vector = transition(target_pair.module_generator(label))
        return codomain.linear_combination(
            {
                source_module_label: pair_map(coefficient)
                for source_module_label, coefficient in source_pair.framing_coefficients(
                    vector
                ).items()
            }
        )

    return images


class _FiniteAtlasProjectivizationSchemeEngine:
    r"""Relative Proj of a finite-atlas quasi-coherent module descent datum."""

    def __init__(
        self,
        projectivization_source_sheaf,
        projectivization_module_datum,
        projectivization_symmetric_algebra,
        **rest,
    ) -> None:
        self._projectivization_module_datum = projectivization_module_datum
        self._projectivization_symmetric_algebra = projectivization_symmetric_algebra
        super().__init__(
            projectivization_source_sheaf=projectivization_source_sheaf,
            **rest,
        )

    def projectivization_module_datum(self):
        return self._projectivization_module_datum

    def symmetric_algebra(self):
        return self._projectivization_symmetric_algebra

    @cached_method
    def projectivization_projection(self):
        base_scheme = self.projectivization_source_sheaf().scheme()
        base_atlas = self.projectivization_module_datum().gluing_datum()
        total_atlas = self.finite_affine_atlas()

        def local_map(role):
            base_index, _module_label = role
            chart = total_atlas.chart(role)
            to_base_chart = _affine_morphism_from_pullback(
                chart,
                base_atlas.chart(base_index),
                chart.coordinate_algebra().algebra_structure_morphism(),
            )
            return base_atlas.chart_embedding(base_index) * to_base_chart

        return self.Mor(base_scheme)(
            finite_indexed_family(
                total_atlas.chart_index_set(),
                local_map,
                name="Local maps of the relative-projectivization projection",
            )
        )

    @cached_method
    def tautological_line_bundle(self):
        from dzack_research.preamble.categories.schemes.ringed_spaces import (
            QuasiCoherentSheaves,
        )

        total_atlas = self.finite_affine_atlas()
        module_datum = self.projectivization_module_datum()
        units = {}
        for source_key, target_key in total_atlas.transition_index_set():
            source_index, source_label = source_key
            target_index, target_label = target_key
            source_overlap = total_atlas.overlap(source_key, target_key)
            if source_index == target_index:
                restriction = source_overlap.inclusion().coordinate_algebra_morphism()
                units[source_key, target_key] = restriction(
                    _chart_ratio(
                        module_datum.local_module(source_index),
                        total_atlas.chart(source_key).coordinate_algebra(),
                        source_label,
                        target_label,
                    )
                )
                continue
            source_pair = module_datum.pair_module(source_index, target_index)
            target_pair = module_datum.pair_module(target_index, source_index)
            transition = module_datum.transition(source_index, target_index).pullback()
            units[source_key, target_key] = _linear_form_on_projective_open(
                module_datum.local_module(source_index),
                source_pair,
                transition(target_pair.module_generator(target_label)),
                total_atlas.chart(source_key),
                source_label,
                source_overlap,
            )
        return (
            QuasiCoherentSheaves(self)
            .Invertible()
            .WithChosenTrivialization()(total_atlas, units)
        )

    @cached_method
    def pulled_source_sheaf(self):
        from dzack_research.preamble.categories.schemes.gluing import (
            FiniteAtlasModuleGluingData,
        )

        total_atlas = self.finite_affine_atlas()
        source_datum = self.projectivization_module_datum()
        fibered = ModulesOverCommutativeRings()
        local_modules = {}
        for role in total_atlas.chart_indices():
            source_index, _source_label = role
            local_modules[role] = fibered.cocartesian_transport(
                total_atlas.chart(role).coordinate_algebra().algebra_structure_morphism()
            )(source_datum.local_module(source_index))

        transitions = {
            (source_key, target_key): (
                _pulled_module_transition_images(
                    source_datum,
                    total_atlas,
                    source_key,
                    target_key,
                ),
                _pulled_module_transition_images(
                    source_datum,
                    total_atlas,
                    target_key,
                    source_key,
                ),
            )
            for source_key, target_key in total_atlas.transition_index_set()
        }
        return FiniteAtlasModuleGluingData(total_atlas)(
            local_modules,
            transitions,
        ).sheaf()

    @cached_method
    def universal_quotient(self):
        from dzack_research.preamble.categories.schemes.ringed_spaces import (
            QuasiCoherentSheaves,
        )

        total_atlas = self.finite_affine_atlas()
        source_datum = self.projectivization_module_datum()
        pulled = self.pulled_source_sheaf()
        line = self.tautological_line_bundle().module_sheaf()
        pulled_datum = pulled.gluing_datum()
        line_datum = line.gluing_datum()
        local_maps = {}
        for role in total_atlas.chart_indices():
            source_index, chart_label = role
            source = pulled_datum.local_module(role)
            target = line_datum.local_module(role)
            basis = target.module_generator(next(iter(target.module_generating_set())))
            local_module = source_datum.local_module(source_index)
            chart_algebra = total_atlas.chart(role).coordinate_algebra()
            local_maps[role] = source.module_category().Mor(source, target)(
                {
                    label: target.scalar_multiple(
                        _chart_ratio(
                            local_module,
                            chart_algebra,
                            chart_label,
                            label,
                        ),
                        basis,
                    )
                    for label in local_module.module_generating_set()
                }
            )
        return QuasiCoherentSheaves(self).Mor(pulled, line)(local_maps)

    @cached_method(key=lambda self, ring_map: id(ring_map))
    def projectivization_base_change(self, ring_map):
        r"""Return the represented finite-atlas scalar base-change comparison."""
        return FiniteAtlasProjectivizationBaseChangeComparison(self, ring_map)

    @cached_method
    def relative_projective_space_comparison(self):
        r"""Identify a represented trivial bundle projectivization with ``X x P^(r-1)``."""
        return _trivial_finite_atlas_relative_projective_space_comparison(self)


def _trivial_finite_atlas_relative_projective_space_comparison(projectivization):
    r"""Compare ``P_quot(O_X^r)`` with ``X x_R P^(r-1)_R`` on standard atlases.

    The represented comparison below is the projective-base specialization in
    which ``X`` itself has its standard finite affine atlas.  Triviality is
    checked on the actual module descent: every chart has the same finite free
    basis and every semilinear transition carries each basis vector to the
    identically labelled vector.  The resulting isomorphism is over ``X``.
    """
    from dzack_research.preamble.categories.schemes.schemes import (
        ProductProjectiveSpaces,
        ProjectiveSpaces,
        _scheme_isomorphism,
    )

    source_sheaf = projectivization.projectivization_source_sheaf()
    source_scheme = source_sheaf.scheme()
    base = source_scheme.scheme_base_ring()
    match source_scheme in ProjectiveSpaces(base):
        case True:
            pass
        case False:
            raise AssertionError(
                "the represented relative-projective-space comparison presently uses a projective-space base with its standard atlas"
            )
    module_datum = projectivization.projectivization_module_datum()
    base_atlas = module_datum.gluing_datum()
    match base_atlas is source_scheme.standard_affine_atlas():
        case True:
            pass
        case False:
            raise ValueError(
                "the trivial-bundle comparison uses the source projective space's selected standard affine atlas"
            )

    first_index = next(iter(base_atlas.chart_indices()))
    first_module = module_datum.local_module(first_index)
    labels = tuple(first_module.module_generating_set())
    match labels:
        case ():
            raise ValueError("the zero bundle has empty projectivization, not a relative projective space")
        case _:
            pass
    for index in base_atlas.chart_indices():
        local = module_datum.local_module(index)
        match (
            local in FramedFreeModules(local.base_ring()),
            tuple(local.module_generating_set()) == labels,
        ):
            case (True, True):
                pass
            case _:
                raise TypeError(
                    "the relative-projective-space comparison requires one finite free basis on every chart"
                )
    for source_index, target_index in base_atlas.transition_index_set():
        source_pair = module_datum.pair_module(source_index, target_index)
        target_pair = module_datum.pair_module(target_index, source_index)
        transition = module_datum.transition(source_index, target_index)
        match all(
            transition.pullback()(target_pair.module_generator(label))
            == source_pair.module_generator(label)
            and transition.inverse_pullback()(source_pair.module_generator(label))
            == target_pair.module_generator(label)
            for label in labels
        ):
            case True:
                pass
            case False:
                raise ValueError(
                    "the finite-atlas module descent is not the trivial bundle in the selected bases"
                )

    fiber = ProjectiveSpaces(base)(len(labels) - 1)
    relative_space = Schemes(base).product((source_scheme, fiber))
    match relative_space in ProductProjectiveSpaces(base):
        case True:
            pass
        case False:
            raise AssertionError(
                "the represented projective-base relative space must be the existing product of projective spaces"
            )
    source_atlas = projectivization.finite_affine_atlas()
    target_atlas = relative_space.standard_affine_atlas()
    ranking = first_module.module_generating_set().ranking_map()
    label_at_position = {
        int(ranking(label)): label
        for label in labels
    }
    forward_local_maps = {}
    inverse_local_maps = {}

    for base_index in base_atlas.chart_indices():
        for fiber_position, module_label in label_at_position.items():
            source_role = (base_index, module_label)
            target_role = (int(base_index), fiber_position)
            source_chart = source_atlas.chart(source_role)
            target_chart = target_atlas.chart(target_role)
            local_module = module_datum.local_module(base_index)
            source_algebra = source_chart.coordinate_algebra()

            to_base_chart = _affine_morphism_from_pullback(
                source_chart,
                base_atlas.chart(base_index),
                source_algebra.algebra_structure_morphism(),
            )
            fiber_chart = fiber.standard_affine_chart(fiber_position)
            fiber_pullback = OwnedRings().Mor(
                fiber_chart.coordinate_algebra(),
                source_algebra,
            )(
                {
                    fiber._standard_chart_coordinate_name(fiber_position, position): _chart_ratio(
                        local_module,
                        source_algebra,
                        module_label,
                        label_at_position[position],
                    )
                    for position in label_at_position
                    if position != fiber_position
                }
            )
            to_fiber_chart = _affine_morphism_from_pullback(
                source_chart,
                fiber_chart,
                fiber_pullback,
            )
            into_target_chart = target_chart.from_product_cone(
                (to_base_chart, to_fiber_chart)
            )
            forward_local_maps[source_role] = (
                target_atlas.chart_embedding(target_role) * into_target_chart
            )

            target_algebra = target_chart.coordinate_algebra()
            base_pullback = target_chart.projection(0).coordinate_algebra_morphism()
            target_view = base_pullback.as_algebra()
            fiber_chart_pullback = target_chart.projection(1).coordinate_algebra_morphism()
            algebra_map = (
                Algebras(local_module.base_ring())
                .Associative()
                .Unital()
                .Mor(source_algebra, target_view)(
                    {
                        _ratio_name(local_module, module_label, label_at_position[position]): fiber_chart_pullback(
                            fiber_chart.coordinate_algebra().algebra_generator(
                                fiber._standard_chart_coordinate_name(
                                    fiber_position,
                                    position,
                                )
                            )
                        )
                        for position in label_at_position
                        if position != fiber_position
                    }
                )
            )
            inverse_pullback = OwnedRings().Mor(
                source_algebra,
                target_algebra,
            ).elementwise(
                lambda element, source_algebra=source_algebra, target_algebra=target_algebra, algebra_map=algebra_map: target_algebra(
                    algebra_map(source_algebra(element))
                )
            )
            inverse_local_maps[target_role] = (
                source_atlas.chart_embedding(source_role)
                * _affine_morphism_from_pullback(
                    target_chart,
                    source_chart,
                    inverse_pullback,
                )
            )

    forward = projectivization.Mor(relative_space)(
        finite_indexed_family(
            source_atlas.chart_index_set(),
            forward_local_maps.__getitem__,
            name="Charts of the trivial-bundle relative-projective-space comparison",
        )
    )
    inverse = relative_space.morphism_from_finite_atlas(
        projectivization,
        finite_indexed_family(
            target_atlas.chart_index_set(),
            inverse_local_maps.__getitem__,
            name="Inverse charts of the trivial-bundle relative-projective-space comparison",
        ),
        atlas=target_atlas,
    )
    match relative_space.projection(0) * forward == projectivization.projectivization_projection():
        case True:
            pass
        case False:
            raise ArithmeticError(
                "the trivial-bundle projective-space comparison does not commute over its base scheme"
            )
    return _scheme_isomorphism(forward, inverse)


def _finite_atlas_module_datum(sheaf):
    r"""Return the concrete finite-atlas module descent datum of a represented QCoh sheaf."""
    from dzack_research.preamble.categories.schemes.gluing import (
        _finite_atlas_of_sheaf_placement,
    )
    from dzack_research.preamble.categories.schemes.ringed_spaces import (
        QuasiCoherentSheaves,
    )

    atlas = _finite_atlas_of_sheaf_placement(sheaf)
    trivialized = (
        QuasiCoherentSheaves(sheaf.scheme())
        .Invertible()
        .WithChosenTrivialization()
    )
    match sheaf in trivialized:
        case True:
            candidate = sheaf.module_sheaf()
        case False:
            candidate = sheaf
    datum = candidate.gluing_datum()
    if datum.gluing_datum() is not atlas:
        raise ValueError(
            "the quasi-coherent sheaf presentation and its selected finite atlas disagree"
        )
    return datum


def _exact_relative_projectivization(sheaf):
    r"""Return the exact relative Proj without requiring a finite affine realization."""
    scheme = sheaf.scheme()
    base = scheme.scheme_base_ring()
    total = RelativeProjectivizations(base)._exact_object(sheaf)
    return Schemes(base).SliceOver(scheme)(
        total.projectivization_projection()
    )


@cached_function(key=lambda sheaf: id(sheaf))
def _finite_atlas_projectivization(sheaf):
    r"""Construct ``Proj_X(Sym(F))`` from one finite-atlas QCoh presentation."""
    module_datum = _finite_atlas_module_datum(sheaf)
    base_atlas = module_datum.gluing_datum()
    if base_atlas.scheme() is not sheaf.scheme():
        raise ValueError("the finite-atlas module datum belongs to a different base scheme")
    materializable = all(
        local in FramedFreeModules(local.base_ring())
        or local in ModulesWithChosenFinitePresentation(local.base_ring())
        for local in (
            module_datum.local_module(index)
            for index in module_datum.chart_indices()
        )
    )
    if not materializable:
        return _exact_relative_projectivization(sheaf)
    symmetric_descent = _symmetric_algebra_descent(module_datum)
    base = sheaf.scheme().scheme_base_ring()
    projective_charts = _projectivization_chart_family(module_datum, base)
    transitions = _projectivization_chart_transitions(
        module_datum,
        projective_charts,
        base,
    )
    total = Schemes(base).glue_affine_atlas(
        projective_charts,
        transitions,
        placements=(RelativeProjectivizations(base),),
        _object_engine=_FiniteAtlasProjectivizationSchemeEngine,
        projectivization_source_sheaf=sheaf,
        projectivization_module_datum=module_datum,
        projectivization_symmetric_algebra=symmetric_descent,
    )
    return Schemes(base).SliceOver(sheaf.scheme())(
        total.projectivization_projection()
    )


@cached_function(key=lambda sheaf: id(sheaf))
def _affine_projectivization(sheaf):
    r"""Construct ``P_X(F) -> X`` for an affine represented quasi-coherent sheaf."""
    scheme = sheaf.scheme()
    base = scheme.scheme_base_ring()
    if scheme not in Schemes(base).Affine():
        raise TypeError("the affine projectivization constructor requires an affine base scheme")
    from dzack_research.preamble.categories.schemes.ringed_spaces import (
        QuasiCoherentSheaves,
    )

    module = QuasiCoherentSheaves(scheme).global_sections(sheaf)
    symmetric = module.symmetric_algebra()
    represented = (
        module in ModulesWithChosenFinitePresentation(module.base_ring())
        or module in FramedFreeModules(module.base_ring())
    )
    if not represented:
        return _exact_relative_projectivization(sheaf)
    labels = module.module_generating_set()
    if labels.cardinality().is_finite() is not True:
        return _exact_relative_projectivization(sheaf)
    match int(labels.cardinality()):
        case 0:
            empty_labels = finite_ordered_set(("empty",))
            empty = scheme.closed_subscheme(scheme.coordinate_algebra().one())
            charts = finite_indexed_family(
                empty_labels,
                lambda _label: empty,
                name="The empty standard atlas of the zero-module projectivization",
            )
            label_values = ()
        case _:
            charts = finite_indexed_family(
                labels,
                lambda label: _chart_algebra(module, label).affine_spectrum(base_ring=base),
                name="Standard affine charts of the relative projectivization",
            )
            label_values = tuple(labels)
    transitions = {
        (left, right): _chart_transition(module, charts, left, right, base)
        for position, left in enumerate(label_values)
        for right in label_values[position + 1 :]
    }
    total = Schemes(base).glue_affine_atlas(
        charts,
        transitions,
        placements=(RelativeProjectivizations(base),),
        _object_engine=_AffineProjectivizationSchemeEngine,
        projectivization_source_sheaf=sheaf,
        projectivization_module=module,
        projectivization_symmetric_algebra=symmetric,
    )
    projection = total.projectivization_projection()
    return Schemes(base).SliceOver(scheme)(projection)


def _projectivization(sheaf):
    r"""Return the represented quotient projectivization ``P_quot(sheaf)``."""
    scheme = sheaf.scheme()
    match scheme in Schemes(scheme.scheme_base_ring()).Affine():
        case True:
            return _affine_projectivization(sheaf)
        case False:
            from dzack_research.preamble.categories.schemes.gluing import (
                _finite_atlas_sheaf_placement,
            )

            match _finite_atlas_sheaf_placement(sheaf):
                case None:
                    return _exact_relative_projectivization(sheaf)
                case _:
                    return _finite_atlas_projectivization(sheaf)


