r"""Relative projectivization of represented quasi-coherent modules.

For a represented quasi-coherent sheaf ``F`` on ``X`` this constructs

``P_quot(F) = Proj_X(Sym(F))``

as an exact owned scheme with its projection and universal invertible quotient.
When a finite affine presentation is available, the scheme is materialized
from the standard opens determined by the selected generators of ``M``.  If
``M = A^n / R`` on generators ``e_i``, then on ``D_+(e_i)`` the coordinate
algebra is generated by the ratios ``e_j/e_i`` and the relations are obtained
by dehomogenizing the selected linear relations of ``M``.  Thus the
construction uses the existing symmetric-algebra presentation and affine
gluing owners rather than a second projective-space algorithm.

The normalization is the quotient convention of Stacks Project, Tag 01OA:
``P_quot(F)`` carries ``O(1)`` and the universal surjection
``pi^* F -> O(1)``.
"""

