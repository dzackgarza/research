class RelativeProjectivizationQuasiCoherentMorphism(Morphism):
    r"""A QCoh arrow whose defining datum comes from the relative-Proj construction."""

    def __init__(self, parent, projectivization, *, identity=False) -> None:
        self._projectivization = projectivization
        self._identity = bool(identity)
        Morphism.__init__(self, parent)

    def relative_projectivization(self):
        return self._projectivization

    def is_identity(self) -> bool:
        return self._identity

    def is_surjective(self) -> bool:
        return True

    def __mul__(self, other):
        if other.codomain() is not self.domain():
            return NotImplemented
        if self.is_identity():
            return other
        if isinstance(other, RelativeProjectivizationQuasiCoherentMorphism) and other.is_identity():
            return self
        return NotImplemented

    def __eq__(self, other) -> bool:
        return (
            isinstance(other, RelativeProjectivizationQuasiCoherentMorphism)
            and other.parent() is self.parent()
            and other.relative_projectivization() is self.relative_projectivization()
            and other.is_identity() == self.is_identity()
        )

    def __ne__(self, other) -> bool:
        return not self == other

    __hash__ = None


class RelativeProjectivizationQuasiCoherentMor(CategoricalMor):
    r"""QCoh Mor on an exact relative Proj when no chartwise Mor is materialized."""

    Element = RelativeProjectivizationQuasiCoherentMorphism

    def _element_constructor_(self, datum):
        match datum:
            case RelativeProjectivizationQuasiCoherentMorphism() if datum.parent() is self:
                return datum
            case RelativeProjectivizationQuasiCoherentMorphism():
                if datum.domain() is not self.domain() or datum.codomain() is not self.codomain():
                    raise ValueError("the relative-projectivization QCoh morphism has the wrong endpoints")
                return self.element_class(
                    self,
                    datum.relative_projectivization(),
                    identity=datum.is_identity(),
                )
            case _ if datum in RelativeProjectivizations(self.domain().scheme().scheme_base_ring()):
                if (
                    self.domain() is datum.pulled_source_sheaf()
                    and self.codomain() is datum.tautological_line_bundle().module_sheaf()
                ):
                    return self.element_class(self, datum)
                raise ValueError("this relative Proj does not define the requested QCoh endpoints")
            case _:
                raise TypeError("this exact QCoh Mor accepts its relative-Proj universal quotient datum")

    @cached_method
    def identity(self):
        if self.domain() is not self.codomain():
            raise ValueError("identity is defined only on an endomorphism Mor")
        scheme = self.domain().scheme()
        return self.element_class(self, scheme, identity=True)


class RelativeProjectivizations(OwnedCategoryOverBaseRing):
    r"""Relative projectivizations ``Proj_X(Sym(F))`` as exact schemes over ``R``.

    This category owns the construction independently of whether a finite
    standard-open atlas is currently computable.  A materialized finite-atlas
    realization may use the same source sheaf and symmetric algebra privately;
    lack of such a realization never changes the defining scheme, projection,
    tautological invertible sheaf, or universal quotient.
    """

    def _repr_object_names(self):
        return f"relative projectivizations over {self.base_ring()}"

    def super_categories(self):
        return [Schemes(self.base_ring())]

    def an_object(self):
        base_scheme = Schemes(self.base_ring()).base_scheme()
        module = self.base_ring().free_module(finite_ordered_set(("e",)))
        return base_scheme.associated_module_sheaf(module).projectivization().arrow().domain()

    def _exact_object(self, source_sheaf):
        r"""Allocate the engine-less realization selected by ``F.projectivization()``.

        This is deliberately private: the canonical public constructor is the
        quasi-coherent sheaf method, which selects this exact realization only
        when no finite affine Proj atlas is represented.
        """
        source_scheme = source_sheaf.scheme()
        if source_scheme.scheme_base_ring() is not self.base_ring():
            raise ValueError("a relative projectivization belongs to the base ring of its source scheme")
        return _object_of(
            self,
            scheme_base_ring=self.base_ring(),
            scheme_engine=None,
            projectivization_source_sheaf=source_sheaf,
        )

    class ParentMethods:
        def __init__(
            self,
            projectivization_source_sheaf,
            **rest,
        ) -> None:
            self._projectivization_source_sheaf = projectivization_source_sheaf
            super().__init__(**rest)

        def projectivization_source_sheaf(self):
            return self._projectivization_source_sheaf

        @cached_method
        def symmetric_algebra(self):
            r"""Return the represented symmetric-algebra datum defining this relative Proj.

            The projectivization itself is retained for every represented
            quasi-coherent sheaf. Materializing the symmetric algebra uses the
            affine module or selected finite-atlas presentation when one is
            available; that computational presentation is not defining data of
            the projectivization.
            """
            source_sheaf = self.projectivization_source_sheaf()
            source_scheme = source_sheaf.scheme()
            match source_scheme in Schemes(source_scheme.scheme_base_ring()).Affine():
                case True:
                    from dzack_research.preamble.categories.schemes.ringed_spaces import (
                        QuasiCoherentSheaves,
                    )

                    return QuasiCoherentSheaves(source_scheme).global_sections(
                        source_sheaf
                    ).symmetric_algebra()
                case False:
                    return _symmetric_algebra_descent(
                        _finite_atlas_module_datum(source_sheaf)
                    )

        @cached_method
        def projectivization_projection(self):
            source_scheme = self.projectivization_source_sheaf().scheme()
            return self.Mor(source_scheme)(
                lambda mor: _RelativeProjectivizationProjection(
                    mor,
                    self.projectivization_source_sheaf(),
                )
            )

        @cached_method
        def tautological_line_bundle(self):
            from dzack_research.preamble.categories.schemes.ringed_spaces import (
                QuasiCoherentSheaves,
            )

            category = QuasiCoherentSheaves(self)
            return category.object(
                categories=(category.Invertible(),),
                construction_data={"relative_projectivization": self},
                _engine=_RelativeProjectivizationTautologicalLineEngine,
            )

        @cached_method
        def pulled_source_sheaf(self):
            from dzack_research.preamble.categories.schemes.ringed_spaces import (
                QuasiCoherentSheaves,
            )

            return QuasiCoherentSheaves(self).object(
                construction_data={
                    "relative_projectivization": self,
                    "source_sheaf": self.projectivization_source_sheaf(),
                },
                _engine=_RelativeProjectivizationPulledSheafEngine,
            )

        @cached_method
        def universal_quotient(self):
            from dzack_research.preamble.categories.schemes.ringed_spaces import (
                QuasiCoherentSheaves,
            )

            line = self.tautological_line_bundle().module_sheaf()
            return QuasiCoherentSheaves(self).Mor(
                self.pulled_source_sheaf(),
                line,
            )(self)

        @cached_method(key=lambda self, ring_map: id(ring_map))
        def projectivization_base_change(self, ring_map):
            source_scheme = self.projectivization_source_sheaf().scheme()
            match source_scheme in Schemes(source_scheme.scheme_base_ring()).Affine():
                case True:
                    return GeneralProjectivizationBaseChangeComparison(self, ring_map)
                case False:
                    from dzack_research.preamble.categories.schemes.gluing import (
                        _finite_atlas_sheaf_placement,
                    )

                    match _finite_atlas_sheaf_placement(
                        self.projectivization_source_sheaf()
                    ):
                        case None:
                            return ExactProjectivizationBaseChangeComparison(
                                self,
                                ring_map,
                            )
                        case _:
                            return ExactFiniteAtlasProjectivizationBaseChangeComparison(
                                self,
                                ring_map,
                            )


def _ratio_name(module, denominator_label, numerator_label) -> str:
    ranking = module.module_generating_set().ranking_map()
    return (
        f"p{int(ranking(numerator_label))}_over_"
        f"p{int(ranking(denominator_label))}"
    )


def _chart_polynomial_algebra(module, chart_label):
    base = module.base_ring()
    labels = tuple(module.module_generating_set())
    names = tuple(
        _ratio_name(module, chart_label, label)
        for label in labels
        if label != chart_label
    )
    return base.free_module(names).symmetric_algebra()


def _chart_algebra(module, chart_label):
    r"""Return the degree-zero standard-open algebra on ``D_+(chart_label)``."""
    polynomial = _chart_polynomial_algebra(module, chart_label)
    labels = tuple(module.module_generating_set())
    ranking = module.module_generating_set().ranking_map()
    chart_position = int(ranking(chart_label))
    structure = polynomial.algebra_structure_morphism()
    relations = []
    if module in ModulesWithChosenFinitePresentation(module.base_ring()):
        matrix = module.presentation_matrix()
        for row in range(matrix.nrows()):
            relation = structure(module.base_ring()(matrix[row, chart_position]))
            for label in labels:
                if label == chart_label:
                    continue
                position = int(ranking(label))
                coefficient = module.base_ring()(matrix[row, position])
                if coefficient:
                    relation += structure(coefficient) * polynomial.algebra_generator(
                        _ratio_name(module, chart_label, label)
                    )
            if relation != polynomial.zero():
                relations.append(relation)
    return (
        polynomial
        if not relations
        else polynomial.quotient_by_relations(tuple(relations))
    )


def _chart_ratio(module, chart_algebra, denominator_label, numerator_label):
    if denominator_label == numerator_label:
        return chart_algebra.one()
    return chart_algebra.algebra_generator(
        _ratio_name(module, denominator_label, numerator_label)
    )


def _chart_transition(module, charts, source_label, target_label, scheme_base_ring):
    r"""Return the standard ratio-coordinate isomorphism on two Proj charts."""
    source_chart = charts[source_label]
    target_chart = charts[target_label]
    source_algebra = source_chart.coordinate_algebra()
    target_algebra = target_chart.coordinate_algebra()
    source_ratio = _chart_ratio(
        module, source_algebra, source_label, target_label
    )
    target_ratio = _chart_ratio(
        module, target_algebra, target_label, source_label
    )
    source_overlap = source_chart.distinguished_open(source_ratio)
    target_overlap = target_chart.distinguished_open(target_ratio)
    source_restriction = source_overlap.inclusion().coordinate_algebra_morphism()
    inverse_ratio = source_restriction(source_ratio).inverse_of_unit()

    images = {}
    for label in module.module_generating_set():
        if label == target_label:
            continue
        target_name = _ratio_name(module, target_label, label)
        images[target_name] = (
            inverse_ratio
            if label == source_label
            else source_restriction(
                _chart_ratio(module, source_algebra, source_label, label)
            )
            * inverse_ratio
        )
    into_source = target_algebra.Mor(source_overlap.coordinate_algebra())(images)
    pullback = target_overlap.coordinate_algebra().induced_morphism(into_source)
    forward = Schemes(scheme_base_ring).Mor(source_overlap, target_overlap)(pullback)

    target_restriction = target_overlap.inclusion().coordinate_algebra_morphism()
    inverse_target_ratio = target_restriction(target_ratio).inverse_of_unit()
    inverse_images = {}
    for label in module.module_generating_set():
        if label == source_label:
            continue
        source_name = _ratio_name(module, source_label, label)
        inverse_images[source_name] = (
            inverse_target_ratio
            if label == target_label
            else target_restriction(
                _chart_ratio(module, target_algebra, target_label, label)
            )
            * inverse_target_ratio
        )
    into_target = source_algebra.Mor(target_overlap.coordinate_algebra())(
        inverse_images
    )
    inverse_pullback = source_overlap.coordinate_algebra().induced_morphism(
        into_target
    )
    inverse = Schemes(scheme_base_ring).Mor(target_overlap, source_overlap)(
        inverse_pullback
    )
    return Schemes(scheme_base_ring).Core().Mor(
        source_overlap,
        target_overlap,
    )(forward, inverse)


def _linear_form_numerator(
    local_module,
    pair_module,
    image,
    projective_algebra,
    projective_chart_label,
):
    r"""Clear overlap denominators from one transported projective coordinate."""
    coefficients = pair_module.framing_coefficients(image)
    fraction_data = []
    for label, coefficient in coefficients.items():
        numerator, denominator = pair_module.base_ring().localization_fraction_data(
            coefficient
        )
        fraction_data.append((label, numerator, denominator))
    result = projective_algebra.zero()
    structure = projective_algebra.algebra_structure_morphism()
    for position, (label, numerator, _denominator) in enumerate(fraction_data):
        cofactor = local_module.base_ring().one()
        for other_position, (_other_label, _other_num, other_denominator) in enumerate(
            fraction_data
        ):
            match other_position == position:
                case True:
                    pass
                case False:
                    cofactor *= local_module.base_ring()(other_denominator)
        result += structure(local_module.base_ring()(numerator) * cofactor) * _chart_ratio(
            local_module,
            projective_algebra,
            projective_chart_label,
            label,
        )
    return result


def _pair_ring_map_to_projective_open(
    local_module,
    pair_module,
    projective_chart,
    projective_open,
):
    r"""Return ``O(U_ij) -> O(D_+(e_a) cap U_ij cap D(L))``."""
    chart_algebra = projective_chart.coordinate_algebra()
    into_open = projective_open.inclusion().coordinate_algebra_morphism()
    base_to_open = into_open * chart_algebra.algebra_structure_morphism()
    match pair_module.base_ring() is local_module.base_ring():
        case True:
            return base_to_open
        case False:
            return pair_module.base_ring().induced_morphism(base_to_open)


def _linear_form_on_projective_open(
    local_module,
    pair_module,
    image,
    projective_chart,
    projective_chart_label,
    projective_open,
):
    r"""Evaluate a transported module vector in the quotient chart trivialization."""
    target = projective_open.coordinate_algebra()
    pair_map = _pair_ring_map_to_projective_open(
        local_module,
        pair_module,
        projective_chart,
        projective_open,
    )
    restrict = projective_open.inclusion().coordinate_algebra_morphism()
    result = target.zero()
    for label, coefficient in pair_module.framing_coefficients(image).items():
        match label == projective_chart_label:
            case True:
                ratio = target.one()
            case False:
                ratio = restrict(
                    _chart_ratio(
                        local_module,
                        projective_chart.coordinate_algebra(),
                        projective_chart_label,
                        label,
                    )
                )
        result += pair_map(coefficient) * ratio
    return result


def _cross_projective_open(
    module_datum,
    projective_chart,
    source_index,
    source_chart_label,
    target_index,
    target_chart_label,
):
    r"""The source open where the target distinguished coordinate is nonzero."""
    atlas = module_datum.gluing_datum()
    local_module = module_datum.local_module(source_index)
    source_pair = module_datum.pair_module(source_index, target_index)
    target_pair = module_datum.pair_module(target_index, source_index)
    transition = module_datum.transition(source_index, target_index).pullback()
    image = transition(target_pair.module_generator(target_chart_label))
    numerator = _linear_form_numerator(
        local_module,
        source_pair,
        image,
        projective_chart.coordinate_algebra(),
        source_chart_label,
    )
    base_open = atlas.overlap(source_index, target_index)
    base_element = local_module.base_ring()(base_open.distinguished_open_element())
    projective_base_element = projective_chart.coordinate_algebra().algebra_structure_morphism()(
        base_element
    )
    return projective_chart.distinguished_open(projective_base_element * numerator)


def _cross_projective_chart_ring_map(
    module_datum,
    projective_charts,
    source_key,
    target_key,
    source_open,
):
    r"""Pull target ratio coordinates to one cross-base projective overlap."""
    source_index, source_chart_label = source_key
    target_index, target_chart_label = target_key
    atlas = module_datum.gluing_datum()
    source_local = module_datum.local_module(source_index)
    target_local = module_datum.local_module(target_index)
    source_pair = module_datum.pair_module(source_index, target_index)
    target_pair = module_datum.pair_module(target_index, source_index)
    transition = module_datum.transition(source_index, target_index).pullback()
    source_chart = projective_charts[source_key]
    target_chart = projective_charts[target_key]
    source_ring = source_open.coordinate_algebra()

    denominator = _linear_form_on_projective_open(
        source_local,
        source_pair,
        transition(target_pair.module_generator(target_chart_label)),
        source_chart,
        source_chart_label,
        source_open,
    )
    denominator_inverse = denominator.inverse_of_unit()

    pair_to_source = _pair_ring_map_to_projective_open(
        source_local,
        source_pair,
        source_chart,
        source_open,
    )
    base_transition = atlas.transition_between(
        source_index, target_index
    ).forward().coordinate_algebra_morphism()
    target_overlap_restriction = atlas.overlap(
        target_index, source_index
    ).inclusion().coordinate_algebra_morphism()
    coefficient_map = pair_to_source * base_transition * target_overlap_restriction
    target_view = coefficient_map.as_algebra()

    generator_images = {}
    for label in target_local.module_generating_set():
        match label == target_chart_label:
            case True:
                continue
            case False:
                pass
        image = transition(target_pair.module_generator(label))
        linear_form = _linear_form_on_projective_open(
            source_local,
            source_pair,
            image,
            source_chart,
            source_chart_label,
            source_open,
        )
        generator_images[
            _ratio_name(target_local, target_chart_label, label)
        ] = target_view(linear_form * denominator_inverse)

    target_algebra = target_chart.coordinate_algebra()
    algebra_map = (
        Algebras(target_local.base_ring())
        .Associative()
        .Unital()
        .Mor(target_algebra, target_view)(generator_images)
    )
    return OwnedRings().Mor(target_algebra, source_ring).elementwise(
        lambda element: source_ring(algebra_map(target_algebra(element)))
    )


def _cross_projective_transition(
    module_datum,
    projective_charts,
    source_key,
    target_key,
    scheme_base_ring,
):
    r"""Return the projective transition induced by one semilinear module isomorphism."""
    source_index, source_chart_label = source_key
    target_index, target_chart_label = target_key
    source_chart = projective_charts[source_key]
    target_chart = projective_charts[target_key]
    source_open = _cross_projective_open(
        module_datum,
        source_chart,
        source_index,
        source_chart_label,
        target_index,
        target_chart_label,
    )
    target_open = _cross_projective_open(
        module_datum,
        target_chart,
        target_index,
        target_chart_label,
        source_index,
        source_chart_label,
    )
    to_source = _cross_projective_chart_ring_map(
        module_datum,
        projective_charts,
        source_key,
        target_key,
        source_open,
    )
    forward_pullback = target_open.coordinate_algebra().induced_morphism(to_source)
    forward = Schemes(scheme_base_ring).Mor(source_open, target_open)(
        forward_pullback
    )
    to_target = _cross_projective_chart_ring_map(
        module_datum,
        projective_charts,
        target_key,
        source_key,
        target_open,
    )
    inverse_pullback = source_open.coordinate_algebra().induced_morphism(to_target)
    inverse = Schemes(scheme_base_ring).Mor(target_open, source_open)(
        inverse_pullback
    )
    return Schemes(scheme_base_ring).Core().Mor(source_open, target_open)(
        forward,
        inverse,
    )


def _chart_base_change_pullback(source_chart, target_chart, ring_map):
    r"""Return ``O(source_chart) -> O(target_chart)`` for coefficient base change.

    The intermediate scalar extension is owned by the algebra base-change
    adjunction.  Its ratio generators map to the identically labelled ratio
    generators of the projectivization constructed from the base-changed
    module; this is the standard ``Proj(Sym(M))`` base-change comparison.
    """
    source = source_chart.coordinate_algebra()
    target = target_chart.coordinate_algebra()
    algebras = Algebras(source.base_ring()).Associative().Unital().Commutative()
    adjunction = algebras.base_change_adjunction(ring_map)
    extended = adjunction.left_adjoint()(source)
    unit = adjunction.unit(source)
    target_algebras = Algebras(target.base_ring()).Associative().Unital().Commutative()
    if extended is target:
        comparison = target_algebras.Mor(target, target).identity()
    else:
        source_labels = extended.algebra_generating_set()
        target_labels = target.algebra_generating_set()
        if source_labels != target_labels:
            raise ValueError(
                "projectivization base change must preserve the standard ratio generators"
            )
        comparison = target_algebras.Mor(extended, target)(
            {
                label: target.algebra_generator(label)
                for label in source_labels
            }
        )

    def image(element):
        restricted_value = unit(source(element))
        return target(comparison(extended(restricted_value)))

    return OwnedRings().Mor(source, target).elementwise(image)


class AffineProjectivizationBaseChangeComparison(SageObject):
    r"""The represented base-change square for one affine projectivization."""

    def __init__(self, projectivization, ring_map) -> None:
        self._projectivization = projectivization
        self._ring_map = ring_map
        source_sheaf = projectivization.projectivization_source_sheaf()
        source_scheme = source_sheaf.scheme()
        source_module = projectivization.projectivization_module()
        if ring_map.domain() is not source_module.base_ring():
            raise ValueError(
                "projectivization base change starts at the affine source coordinate ring"
            )
        changed_ring = ring_map.codomain()
        changed_scheme = changed_ring.affine_spectrum(
            base_ring=source_scheme.scheme_base_ring()
        )
        changed_module = source_module.base_change(ring_map)
        changed_sheaf = changed_scheme.associated_module_sheaf(changed_module)
        changed_family = changed_sheaf.projectivization()
        changed_total = changed_family.arrow().domain()

        source_atlas = projectivization.finite_affine_atlas()
        changed_atlas = changed_total.finite_affine_atlas()
        if source_atlas.chart_index_set() != changed_atlas.chart_index_set():
            raise ValueError(
                "projectivization base change must retain the standard chart index set"
            )
        local_maps = finite_indexed_family(
            changed_atlas.chart_index_set(),
            lambda label: source_atlas.chart_embedding(label)
            * _affine_morphism_from_pullback(
                changed_atlas.chart(label),
                source_atlas.chart(label),
                _chart_base_change_pullback(
                    source_atlas.chart(label),
                    changed_atlas.chart(label),
                    ring_map,
                ),
            ),
            name="Chart maps of projectivization base change",
        )
        to_original = changed_total.Mor(projectivization)(local_maps)
        base_morphism = _affine_morphism_from_pullback(
            changed_scheme,
            source_scheme,
            ring_map,
        )
        changed_projection = changed_family.arrow()
        if (
            projectivization.projectivization_projection() * to_original
            != base_morphism * changed_projection
        ):
            raise ArithmeticError(
                "the projectivization base-change comparison does not commute over the affine base"
            )

        self._changed_source_sheaf = changed_sheaf
        self._changed_projectivization = changed_family
        self._base_morphism = base_morphism
        self._projection_to_original = to_original

    def projectivization(self):
        return self._projectivization

    def ring_map(self):
        return self._ring_map

    def base_morphism(self):
        return self._base_morphism

    def changed_source_sheaf(self):
        return self._changed_source_sheaf

    def changed_projectivization(self):
        return self._changed_projectivization

    def projection_to_original(self):
        r"""Return ``P(F_A') -> P(F)`` in the base-change square."""
        return self._projection_to_original

    def projection_to_changed_base(self):
        r"""Return ``P(F_A') -> Spec(A')`` in the base-change square."""
        return self.changed_projectivization().arrow()

    def universal_quotient(self):
        r"""Return the universal quotient on the base-changed projectivization."""
        return self.changed_projectivization().arrow().domain().universal_quotient()


class _AffineProjectivizationSchemeEngine:
    r"""The retained relative-Proj data on the glued standard-open scheme."""

    def __init__(
        self,
        projectivization_source_sheaf,
        projectivization_module,
        projectivization_symmetric_algebra,
        **rest,
    ) -> None:
        self._projectivization_module = projectivization_module
        self._projectivization_symmetric_algebra = projectivization_symmetric_algebra
        super().__init__(
            projectivization_source_sheaf=projectivization_source_sheaf,
            **rest,
        )

    def projectivization_module(self):
        return self._projectivization_module

    def symmetric_algebra(self):
        return self._projectivization_symmetric_algebra

    @cached_method
    def projectivization_projection(self):
        r"""Return ``pi : P(M~) -> Spec(A)`` from the chart algebra structures."""
        base_scheme = self.projectivization_source_sheaf().scheme()
        datum = self.gluing_datum()
        local_maps = finite_indexed_family(
            datum.chart_index_set(),
            lambda label: _affine_morphism_from_pullback(
                datum.chart(label),
                base_scheme,
                datum.chart(label).coordinate_algebra().algebra_structure_morphism(),
            ),
            name="Relative-projectivization chart maps to the base",
        )
        return self.Mor(base_scheme)(local_maps)

    @cached_method
    def tautological_line_bundle(self):
        r"""Return ``O_{P(M)}(1)`` on the selected standard affine atlas."""
        from dzack_research.preamble.categories.schemes.ringed_spaces import (
            QuasiCoherentSheaves,
        )

        atlas = self.finite_affine_atlas()
        module = self.projectivization_module()
        units = {}
        for source_label, target_label in atlas.transition_index_set():
            overlap = atlas.overlap(source_label, target_label)
            restriction = overlap.inclusion().coordinate_algebra_morphism()
            units[source_label, target_label] = restriction(
                _chart_ratio(
                    module,
                    atlas.chart(source_label).coordinate_algebra(),
                    source_label,
                    target_label,
                )
            )
        return (
            QuasiCoherentSheaves(self)
            .Invertible()
            .WithChosenTrivialization()(atlas, units)
        )

    @cached_method
    def pulled_source_sheaf(self):
        r"""Return the represented pullback ``pi^*M~`` on the standard atlas."""
        from dzack_research.preamble.categories.schemes.gluing import (
            FiniteAtlasModuleGluingData,
        )

        atlas = self.finite_affine_atlas()
        module = self.projectivization_module()
        fibered = ModulesOverCommutativeRings()
        local_modules = {
            label: fibered.cocartesian_transport(
                atlas.chart(label).coordinate_algebra().algebra_structure_morphism()
            )(module)
            for label in atlas.chart_indices()
        }

        def identity_images(label, _domain, codomain):
            return codomain.module_generator(label)

        transitions = {
            pair: (identity_images, identity_images)
            for pair in atlas.transition_index_set()
        }
        return FiniteAtlasModuleGluingData(atlas)(
            local_modules,
            transitions,
        ).sheaf()

    @cached_method
    def universal_quotient(self):
        r"""Return the universal quotient ``pi^*M~ -> O(1)`` as a QCoh morphism."""
        from dzack_research.preamble.categories.schemes.ringed_spaces import (
            QuasiCoherentSheaves,
        )

        atlas = self.finite_affine_atlas()
        module = self.projectivization_module()
        pulled = self.pulled_source_sheaf()
        line_bundle = self.tautological_line_bundle()
        line = line_bundle.module_sheaf()
        source_datum = pulled.gluing_datum()
        target_datum = line.gluing_datum()

        local_maps = {}
        for chart_label in atlas.chart_indices():
            source = source_datum.local_module(chart_label)
            target = target_datum.local_module(chart_label)
            basis_label = next(iter(target.module_generating_set()))
            basis = target.module_generator(basis_label)
            chart_algebra = atlas.chart(chart_label).coordinate_algebra()
            local_maps[chart_label] = source.module_category().Mor(source, target)(
                {
                    label: target.scalar_multiple(
                        _chart_ratio(module, chart_algebra, chart_label, label),
                        basis,
                    )
                    for label in module.module_generating_set()
                }
            )
        return QuasiCoherentSheaves(self).Mor(pulled, line)(local_maps)

    @cached_method(key=lambda self, ring_map: id(ring_map))
    def projectivization_base_change(self, ring_map):
        r"""Return the represented affine base-change comparison along ``ring_map``."""
        return AffineProjectivizationBaseChangeComparison(self, ring_map)

    @cached_method
    def projective_space_comparison(self, projective_space=None):
        r"""Identify this quotient projectivization with ``P^(r-1)`` in the free base-point case."""
        from dzack_research.preamble.categories.schemes.schemes import ProjectiveSpaces

        module = self.projectivization_module()
        base = self.projectivization_source_sheaf().scheme().scheme_base_ring()
        match projective_space:
            case None:
                projective_space = ProjectiveSpaces(base)(
                    int(module.module_generating_set().cardinality().finite_value()) - 1
                )
            case _:
                pass
        return _free_projectivization_projective_space_comparison(
            self,
            projective_space,
        )


class FiniteAtlasProjectivizationBaseChangeComparison(SageObject):
    r"""Base change of a finite-atlas relative projectivization.

    This comparison uses the scalar base change already represented for the
    base scheme and transports the selected affine-atlas module descent across
    its chart maps.  Projective, multiprojective, and finite-affine-gluing base
    schemes therefore all enter through the common scheme base-change functor;
    this constructor adds only the module descent and relative-Proj comparison.
    """

    def __init__(self, projectivization, ring_map) -> None:
        self._projectivization = projectivization
        self._ring_map = ring_map
        source_sheaf = projectivization.projectivization_source_sheaf()
        source_scheme = source_sheaf.scheme()
        match ring_map.domain() is source_scheme.scheme_base_ring():
            case True:
                pass
            case False:
                raise ValueError(
                    "finite-atlas projectivization scalar base change starts at the scheme base ring"
                )
        changed_base = source_scheme.base_change(ring_map)
        changed_atlas = changed_base.selected_finite_affine_atlas()
        changed_datum = _base_changed_finite_atlas_module_datum(
            projectivization.projectivization_module_datum(),
            changed_atlas,
            ring_map,
        )
        changed_sheaf = changed_datum.sheaf()
        changed_family = changed_sheaf.projectivization()
        changed_total = changed_family.arrow().domain()

        source_base_atlas = projectivization.projectivization_module_datum().gluing_datum()
        source_total_atlas = projectivization.finite_affine_atlas()
        changed_total_atlas = changed_total.finite_affine_atlas()
        match source_total_atlas.chart_index_set() == changed_total_atlas.chart_index_set():
            case True:
                pass
            case False:
                raise ValueError(
                    "finite-atlas projectivization base change must retain the Proj chart index set"
                )

        def local_total_projection(role):
            source_index, _module_label = role
            chart_ring_map = _chart_base_change_pullback(
                source_base_atlas.chart(source_index),
                changed_atlas.chart(source_index),
                ring_map,
            )
            source_chart = source_total_atlas.chart(role)
            changed_chart = changed_total_atlas.chart(role)
            pullback = _chart_base_change_pullback(
                source_chart,
                changed_chart,
                chart_ring_map,
            )
            into_source_chart = _affine_morphism_from_pullback(
                changed_chart,
                source_chart,
                pullback,
            )
            return source_total_atlas.chart_embedding(role) * into_source_chart

        total_projection = changed_total.Mor(projectivization)(
            finite_indexed_family(
                changed_total_atlas.chart_index_set(),
                local_total_projection,
                name="Chart maps of finite-atlas projectivization base change",
            )
        )
        base_projection = changed_base.left_projection()
        match (
            projectivization.projectivization_projection() * total_projection
            == base_projection * changed_total.projectivization_projection()
        ):
            case True:
                pass
            case False:
                raise ArithmeticError(
                    "the finite-atlas projectivization base-change square does not commute"
                )

        self._changed_base = changed_base
        self._changed_atlas = changed_atlas
        self._changed_module_datum = changed_datum
        self._changed_source_sheaf = changed_sheaf
        self._changed_projectivization = changed_family
        self._base_projection = base_projection
        self._total_projection = total_projection

    def projectivization(self):
        return self._projectivization

    def ring_map(self):
        return self._ring_map

    def changed_base_scheme(self):
        return self._changed_base

    def changed_atlas(self):
        return self._changed_atlas

    def changed_module_datum(self):
        return self._changed_module_datum

    def changed_source_sheaf(self):
        return self._changed_source_sheaf

    def changed_projectivization(self):
        return self._changed_projectivization

    def base_projection(self):
        return self._base_projection

    def total_projection(self):
        return self._total_projection

    def projection_to_changed_base(self):
        return self.changed_projectivization().arrow()

