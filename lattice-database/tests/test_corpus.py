"""A corpus is valid exactly when the tags, families and file names that its records name exist and are unique."""

from pathlib import Path

import pytest
import yaml
from latticedb import corpus, records
from latticedb.model import Yaml


def rank_one(tag: str) -> dict[str, Yaml]:
    """The lattice <1> of rank 1 with b(e_1, e_1) = 1: its two vectors of norm 1 are roots of type A1 at scale 1/2."""
    return {
        "tag": tag,
        "name": "<1>",
        "latex": r"\langle 1 \rangle",
        "rank": 1,
        "gram_tensor": [[1]],
        "signature": [1, 0],
        "determinant": 1,
        "definiteness": "positive_definite",
        "integral": {"parity": "odd", "discriminant_group": [], "overlattice_count": 1},
        "definite": {
            "minimum": 1,
            "kissing_number": 2,
            "theta_series": [1, 2, 0, 0, 2, 0, 0, 0, 0, 2, 0, 0, 0],
            "root_system": [],
            "roots": [{"type": "A1", "scale": "1/2", "simple_roots": [[1]]}],
        },
        "root_sublattice": {"invariant_factors": [1], "norms": [1]},
    }


def hyperbolic_plane(summands: list[dict[str, str | int]]) -> dict[str, Yaml]:
    """U with its roots (1, 1) and (1, -1), which have b(r, r) = 2 and b(r, r) = -2 and are orthogonal: they generate <1>(2) + <1>(-2)."""
    return {
        "tag": "0016",
        "name": "U",
        "latex": "U",
        "rank": 2,
        "gram_tensor": [[0, 1], [1, 0]],
        "signature": [1, 1],
        "determinant": -1,
        "definiteness": "indefinite",
        "integral": {"parity": "even", "discriminant_group": [], "overlattice_count": 1, "delta": 0},
        "indefinite": {"isotropic": True},
        "root_span": {"roots": [[1, 1], [1, -1]], "norms": [2, -2], "summands": summands, "embedding": [[1, 1], [1, -1]]},
        "root_sublattice": {"invariant_factors": [1, 2]},
    }


FAMILIES = {"root-lattice": "Generated by its roots.", "even-unimodular": "Even, of determinant $\\pm 1$."}
RETIRED = {"000Z": "<3> = <1>(3)"}


def write(root: Path, *records: dict[str, Yaml]) -> Path:
    """A corpus under `root`: the records under `lattices/`, `FAMILIES` as its families and `RETIRED` as its retired tags."""
    (root / corpus.FAMILIES_FILE).write_text(yaml.safe_dump(FAMILIES))
    (root / corpus.RETIRED_FILE).write_text(yaml.safe_dump(RETIRED))
    (root / "lattices").mkdir()
    for record in records:
        (root / "lattices" / f"{record['tag']}.md").write_text("---\n" + yaml.safe_dump(record) + "---\n\nA test record.\n")
    return root


def test_a_root_span_is_accepted_when_its_embedding_has_the_gram_tensor_of_the_sum_of_its_summands(tmp_path: Path) -> None:
    directory = write(tmp_path, rank_one("0001"), hyperbolic_plane([{"tag": "0001", "scale": 2}, {"tag": "0001", "scale": -2}]))
    assert [entry.lattice.tag for entry in corpus.load(directory).entries] == ["0001", "0016"]


def test_a_root_span_is_rejected_when_a_summand_is_not_a_record_of_the_corpus(tmp_path: Path) -> None:
    directory = write(tmp_path, rank_one("0001"), hyperbolic_plane([{"tag": "0001", "scale": 2}, {"tag": "0008", "scale": -2}]))
    with pytest.raises(corpus.CorpusInvalid) as raised:
        corpus.load(directory)
    assert len(raised.value.problems) == 1


def test_a_record_is_accepted_when_each_of_its_families_is_listed_and_rejected_when_one_is_not(tmp_path: Path) -> None:
    listed = rank_one("0001") | {"families": ["root-lattice", "even-unimodular"]}
    plane = hyperbolic_plane([{"tag": "0001", "scale": 2}, {"tag": "0001", "scale": -2}]) | {"families": ["root-lattice"]}
    directory = write(tmp_path, listed, plane)
    assert [entry.lattice.families for entry in corpus.load(directory).entries] == [("root-lattice", "even-unimodular"), ("root-lattice",)]

    unlisted = rank_one("0001") | {"families": ["root-lattice", "hexagonal", "laminated"]}
    (directory / "lattices" / "0001.md").write_text("---\n" + yaml.safe_dump(unlisted) + "---\n\nA test record.\n")
    with pytest.raises(corpus.CorpusInvalid) as raised:
        corpus.load(directory)
    assert len(raised.value.problems) == 2


def test_a_record_cannot_take_a_retired_tag_and_the_next_tag_counts_the_retired_ones(tmp_path: Path) -> None:
    directory = write(tmp_path, rank_one("0001"))
    loaded = corpus.load(directory)
    assert loaded.retired == RETIRED
    assert corpus.next_tag(loaded) == "0010"

    (directory / "lattices" / "000Z.md").write_text("---\n" + yaml.safe_dump(hyperbolic_plane([]) | {"tag": "000Z"}) + "---\n\nA test record.\n")
    with pytest.raises(corpus.CorpusInvalid) as raised:
        corpus.load(directory)
    assert [problem for problem in raised.value.problems if "000Z" in problem and "retired" in problem]


def test_the_families_file_is_read_as_one_line_of_meaning_per_family(tmp_path: Path) -> None:
    directory = write(tmp_path, rank_one("0002"))
    assert corpus.load(directory).families == FAMILIES

    (directory / corpus.FAMILIES_FILE).write_text(yaml.safe_dump({"Root Lattice": "A family whose name is not lower-case with hyphens."}))
    with pytest.raises(corpus.CorpusInvalid) as raised:
        corpus.load(directory)
    assert len(raised.value.problems) == 1


def square_sum() -> dict[str, Yaml]:
    """<1> + <1>, with the fields that its Gram tensor determines computed by `records.derive`."""
    declared: dict[str, Yaml] = {"tag": "0002", "name": "<1>^2", "latex": r"\langle 1 \rangle^2", "gram_tensor": [[1, 0], [0, 1]]}
    return records.derive(declared)


def write_morphisms(root: Path, source: str, target: str, morphisms: list[dict[str, Yaml]], stem: str | None = None) -> Path:
    """The file `morphisms/<stem>.md` under `root`, with `<source>-<target>` as the stem unless another is given."""
    (root / "morphisms").mkdir(exist_ok=True)
    (root / "morphisms" / f"{stem or f'{source}-{target}'}.md").write_text(records.morphisms_text(source, target, morphisms, "Test morphisms."))
    return root


VALID_U = [{"tag": "0001", "scale": 2}, {"tag": "0001", "scale": -2}]


def morphism_problems(tmp_path: Path, source: str, target: str, morphisms: list[dict[str, Yaml]], stem: str | None = None) -> tuple[str, ...]:
    directory = write_morphisms(write(tmp_path, rank_one("0001"), square_sum(), hyperbolic_plane(VALID_U)), source, target, morphisms, stem)
    with pytest.raises(corpus.CorpusInvalid) as raised:
        corpus.load(directory)
    return raised.value.problems


def test_the_identity_and_the_exchange_of_e_and_f_are_morphisms_of_u(tmp_path: Path) -> None:
    morphisms: list[dict[str, Yaml]] = [{"name": "identity", "matrix": [[1, 0], [0, 1]]}, {"name": "exchange", "matrix": [[0, 1], [1, 0]]}]
    directory = write_morphisms(write(tmp_path, rank_one("0001"), hyperbolic_plane(VALID_U)), "0016", "0016", morphisms)
    (loaded,) = corpus.load(directory).morphisms
    assert [morphism.name for morphism in loaded.morphisms.morphisms] == ["identity", "exchange"]


def test_an_embedding_of_u_bounds_the_hyperbolic_index_from_below(tmp_path: Path) -> None:
    identity: list[dict[str, Yaml]] = [{"name": "identity", "matrix": [[1, 0], [0, 1]]}]
    directory = write_morphisms(write(tmp_path, rank_one("0001"), hyperbolic_plane(VALID_U)), "0016", "0016", identity)
    loaded = corpus.load(directory)
    assert corpus.hyperbolic_index_bounds(loaded.morphisms, loaded.entries) == {"0016": 1}


def test_a_hyperbolic_index_below_an_embedding_of_u_is_refused(tmp_path: Path) -> None:
    plane = hyperbolic_plane(VALID_U)
    plane["integral"] = {"parity": "even", "discriminant_group": [], "overlattice_count": 1, "delta": 0, "hyperbolic_index": 0}
    identity: list[dict[str, Yaml]] = [{"name": "identity", "matrix": [[1, 0], [0, 1]]}]
    directory = write_morphisms(write(tmp_path, rank_one("0001"), plane), "0016", "0016", identity)
    with pytest.raises(corpus.CorpusInvalid) as raised:
        corpus.load(directory)
    assert raised.value.problems == ("0016: integral.hyperbolic_index is 0, and a morphism file embeds U^1 into it",)


def test_the_inclusion_of_a_summand_is_a_morphism_whose_lines_cut_orthogonal_summands(tmp_path: Path) -> None:
    morphisms: list[dict[str, Yaml]] = [{"name": "first summand", "matrix": [[1], [0]], "row_subdivisions": [1]}]
    directory = write_morphisms(write(tmp_path, rank_one("0001"), square_sum()), "0001", "0002", morphisms)
    (loaded,) = corpus.load(directory).morphisms
    assert loaded.morphisms.morphisms[0].images == ((1, 0),)


def test_a_morphism_file_is_rejected_when_a_tag_is_not_in_the_corpus_or_is_retired(tmp_path: Path) -> None:
    problems = morphism_problems(tmp_path, "0003", "000Z", [{"name": "identity", "matrix": [[1]]}])
    assert sorted(problems) == sorted(
        [
            f"{tmp_path / 'morphisms' / '0003-000Z.md'}: the tag 0003 is not in the corpus",
            f"{tmp_path / 'morphisms' / '0003-000Z.md'}: the tag 000Z is retired ({RETIRED['000Z']})",
        ]
    )


def test_a_morphism_file_is_rejected_when_its_name_is_not_source_dash_target(tmp_path: Path) -> None:
    (problem,) = morphism_problems(tmp_path, "0016", "0016", [{"name": "identity", "matrix": [[1, 0], [0, 1]]}], stem="0016-0001")
    assert "the file name must be 0016-0016" in problem
