r"""Finite quotients of the absolute Galois group of $\mathbf{F}_5$."""

from dzack_research.preamble.all import *  # noqa: F401,F403


def test_frobenius_generates_each_finite_galois_group_of_f5() -> None:
    r"""$\operatorname{Gal}(\mathbf{F}_{5^n}/\mathbf{F}_5)$ is cyclic of order $n$, generated by Frobenius."""
    group = GF(5).absolute_galois_group()
    frobenius = group.frobenius()

    for degree in (2, 3, 4):
        stage = group.finite_extension(degree)
        quotient = group.finite_quotient(stage)
        image = group.restriction_map(stage)(frobenius)
        assert quotient.order() == degree
        assert image.multiplicative_order() == degree
