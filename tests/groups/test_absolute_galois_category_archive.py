r"""The absolute Galois group of a finite field is procyclic, generated by Frobenius $x \mapsto x^q$."""

from dzack_research.preamble.all import *  # noqa: F401,F403


def test_the_frobenius_of_f25_is_the_25th_power_not_the_fifth() -> None:
    r"""For $q = 25$, $\mathrm{Frob}(x) = x^{25}$; on a generator $g$ of $\mathbb{F}_{25}^\times$ (order $24$), $g^{25} = g \ne g^5$."""
    field = GF(25, "a")
    group = field.absolute_galois_group()
    generator = group.base_embedding()(field.multiplicative_generator())
    frobenius = group.frobenius()

    assert group.base_field_order() == 25
    assert frobenius(generator) == generator**25
    assert frobenius(generator) == generator
    assert frobenius(generator) != generator**5


def test_every_finite_quotient_of_the_galois_group_of_f5_is_cyclic_generated_by_frobenius() -> None:
    r"""$G_{\mathbb{F}_5} \cong \widehat{\mathbb{Z}}$: infinite, abelian, and $\operatorname{Gal}(\mathbb{F}_{5^n}/\mathbb{F}_5)$ is cyclic of order $n$ generated by the image of Frobenius.

    Source: Serre, *Local Fields*, XIII §1.
    """
    group = GF(5).absolute_galois_group()
    frobenius = group.frobenius()

    assert not group.is_finite()
    assert group.is_abelian()
    for degree in (2, 3, 6):
        stage = group.finite_extension(degree)
        assert group.finite_quotient(stage).order() == degree
        assert group.restriction_map(stage)(frobenius).multiplicative_order() == degree
