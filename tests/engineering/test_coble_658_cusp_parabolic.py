"""Acceptance gate for the cusp part of research#658 item 1e.

The reflective part of the Coble monodromy is in ker(rho_{T_Co}); the other part is the unipotent
monodromy at the cusps.  computations/reports/coble_658-cusp-parabolic-probe.py verifies, from the cusp
data as the book states it --

  0-cusp vector v_1 = e', and the 1-cusp plane <v_1, v_2> with v_2 = 2h + a_1 + a_3,
  both isotropic and orthogonal (lem:divisibilityTcoOne, lem:1_cusp_correspondence) --

that the transvections tau_{cusp, x} for x isotropic and orthogonal to the cusp vector are integral
isometries acting trivially on A_{T_Co}: 16 of them, with a control element that acts non-trivially.

So every kind of monodromy element of this family is verified to lie in the discriminant kernel, and item
1e holds for any subgroup generated by them.  Whether Gamma_Co is such a subgroup -- the index
[Gamma_Co : W(T_Co)] together with the parabolic generation -- remains open, and the transcript says so
rather than implying more.

The RED test: no page records this, so the test asserting that one does is strict xfail.

Run standalone (``python3 tests/engineering/test_coble_658_cusp_parabolic.py``) or under pytest.
"""

from __future__ import annotations

import contextlib
import io
import pathlib

try:                                        # pytest marks the red item; standalone prints it as RED
    import pytest
except ImportError:                         # pragma: no cover
    pytest = None


ROOT = pathlib.Path(__file__).resolve().parents[2]
PROBE = ROOT / "computations/reports/coble_658-cusp-parabolic-probe.py"
TRANSCRIPT = ROOT / "computations/reports/coble_658-cusp-parabolic-probe-run.txt"
RED_NAME = "test_the_cusp_parabolic_record_is_on_a_page"


def _red(fn):
    if pytest is None:
        return fn
    return pytest.mark.xfail(
        strict=True,
        reason="research#658 item 1e: the cusp monodromies are Eichler transvections and lie in "
               "ker(rho_{T_Co}); no page records it. Remove this marker when one does.",
    )(fn)


def test_the_transcript_is_the_script_output():
    ns = {}
    exec(compile(PROBE.read_text(encoding="utf-8"), str(PROBE), "exec"), ns)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ns["main"]()
    assert buf.getvalue() == TRANSCRIPT.read_text(encoding="utf-8")


def test_the_cusp_data_is_as_the_book_states_it():
    out = TRANSCRIPT.read_text(encoding="utf-8")
    assert "0-cusp vector v_1 = e':   square 0" in out
    assert "1-cusp plane <v_1, v_2>:   v_1.v_2 = 0, v_2^2 = 0" in out


def test_the_cusp_transvections_lie_in_the_kernel():
    out = TRANSCRIPT.read_text(encoding="utf-8")
    assert "transvections tau_{cusp, x} with x orthogonal to the cusp vector: 16 checked" in out
    assert "all integral isometries and all acting trivially on A_{T_Co}" in out
    assert "control, the swap e' <-> f': isometry True, acts trivially on A_{T_Co} False" in out


def test_the_verdict_does_not_overclaim():
    out = TRANSCRIPT.read_text(encoding="utf-8")
    assert "Item 1e therefore holds for any subgroup generated by them" in out
    assert "open at" in out and "@qst:gamma-co-generators" in out


@_red
def test_the_cusp_parabolic_record_is_on_a_page():
    """Red until a page records that the cusp monodromy of the Coble family lies in the discriminant kernel."""
    # the recorded sentence must say all three parts: that the element is a cusp transvection AND that it
    # acts trivially on A_{T_Co}.  A line that mentions a cusp and a transvection does not carry it.
    for path in sorted((ROOT / "writing").rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if "cusp" not in line.lower() or "transvection" not in line:
                continue
            if "A_{T_\\Co}" in line and ("trivial" in line or "kernel" in line):
                return
    raise AssertionError(
        "no page records that the unipotent monodromy at the Coble cusps is an Eichler transvection and "
        "acts trivially on A_{T_Co}"
    )


def _run_all() -> int:
    items = [(name, fn) for name, fn in sorted(globals().items())
             if name.startswith("test_") and callable(fn)]
    failures = 0
    for name, fn in items:
        try:
            fn()
        except AssertionError as exc:
            if name == RED_NAME:
                print(f"RED  {name}: {exc}")
                continue
            failures += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"\n{len(items) - failures}/{len(items)} checks pass (1 red expected: the cusp parabolic record)")
    return failures


if __name__ == "__main__":
    raise SystemExit(1 if _run_all() else 0)
