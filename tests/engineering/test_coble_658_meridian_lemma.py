"""Red test first: the meridian lemma is not on any page.

LEMMA (meridian lemma).  Let L be an integral lattice with discriminant group A = L^v/L and
rho: O(L) -> O(A) the discriminant representation.  If Gamma <= O(L) is generated by elements of the two
forms

   (i)  a reflection s_d in a vector d of square -2,
   (ii) an Eichler transvection tau_{u,v}(x) = x + (x.u)v - (x.v)u with u, v isotropic and (u,v) = 0,

then Gamma <= ker(rho).  Consequently, for Gamma = Gamma_Co and L = T_Co, the sign lemma turns this into
Gamma_Co <= O~+(T_Co), and prop:gamma-co-strong-lifting gives the Gamma_Co form of the lifting.

Both forms satisfy g(x) - x in L for x in L^v: s_d(x) - x = (x,d)d and tau_{u,v}(x) - x = (x.u)v - (x.v)u,
with (x, L) in Z.  So each generator acts trivially on A, and a generating set of trivial elements
generates a subgroup on which rho is trivial.

This test is RED because no page of writing/ states the lemma.  It is strict xfail: it goes green when a
page states it, and fails loudly if the marker is left behind after that.
"""

from __future__ import annotations

import pathlib

try:
    import pytest
except ImportError:                         # pragma: no cover
    pytest = None


ROOT = pathlib.Path(__file__).resolve().parents[2]
RED_NAME = "test_the_meridian_lemma_is_on_a_page"


def _red(fn):
    if pytest is None:
        return fn
    return pytest.mark.xfail(
        strict=True,
        reason="research#658 item 1e: the meridian lemma -- a subgroup generated by (-2)-reflections and "
               "Eichler transvections lies in ker(rho) -- is proved here and in "
               "computations/reports/coble_658-meridian-lemma-probe-run.txt, but no page states it. "
               "Remove this marker when one does.",
    )(fn)


@_red
def test_the_meridian_lemma_is_on_a_page():
    for path in sorted((ROOT / "writing").rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if "transvection" in line and "kernel" in line and "generated" in line:
                if "(x.u)v" in line or "(x\\\\cdot u)v" in line or "x + (x" in line:
                    return
    raise AssertionError(
        "no page states the meridian lemma: a subgroup generated by (-2)-reflections and Eichler "
        "transvections lies in the discriminant kernel, so Gamma_Co does once it is so generated"
    )


def test_the_smallest_case_is_verified_by_the_probe():
    """The lemma's smallest case: T_Co, d = h + a_1, tau_{e',v} with v = 2h + a_1 + a_3."""
    probe = ROOT / "computations/reports/coble_658-meridian-lemma-probe.py"
    transcript = (ROOT / "computations/reports/coble_658-meridian-lemma-probe-run.txt").read_text(encoding="utf-8")
    import contextlib
    import io
    ns = {}
    exec(compile(probe.read_text(encoding="utf-8"), str(probe), "exec"), ns)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ns["main"]()
    assert buf.getvalue() == transcript
    assert "d = h + a_1:  d^2 = -2" in transcript
    assert "s_d        integral True  isometry True  g(x)-x in L on the dual generators True" in transcript
    assert "tau_{u,v}  integral True  isometry True  g(x)-x in L on the dual generators True" in transcript
    assert "verdict: the meridian lemma is PROVED" in transcript


def _run_all() -> int:
    items = [(name, fn) for name, fn in sorted(globals().items())
             if name.startswith("test_") and callable(fn)]
    failures = 0
    for name, fn in items:
        try:
            fn()
        except AssertionError as exc:
            if name == RED_NAME:
                print(f"RED  {name}: {exc}")
                continue
            failures += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"\n{len(items) - failures}/{len(items)} checks pass (1 red expected: the meridian lemma)")
    return failures


if __name__ == "__main__":
    raise SystemExit(1 if _run_all() else 0)
