"""Acceptance gate for research#671 (A28), the increment on Target theorem A clause three.

The issue's acceptance is one sentence: "Done when the question is settled in ``writing/`` with a
proof, a disproof, or a computation record, and every page that cites the open form is updated."
Neither target theorem is settled, and this gate does not pretend otherwise: what it locks is that
the page carries the *negative* result reached this round, that the sentence it replaces is gone,
and that the arithmetic of the record is the arithmetic stated on the page.

  item 1   the labelled chamber at a 0-cusp has strictly more walls than the eight unpolarized
           simple roots that lie in the stabilizer's image, so the labelled diagram is not the
           unpolarized one with the node ``r_0`` deleted.  The page states it as a theorem with a
           proof and names the withdrawn inference where the corollary used to draw it.
  item 2   the record exists, prints its witness, and the numbers on the page are re-derived here
           from the lattice alone, with no Sage and no import of the library.
  item 3   every page that carried the open form is updated: the status ledger's row for clause
           three and the open-question register row.

The tests read the page and the transcript for structure, and ``test_a2_the_arithmetic_is_re_derived``
is a genuine computation: it rebuilds K = I_{1,8}(2), the witness and the Cartan matrix of the eight
retained roots in exact arithmetic.
"""

