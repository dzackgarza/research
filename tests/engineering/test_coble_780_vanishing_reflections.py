"""Red test first: the reflection group is not yet known to be monodromy.

The reverse inclusion Gamma_Co >= Otilde^+ has a standard route: a nodal degeneration
gives, by the Picard-Lefschetz formula, the reflection in its vanishing (-2)-class, and
if every (-2)-class of T_Co occurs, then W(T_Co) (the group generated by all reflections
in square-(-2) vectors) is contained in Gamma_Co.  The book has W(T_Co) subset Otilde^+
as a lattice statement (prop:gamma-co-reflective-set(1)); what it does not have is
W(T_Co) subset Gamma_Co, nor the description of which (-2)-classes T_Co has.

This test is RED until both are on the page, with [@Dol96, Thm. 3.1] for the surjectivity
of the period map and [@Voi07, Thm. 3.16] for the local monodromy.
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
LA = ROOT / "writing/coble/lattices-and-moduli/lattices.md"

LEMMA = "lem:d2-vanishing-reflections"


def _block(text: str, label: str) -> str:
    assert "#" + label in text, f"#{label} is not on the page"
    start = text.index("#" + label)
    body = text.index("\n", start) + 1
    return text[body:text.index("\n:::", body)]


def test_the_lemma_states_the_vanishing_classes():
    body = _block(LA.read_text(encoding="utf-8"), LEMMA)
    # the (-2)-classes are parametrised, not left vague
    assert "E_{10}(2)" in body
    assert "-2" in body and "-4" in body


def test_the_lemma_proves_the_geometric_inclusion():
    text = LA.read_text(encoding="utf-8")
    assert "#" + LEMMA in text, "the lemma is not on the page"
    start = text.index("#" + LEMMA)
    proof = text[start:]
    proof = proof[proof.index("::: {.proof}"):]
    proof = proof[:proof.index("\n:::", 10)]
    assert "@Dol96, Thm. 3.1" in proof or "@Dol96, Theorem 3.1" in proof
    assert "@Voi07, Thm. 3.16" in proof or "@Voi07, Theorem 3.16" in proof
    assert "W(T_\\Co)" in proof


def test_the_lemma_names_the_kernel():
    text = LA.read_text(encoding="utf-8")
    body = _block(text, LEMMA)
    assert "@qst:gamma-co-reflection-index" in body or "@qst:gamma-co-reflection-index" in text
    # and says that the reverse inclusion needs the index to be one
    assert "index" in body


def test_the_divisor_is_the_boundary_and_not_met_by_the_family():
    """delta-perp does not meet the period image of the Coble family: the base is the
    complement of the arrangement (YZZ25, Section 3.3 and Theorem 3.4).  The monodromy
    comes from meridian loops about the removed divisors, and the degeneration is named:
    the sextic acquires an eleventh node, the branch curve an ordinary double point."""
    text = LA.read_text(encoding="utf-8")
    body = _block(text, LEMMA)
    assert "eleventh" in body
    assert "@YZZ25, §3.3" in body or "@YZZ25, Thm. 3.4" in body


def test_the_monodromy_group_is_the_reflection_group():
    """Gamma_Co = W(T_Co): pi_1 of the complement of an arrangement is generated by the
    meridians (van Kampen--Zariski), and each meridian acts by its reflection."""
    text = LA.read_text(encoding="utf-8")
    assert "\\Gamma_\\Co=W(T_\\Co)" in text, \
        "the identification of the monodromy group with the reflection group is not on the page"


def _run_all() -> int:
    items = [(n, f) for n, f in sorted(globals().items())
             if n.startswith("test_") and callable(f)]
    bad = 0
    for n, f in items:
        try:
            f()
        except AssertionError as exc:
            bad += 1
            print(f"FAIL {n}: {exc}")
        else:
            print(f"ok   {n}")
    print(f"\n{len(items) - bad}/{len(items)} checks pass")
    return bad


if __name__ == "__main__":
    raise SystemExit(_run_all())
