"""Red test first: the reduction of item 1e to the 527 isotropic classes is not on any page.

LEMMA.  An isometry of (A_{T_Co}, q) is trivial if and only if it fixes every nonzero isotropic class.
Hence rho(Gamma_Co) = 1 -- that is, item 1e -- if and only if Gamma_Co acts trivially on the 527 nonzero
isotropic classes of A_{T_Co}, i.e. every Gamma_Co-orbit on them is a singleton.

PROOF.  One direction is immediate.  For the other, note that 2q: A -> Z/2 is a surjective linear form
whose kernel has index 2, and that the nonzero isotropic classes generate ker(2q) (computed: the subgroup
they generate has order 1024, half of |A_{T_Co}| = 2048, and every isotropic class lies in ker(2q)).  If g
fixes them pointwise it fixes ker(2q) pointwise, and since g preserves q it preserves the form 2q, so it
acts trivially on the quotient A/ker(2q).  For any x write g(x) = x + k with k in ker(2q); then
q(g x) = q(x) + q(k) + 2b(x,k) = q(x) + 2b(x,k), so preserving q forces b(x,k) = 0 for every x, and
nondegeneracy of b gives k = 0.  So g is the identity.  []

So item 1e is a finite orbit question on 527 points.

This test is RED because no page states the reduction.
"""

from __future__ import annotations

import pathlib

try:
    import pytest
except ImportError:                         # pragma: no cover
    pytest = None


ROOT = pathlib.Path(__file__).resolve().parents[2]
RED_NAME = "test_the_isotropic_reduction_is_on_a_page"


def _red(fn):
    if pytest is None:
        return fn
    return pytest.mark.xfail(
        strict=True,
        reason="research#658 item 1e: rho(Gamma_Co) = 1 iff Gamma_Co fixes each of the 527 nonzero "
               "isotropic classes of A_{T_Co}, because they generate ker(2q) of index 2 and an isometry "
               "fixing ker(2q) pointwise is the identity. No page states it. Remove this marker when one "
               "does.",
    )(fn)


@_red
def test_the_isotropic_reduction_is_on_a_page():
    for path in sorted((ROOT / "writing").rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if "isotropic" in line and "527" in line and ("fixes" in line or "fix" in line):
                if "kernel" in line or "generat" in line or "identity" in line:
                    return
    raise AssertionError(
        "no page records that rho(Gamma_Co) = 1 iff Gamma_Co fixes each of the 527 nonzero isotropic "
        "classes, so the item is a finite orbit question on 527 points"
    )


def test_the_spanning_is_computed():
    probe = ROOT / "computations/reports/coble_658-isotropic-separates-probe.py"
    transcript = (ROOT / "computations/reports/coble_658-isotropic-separates-probe-run.txt").read_text(
        encoding="utf-8")
    import contextlib
    import io
    ns = {}
    exec(compile(probe.read_text(encoding="utf-8"), str(probe), "exec"), ns)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ns["main"]()
    assert buf.getvalue() == transcript
    assert "A_{T_Co}: |A| = 2048" in transcript
    assert "nonzero isotropic classes: 527" in transcript
    assert "subgroup generated by them: 1024  (half of |A|, so ker(2q) of index 2)" in transcript
    assert "verdict: the lemma holds" in transcript


def _run_all() -> int:
    items = [(name, fn) for name, fn in sorted(globals().items())
             if name.startswith("test_") and callable(fn)]
    failures = 0
    for name, fn in items:
        try:
            fn()
        except AssertionError as exc:
            if name == RED_NAME:
                print(f"RED  {name}: {exc}")
                continue
            failures += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"\n{len(items) - failures}/{len(items)} checks pass (1 red expected: the isotropic reduction)")
    return failures


if __name__ == "__main__":
    raise SystemExit(1 if _run_all() else 0)
