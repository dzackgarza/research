"""Red test first: the refutation of "meridians generate the monodromy" is not on any page.

LEMMA (refuted here).  For a family of Coble type, the monodromy group is generated by the meridians
about the components of its discriminant and about its cusps.

REFUTATION.  Take the degree-2 polarized family, whose monodromy is Gamma_{Co,2} = rho^{-1}(P) by
@def:gamma-co-groups(5) with P the decomposition stabilizer of @prop:gamma-co-images(3).  By
coble_658-meridian-lemma-probe.py every wall meridian (a (-2)-reflection) and every cusp meridian (an
Eichler transvection, coble_658-cusp-parabolic-probe.py) lies in ker(rho_{T_Co}) cap O^+(T_Co) =
O~+(T_Co), so the meridians generate a subgroup of O~+(T_Co).  But the swap s of e' and f' is an isometry
of T_Co in rho^{-1}(P) = Gamma_{Co,2} with rho(s) != 1
(coble_658-polarized-not-kernel-probe.py), so s lies in Gamma_{Co,2} and outside O~+(T_Co).  Hence the
meridians do not generate Gamma_{Co,2}, and the claim fails for the sibling family.

Consequently the corresponding claim for Gamma_Co cannot be imported by analogy: it needs its own proof,
which is exactly what item 1e is waiting on.

This test is RED because no page states the refutation.
"""

from __future__ import annotations

import pathlib

try:
    import pytest
except ImportError:                         # pragma: no cover
    pytest = None


ROOT = pathlib.Path(__file__).resolve().parents[2]
RED_NAME = "test_the_refutation_is_on_a_page"


def _red(fn):
    if pytest is None:
        return fn
    return pytest.mark.xfail(
        strict=True,
        reason="research#658 item 1e: the meridians lie in O~+(T_Co) while Gamma_{Co,2} does not, so "
               "'the meridians generate the monodromy' is false for the polarized family and cannot be "
               "imported for Gamma_Co. No page states the refutation. Remove this marker when one does.",
    )(fn)


@_red
def test_the_refutation_is_on_a_page():
    for path in sorted((ROOT / "writing").rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if "meridian" in line and ("generate" in line or "generated" in line):
                if "Gamma_{\\\\Co,2}" in line or "\\\\Gamma_{\\\\Co,2}" in line:
                    return
    raise AssertionError(
        "no page states that the meridians do not generate Gamma_{Co,2}, since they lie in O~+(T_Co) "
        "while the swap e' <-> f' lies in Gamma_{Co,2} outside it"
    )


def test_the_refutation_is_computed():
    """The refutation's two halves: meridians in the kernel, the swap in Gamma_{Co,2} outside it."""
    probe = ROOT / "computations/reports/coble_658-meridians-do-not-generate-probe.py"
    transcript = (ROOT / "computations/reports/coble_658-meridians-do-not-generate-probe-run.txt").read_text(
        encoding="utf-8")
    import contextlib
    import io
    ns = {}
    exec(compile(probe.read_text(encoding="utf-8"), str(probe), "exec"), ns)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ns["main"]()
    assert buf.getvalue() == transcript
    assert "wall meridian s_d (d = h + a_1):      isometry True, acts trivially on A True" in transcript
    assert "cusp meridian tau_{e', 2h+a_1+a_3}:   isometry True, acts trivially on A True" in transcript
    assert "the swap s of e', f':                 isometry True, acts trivially on A False" in transcript
    assert "preserves the E8(2) part of A_{T_Co}: True   (so rho(s) lies in P)" in transcript
    assert "verdict: REFUTED." in transcript


def _run_all() -> int:
    items = [(name, fn) for name, fn in sorted(globals().items())
             if name.startswith("test_") and callable(fn)]
    failures = 0
    for name, fn in items:
        try:
            fn()
        except AssertionError as exc:
            if name == RED_NAME:
                print(f"RED  {name}: {exc}")
                continue
            failures += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"\n{len(items) - failures}/{len(items)} checks pass (1 red expected: the refutation)")
    return failures


if __name__ == "__main__":
    raise SystemExit(1 if _run_all() else 0)
