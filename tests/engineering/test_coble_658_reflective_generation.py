"""Acceptance gate for the reduction of research#658 item 1e to the generation of Gamma_Co.

Item 1e is Gamma_Co <= ker(rho_{T_Co}), the monodromy group of the family of unpolarized Coble surfaces.
computations/reports/coble_658-reflective-generation-probe.py verifies, exactly and element by element,
that the subgroup generated by the two kinds of element that occur as monodromy of a period-domain family
lies in ker(rho_{T_Co}):

  reflections s_d in vectors of square -2 (the Picard--Lefschetz monodromy of a (-2)-wall, and
  prop:monodromy-contains-root-reflections puts them in the geometric monodromy), and
  Eichler transvections tau_{u,v}(x) = x + (x.u)v - (x.v)u for isotropic u, v of product zero,

with products of the two kinds checked as well, and with a control element that acts NON-trivially on
A_{T_Co}, so the test discriminates.

So the reduction: item 1e holds for any subgroup generated by such elements.  It therefore holds for
Gamma_Co as soon as Gamma_Co is so generated, i.e. as soon as the index [Gamma_Co : W(T_Co)] is 1 --
which is open, and is the question of @qst:gamma-co-generators and @prob:coxeter-completeness.

The RED test: no page records this reduction, so the test asserting that one does is strict xfail.

Run standalone (``python3 tests/engineering/test_coble_658_reflective_generation.py``) or under pytest.
"""

from __future__ import annotations

import contextlib
import io
import pathlib

try:                                        # pytest marks the red item; standalone prints it as RED
    import pytest
except ImportError:                         # pragma: no cover
    pytest = None


ROOT = pathlib.Path(__file__).resolve().parents[2]
PROBE = ROOT / "computations/reports/coble_658-reflective-generation-probe.py"
TRANSCRIPT = ROOT / "computations/reports/coble_658-reflective-generation-probe-run.txt"
RED_NAME = "test_the_reflective_generation_reduction_is_recorded"


def _red(fn):
    if pytest is None:
        return fn
    return pytest.mark.xfail(
        strict=True,
        reason="research#658 item 1e: the inclusion holds for every subgroup generated by (-2)-reflections "
               "and Eichler transvections, so it holds for Gamma_Co once [Gamma_Co : W(T_Co)] = 1. No "
               "page records this reduction. Remove this marker when one does.",
    )(fn)


def test_the_transcript_is_the_script_output():
    ns = {}
    exec(compile(PROBE.read_text(encoding="utf-8"), str(PROBE), "exec"), ns)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ns["main"]()
    assert buf.getvalue() == TRANSCRIPT.read_text(encoding="utf-8")


def test_the_generators_lie_in_the_discriminant_kernel():
    out = TRANSCRIPT.read_text(encoding="utf-8")
    assert "(-2)-vectors with small coefficients: 2668" in out
    assert "acting trivially on A_{T_Co}: 2668 of 2668" in out
    assert "transvections tau_{u,v} with u.v = 0: 200 examined; acting trivially on A_{T_Co}: 200 of 200" in out
    assert "products s_d o tau_{u,v}: 100 examined; trivial on A_{T_Co}: 100 of 100" in out


def test_the_control_discriminates():
    out = TRANSCRIPT.read_text(encoding="utf-8")
    assert "control, the swap e' <-> f' of the U(2) block: isometry True, acts trivially on A_{T_Co} False" in out


def test_the_verdict_names_the_open_index():
    out = TRANSCRIPT.read_text(encoding="utf-8")
    assert "verdict: item 1e holds for every subgroup generated by these elements" in out
    assert "[Gamma_Co : W(T_Co)] = 1" in out
    assert "@qst:gamma-co-generators" in out


@_red
def test_the_reflective_generation_reduction_is_recorded():
    """Red until a page records that the inclusion reduces to [Gamma_Co : W(T_Co)] = 1."""
    # the recorded sentence must say the implication: generation by these elements puts Gamma_Co in the
    # kernel.  A line that merely mentions W(T_Co) and reflections does not carry it.
    for path in sorted((ROOT / "writing").rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if "transvection" not in line:
                continue
            if "kernel" not in line and "discriminant" not in line:
                continue
            if "generated by" in line and ("Gamma_\\Co" in line or "\\Gamma_{\\mathrm{Co}}" in line):
                return
    raise AssertionError(
        "no page records that Gamma_Co <= ker(rho_{T_Co}) holds whenever Gamma_Co is generated by "
        "(-2)-reflections and Eichler transvections, i.e. whenever [Gamma_Co : W(T_Co)] = 1"
    )


def _run_all() -> int:
    items = [(name, fn) for name, fn in sorted(globals().items())
             if name.startswith("test_") and callable(fn)]
    failures = 0
    for name, fn in items:
        try:
            fn()
        except AssertionError as exc:
            if name == RED_NAME:
                print(f"RED  {name}: {exc}")
                continue
            failures += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"\n{len(items) - failures}/{len(items)} checks pass (1 red expected: the reflective reduction)")
    return failures


if __name__ == "__main__":
    raise SystemExit(1 if _run_all() else 0)
