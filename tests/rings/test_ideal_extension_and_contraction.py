r"""Extension and contraction of an ideal along a ring morphism.

For ``f: R -> S`` the extension ``I S`` is generated by the images of ``I``,
and the contraction ``f^{-1}(J)`` is the preimage.  Along the quotient map of
the plane onto the line ``y = 0`` the defining ideal extends to zero, an ideal
of the line contracts to the ideal of its preimage in the plane, and the
kernel is the contraction of zero, which is the defining ideal again.
"""

from dzack_research.preamble.all import (
    PolynomialRing,
    QQ,
    QuotientRing,
)


def _plane_and_line():
    r"""Return the plane, its quotient by ``y``, and the quotient map."""
    plane = PolynomialRing(QQ, "x,y")
    y = plane.algebra_generator("y")
    line = QuotientRing(plane, plane.ideal(y))
    return plane, line, line.quotient_map()


def test_the_defining_ideal_extends_to_zero() -> None:
    plane, line, quotient = _plane_and_line()
    y = plane.algebra_generator("y")

    extended = quotient.extension_of_ideal(plane.ideal(y))

    assert extended == line.ideal(line.zero())


def test_a_coordinate_extends_to_the_coordinate_of_the_quotient() -> None:
    plane, line, quotient = _plane_and_line()
    x = plane.algebra_generator("x")

    extended = quotient.extension_of_ideal(plane.ideal(x))

    assert extended == line.ideal(quotient(x))


def test_contraction_of_zero_is_the_defining_ideal_and_the_kernel() -> None:
    plane, line, quotient = _plane_and_line()
    y = plane.algebra_generator("y")

    contracted = quotient.contraction_of_ideal(line.ideal(line.zero()))

    assert contracted == plane.ideal(y)
    assert quotient.kernel() == plane.ideal(y)


def test_contraction_adds_the_defining_ideal_to_a_lift() -> None:
    plane, line, quotient = _plane_and_line()
    x = plane.algebra_generator("x")
    y = plane.algebra_generator("y")

    contracted = quotient.contraction_of_ideal(line.ideal(quotient(x)))

    assert contracted == plane.ideal(x, y)


def test_extension_after_contraction_returns_the_ideal_of_the_quotient() -> None:
    plane, line, quotient = _plane_and_line()
    x = plane.algebra_generator("x")
    ideal = line.ideal(quotient(x))

    assert quotient.extension_of_ideal(quotient.contraction_of_ideal(ideal)) == ideal
