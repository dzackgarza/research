r"""The unit group of a finite field, and the subgroup of its square roots of one."""

from dzack_research.preamble.all import *


def test_the_units_of_the_field_with_five_elements_are_cyclic_of_order_four_generated_by_two() -> None:
    r"""\(\mathbf F_5^\times\) is cyclic of order \(4\), generated by \(2\): \(2^1,2^2,2^3,2^4 = 2,4,3,1\)."""
    field = GF(5)
    units = field.unit_group()

    assert units.cardinality() == 4
    assert units.is_cyclic()
    assert field(0) not in units
    assert field(2) in units
    assert units(field(2)).order() == 4
    assert units(field(4)).order() == 2


def test_the_square_roots_of_one_in_the_units_of_the_field_with_five_elements_are_one_and_four() -> None:
    r"""The solutions of \(u^2 = 1\) in \(\mathbf F_5^\times\) are \(\{1, 4\}\), a subgroup of index \(2\).

    A cyclic group of order \(4\) has a unique subgroup of order \(2\).
    """
    field = GF(5)
    units = field.unit_group()

    roots = Subgroups(units)(lambda unit: unit * unit == units.one(), "u^2 = 1")

    assert field(1) in roots
    assert field(4) in roots
    assert field(2) not in roots
    assert field(3) not in roots
    assert roots.cardinality() == 2
    assert units.cardinality() / roots.cardinality() == 2


def test_reduction_modulo_five_sends_minus_one_to_the_element_of_order_two() -> None:
    r"""The unit-group functor applied to \(\mathbf Z\to\mathbf F_5\) sends \(-1\in\mathbf Z^\times=\{\pm1\}\) to \(4\), the unique element of order \(2\) in \(\mathbf F_5^\times\)."""
    field = GF(5)
    reduction = ZZ.Mor(field)(lambda integer: field(integer))

    restricted = Rings().unit_group()(reduction)

    assert ZZ.unit_group().cardinality() == 2
    assert restricted(ZZ(-1)) == field(4)
    assert restricted(ZZ(-1)) * restricted(ZZ(-1)) == field.one()
