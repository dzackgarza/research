r"""The units of a ring are a group, and a predicate cuts a subgroup out of it.

\(\mathbf F_5^\times\) is cyclic of order four, generated by \(2\), and the
elements killed by squaring are \(\{1,4\}\), a subgroup of index two.  That
subgroup is what the predicate construction produces, and producing it is the
point: a predicate needs a group to carve, which is why the units of a ring
have to be a group object rather than a set that happens to compose.

The functor also acts on morphisms.  Reduction \(\mathbf Z\to\mathbf F_5\)
carries \(\mathbf Z^\times=\{\pm 1\}\) into \(\mathbf F_5^\times\), sending
\(-1\) to \(4\), which is the element of order two.
"""

from dzack_research.preamble.all import (
    OwnedGroups,
    OwnedRings,
    ZZ,
    predicate_subgroup,
)
from dzack_research.preamble.categories.rings.ring_foundation import ring_morphism
from dzack_research.preamble.rings import GF


def _units_of_the_field_of_five_elements():
    return OwnedRings().unit_group()(GF(5))


def test_the_units_of_a_field_are_a_group_and_exclude_zero() -> None:
    field = GF(5)
    units = _units_of_the_field_of_five_elements()

    assert units in OwnedGroups()
    assert field(2) in units
    assert field(0) not in units
    assert units.one() == field.one()
    assert field(2) * field(3) == field.one()


def test_the_square_roots_of_one_are_a_subgroup_of_the_units() -> None:
    field = GF(5)
    units = _units_of_the_field_of_five_elements()

    roots = predicate_subgroup(
        units,
        lambda unit: unit * unit == units.one(),
        "u^2 = 1",
    )

    assert roots in OwnedGroups()
    assert roots.supergroup() is units
    assert field(1) in roots
    assert field(4) in roots
    assert field(2) not in roots


def test_reduction_carries_the_units_of_the_integers_into_the_units_of_the_field() -> None:
    field = GF(5)
    functor = OwnedRings().unit_group()
    reduction = ring_morphism(ZZ, field, lambda integer: field(integer))

    restricted = functor(reduction)

    assert restricted.domain() is functor(ZZ)
    assert restricted.codomain() is functor(field)
    assert restricted(ZZ(-1)) == field(4)
    assert restricted(ZZ(1)) == field.one()
