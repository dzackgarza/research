def test_picard_group_of_the_rational_projective_plane_is_Z_on_the_hyperplane() -> None:
    r"""``Pic(P^2_Q) = Z``, freely generated by the hyperplane class ``[O(1)]``.

    Hartshorne, *Algebraic Geometry*, II.6.17.
    """
    plane = ProjectiveSpaces(QQ)(2)
    picard = plane.picard_group()
    hyperplane = plane.hyperplane_picard_class()

    assert picard.is_free()
    assert picard.module_rank() == 1
    assert hyperplane != picard.zero()
    assert picard.span((hyperplane,)).inclusion().index() == 1


def test_picard_group_of_the_projective_line_over_Z_sqrt_minus_5_is_Z_mod_2_plus_Z() -> None:
    r"""``Pic(P^1_{O_K}) = Pic(O_K) + Z = Z/2 + Z`` for ``K = Q(sqrt -5)``.

    ``Pic(X x P^n) = Pic(X) x Z`` for ``X`` regular (Hartshorne, II,
    Exercise 6.1 with II.6.16); ``O_K`` has class number 2.  The pullback of
    the nontrivial class of ``O_K`` along ``P^1_{O_K} -> Spec O_K`` has order 2.
    """
    field = QuadraticField(-5, "a")
    order = field.ring_of_integers()
    relative_line = ProjectiveSpaces(order)(1)
    picard = relative_line.picard_group()
    base_picard = order.affine_spectrum().picard_group()
    pullback = relative_line.picard_pullback_morphism()

    assert field.class_number() == 2
    assert base_picard.cardinality() == 2
    assert picard.torsion_submodule().cardinality() == 2
    assert picard.vector_space().dimension() == 1
    assert pullback.kernel().cardinality() == 1
    assert all(pullback(c).additive_order() == 2 for c in base_picard if c != base_picard.zero())


def test_the_line_bundle_of_a_rational_point_on_the_projective_line_is_O_1() -> None:
    r"""On ``P^1_Q``, ``O(p) = O(1)`` for a rational point ``p``, of degree 1.

    Two rational points are linearly equivalent: ``div(x0/x1) = (0:1) - (1:0)``.
    """
    line = ProjectiveSpaces(QQ)(1)
    weil = line.weil_divisor_group()
    zero = weil.prime_divisor(line.point((0, 1)))
    infinity = weil.prime_divisor(line.point((1, 0)))

    bundle = line.invertible_sheaf_of_divisor(infinity)

    assert bundle.is_isomorphic(line.O(1))
    assert bundle.degree() == 1
    assert line.class_group_projection()(zero) == line.class_group_projection()(infinity)
    assert zero - infinity != weil.zero()


def test_normal_a1_surface_has_a_weil_prime_that_is_not_cartier() -> None:
    r"""On the cone ``xy = z^2`` the ruling ``(x, z)`` is Weil but not Cartier at the vertex.

    ``div(x) = 2 (x, z)``, and the prime is Cartier away from the vertex
    (Hartshorne, *Algebraic Geometry*, II.6.5.2 and II.6.11.3).
    """
    polynomial = QQ.polynomial_ring("x,y,z")
    x = polynomial.algebra_generator("x")
    y = polynomial.algebra_generator("y")
    z = polynomial.algebra_generator("z")
    ring = polynomial.quotient_ring(polynomial.ideal(x * y - z**2))
    x, y, z = ring(x), ring(y), ring(z)
    scheme = (ring).affine_spectrum(base_ring=QQ)
    prime = ring.spectrum()(ring.ideal(x, z))
    vertex = ring.spectrum()(ring.ideal(x, y, z))
    outside_prime = ring.spectrum()(ring.ideal(y, z))
    full_weil = scheme.full_weil_divisor_group()
    prime_divisor = full_weil.prime_divisor(prime)
    divisor_of_x = full_weil.principal_divisor(x)

    assert ring.is_normal()
    assert prime.height() == 1
    assert not full_weil.prime_is_cartier_at(prime, vertex)
    assert full_weil.prime_is_cartier_at(prime, prime)
    assert full_weil.prime_is_cartier_at(prime, outside_prime)
    assert full_weil.multiplicity(divisor_of_x, prime) == 2
    assert divisor_of_x == 2 * prime_divisor
