def test_projective_n_space_over_a_field_has_picard_and_class_group_Z() -> None:
    r"""``Pic(P^3_Q) = Cl(P^3_Q) = Z``, generated by the hyperplane class.

    Hartshorne, *Algebraic Geometry*, II.6.4 and II.6.16 (``P^n`` is regular,
    so ``Pic = Cl``).
    """
    projective = ProjectiveSpaces(QQ)(3)
    picard = projective.picard_group()
    classes = projective.class_group()
    comparison = projective.picard_to_class_group_morphism()
    hyperplane = projective.hyperplane_picard_class()

    assert picard.is_free()
    assert picard.module_rank() == 1
    assert classes.module_rank() == 1
    assert comparison.is_isomorphism()
    assert picard.span((hyperplane,)).inclusion().index() == 1
    assert comparison(hyperplane) != classes.zero()


def test_projective_plane_over_a_base_keeps_the_base_class_group() -> None:
    r"""``Cl(P^2_{O_K}) = Cl(O_K) + Z = Z/2 + Z`` for ``K = Q(sqrt -5)``.

    ``Cl(X x P^n) = Cl(X) x Z`` (Hartshorne, II, Exercise 6.1), and ``O_K``
    has class number 2, the class of ``(2, 1 + sqrt -5)`` being nontrivial.
    ``P^2_{O_K}`` is regular, so ``Pic = Cl``.
    """
    field = QuadraticField(-5, "a")
    order = field.ring_of_integers()
    projective = ProjectiveSpaces(order)(2)
    picard = projective.picard_group()
    classes = projective.class_group()

    assert field.class_number() == 2
    assert order.affine_spectrum().class_group().cardinality() == 2
    assert classes.torsion_submodule().cardinality() == 2
    assert classes.vector_space().dimension() == 1
    assert picard.torsion_submodule().cardinality() == 2
    assert projective.picard_to_class_group_morphism().is_isomorphism()


def test_normal_singular_surface_has_a_noncartier_weil_class() -> None:
    polynomial = QQ.polynomial_ring("x,y,z")
    x = polynomial.algebra_generator("x")
    y = polynomial.algebra_generator("y")
    z = polynomial.algebra_generator("z")
    ring = polynomial.quotient_ring(polynomial.ideal(x * y - z**2))
    x, y, z = ring(x), ring(y), ring(z)
    scheme = (ring).affine_spectrum(base_ring=QQ)
    prime = ring.spectrum()(ring.ideal(x, z))
    vertex = ring.spectrum()(ring.ideal(x, y, z))
    weil = scheme.full_weil_divisor_group()

    assert ring.is_normal()
    assert not weil.prime_is_cartier_at(prime, vertex)
    assert weil.principal_divisor(x) == 2 * weil.prime_divisor(prime)
