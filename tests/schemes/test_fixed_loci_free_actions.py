r"""Fixed loci of finite group actions on affine schemes over ``GF(2)``.

The fixed locus of an automorphism ``sigma`` of ``Spec A`` is cut out by the ideal
generated by ``f - sigma^* f`` for ``f`` in ``A``.  The Artin--Schreier translation
``x -> x + 1`` of the affine line over ``GF(2)`` has fixed ideal ``(1)``: it acts
freely.  The Klein four-group acting on the plane by a translation and a shear has
empty common fixed locus while the shear fixes the curve ``x^2 + x = 0``, so an
empty ``X^G`` does not imply freeness.
"""

from dzack_research.preamble.all import *  # noqa: F401,F403


def _automorphism(A, images):
    X = A.affine_spectrum()
    return X, X.Mor(X)(A.Mor(A)(images))


def test_the_artin_schreier_translation_acts_freely_on_the_affine_line() -> None:
    r"""``x -> x + 1`` on ``A^1_{GF(2)}``: fixed ideal ``(x - (x + 1)) = (1)``, so the ``C_2``-action is free."""
    A = GF(2)['x']
    x = A.gen()
    X, tau = _automorphism(A, {x: x + 1})
    G = Groups.C(2)
    acted = GObjects(G, Schemes(GF(2)))(X, G.Mor(X.automorphism_group())({G.gen(): tau}))

    assert tau * tau == X.identity_morphism()
    assert tau != X.identity_morphism()
    assert X.fixed_locus(tau).defining_ideal() == A.unit_ideal()
    assert acted.is_free()


def test_an_empty_common_fixed_locus_does_not_make_the_klein_four_action_free() -> None:
    r"""``V_4 = <x -> x+1, y -> y + x^2 + x>`` on ``A^2_{GF(2)}``: ``X^G`` is empty, the shear fixes ``V(x^2 + x)``.

    Derivation: both maps are involutions and commute in characteristic 2, since
    ``(x+1)^2 + (x+1) = x^2 + x``; the fixed ideal of the shear is
    ``(y - (y + x^2 + x)) = (x^2 + x)``, which contains the two rational points
    ``x = 0`` and ``x = 1`` of each vertical line; the translation's is ``(1)``.
    """
    A = GF(2)['x,y']
    x, y = A.gens()
    X, translation = _automorphism(A, {x: x + 1, y: y})
    X, shear = _automorphism(A, {x: x, y: y + x**2 + x})
    G = Groups.C(2).direct_product(Groups.C(2))
    a, b = G.group_generators()
    acted = GObjects(G, Schemes(GF(2)))(X, G.Mor(X.automorphism_group())({a: translation, b: shear}))

    assert translation * shear == shear * translation
    assert X.fixed_locus(shear).defining_ideal() == A.ideal(x**2 + x)
    assert X.fixed_locus(translation).defining_ideal() == A.unit_ideal()
    assert X.fixed_locus(translation * shear).defining_ideal() == A.unit_ideal()
    assert acted.fixed_locus().defining_ideal() == A.unit_ideal()
    assert not acted.is_free()


def test_the_scheme_theoretic_fixed_locus_of_x_to_x_plus_e_squared_is_nonreduced() -> None:
    r"""On ``GF(2)[x, e]/(e^3)``, ``x -> x + e^2`` has fixed ideal ``(e^2)``; ``e`` survives as a nilpotent there.

    Derivation: ``x - (x + e^2) = e^2`` and ``e - e = 0``; the fixed locus is
    ``Spec GF(2)[x, e]/(e^2)``, in which ``e != 0`` and ``e^2 = 0``.
    """
    P = GF(2)['x,e']
    A = P.quotient(P.ideal(P.gen(1) ** 3))
    x, e = A.gens()
    X, sigma = _automorphism(A, {x: x + e**2, e: e})
    fixed = X.fixed_locus(sigma)
    e_fixed = fixed.coordinate_ring()(e)

    assert sigma * sigma == X.identity_morphism()
    assert fixed.defining_ideal() == A.ideal(e**2)
    assert e_fixed != 0
    assert e_fixed**2 == 0
    assert not fixed.is_reduced()
