r"""Projectivity decided from a presentation, and trivialized locally.

A finitely presented module is projective exactly when every Fitting ideal is
generated by an idempotent, which over an integral domain says the module has
one rank ``r`` with ``Fitt_{r-1}(M) = 0`` and ``Fitt_r(M) = R``.  Nothing about
that reads a placement, so a presented module answers the question rather than
being declared projective.  At a point of the spectrum the residue field picks
a basis of the fibre, and Nakayama turns it into a local trivialization.
"""

from dzack_research.preamble.all import (
    BasedFreeModule,
    FinitelyPresentedModule,
    ZZ,
    module_homset,
)
from dzack_research.preamble.categories.sets import finite_ordered_set


def _presented_by_multiple_of_a_generator(scalar):
    r"""Return the module on ``g, h`` with the single relation ``scalar * g``."""
    free = BasedFreeModule(ZZ, finite_ordered_set(("g", "h")))
    relations = BasedFreeModule(ZZ, finite_ordered_set(("r",)))
    return FinitelyPresentedModule(
        module_homset(relations, free)({"r": scalar * free.module_generator("g")})
    )


def test_a_unit_relation_leaves_a_projective_module() -> None:
    module = _presented_by_multiple_of_a_generator(ZZ(1))

    assert module.is_projective()


def test_a_torsion_relation_leaves_a_module_that_is_not_projective() -> None:
    module = _presented_by_multiple_of_a_generator(ZZ(6))

    assert not module.is_projective()


def test_a_free_module_has_its_rank_as_the_projective_rank_at_a_point() -> None:
    free = BasedFreeModule(ZZ, finite_ordered_set(("g", "h")))
    point = ZZ.spectrum()(ZZ.ideal(ZZ(5)))

    assert free.projective_rank(point) == 2


def test_the_local_free_trivialization_is_an_isomorphism_of_that_rank() -> None:
    free = BasedFreeModule(ZZ, finite_ordered_set(("g", "h")))
    point = ZZ.spectrum()(ZZ.ideal(ZZ(5)))

    trivialization = free.local_free_trivialization(point)

    assert trivialization.codomain() is free.localize_at_prime(point)
    assert trivialization.domain().rank() == free.projective_rank(point)
    assert trivialization.is_injective()
    assert trivialization.is_surjective()
