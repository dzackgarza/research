def invZ(M):
    a = [[Fraction(M[i][j]) for j in range(N)] + [Fraction(int(i == j)) for j in range(N)] for i in range(N)]
    for c in range(N):
        p = next(r for r in range(c, N) if a[r][c] != 0)
        a[c], a[p] = a[p], a[c]
        pv = a[c][c]
        a[c] = [x/pv for x in a[c]]
        for r in range(N):
            if r != c and a[r][c] != 0:
                f = a[r][c]
                a[r] = [x - f*y for x, y in zip(a[r], a[c])]
    res = [[a[i][N+j] for j in range(N)] for i in range(N)]
    assert all(x.denominator == 1 for row in res for x in row)
    return [[int(x) for x in row] for row in res]
def red(M):
    return tuple(tuple(M[i][j] % 2 for j in range(N)) for i in range(N))
def act(M, x):
    return tuple(sum(M[i][j]*x[j] for j in range(N)) % 2 for i in range(N))
def inv2(M):
    a = [list(r) + [int(i == j) for j in range(N)] for i, r in enumerate(M)]
    for c in range(N):
        p = next(r for r in range(c, N) if a[r][c])
        a[c], a[p] = a[p], a[c]
        for r in range(N):
            if r != c and a[r][c]:
                a[r] = [(x + y) % 2 for x, y in zip(a[r], a[c])]
    return tuple(tuple(a[i][N+j] for j in range(N)) for i in range(N))

def bfs(F):
    Fs = {}
    for nm, M in F.items():
        Fs[nm] = M
        Fs[nm+'^-1'] = invZ(M)
    Fs2 = [(nm, inv2(red(M)), M) for nm, M in Fs.items()]
    states = {Wsp: I}; tree = {}
    front = [Wsp]
    while front:
        nf = []
