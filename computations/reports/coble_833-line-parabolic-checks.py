from fractions import Fraction
from itertools import product


def det_int(M):
    M = [[Fraction(x) for x in row] for row in M]
    n = len(M)
    s = Fraction(1)
    for i in range(n):
        p = None
        for r in range(i, n):
            if M[r][i] != 0:
                p = r
                break
        if p is None:
            return Fraction(0)
        if p != i:
            M[i], M[p] = M[p], M[i]
            s = -s
        s *= M[i][i]
        inv = Fraction(1) / M[i][i]
        for r in range(i + 1, n):
            f = M[r][i] * inv
            if f:
                M[r] = [a - f * b for a, b in zip(M[r], M[i])]
    return s


