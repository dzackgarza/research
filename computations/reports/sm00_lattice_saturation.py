#!/usr/bin/env python3
"""
m5 / d7, appendix B: the exact content of the saturation question for
Lambda = U(2) perp <-2> inside S_dP (premise-ledger.md, section 4(c)).

Exact integer/rational arithmetic.  With Lambda = U(2) perp <-2> and Gram G:
  (1) the discriminant group A_Lambda = Lambda^#/Lambda is (Z/2)^3, generated by
      e/2, f/2, g/2, with q(x) = x^T G x in Q/2Z;
  (2) its isotropic elements of order 2 are exactly e/2 and f/2;
  (3) for each, the index-2 superlattice S = Lambda + Z w is even, of determinant 2,
      discriminant group Z/2, signature (1,2), and is isometric to U perp <-2>;
  (4) hence an even lattice of rank 3, signature (1,2), containing Lambda has
      det 8 (Lambda) or det 2 (U perp <-2>), and no other value.
"""
import itertools
import sympy as sp

G = sp.Matrix([[0, 2, 0], [2, 0, 0], [0, 0, -2]])   # Lambda = U(2) perp <-2>
print("Gram Lambda =", G.tolist(), "| det =", G.det())
assert abs(int(G.det())) == 8

def q_of(coords):
    """coords: rational vector in the basis e,f,g;  q(x) = x^T G x."""
    v = sp.Matrix(coords)
    return sp.Rational((v.T * G * v)[0, 0])

half = [sp.Matrix([sp.Rational(c, 2) for c in coeffs])
        for coeffs in itertools.product([0, 1], repeat=3)]
print("A_Lambda = (Z/2)^3, elements x = sum c_i/2 * basis vector:")
for coeffs, v in zip(itertools.product([0, 1], repeat=3), half):
    q = q_of(v)
    print("   c =", coeffs, " x =", [sp.nsimplify(e) for e in v], " q =", q,
          " (q mod 2Z =", sp.nsimplify(q - 2 * sp.floor(q / 2)) if q != 0 else 0, ")")

order2 = [v for coeffs, v in zip(itertools.product([0, 1], repeat=3), half) if any(coeffs)]
isotropic = [v for v in order2 if q_of(v) % 2 == 0]
print("isotropic elements of order 2:", [[sp.nsimplify(e) for e in v] for v in isotropic])
assert len(isotropic) == 2, "exactly two isotropic subgroups of order 2, generated by e/2 and f/2"

print()
basis = [sp.Matrix([1, 0, 0]), sp.Matrix([0, 1, 0]), sp.Matrix([0, 0, 1])]
for w in [v for v in isotropic if any(v)]:
    # S = Lambda + Z w : pick w and the two basis vectors not parallel to w mod 2
    cand = [basis[0], basis[1], basis[2]]
    best = None
    for drop in range(3):
        sub = [w] + [cand[i] for i in range(3) if i != drop]
        B = sp.Matrix.hstack(*sub)
        if B.det() == 0:
            continue
        Gm = sp.simplify(B.T * G * B)
        if abs(int(Gm.det())) == 2:
            best = (sub, Gm)
    sub, Gm = best
    print("w =", [sp.nsimplify(e) for e in w], "-> S has basis", [[sp.nsimplify(e) for e in v] for v in sub])
    print("   Gram =", Gm.tolist(), " det =", Gm.det(),
          "| diagonal even:", all(int(Gm[i, i]) % 2 == 0 for i in range(3)))
    ev = Gm.eigenvals()
    pos = sum(m for e, m in ev.items() if sp.sign(sp.simplify(e)) > 0)
    neg = sum(m for e, m in ev.items() if sp.sign(sp.simplify(e)) < 0)
    print("   signature =", (pos, neg))
    # explicit isometry to U perp <-2>: compare Gram of the standard U perp <-2> basis
    V = sp.Matrix([[0, 1, 0], [1, 0, 0], [0, 0, -2]])   # Gram of U perp <-2>
    print("   equals the Gram of U perp <-2>:", Gm.tolist() == V.tolist(), "in the basis",
          [[sp.nsimplify(e) for e in v] for v in sub], ":", Gm == Gm and Gm.tolist() == V.tolist())
print()
print("Conclusion: [S_dP : Lambda]^2 = 8/det S_dP with S_dP even of rank 3 and signature (1,2),")
print("so det S_dP in {8, 2}: S_dP = Lambda (a = 3) or S_dP = U perp <-2> (a = 1).  QED")
