"""A3: the integral stabilizer of the polarization, its generators, and the group above it.

    JULIA_DEPOT_PATH=/root/.julia:/opt/julia-depot: \
    PYTHONPATH=/repo/.scratch/se-provider-c546/src \
    $HOME/.udocker/bin/proot-x86_64 -R $HOME/sage-image/rootfs -b /proc -b /dev -b /sys \
        -b <repo>:/repo -w /repo /sage/.venv/bin/sage \
    /repo/computations/reports/coble_stabilizer_generators.py

Fixed data, from the reconciled definitions and not varied here:

  C   = U + E8(-1)                        even unimodular, signature (1,9)
  h   = u_0 + w_0 in U                     the degree-2 Enriques polarization, h^2 = 2 in C
  S   = C(2) = U(2) + E8(2)                the invariant lattice S_En, h^2 = 4 there
  K   = <e_0 - f_0> + E8(-1) = h^perp_C    negative definite, rank 9, det -2, isometric to < -2 > + E8
  T   = <2> + U(2) + E8(2)                 the Coble lattice T_Co

What is constructed and verified, all through owner operations:

  (a) The integral generators of the stabilizer.  By prop:polarization-stabilizer-enriques the
      restriction Stab_{O(S)}(h) -> O(h^perp) is an isomorphism onto O(K), so generators of O(K) are
      generators of the integral stabilizer of h.  The proposed set is the reflection in the <2>
      direction (u_0 - w_0, of square -2) together with the eight reflections in the simple roots of
      E8(-1); each is built by Lattices.reflection, membership in O(K) is decided by K.Aut(), and
      completeness is the owner's own subgroup comparison: K.Aut().subgroup(the nine reflections)
      has the cardinality of K.Aut() itself.  The order 1393459200 = 2|W(E8)| is the number
      prop:polarization-stabilizer-enriques records, so the run checks the owner against that
      proposition and the proposition against the owner.

  (b) The image in the discriminant group.  The same nine vectors, read in S, are reflections of S
      fixing h, hence elements of the integral stabilizer there; their images under
      S.discriminant_representation() generate a subgroup of O(A_S), and its cardinality is the order
      of the group that thm:coble-heegner-finite-orbits (1) calls G.  Whether that order is
      |W(E8)| = 696729600 is recorded in TODO B2 as unproved; this run answers it at the owner.

  (c) The groups of the reconciled definitions as owned objects.  Gamma_Co = O^+(T) cap ker(rho_T) is
      the intersection of T.O_plus() with T.stable_orthogonal_group(); the congruence preimage is
      T.discriminant_representation().discriminant_preimage(P) for the subgroup P generated by the
      discriminant action of the witness sigma of coble_congruence_witness.py.  Membership of sigma
      in the second and not the first is decided by those objects, so the strict inclusion proved in
      sec-gamma-co-comparison is visible as an object-level containment.

  (d) An integral element of Gamma_Co itself, and where the reflection route stops.  T does carry
      (-2)-vectors, which a minimum-norm guess would deny: zeta + a_1 has square 2 - 4 = -2, and the
      owner confirms that its reflection lies in O^+(T) and in ker(rho_T), hence in Gamma_Co.  So the reflection group of T is nontrivial and the reflections of T give
      genuine integral elements of Gamma_Co.  What is not available is the other direction: whether
      the reflections, with finitely many further isometries, generate Gamma_Co.  The owner will not
      enumerate the roots of an indefinite lattice (`Lattices.roots` is a definite-lattice operation,
      correctly, since an indefinite even lattice has infinitely many (-2)-vectors), so that set is
      not a finite owner object, and completeness is the Vinberg-type theorem this book records as
      required and open (prob:coxeter-completeness, B32--B34).

What is not obtained, and why.  Generators of Gamma_Co itself, not merely of the finite stabilizer and
its finite image, are not produced: no owner operation returns generators, or a finite-index
certificate, for O^+(L) cap ker(rho_L) of an indefinite lattice, and on T the reflection route is
empty by (d).  The mathematical input needed is a completeness theorem (Vinberg/Eichler type: that an
explicit set of isometries generates the arithmetic group modulo the kernel), which this book records
as required and open (prob:coxeter-completeness, and B32--B34 in the research report's taxonomy).  The
semantic handoff, if the owner wants this capability, is a single operation

    generators_of_arithmetic_subgroup(L, predicates) -> generating set or finite-index certificate

for a ZZ-lattice L and a list of predicates on O(L) (component condition, preimage of a subgroup of
O(A_L)), returning either generators of the intersection or a proof-carrying finite-index statement;
nothing in research can substitute for it without implementing a group algorithm, which is excluded.

Provenance is printed before anything is computed.
"""
import sys

from sage.all import CartanMatrix, ZZ, block_diagonal_matrix, matrix
from sage.version import version as sage_version

from sage_extensions.all import Lattices

sys.stdout.reconfigure(line_buffering=True)

PIN = 'c546077dce79a76eb32e92d080aa9c44e4c67552'

print('provenance')
print('  sage-extensions provider pin: %s (.scratch/se-provider-c546/src, read-only export)' % PIN)
print('  Sage: %s' % sage_version)
print('  image rootfs: $HOME/sage-image/rootfs, mounted read-only; repo bound at /repo')
print('')

U = matrix(ZZ, [[0, 1], [1, 0]])
E8 = -CartanMatrix(['E', 8])          # negative definite E8
C_GRAM = block_diagonal_matrix(U, E8)
C = Lattices(ZZ)([list(row) for row in C_GRAM.rows()])
S = Lattices(ZZ)([list(row) for row in (2 * C_GRAM).rows()])
K = Lattices(ZZ)([list(row) for row in block_diagonal_matrix(matrix(ZZ, [[-2]]), E8).rows()])
T_GRAM = block_diagonal_matrix(matrix(ZZ, [[2]]), 2 * U, 2 * E8)
T = Lattices(ZZ)([list(row) for row in T_GRAM.rows()])

c_basis = [C.basis_vector(i) for i in range(C.rank())]
u0, w0 = c_basis[0], c_basis[1]
h_C = u0 + w0
s_basis = [S.basis_vector(i) for i in range(S.rank())]
h_S = s_basis[0] + s_basis[1]
print('C = U + E8(-1): rank %d, signature %s, det %s' % (C.rank(), C.signature_pair(), C.determinant()))
print('S = C(2) = U(2) + E8(2): rank %d, signature %s, det %s'
      % (S.rank(), S.signature_pair(), S.determinant()))
print('K = <-2> + E8(-1): rank %d, signature %s, det %s, roots %d'
      % (K.rank(), K.signature_pair(), K.determinant(), len(list(K.roots()))))
print('h: h^2 = %d in C, h^2 = %d in S' % (h_C.q(), h_S.q()))
assert h_C.q() == 2 and h_S.q() == 4

# ---------------------------------------------------------------- (a) integral generators of O(K)
f0 = K.basis_vector(0)
alphas = [K.basis_vector(i) for i in range(1, K.rank())]
print('  squares: <2> direction %d, simple E8 roots %s'
      % (f0.q(), sorted({int(a.q()) for a in alphas})))
reflections_K = [K.reflection(f0)] + [K.reflection(a) for a in alphas]
aut_K = K.Aut()
print('  |O(K)| = %d, finite: %s' % (aut_K.cardinality(), aut_K.is_finite()))
print('  every proposed generator is an automorphism of K: %s'
      % all(g in aut_K for g in reflections_K))
generated = aut_K.subgroup(tuple(reflections_K))
print('  |<the nine reflections>| = %d' % generated.cardinality())
assert aut_K.cardinality() == 1393459200, 'owner disagrees with prop:polarization-stabilizer-enriques'
assert generated.cardinality() == aut_K.cardinality(), 'the nine reflections do not generate O(K)'
print('  COMPLETE: the nine reflections generate O(K) = Stab_{O(S)}(h) up to the restriction isomorphism')

# ---------------------------------------------------------------- (b) the finite image on A_S
f0_S = s_basis[0] - s_basis[1]                   # u_0 - w_0, square -4 in S
alphas_S = [s_basis[2 + i] for i in range(8)]    # simple E8 roots, square -4 in S
reflections_S = [S.reflection(f0_S)] + [S.reflection(a) for a in alphas_S]
print('  the nine reflections of S fix h: %s' % all(g(h_S) == h_S for g in reflections_S))
assert all(g(h_S) == h_S for g in reflections_S)

A_S = S.discriminant_group()
rho_S = S.discriminant_representation()
O_AS = A_S.orthogonal_group()
images = tuple(rho_S(g) for g in reflections_S)
G_S = O_AS.subgroup(images)
print('  |A_S| = %d, |O(A_S)| = %d' % (A_S.cardinality(), O_AS.cardinality()))
print('  |G| = |<images of the nine reflections>| = %d' % G_S.cardinality())
print('  |W(E8)| = 696729600; G equals it: %s' % (G_S.cardinality() == 696729600))
assert G_S.cardinality() == 696729600, 'the image order is not |W(E8)|'

# ---------------------------------------------------------------- (c) Gamma_Co and the preimage as objects
T_basis = [T.basis_vector(i) for i in range(T.rank())]
sigma = T.reflection(T_basis[1] - T_basis[2])     # the witness of coble_congruence_witness.py
Gamma_Co = T.stable_orthogonal_group().intersection(T.O_plus())
print('  Gamma_Co = O^+(T) cap ker(rho_T) constructed as an owned object: %s'
      % type(Gamma_Co).__name__)
print('  sigma in Gamma_Co: %s' % (sigma in Gamma_Co))
assert sigma not in Gamma_Co

A_T = T.discriminant_group()
O_AT = A_T.orthogonal_group()
P = O_AT.subgroup((sigma.discriminant_morphism(),))
preimage = T.Aut().discriminant_preimage(P)
print('  congruence preimage rho^{-1}(P) constructed; sigma in it: %s' % (sigma in preimage))
assert sigma in preimage
print('  so sigma lies in rho^{-1}(P) and not in Gamma_Co: Gamma_Co is strictly inside the preimage')
assert sigma in preimage and sigma not in Gamma_Co

# ---------------------------------------------------------------- (d) a reflection inside Gamma_Co
# T = <2> + U(2) + E8(2), basis zeta; e', f'; a_1..a_8.  zeta + a_1 has square 2 - 4 = -2, so T
# carries (-2)-vectors and its reflection group is nontrivial.  Its divisibility is 2, which is not an
# obstruction: the reflection of a primitive vector acts trivially on the discriminant exactly when the
# square is +-2, and on a 2-elementary lattice every primitive vector has divisibility 2
# (lem:divisibilityAlwaysTwoTco).
x = T_basis[0] + T_basis[3]
print('  x = zeta + a_1: q(x) = %d, div(x) = %d' % (x.q(), T.div(x)))
assert x.q() == -2 and T.div(x) == 2
sigma_x = T.reflection(x)
print('  its reflection in O_plus: %s; in ker(rho_T): %s; hence in Gamma_Co: %s'
      % (sigma_x in T.O_plus(), sigma_x in T.stable_orthogonal_group(), sigma_x in Gamma_Co))
assert sigma_x in T.O_plus() and sigma_x in T.stable_orthogonal_group()
assert sigma_x in Gamma_Co, 'a reflection in a primitive (-2)-vector should lie in Gamma_Co'
try:
    list(T.roots())
    print('  T.roots() returned a finite list (unexpected for an indefinite lattice)')
except ValueError as exc:
    print('  T.roots() declined, as designed for an indefinite lattice: %s'
          % str(exc).split(':')[0])

print('')
print('SUMMARY')
print('  (a) the nine reflections generate the integral stabilizer O(K) = Stab_{O(S)}(h), |O(K)| =')
print('      1393459200 = 2|W(E8)|, completeness decided by the owner subgroup comparison;')
print('  (b) their images generate G <= O(A_S) with |G| = 696729600 = |W(E8)|, which is the order')
print('      thm:coble-heegner-finite-orbits (1) asserts and TODO B2 records as unproved;')
print('  (c) Gamma_Co, its congruence preimage and the witness containment are owned objects, and the')
print('      witness lies in the preimage and not in Gamma_Co;')
print('  (d) zeta + a_1 is a (-2)-vector of T and its reflection is in Gamma_Co, so')
print('      reflections of T give integral elements of Gamma_Co; that they generate it is the')
print('      completeness theorem prob:coxeter-completeness and B32--B34 record as open, and the')
print('      roots of an indefinite lattice are not an enumerable owner object.')
print('OK: integral generators of the stabilizer and its finite image verified at the owner;')
print('    generators of Gamma_Co itself remain the named open obligation, with the handoff stated.')
