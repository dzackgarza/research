from __future__ import annotations

from fractions import Fraction as F
from itertools import product


def e8_cartan():
    c = [[0] * 8 for _ in range(8)]
    for i in range(8):
        c[i][i] = 2
    for i in range(6):
        c[i][i + 1] = c[i + 1][i] = -1
    c[2][7] = c[7][2] = -1
    return c


def block_diagonal(blocks):
    n = sum(len(b) for b in blocks)
    g = [[0] * n for _ in range(n)]
    off = 0
    for b in blocks:
        for i in range(len(b)):
            for j in range(len(b)):
                g[off + i][off + j] = b[i][j]
        off += len(b)
    return g


U = [[0, 1], [1, 0]]
G = block_diagonal([[[2]], [[2 * x for x in row] for row in U],
                    [[-2 * x for x in row] for row in e8_cartan()]])      # T_Co, rank 11
N = len(G)


def mv(m, v):
    return [sum(m[i][j] * v[j] for j in range(len(v))) for i in range(len(m))]


def inverse(m):
    n = len(m)
    a = [[F(m[i][j]) for j in range(n)] + [F(int(i == j)) for j in range(n)] for i in range(n)]
    for col in range(n):
        piv = next(r for r in range(col, n) if a[r][col] != 0)
        a[col], a[piv] = a[piv], a[col]
        pv = a[col][col]
        a[col] = [x / pv for x in a[col]]
        for r in range(n):
            if r != col and a[r][col] != 0:
                f = a[r][col]
                a[r] = [x - f * y for x, y in zip(a[r], a[col])]
    return [row[n:] for row in a]


GINV = inverse(G)


def main():
    classes = {}
    for bits in product([0, 1], repeat=N):
        v = list(bits)
        classes.setdefault(tuple(x % 1 for x in mv(GINV, v)), v)
    print("A_{T_Co}: |A| = %d" % len(classes))

    iso = {}
    for key, v in classes.items():
        if not any(key):
            continue
        q = sum(a * b for a, b in zip(v, mv(GINV, v))) % 2
        if q == 0:
            iso[key] = v
    print("nonzero isotropic classes: %d" % len(iso))

    zero = tuple([F(0)] * N)
    S = {zero}
    for g in iso:
        add = set()
        for s in S:
            t = tuple((a + b) % 1 for a, b in zip(s, g))
            if t not in S:
                add.add(t)
        S |= add
    print("subgroup generated by them: %d  (half of |A|, so ker(2q) of index 2)" % len(S))
    assert len(S) * 2 == len(classes)

    print()
    print("verdict: the lemma holds.  An isometry fixing the 527 classes fixes ker(2q) pointwise and acts")
    print("  trivially on the quotient, and preserving q then forces it to be the identity.  So item 1e")
    print("  is the finite orbit question: does Gamma_Co act trivially on the 527 classes?")


if __name__ == "__main__":
    main()
