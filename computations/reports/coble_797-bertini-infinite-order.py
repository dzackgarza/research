#!/usr/bin/env python3
"""research#797: the automorphism group of a ten-nodal Coble surface is infinite.

Run from the repository root:
    python3 computations/reports/coble_797-bertini-infinite-order.py

S = Bl_{p_1,...,p_10} P^2 at the ten nodes of an irreducible plane sextic Z, with
Pic(S) = Z<H, E_1, ..., E_10>, H^2 = 1, E_i^2 = -1, all other products 0, and
K_S = -3H + sum_i E_i.  For I a subset of {1,...,10} with |I| = 8 and {a,b} its
complement, the Bertini involution sigma_I of the eight nodes I acts on Pic(S) by

    sigma_I^*(H)   = 17 H - 6 sum_{i in I} E_i,
    sigma_I^*(E_i) = 6 H - 3 E_i - 2 sum_{j in I, j != i} E_j     (i in I),
    sigma_I^*(E_a) = E_a,   sigma_I^*(E_b) = E_b.

The H-image is prop:coble-plane-model-comparison(2) ([@Pie26, Prop. 59]); the rest
is the lattice form of the eigenspace decomposition tau^* = id_h + (-id_{E_8}) on
K_S^perp = <f_a, f_b> + E_8 of [@CD12, Thm. 3.5 and its proof], with f_j = E_j - K_S
(passing to the basis K_S, f_a, f_b and using K_S.f_j = 0, f_a.f_b = 1 gives
E_i = K_S + f_a + f_b + w and tau(x) = 2 x_parallel - x).

What is computed, exactly, over Z:
  (1) the 45 matrices are isometries of the form and involutions;
  (2) the product sigma_I sigma_J for I = {1..8}, J = {1,2,3,4,5,6,9,10} has
      characteristic polynomial (t-1)^7 (t+1)^2 (t^2-14t+1);
  (3) that product therefore has infinite order: the quadratic factor is
      irreducible over Q with roots 7 +- 4 sqrt 3, and a real root of unity is +-1,
      at which the factor does not vanish.
Hence the image of Aut(S) in O(Pic(S)) is infinite, and Aut(S) is infinite.
"""
import itertools
import sympy as sp

N = 11
G = sp.diag(1, *[-1] * 10)
t = sp.Symbol("t")


def vector(**kw):
    v = [0] * N
    v[0] = kw.get("H", 0)
    for i in range(1, N):
        v[i] = kw.get("E%d" % i, 0)
    return sp.Matrix(v)


def matrix(I):
    """Image of the basis (H, E_1, ..., E_10) under sigma_I^*, as a matrix."""
    I = set(I)
    comp = [j for j in range(1, 11) if j not in I]
    assert len(I) == 8 and len(comp) == 2
    imH = [17] + [(-6 if i in I else 0) for i in range(1, 11)]
    cols = [imH]
    for i in range(1, 11):
        if i in I:
            v = [0] * N
            v[0] = 6
            v[i] = -3
            for j in I - {i}:
                v[j] = -2
            cols.append(v)
        else:
            v = [0] * N
            v[i] = 1
            cols.append(v)
    return sp.Matrix(cols).T


def isometry(A):
    return sp.expand(A.T * G * A - G) == sp.zeros(N)


def main():
    K = vector(H=-3, **{"E%d" % i: 1 for i in range(1, 11)})
    C = vector(H=6, **{"E%d" % i: -2 for i in range(1, 11)})
    assert (K.T * G * K)[0] == -1 and (C.T * G * C)[0] == -4 and C == -2 * K
    print("K_S^2 = -1, C = -2K_S, C^2 = -4")

    subsets = list(itertools.combinations(range(1, 11), 8))
    assert len(subsets) == 45
    for I in subsets:
        A = matrix(I)
        a, b = [j for j in range(1, 11) if j not in I]
        assert isometry(A), I
        assert sp.expand(A * A - sp.eye(N)) == sp.zeros(N), I
        # the H-image is the one of prop:coble-plane-model-comparison(2)
        imgH = A * vector(H=1)
        expected = vector(H=17, **{"E%d" % i: (-6 if i in I else 0) for i in range(1, 11)})
        assert imgH == expected, I
        # the two remaining classes are fixed
        assert A * vector(**{"E%d" % a: 1}) == vector(**{"E%d" % a: 1})
        assert A * vector(**{"E%d" % b: 1}) == vector(**{"E%d" % b: 1})
    print("45 subsets: each sigma_I is an isometry, an involution, has the proved H-image,")
    print("             and fixes the two classes outside I")

    I = set(range(1, 9))
    J = {1, 2, 3, 4, 5, 6, 9, 10}
    P = matrix(I) * matrix(J)
    chi = sp.factor(P.charpoly(t).as_expr())
    print("charpoly(sigma_I sigma_J) =", chi)
    expected = (t - 1) ** 7 * (t + 1) ** 2 * (t ** 2 - 14 * t + 1)
    assert sp.expand(chi - expected) == 0

    quad = t ** 2 - 14 * t + 1
    roots = sp.solve(quad, t)
    assert roots == [7 - 4 * sp.sqrt(3), 7 + 4 * sp.sqrt(3)]
    assert quad.subs(t, 1) == -12 and quad.subs(t, -1) == 16
    big = 7 + 4 * sp.sqrt(3)
    assert big > 1 and abs(7 - 4 * sp.sqrt(3)) < 1
    print("roots of t^2 - 14t + 1: 7 +- 4 sqrt 3 = %.6f and %.6f" % (7 + 4 * 3 ** 0.5, 7 - 4 * 3 ** 0.5))
    print("neither is +-1, and a real root of unity is +-1: the factor is not cyclotomic,")
    print("so the product has infinite order in GL_11(Z), hence in O(Pic(S)).")
    print()
    print("Therefore the subgroup of O(Pic(S)) generated by the 45 Bertini involutions is")
    print("infinite, and Aut(S) is infinite at every irreducible ten-nodal sextic.")


if __name__ == "__main__":
    main()
