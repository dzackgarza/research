"""#759/#760: does the cusp-5 symmetry that exchanges 13 and 14 preserve the Coble root?

coble_760-cusp-symmetry-run.txt records that exactly one symmetry of the labelled cusp-5 Gram
fixes the Coble root's label 11 and exchanges labels 13 and 14, and that a lift of it would
make roots 13 and 14 Gamma_Co,2-equivalent.  This record tests the elementary half of that
lift, which needs no gluing theory: delta lies in the span of the fourteen roots (the saturated
span of the roots and delta has rank 10, the roots' own), so any lift restricts to the map the
permutation induces on that span, and that map is well defined because the permutation is a
Gram automorphism of the fourteen roots.

Decided here
------------
The induced map fixes the Coble root exactly: M(delta) = delta = e - f, not merely its line.
So the permutation is not excluded by the condition that a Gamma_Co,2-element preserve Z delta.

Not decided here
----------------
Whether the map extends from the rank-10 span to an integral isometry of T_En: the span has a
rank-2 complement (generated by v with v^2 = -2 and divisibility 1), T_En exceeds the sum of the
two by a finite 2-group, and the extension exists exactly when the gluing is preserved.  That is
the gluing question, and it is not settled by this record.  What the record settles is that the
question is confined there: everything the Coble root itself can say has been said.

Run
---
  $HOME/.udocker/bin/proot-x86_64 -R $HOME/sage-image/rootfs -b /proc -b /dev -b /sys \\
      -b <repo>:/repo -w /repo /sage/.venv/bin/python \\
      computations/reports/coble_759-lift-1314.py

Transcript: coble_759-lift-1314-run.txt.  Sage in the shared runtime, exact ZZ/QQ algebra.
"""
import sys
from sage.all import ZZ, QQ, matrix, vector, block_diagonal_matrix, CartanMatrix
sys.stdout.reconfigure(line_buffering=True)
C = CartanMatrix(["E", 8]); U = matrix(ZZ, [[0, 1], [1, 0]])
G = block_diagonal_matrix(U, 2 * U, -2 * C); N = 12
BAS = [vector(ZZ, [1 if k == i else 0 for k in range(N)]) for i in range(N)]
e, f, ep, fp = BAS[0], BAS[1], BAS[2], BAS[3]
alpha = [BAS[4 + i] for i in range(8)]
Cinv = C.inverse()
abar = [vector(ZZ, [int(c) for c in sum(QQ(-Cinv[k, i]) * alpha[k] for k in range(8))]) for i in range(8)]
def ip(x, y): return int(vector(ZZ, x) * G * vector(ZZ, y))
delta = e - f
et, ft = e + ep + fp - alpha[0], f + ep + fp - alpha[0]
at = [ep - fp, alpha[1], fp + alpha[2]] + list(alpha[3:8])
Gt = matrix(ZZ, 8, 8, lambda i, j: ip(at[i], at[j])); Gti = Gt.inverse()
abart = [vector(ZZ, [int(c) for c in sum(QQ(2 * Gti[k, i]) * at[k] for k in range(8))]) for i in range(8)]
eta = 2 * e + 2 * f + abar[0]
ROOTS = ([at[1], at[3], at[4], at[5], at[6], at[7], at[0], abart[7], 2 * et - at[0],
          2 * et + (abart[1] - abart[2]), ft - et, et + ft + (abart[5] - abart[2]),
          et + ft + (abart[0] + abart[7] - abart[2]), et + ft + at[2]])
SIG = [8, 6, 5, 4, 3, 2, 7, 1, 9, 10, 11, 12, 14, 13]      # 1-based labels
print("the permutation on labels 1..14: %s" % SIG)
print("  it fixes label 11 (the Coble root's class) and swaps 13 and 14: %s"
      % (SIG[10] == 11 and SIG[12] == 14 and SIG[13] == 13))
print("  it is a Gram automorphism of the fourteen roots: %s"
      % all(ip(ROOTS[i], ROOTS[j]) == ip(ROOTS[SIG[i] - 1], ROOTS[SIG[j] - 1])
            for i in range(14) for j in range(14)))

rows = [vector(ZZ, r) for r in ROOTS] + [vector(ZZ, delta)]
S = matrix(ZZ, rows).saturation()
print("rank of span(roots, delta) saturated: %d" % S.nrows())
Gb = matrix(ZZ, S.nrows(), S.nrows(), lambda i, j: ip(S[i], S[j]))
# the complement of S is rank 1; take its primitive generator
K = S.right_kernel_matrix()
KZ = matrix(ZZ, K).saturation()
print("rank of the complement: %d" % KZ.nrows())
v = vector(ZZ, KZ[0])
print("complement generator v: v^2 = %d, div = %d"
      % (ip(v, v), __import__("math").gcd(*[ip(v, b) for b in BAS])))

# delta lies in span(roots) (rank 10 above), so any lift restricts to the map the permutation
# induces there; that map is well defined because the permutation preserves every relation.
Mt, rhs = [], []
for i in range(14):
    src = vector(ZZ, ROOTS[i]); tgt = vector(ZZ, ROOTS[SIG[i] - 1])
    for k in range(N):
        row = [0] * (N * N)
        for j in range(N):
            row[k * N + j] = src[j]
        Mt.append(row); rhs.append(int(tgt[k]))
A = matrix(QQ, Mt); b = vector(QQ, rhs)
consistent = A.rank() == A.augment(b.column()).rank()
print("the permutation on the roots: %d equations, rank %d of %d unknowns, consistent %s"
      % (A.nrows(), A.rank(), A.ncols(), consistent))
sol = A.solve_right(b) if consistent else None
if sol is None:
    print("RESULT: the permutation does not extend linearly on span(roots); it cannot lift.")
    print("PYEXIT=0"); raise SystemExit
M = matrix(QQ, N, N, list(sol))
print("  M is an isometry on the span: %s" % (M.transpose() * matrix(QQ, G) * M == matrix(QQ, G) or "not on all of T_En"))
print("  M delta = %s" % list(M * vector(QQ, delta)))
md = M * vector(QQ, delta)
ck = vector(QQ, delta)
print("  M delta == delta: %s ; M delta == -delta: %s" % (md == ck, md == -ck))
print()
if md == ck or md == -ck:
    print("RESULT: the permutation fixes the Coble root's line, so it is not excluded at this stage;")
    print("the remaining question is the gluing of span(roots) with its rank-2 complement.")
else:
    print("RESULT: the permutation does not preserve the line Z delta, so no lift of it lies in")
    print("Gamma_Co,2 = Stab_{Orth(T_En)}(Z delta): it yields no transporter, and the exchange of")
    print("labels 13 and 14 by this symmetry says nothing about the Gamma_Co,2-orbits.")
print("PYEXIT=0")
