    for local_class in R_basis_classes:
        local_mask = maskR[theta(local_class)]
        full_mask = sum(((local_mask >> local_j) & 1) << global_j
                        for local_j, global_j in enumerate(complement_positions))
        complement_blocks.append(full_mask)
    full = matrix.identity(GF(2), int(Q.rank()))
    for local_i, global_i in enumerate(complement_positions):
        for local_j, global_j in enumerate(complement_positions):
            # full_mask is in global coordinates, so the test bit is global_i.
            full[global_i, global_j] = (complement_blocks[local_j] >> global_i) & 1
    assert full.rank() == int(Q.rank())
    R0_matrices.append(full.transpose())
