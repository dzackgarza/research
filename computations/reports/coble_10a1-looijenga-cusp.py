def mask_table(lattice, form):
    basis = [lattice.basis_vector(i) for i in range(lattice.rank())]
    classes = [lattice.discriminant_class(lattice.primitive_dual(v)) for v in basis]
    table = {form.zero(): 0}
    for i in range(lattice.rank()):
        for element, value in list(table.items()):
            table.setdefault(element + classes[i], value | (1 << i))
    assert len(table) == int(form.cardinality())
    return table


maskP = mask_table(P, DP)
