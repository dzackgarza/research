# 2.  The reflections and the subgroup collection.
# ---------------------------------------------------------------------------------------------
def reflection(vector):
    vector = vector.reshape(11)
    return np.mod(IDENTITY + 2 * np.outer(vector, G @ vector), 16)


def is_identity_mod(element, modulus):
    return bool(np.array_equal(element % modulus, IDENTITY % modulus))


def inverse_isometry(element, modulus):
    ring = Integers(modulus)
    inverse = matrix(ring, 11, 11, [int(entry) for entry in element.ravel()]).inverse()
    result = np.array([[int(inverse[i, j]) for j in range(11)] for i in range(11)], dtype=np.int64)
    assert is_identity_mod((element @ result) % modulus, modulus)
    return result


def sift(element, pivots, inverses, levels, modulus):
    """Kill the leading matrix at each level, from the highest entry down.

    Returns the residual and, if the residual is a new direction, its (level, entry) key.
    """
    element = element.copy()
    for level in levels:
        while True:
            leading = ((element - IDENTITY) // level) % 2
            positions = np.flatnonzero(leading.ravel())
            if positions.size == 0:
                break
            key = int(positions[-1])
            if key not in pivots[level]:
                return element, (level, key)
            element = (element @ inverses[level][key]) % modulus
    return element, None


def generated_subgroup(generators, levels, modulus):
    """The image of the subgroup generated by ``generators`` in Gamma(2)/Gamma(modulus).

    Subgroup collection: admit every generator through the pivot set, then close the admitted set
    under squares and commutators, admitting each new graded direction.  The pivot set that remains
    is a pc basis of the image; its cardinality at a level is that layer's dimension, and sifting
    against it is the membership test.
    """
    pivots = {level: {} for level in levels}
    inverses = {level: {} for level in levels}
    queue = []

    def admit(element):
        while True:
            residual, new = sift(element, pivots, inverses, levels, modulus)
            if new is None:
                assert is_identity_mod(residual, modulus)
                return
            level, key = new
            pivots[level][key] = residual
            inverses[level][key] = inverse_isometry(residual, modulus)
            queue.append((residual, inverses[level][key]))
            return

    for generator in generators:
        assert is_identity_mod(generator, 2), "a generator is not in Gamma(2)"
        admit(generator)
    position = 0
    while position < len(queue):
        element, element_inverse = queue[position]
        position += 1
        admit((element @ element) % modulus)
        for previous, previous_inverse in queue[:position]:
            commutator = (element @ previous @ element_inverse @ previous_inverse) % modulus
            admit(commutator)
    return pivots, inverses


def membership(target, pivots, inverses, levels, modulus):
    residual, new = sift(target, pivots, inverses, levels, modulus)
    return new is None and is_identity_mod(residual, modulus), residual


# Every norm -1 vector of B with entries in {-1,0,1}.
vectors = []
for entries in itertools.product((-1, 0, 1), repeat=11):
    vector = np.array(entries, dtype=np.int64)
    if int(vector @ G @ vector) == -1:
        vectors.append(vector)
assert len(vectors) == 3282, f"expected 3282 norm -1 vectors, got {len(vectors)}"
generators = [reflection(vector) for vector in vectors]
# v and -v give the same reflection, so the 3282 vectors give 1641 distinct generators.
assert len({generator.tobytes() for generator in generators}) == len(vectors) // 2
generators = list({generator.tobytes(): generator for generator in generators}.values())

images = {}
members = {}
for modulus, levels in ((8, (2, 4)), (16, (2, 4, 8))):
    pivots, inverses = generated_subgroup(generators, levels, modulus)
    layers = tuple(len(pivots[level]) for level in levels)
    images[modulus] = layers
    record = {}
    for name, element in (("delta_E8", np.array(DELTA, dtype=np.int64)),
                          ("minus_id", np.array(MINUS_ID, dtype=np.int64)),
                          ("epsilon_prime", np.array(EPSILON_PRIME, dtype=np.int64))):
        inside, residual = membership(element, pivots, inverses, levels, modulus)
        record[name] = bool(inside)
        assert inside, f"{name} is not in the subgroup modulo {modulus}"
    members[modulus] = record
    if modulus == 16:
        pivots16, inverses16 = pivots, inverses

assert images[8] == (55, 54), images[8]
assert images[16] == (55, 54, 55), images[16]

