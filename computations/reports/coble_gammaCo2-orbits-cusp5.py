"""#760: the Gamma_Co,2-orbits of the three admissible roots at cusp 5, by exact walk.

The question
------------
research#760 compares two admissible roots r_1, r_2 of K_I that are INEQUIVALENT under
Gamma_Co,2 = Stab_{O(T_En)}(Z delta) (prop:gamma-co-2-line-stabilizer).  At cusp 5 the three
admissible T_Co-roots are Sterk's printed labels 12, 13, 14; they have pairwise distinct classes
in K_5 (coble_coble-root-orbits-run.txt), but distinct classes are not distinct orbits, because
Gamma_Co,2 acts on K_5 non-trivially: the reflection in a lift of any class orthogonal to delta is
an integral isometry of T_En preserving delta, hence lies in Gamma_Co,2, and it carries the class of
r to the class of -r.  This record decides the orbit question itself.

The acting family, and why each generator is in Gamma_Co,2
----------------------------------------------------------
Every root of K_5 that is the class of a (-2)- or (-4)-vector of T_Co orthogonal to eta_5 lifts to
a vector w of T_En with w.delta = 0 and 2 div(w) in (w.w) Z, so s_w is an integral isometry of
T_En [@AEGS25, section 3.4, printed p. 591]; it fixes delta, so s_w in Stab_{O(T_En)}(Z delta)
= Gamma_Co,2; and it fixes eta_5, because w.eta_5 = 0, so it acts on K_5 = eta_5^perp / Z eta_5.
At cusp 5 there are eleven such roots: printed labels 1--8 (square -4) and 12, 13, 14 (square -2)
(coble_irrelevant-marking-face-run.txt, line printing the walls in T_Co).  The record asserts, for
each, the three facts above -- integrality of the matrix, w.delta = 0, s_w(eta_5) = eta_5 -- rather
than assuming them.

What a reached class proves, and what its absence does not
---------------------------------------------------------
The walk searches the subgroup generated by those eleven reflections.  A class reached from 12 is
Gamma_Co,2-EQUIVALENT to it, certified by the word that reaches it, and so closes the question for
that pair in the affirmative.  A class not reached within the depth bound is NOT thereby proved
inequivalent: the subgroup computed with may be a proper subgroup of the stabilizer of eta_5 in
Gamma_Co,2.  The record therefore reports its orbit size and its depth bound with the verdict, so
that the bound is on the record rather than implied away.

The data
--------
T_En = U + U(2) + E8(2) with basis (e, f, e', f', a_1..a_8): e.f = 1, e'.f' = 2, and the a_i have
Gram matrix -2 cartan(E8).  delta = e - f, delta^2 = -2, T_Co = delta^perp; eta_5 = 2e + 2f + abar_1
is Sterk's representative, and the fourteen printed roots are transcribed from
computations/reports/coble_sterk-reflection-subgroups.py, as in the two accepted records.

Classes.  A class of K_5 is represented canonically by the unique vector x of eta_5^perp whose
e-coordinate is 0 or 1: every x of eta_5^perp has e-coordinate x_e, eta_5 has e-coordinate 2, so
x - floor(x_e/2) eta_5 is the representative, and two vectors lie in one class exactly when their
representatives are equal.  The quotient is legitimate because Z eta_5 is primitive in eta_5^perp.

Run
---
  $HOME/.udocker/bin/proot-x86_64 -R $HOME/sage-image/rootfs -b /proc -b /dev -b /sys \\
      -b <repo>:/repo -w /repo /bin/sh -c \\
      'PATH=/sage/.venv/bin:$PATH python /repo/computations/reports/coble_gammaCo2-orbits-cusp5.py'

Transcript: coble_gammaCo2-orbits-cusp5-run.txt.  Sage in the shared runtime; exact integer and
rational linear algebra only, no provider call, no GAP, no pari.
"""
import sys
import time

sys.stdout.reconfigure(line_buffering=True)

from sage.all import ZZ, QQ, matrix, vector, block_diagonal_matrix, CartanMatrix, identity_matrix, gcd
from sage.version import version as SAGE_VERSION

t0 = time.time()

C = CartanMatrix(["E", 8])
U = matrix(ZZ, [[0, 1], [1, 0]])
G = block_diagonal_matrix(U, 2 * U, -2 * C)
N = 12
BAS = [vector(ZZ, [1 if k == i else 0 for k in range(N)]) for i in range(N)]
e, f, ep, fp = BAS[0], BAS[1], BAS[2], BAS[3]
alpha = [BAS[4 + i] for i in range(8)]
Cinv = C.inverse()
abar = [vector(ZZ, [int(c) for c in sum(QQ(-Cinv[k, i]) * alpha[k] for k in range(8))])
        for i in range(8)]


def ip(x, y):
    return int(vector(ZZ, x) * G * vector(ZZ, y))


delta = e - f
eta = 2 * e + 2 * f + abar[0]

a9, a10 = f - e, 2 * fp + abar[7]
et, ft = e + ep + fp - alpha[0], f + ep + fp - alpha[0]
at = [ep - fp, alpha[1], fp + alpha[2]] + list(alpha[3:8])
Gt = matrix(ZZ, 8, 8, lambda i, j: ip(at[i], at[j]))
Gti = Gt.inverse()
abart = [vector(ZZ, [int(c) for c in sum(QQ(2 * Gti[k, i]) * at[k] for k in range(8))])
         for i in range(8)]
ROOTS5 = [at[1], at[3], at[4], at[5], at[6], at[7], at[0], abart[7],
          2 * et - at[0], 2 * et + (abart[1] - abart[2]), ft - et,
          et + ft + (abart[5] - abart[2]), et + ft + (abart[0] + abart[7] - abart[2]),
          et + ft + at[2]]

print("the Gamma_Co,2-orbits of the three admissible roots at cusp 5")
print("Sage %s; exact ZZ/QQ arithmetic; T_En determinant %d" % (SAGE_VERSION, G.det()))
print("delta = e - f, delta^2 = %d; eta_5 = 2e + 2f + abar_1, eta_5^2 = %d" % (ip(delta, delta), ip(eta, eta)))
print()

# the reflections in Gamma_Co,2 that act on K_5: the roots orthogonal to delta, and delta itself,
# which is a class of K_5 (its printed label is 11) and whose reflection fixes delta by definition
# and fixes eta_5 because delta . eta_5 = 0
walls = [label for label in range(1, 15) if ip(ROOTS5[label - 1], delta) == 0]
delta_label = [label for label in range(1, 15)
               if abs(ip(ROOTS5[label - 1], delta)) == 2 and ip(ROOTS5[label - 1], ROOTS5[label - 1]) == -2]
print("the root of K_5 that is +-delta: printed label %s" % delta_label)
assert len(delta_label) == 1 and ip(ROOTS5[delta_label[0] - 1], ROOTS5[delta_label[0] - 1]) == -2
generators = walls + delta_label
admissible = [label for label in walls if ip(ROOTS5[label - 1], ROOTS5[label - 1]) == -2]
print("the eleven walls in T_Co at cusp 5, and delta itself: %s" % generators)
print("the admissible (-2) ones: %s" % admissible)
assert walls == [1, 2, 3, 4, 5, 6, 7, 8, 12, 13, 14], walls
assert generators == walls + [11], generators
assert admissible == [12, 13, 14], admissible

print()
print("=== each wall's reflection: integral, preserving delta, preserving eta_5")
mats = {}
for label in generators:
    w = ROOTS5[label - 1]
    w2 = ip(w, w)
    S = identity_matrix(QQ, N) - (QQ(2) / w2) * matrix(QQ, N, 1, list(w)) * matrix(
        QQ, 1, N, list(G * vector(ZZ, w)))
    integral = all(x in ZZ for x in S.list())
    assert integral, ("cusp 5 label %d: the reflection is not integral" % label)
    S = matrix(ZZ, S)
    assert S * vector(ZZ, delta) == vector(ZZ, delta) or S * vector(ZZ, delta) == -vector(ZZ, delta), label
    assert S * vector(ZZ, eta) == vector(ZZ, eta), label
    # the root condition of AEGS25 section 3.4, checked rather than cited: div(w) is the gcd of
    # its pairings with a basis, and 2 div(w) must lie in (w.w) Z
    div = 0
    for k in range(N):
        div = gcd(div, abs(ip(w, BAS[k])))
    assert (2 * div) % abs(w2) == 0, ("cusp 5 label %d: 2 div(w) = %d not in %d Z" % (label, 2 * div, w2))
    mats[label] = S
    print("  label %2d: w^2 = %2d, div(w) = %d, w.delta = %d, w.eta_5 = %d, integral: %s"
          % (label, w2, div, ip(w, delta), ip(w, eta), integral))


print()
print("=== the classes of the three admissible roots in K_5, canonically represented")
print("a class is represented by the unique x of eta_5^perp with e-coordinate 0 or 1,")
print("namely x - floor(x_e/2) eta_5; Z eta_5 is primitive in eta_5^perp")


def canon(x):
    """The canonical representative of the class of x in K_5 = eta_5^perp / Z eta_5."""
    x = vector(ZZ, x)
    assert ip(x, eta) == 0, ("not in eta_5^perp", list(x))
    k = x[0] // 2
    rep = x - k * vector(ZZ, eta)
    assert rep[0] in (0, 1), (x, rep)
    assert ip(rep, eta) == 0
    return tuple(rep)


for label in admissible:
    print("  label %2d: class %s  square %d" % (label, canon(ROOTS5[label - 1]), ip(ROOTS5[label - 1], ROOTS5[label - 1])))

# the scalar invariants of a class: its square, its pairing with delta, and its divisibility in K_5,
# the last computed as the gcd of its pairings with a Z-basis of eta_5^perp (a basis of the quotient
# plus eta_5, which pairs trivially with everything, gives the same gcd)
row = vector(ZZ, G * vector(ZZ, eta))
S_, U_, V_ = matrix(ZZ, 1, N, list(row)).smith_form()
assert S_[0, 0] != 0
Lbasis = [vector(ZZ, [V_[i, j] for i in range(N)]) for j in range(1, N)]
assert len(Lbasis) == 11 and all(ip(b, eta) == 0 for b in Lbasis)
print()
print("=== the scalar invariants of the three classes (square, pairing with delta, divisibility in K_5)")
for label in admissible:
    r = ROOTS5[label - 1]
    d = 0
    for b in Lbasis:
        d = gcd(d, abs(ip(r, b)))
    print("  label %2d: r^2 = %2d, (r, delta) = %d, div_{K_5}(r) = %d"
          % (label, ip(r, r), ip(r, delta), d))
print("no scalar invariant separates them, so the orbit question is not settled by one")

start = canon(ROOTS5[11])
targets = {canon(ROOTS5[12]): 13, canon(ROOTS5[13]): 14}
seen = {start: (0, None, None)}

print()
print("=== the walk from the class of label 12 under the twelve certified reflections")
print("the reflection in delta fixes every class orthogonal to delta, so it adds nothing to the walk;")
print("it is carried along for completeness")
DEPTH = int(sys.argv[1]) if len(sys.argv) > 1 else 12
CAP = 200000
frontier = [start]
found = {}
depth = 0
while frontier and depth < DEPTH and len(seen) < CAP:
    depth += 1
    nxt = []
    for x in frontier:
        for label in generators:
            y = canon(mats[label] * vector(ZZ, x))
            if y in seen:
                continue
            seen[y] = (depth, x, label)
            nxt.append(y)
            if y in targets and targets[y] not in found:
                found[targets[y]] = (depth, y)
    print("  depth %2d: %6d classes reached in all" % (depth, len(seen)))
    if len(found) == len(targets):
        break
    frontier = nxt


def word(y):
    """The word in the eleven reflections that reaches the class y from the start."""
    steps = []
    while seen[y][2] is not None:
        depth_of, parent, label = seen[y]
        steps.append(label)
        y = parent
    return list(reversed(steps))


print()
for label_of_target in (13, 14):
    hit = targets[canon(ROOTS5[label_of_target - 1])]
    if hit in found:
        print("label 12 and label %d: THE SAME Gamma_Co,2-orbit; a word reaching it: %s"
              % (label_of_target, word(canon(ROOTS5[label_of_target - 1]))))
    else:
        print("label 12 and label %d: not reached within depth %d over %d classes"
              % (label_of_target, DEPTH, len(seen)))
print()
print("orbit of the class of label 12 under the twelve reflections: %d classes at depth %d, cap %d"
      % (len(seen), DEPTH, CAP))
if len(found) == len(targets):
    print("verdict: labels 12, 13 and 14 are pairwise Gamma_Co,2-equivalent at cusp 5, so the")
    print("hypothesis of conj:no_moduli_loss (two INEQUIVALENT admissible T_Co-roots at a marked")
    print("cusp) is never met at cusp 5, and none of the three pairs is a counterexample to it.")
else:
    print("verdict: the subgroup generated by the twelve certified reflections does not carry the class of")
    print("label 12 to that of label 13 or of label 14 within the bound above; this is not a proof")
    print("of inequivalence under the whole of Gamma_Co,2, since the subgroup may be proper.")
print("elapsed %d s" % round(time.time() - t0))
print("PYEXIT=0")
