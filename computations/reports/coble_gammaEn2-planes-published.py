def _root_count(Gram, budget=None):
    """Exact root counts through the owned library call vectors_of_square.

    The provider enumerates shells exactly (exhaustive inverse-Gram coordinate box for small
    shells, Hecke short_vectors after Gram LLL for large ones -- see
    sage_extensions/categories/definite_lattices.py, _square_shell).  No floating-point bound
    enters: the library owns the exhaustiveness.  Counts are taken on the positive form -Gram
    (same module, bijective correspondence of shells: square s on -Gram is square -s on Gram).
    """
    P = matrix(ZZ, 8, 8, [[-int(x) for x in row] for row in Gram])
    L = Lattices(ZZ)([list(r) for r in P.rows()])
    hist = {}
    for pos, neg in ((4, -4), (2, -2)):
        shells = L.vectors_of_square(pos)
        try:
            cnt = int(shells.cardinality())
        except AttributeError:
            cnt = int(shells.domain().cardinality())
        hist[neg] = cnt
    return hist.get(-4, 0), hist


