def subgroup_elements(gens):
    elems = set()
    for mask in range(1 << len(gens)):
        acc = [0] * N
        for b in range(len(gens)):
            if mask >> b & 1:
                acc = [(a + c) % 2 for a, c in zip(acc, gens[b])]
        elems.add(tuple(acc))
    return elems


def type_set(gens):
    out = set()
    for e in subgroup_elements(gens):
        if any(e):
            out.add(TYPE_OF_ORBIT[ORBIT_OF[e]])
    return tuple(sorted(out))


# --------------------------------------------------------------------------- plane invariants
def pi_star_order(v, w):
    """|Pi*/Pi| = |det of the lattice generated by ((v,b_i),(w,b_i))|, i = 0..11"""
    rows = []
    for i in range(N):
        unit = [1 if k == i else 0 for k in range(N)]
        rows.append((pairing(v, unit), pairing(w, unit)))
    L = matrix(ZZ, rows)
    det = 1
    rank = 0
    for x in L.elementary_divisors():
        if x:
            det *= x
            rank += 1
    assert rank == 2, "pairing lattice not rank 2"
    return det


def perp_quotient(v, w):
    """Pi_perp/Pi: (determinant, root count at -4, norm histogram, bound)"""
    gv = list(G * vector(ZZ, v))
    gw = list(G * vector(ZZ, w))
    Mp = matrix(ZZ, 2, N, [gv, gw])
    Kern = Mp.right_kernel().basis_matrix()           # 10 x 12, saturated
    Gp = Kern * G * Kern.transpose()                  # 10 x 10
    C = matrix(ZZ, 2, 10)
    for idx, u in enumerate((v, w)):
        c = Kern.transpose().solve_right(vector(ZZ, u))
        assert all(x in ZZ for x in c), "generator not in Pi_perp"
        C.set_row(idx, [int(x) for x in c])
    Dm, Um, Vm = C.smith_form()          # sage convention: Dm = Um * C * Vm
    assert [x for x in Dm.diagonal() if x] == [1, 1], "plane not primitive in Pi_perp"
    Vi = Vm.inverse()                     # rowspace(C) = <rows 0,1 of Vi>
    R = Vi.rows()[2:]
    Gq = [[sum(R[i][k] * Gp[k][l] * R[j][l] for k in range(10) for l in range(10))
           for j in range(8)] for i in range(8)]
    Gqm = matrix(ZZ, 8, 8, Gq)
    det = Gqm.determinant()
    # certificate: [C; R] must be unimodular, so R really complements rowspace(C)
    stack = C.stack(matrix(ZZ, 8, 10, R))
    assert abs(stack.determinant()) == 1, "complement does not split the lattice"
    count4, hist = _root_count(Gq)
    return abs(det), count4, hist, None


def plane_report(label, v, w):
    P = matrix(ZZ, 2, N, [v, w])
    d = P.elementary_divisors()
    cls_gens = [parity(x) for x in (v, w) if even_pairing(x)]
    sub = subgroup_elements(cls_gens)
    det, count4, hist, bound = perp_quotient(v, w)
    print("  %s" % label)
    print("    generators: %s / %s" % (v, w))
    print("    Smith divisors: %s (primitive: %s)" % (d, d == [1, 1]))
    print("    |Pi*/Pi| = %d" % pi_star_order(v, w))
    print("    Pi_perp/Pi: det %d, root count (-4) %d, norm histogram %s"
          % (det, count4, hist))
    print("    discriminant image: order %d, orbit-type set %s"
          % (len(sub), type_set(cls_gens)))
    print("")
    return det, count4


