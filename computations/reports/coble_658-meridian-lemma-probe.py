"""research#658 item 1e: the meridian lemma, and its smallest case verified.

LEMMA.  Let L be an integral lattice, A = L^v/L, rho: O(L) -> O(A) the discriminant representation.  Let
Gamma <= O(L) be generated by elements of the two forms

  (i)  a reflection s_d in a vector d with d^2 = -2;
  (ii) an Eichler transvection tau_{u,v}(x) = x + (x.u)v - (x.v)u, with u, v isotropic and (u,v) = 0.

Then Gamma <= ker(rho).

PROOF.  For x in L^v and d in L, (x,d) is an integer, so

  s_d(x) - x = -2(x,d)d/(d,d) = (x,d) d  lies in L;

for x in L^v and u, v in L, (x,u) and (x,v) are integers, so

  tau_{u,v}(x) - x = (x.u) v - (x.v) u  lies in L.

Hence each generator acts trivially on A = L^v/L; rho is a homomorphism, so rho is trivial on the subgroup
they generate.  []

CONSEQUENCE for item 1e, with L = T_Co: the sign lemma (lem:monodromy-is-spinor-positive) puts
Gamma_Co in O^+(T_Co); if Gamma_Co is generated by the two forms above -- the reflections being the
Picard--Lefschetz monodromies of the (-2)-walls (prop:monodromy-contains-root-reflections) and the
transvections the unipotent monodromies at the cusps (coble_658-cusp-parabolic-probe.py) -- then
Gamma_Co <= ker(rho) cap O^+ = O~+(T_Co), which is exactly item 1e, and prop:gamma-co-strong-lifting
gives the Gamma_Co form of thm:coble-strong-lifting.

SMALLEST CASE, computed here: L = T_Co = <2> + U(2) + E8(2), d = h + a_1 (square -2), and
tau_{e', v} with v = 2h + a_1 + a_3 (both isotropic, and e'.v = 0).  The probe checks that both are
integral isometries, that the identity g(x) - x in T_Co holds for the ten generators x = G^{-1}e_i of the
dual, and that both act trivially on A_{T_Co}.

Usage: python3 computations/reports/coble_658-meridian-lemma-probe.py
"""

from __future__ import annotations

from fractions import Fraction as F


def e8_cartan():
    c = [[0] * 8 for _ in range(8)]
    for i in range(8):
        c[i][i] = 2
    for i in range(6):
        c[i][i + 1] = c[i + 1][i] = -1
    c[2][7] = c[7][2] = -1
    return c


def block_diagonal(blocks):
    n = sum(len(b) for b in blocks)
    g = [[0] * n for _ in range(n)]
    off = 0
    for b in blocks:
        for i in range(len(b)):
            for j in range(len(b)):
                g[off + i][off + j] = b[i][j]
        off += len(b)
    return g


U = [[0, 1], [1, 0]]
G = block_diagonal([[[2]], [[2 * x for x in row] for row in U],
                    [[-2 * x for x in row] for row in e8_cartan()]])      # T_Co, rank 11
N = len(G)


def mv(m, v):
    return [sum(m[i][j] * v[j] for j in range(len(v))) for i in range(len(m))]


def dot(x, y):
    return sum(x[i] * G[i][j] * y[j] for i in range(N) for j in range(N))


def transpose(m):
    cols = len(m[0])
    return [[m[j][i] for j in range(len(m))] for i in range(cols)]


def matmul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(len(b))) for j in range(len(b[0]))]
            for i in range(len(a))]


def inverse(m):
    n = len(m)
    a = [[F(m[i][j]) for j in range(n)] + [F(int(i == j)) for j in range(n)] for i in range(n)]
    for col in range(n):
        piv = next(r for r in range(col, n) if a[r][col] != 0)
        a[col], a[piv] = a[piv], a[col]
        pv = a[col][col]
        a[col] = [x / pv for x in a[col]]
        for r in range(n):
            if r != col and a[r][col] != 0:
                f = a[r][col]
                a[r] = [x - f * y for x, y in zip(a[r], a[col])]
    return [row[n:] for row in a]


GINV = inverse(G)


def is_integral(m):
    return all(getattr(x, "denominator", 1) == 1 for row in m for x in row)


def is_isometry(m):
    return is_integral(m) and matmul(transpose(m), matmul(G, m)) == G


def action_trivial_on_dual_generators(m):
    """g(x) - x in L for the generators x = G^{-1} e_i of L^v: the identity the lemma's proof uses."""
    ok = True
    for i in range(N):
        y = [F(0)] * N
        y[i] = F(1)
        y = mv(GINV, y)
        z = mv(m, y)
        if any((a - b).denominator != 1 for a, b in zip(z, y)):
            ok = False
    return ok


def reflection(v):
    gv = mv(G, v)
    q = dot(v, v)
    out = [[0] * N for _ in range(N)]
    for j in range(N):
        c = F(2 * gv[j], q)
        for i in range(N):
            out[i][j] = F(1 if i == j else 0) - c * v[i]
    return [[int(x) for x in row] for row in out]


def transvection(u, v):
    gu, gv = mv(G, u), mv(G, v)
    out = [[0] * N for _ in range(N)]
    for j in range(N):
        e = [0] * N
        e[j] = 1
        a = sum(e[i] * gu[i] for i in range(N))
        b = sum(e[i] * gv[i] for i in range(N))
        for i in range(N):
            out[i][j] = e[i] + a * v[i] - b * u[i]
    return out


def main():
    def vec(h=0, ep=0, fp=0, roots=()):
        v = [0] * N
        v[0], v[1], v[2] = h, ep, fp
        for index, value in roots:
            v[3 + index] = value
        return v

    d = vec(h=1, roots=((0, 1),))
    u = vec(ep=1)
    v = vec(h=2, roots=((0, 1), (2, 1)))

    print("L = T_Co = <2> + U(2) + E8(2), rank %d" % N)
    print("d = h + a_1:  d^2 = %d" % dot(d, d))
    print("u = e': square %d;  v = 2h + a_1 + a_3: square %d;  (u,v) = %d"
          % (dot(u, u), dot(v, v), dot(u, v)))

    s_d = reflection(d)
    tau = transvection(u, v)
    for name, g in (("s_d", s_d), ("tau_{u,v}", tau)):
        print("%-10s integral %s  isometry %s  g(x)-x in L on the dual generators %s"
              % (name, is_integral(g), is_isometry(g), action_trivial_on_dual_generators(g)))
        assert is_integral(g) and is_isometry(g) and action_trivial_on_dual_generators(g)
    print()
    print("verdict: the meridian lemma is PROVED (both forms satisfy g(x) - x in L for x in L^v, so both")
    print("act trivially on A_L), and its smallest case is verified above: on T_Co with d = h + a_1 and")
    print("tau_{e',v}, both generators are integral isometries with trivial discriminant action.")
    print("item 1e therefore holds for every subgroup of O(T_Co) generated by such elements; the")
    print("remaining input is that Gamma_Co is one, i.e. the monodromy generation (prop:monodromy-")
    print("contains-root-reflections for the walls and coble_658-cusp-parabolic-probe.py for the cusps).")


if __name__ == "__main__":
    main()
