Hre = matrix(ZZ, 14, N, [list(r) for r in R5])
rows2 = matrix(ZZ, 14, N, [list(G * vector(ZZ, r)) for r in R5])
S2, _, V2 = rows2.smith_form()
K = [vector(ZZ, [V2[i, j] for i in range(N)]) for j in range(N) if all(S2[k, j] == 0 for k in range(14))]
h = Hre.hermite_form(include_zero_rows=False)
L0 = [vector(ZZ, list(h.row(i))) for i in range(h.nrows()) if any(x != 0 for x in h.row(i))]
L0q = matrix(QQ, matrix(ZZ, len(L0), N, [list(v) for v in L0]))
L0pinv = L0q.transpose() * (L0q * L0q.transpose()).inverse()
basisq = matrix(QQ, matrix(ZZ, 12, 12, [list(v) for v in L0] + [list(v) for v in K]).transpose())

Mgram = matrix(ZZ, G)
V = ZZ**N
U2 = [2, 3]                 # A_{U(2)}  : e_3, e_4   (0-based)
E8M = list(range(4, N))     # A_{E8(-2)}: e_5..e_12 (0-based)


def subgroup(block):
    """the subgroup of A generated by the classes of the block's basis vectors, as a lattice in Z^12"""
    gens = [vector(ZZ, list(Mgram.column(j))) for j in range(N)]
    gens += [vector(ZZ, [1 if k == b else 0 for k in range(N)]) for b in block]
    return V.submodule(gens)


def order_in_A(block):
    covol = abs(subgroup(block).basis_matrix().det())
    return abs(Mgram.det()) // covol


def summands_preserved(g):
    C = matrix(QQ, g.transpose())
    out = []
    for tag, block in (("A_{U(2)}", U2), ("A_{E8(-2)}", E8M)):
        W = subgroup(block)
        bad = []
        for b in block:
            c = C * vector(QQ, [1 if k == b else 0 for k in range(N)])
            if not (all(x in ZZ for x in c) and vector(ZZ, c) in W):
                bad.append(b + 1)
        out.append((tag, block, bad))
    return out


def build_13_14():
    SIG = [8, 6, 5, 4, 3, 2, 7, 1, 9, 10, 11, 12, 14, 13]
    Him = matrix(ZZ, 14, N, [list(R5[SIG[i] - 1]) for i in range(14)])
    Cq = matrix(ZZ, matrix(QQ, Hre) * L0pinv)
    Dq = matrix(ZZ, matrix(QQ, Him) * L0pinv)
    F = (matrix(QQ, Cq).pseudoinverse() * matrix(QQ, Dq)).transpose()
    imgs = [sum((int(F[j, i]) * L0[j] for j in range(len(L0))), vector(ZZ, [0] * N)) for i in range(len(L0))]
    img = matrix(ZZ, 12, 12, [list(v) for v in imgs] + [list(v) for v in K]).transpose()
    return matrix(ZZ, img * basisq.inverse())


def build_12_13():
    r12, r13 = R5[11], R5[12]
    Sy, _, Vy = matrix(ZZ, 3, N, [list(G * vector(ZZ, v)) for v in (delta, r12, r13)]).smith_form()
    K3 = [vector(ZZ, [Vy[i, j] for i in range(N)]) for j in range(N) if all(Sy[k, j] == 0 for k in range(3))]
    Sb, _, Vb = matrix(ZZ, len(K3), N, [list(G * vector(ZZ, k)) for k in K3]).smith_form()
    P = [vector(ZZ, [Vb[i, j] for i in range(N)]) for j in range(N) if all(Sb[k, j] == 0 for k in range(len(K3)))]
    T = matrix(QQ, [list(delta), list(r12), list(r13)]).transpose()
    swapped = []
    for b in P:
        co = T.solve_right(vector(QQ, b))
        assert all(x in ZZ for x in co), co
        swapped.append(int(co[0]) * delta + int(co[2]) * r12 + int(co[1]) * r13)
    PP = matrix(ZZ, 12, 12, [list(v) for v in P] + [list(v) for v in K3]).transpose()
    im = matrix(ZZ, 12, 12, [list(v) for v in swapped] + [list(v) for v in K3]).transpose()
    return matrix(ZZ, matrix(QQ, im) * matrix(QQ, PP).inverse()), abs(PP.det())


def reflection(w):
    w = vector(ZZ, w)
    S = identity_matrix(QQ, N) - (QQ(2) / ip(w, w)) * matrix(QQ, N, 1, list(w)) * matrix(QQ, 1, N, list(G * w))
    return matrix(ZZ, S) if all(x in ZZ for x in S.list()) else None


def verdict(name, g, swap=None):
    ok = all(x in ZZ for x in g.list())
    form = matrix(QQ, N, N, list(g.transpose() * G * g)) == matrix(QQ, G)
    keeps = g * vector(ZZ, delta) == vector(ZZ, delta) and g * vector(ZZ, eta) == vector(ZZ, eta)
    rows = summands_preserved(g)
    ingent = all(not bad for (_, _, bad) in rows)
    print("%-46s integral %s  form %s  fixes delta,eta_5 %s  in Gent %s"
          % (name, ok, form, keeps, ingent))
    for tag, block, bad in rows:
        if bad:
            print("      carried out of %-10s by the classes [d_%s]"
                  % (tag, "], [d_".join(str(b) for b in bad)))
    if swap is not None:
        print("      swaps printed labels %d and %d: %s"
              % (swap[0], swap[1],
                 g * vector(ZZ, R5[swap[0] - 1]) == vector(ZZ, R5[swap[1] - 1])
                 and g * vector(ZZ, R5[swap[1] - 1]) == vector(ZZ, R5[swap[0] - 1])))
    return ingent


