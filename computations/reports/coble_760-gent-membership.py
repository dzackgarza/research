"""#760: the 12 <-> 13 witness is an isometry of T_En but not an element of Gent, so it does not
settle the Gamma_Co,2-orbit; the 13 <-> 14 witness does.

The page claimed (bdb78a77ce) that the three admissible T_Co-roots at cusp 5 are one
Gamma_Co,2-orbit, hence that conj:no_moduli_loss holds vacuously.  Both witnesses were checked
there as integral form-preserving matrices fixing delta and eta_5, and that is all they are:

  Gamma_Co,2 = R_Gent, the image of Stab_Gent(delta) in O(T_Co)   (@def:gamma-co-groups(5)),

and Gent = rho^{-1}(M) is *smaller* than O(T_En).  By [@AEGS25, Def. 2.6] the group Gamma_En,2 is
the image of the centralizer {g in O(L) : g I = I g, g(h) = h}, not all of O(T_En); by
[@Ste91, Prop. 2.7] that image is exactly the set of isometries whose induced map on

    A_{T_En} = A_{U(2)} + A_{E8(-2)} ,   of order 4 and 256,

respects the decomposition in the two summands.  The page's own @prop:gamma-co-images proof states
the same criterion.  So membership in Gamma_Co,2 needs one further check beyond integrality, and
the record makes it:

    g in Gent  <=>  the induced map a |-> g^T a on A_{T_En} = Z^12 / G Z^12
                    carries each summand into itself.

The action is read in a-coordinates: a in Z^12 stands for the class of sum_{i} a_i d_i, where
d_i is the dual basis vector, and then the class of g(d_i) is the i-th column of g^T, so the
induced map is literally a |-> g^T a modulo G Z^12, and it is well defined because
g^T G = G g^{-1} is integral.

Result:

  13 <-> 14 witness (the diagram symmetry):  in Gent, both summands preserved.  Roots 13 and 14
      are Gamma_Co,2-equivalent, and that claim of the page stands.
  12 <-> 13 witness (transposition on the saturation of <delta, r12, r13>, extended by the
      identity on its complement):  integral and form-preserving, fixes delta and eta_5, but it
      does NOT preserve A_{E8(-2)}: the classes [d_6], [d_7] and [d_11] are carried out of that
      summand.  So it lies outside Gent, and it witnesses only that roots 12 and 13 are in one
      O(T_En)-orbit --- not that they are Gamma_Co,2-equivalent.

The test is calibrated on elements the page already places in Gamma_Co,2: the identity, -id, and
the reflections s_w in all eleven printed roots w with (w, delta) = 0, which [@AEGS25, Sec. 3.4]
makes integral; every one of them is in Gent by this test.  The one element the test rejects is
the one witness the vacuity argument needed.

    usage: python3 computations/reports/coble_760-gent-membership.py
"""
