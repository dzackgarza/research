import os
import sys
import time

sys.stdout.reconfigure(line_buffering=True)
os.environ["PATH"] = os.path.dirname(os.path.realpath("/sage/.venv/bin/sage")) + os.pathsep + os.environ.get("PATH", "")

import sage_extensions  # noqa: E402
import sage_indefinite_port  # noqa: E402

from sage.all import CartanMatrix, ZZ, block_diagonal_matrix, matrix  # noqa: E402
from sage.version import version as SAGE_VERSION  # noqa: E402
from sage_extensions.all import Lattices  # noqa: E402

print('provenance')
print('  Sage: %s' % SAGE_VERSION)
print('  sage-indefinite-port: %s' % os.path.dirname(sage_indefinite_port.__file__))
print('  sage-extensions:      %s' % os.path.dirname(sage_extensions.__file__))
print('')

U = matrix(ZZ, [[0, 1], [1, 0]])
E8 = -CartanMatrix(['E', 8])
T = Lattices(ZZ)([list(r) for r in block_diagonal_matrix(U, 2 * U, 2 * E8).rows()])
A = T.discriminant_quadratic_form()
print('T_En: rank %d, det %s, signature %s' % (T.rank(), T.determinant(), T.signature_pair()))
print('|A| = %d, isotropic classes %d' % (int(A.cardinality()), len(list(A.isotropic_elements()))))
print('')

basis = [T.basis_vector(i) for i in range(T.rank())]
e, f = basis[2], basis[3]                    # U(2) summand of T_En = U + U(2) + E8(2)
roots = basis[4:12]                          # E8(2) summand

# the nine isometries, as isometries of T_En itself
swap = T.reflection(e - f)                   # the reflection in the <2> direction e - f of U(2)
reflections = [T.reflection(r) for r in roots]
generators = [swap] + reflections
print('the nine isometries of T_En')
print('  s_(e-f): square of (e-f) = %s' % (e - f).q())
print('  eight root reflections in E8(2): squares %s' % [r.q() for r in roots])
print('')

start = time.time()
rho = T.discriminant_representation()
images = tuple(rho(g) for g in generators)
print('their discriminant images: built in %.0f s' % (time.time() - start))
O_T = A.orthogonal_group()
print('|O(A_T,q)| = %d' % int(O_T.order()))
M = O_T.subgroup(images)
print('|M| = %d   (|W(E8)| = 696729600: %s)' % (int(M.order()), int(M.order()) == 696729600))
print('')

print('Gamma_En,2 = T.Aut().discriminant_preimage(M)')
start = time.time()
preimage = T.Aut().discriminant_preimage(M)
print('  built in %.0f s: %s' % (time.time() - start, str(preimage)[:160]))
print('  character data retained: %s' % (preimage.character_data_is_complete(),))
print('')

for rank, published in ((1, 5), (2, 9)):
    print('rank %d' % rank)
    for label, group in (('Gamma_En,2', preimage), ('O(T_En)', T.Aut())):
        start = time.time()
        try:
            reps = group.isotropic_orbit_representatives(rank)
            count = reps.cardinality() if hasattr(reps, 'cardinality') else len(list(reps))
            print('  %-10s isotropic_orbit_representatives(%d) -> %s   (%.0f s)'
                  % (label, rank, count, time.time() - start))
        except Exception as exc:
            print('  %-10s FAILED %s   (%.0f s): %s' % (label, type(exc).__name__, time.time() - start,
                                                        str(exc)[:300]))
    print('  published: %d' % published)
    print('')
