import os
import sys
import time

sys.stdout.reconfigure(line_buffering=True)
os.environ["PATH"] = os.path.dirname(os.path.realpath("/sage/.venv/bin/sage")) + os.pathsep + os.environ.get("PATH", "")

from sage.all import ZZ, block_diagonal_matrix, matrix  # noqa: E402
from sage.version import version as SAGE_VERSION  # noqa: E402

from sage_extensions.all import Lattices  # noqa: E402

PIN = '15db925b0c92e525f769fcbf57135f1391263a9e'
print('provenance')
print('  Sage: %s' % SAGE_VERSION)
print('  sage-extensions: .scratch/se-provider-15db925b/src, pin %s' % PIN[:12])
print('')

U = matrix(ZZ, [[0, 1], [1, 0]])
B = Lattices(ZZ)([list(r) for r in block_diagonal_matrix(U, U, -matrix.identity(ZZ, 7)).rows()])
T = Lattices(ZZ)([list(r) for r in (2 * block_diagonal_matrix(U, U, -matrix.identity(ZZ, 7))).rows()])
basis = [B.basis_vector(i) for i in range(B.rank())]
e1, e2 = basis[0], basis[2]
print('B = U + U + I_{0,7}: rank %d, det %s, signature %s;  T = B(2): det %s'
      % (B.rank(), B.determinant(), B.signature_pair(), T.determinant()))
P = B.primitive_sublattice_from([e1, e2])
print('P = <e1,e2>: rank %d, primitive' % P.rank())
print('')

start = time.time()
A = T.discriminant_quadratic_form()
O = A.orthogonal_group()
n = int(A.cardinality())
order_O = int(O.order())
print('A_{T_Co}: %d classes;  |O(q)| = %d   (%.0f s)' % (n, order_O, time.time() - start))
print('')

# J = [P/2] <= A, of order 4
eT1, eT2 = T.basis_vector(0), T.basis_vector(2)
c1 = T.discriminant_class(T.primitive_dual(eT1))
c2 = T.discriminant_class(T.primitive_dual(eT2))
print('J = [P/2]: classes of e1/2 and e2/2; q-values %s and %s'
      % (A.q(c1), A.q(c2)))
try:
    J = A.primitive_isotropic_subobject(c1, c2)
    print('  as a subobject: cardinality %s, primitive_isotropic %s'
          % (int(J.cardinality()), True))
except Exception as exc:                                    # noqa: BLE001
    J = None
    print('  could not form the subobject: %s: %s' % (type(exc).__name__, exc))
print('')

print('stage 1a: Stab_{O(B)}(P) from the lattice side, setwise')
start = time.time()
try:
    stabB = B.Isom(B).stabilizer(P, action='setwise')
    gens = list(stabB.group_generators())
    print('  the stabilizer returns %d generators   (%.0f s)' % (len(gens), time.time() - start))
    print('  each is an isometry of B: %s'
          % all(all(B.pairing(g(basis[i]), g(basis[j])) == B.pairing(basis[i], basis[j])
                    for i in range(B.rank()) for j in range(B.rank())) for g in gens))
    print('  each preserves P: %s'
          % all(all(g(x) in P for x in (e1, e2)) for g in gens))
    rho_T = T.discriminant_representation()
    images = [rho_T(g) for g in gens]
    print('stage 1b: |rho(Stab_{O(B)}(P))| as a subgroup of O(q)')
    start = time.time()
    H = O.subgroup(images)
    order_H = int(H.order())
    print('  |rho(Stab_{O(B)}(P))| = %d   (%.0f s)' % (order_H, time.time() - start))
except Exception as exc:                                    # noqa: BLE001
    order_H = None
    print('  FAILED: %s: %s' % (type(exc).__name__, exc))
print('')

print('stage 2: |Stab_{O(q)}(J)|, by orbit-stabilizer on the order-4 isotropic subgroups')
start = time.time()
try:
    stabJ = O.stabilizer(J, action='setwise')
    order_stabJ = int(stabJ.order())
    print('  |Stab_{O(q)}(J)| = %d   (%.0f s)' % (order_stabJ, time.time() - start))
except Exception as exc:                                    # noqa: BLE001
    order_stabJ = None
    print('  FAILED: %s: %s' % (type(exc).__name__, exc))
print('')

if order_H is not None and order_stabJ is not None:
    print('THE EXACT INDEX')
    print('  [Stab_{O(q)}(J) : rho(Stab_{O(B)}(P))] = %d / %d = %d'
          % (order_stabJ, order_H, order_stabJ // order_H))
else:
    print('THE INDEX IS NOT DETERMINED BY THIS RUN')
    print('  order of the image: %s; order of the stabilizer: %s' % (order_H, order_stabJ))
