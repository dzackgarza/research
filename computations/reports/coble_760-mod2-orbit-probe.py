"""#760: the mod-2 orbit of Sterk's label 12, under the Gent elements this record can build.

The pair (12,13) at cusp 5 is the one open orbit question on the page (@rmk:coble-root-orbits-cusp-five).
Gamma_Co,2 = R_Gent, and Gamma(2) = ker(O(T_En) -> O(T_En/2T_En)) is contained in ker rho, hence in
Gent: an isometry congruent to the identity mod 2 acts trivially on A_{T_En} = T_En^*/T_En, because
2(L*) is contained in L.  So the action of Gent on T_En/2T_En is an action of the finite group
Gent/Gamma(2), and the class of a root mod 2 is a Gent-invariant of its Gamma_Co,2-orbit:

    r12 ~_Gent r13  =>  the classes of r12 and r13 in T_En/2T_En are in one orbit of Gent.

What this record computes is that orbit for the subgroup H of Gent generated by elements it can build
and check: the fourteen reflections in the printed roots, the eight reflections in the E8(-2) basis
vectors, and the swap of the two U(2) basis vectors.  Every generator is put through the summand test
of coble_760-gent-membership.py before it is used, so H is inside Gent and the H-orbit it reports is
inside the Gent-orbit.

The result is one-sided and decides nothing about the pair:

    the orbit of the mod-2 class of label 12 under H has 512 classes and contains neither the class of
    label 13 nor that of label 14, while the classes of 13 and 14 lie in one H-orbit.

A negative answer for H is not a negative answer for Gent.  The decisive object is the image of the
whole of Gent in O(T_En/2T_En), that is

    G_g = { sigma in O(T_En/2T_En) : rho(sigma) in M }   (M the summand-preserving subgroup),

and the orbit of the class of 12 under G_g.  Equivalently, with g any isometry carrying r12 to r13,
the pair is decided by whether the image of g in O(A_{T_En}, q) lies in
M . rho(Stab_O(r12) cap Stab_O(delta) cap Stab_O(Z eta_5)).  The stabilizer generators the provider
needs for that are available at this checkout for a single vector (lattice_morphisms.py:4282, :4791);
what is missing is the intersection, which the library builds as a predicate but does not resolve
into generators (coble_760-transporter-in-gent-run.txt prints the failure).  Nothing here is a
substitute for it, and no statement on the page is read off this record.

    usage: python3 computations/reports/coble_760-mod2-orbit-probe.py
"""
