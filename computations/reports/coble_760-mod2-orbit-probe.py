exec(src.split('Hre = matrix')[0].split('print("the cusp symmetries')[0])   # G, N, delta, eta, R5, ip

Mgram = matrix(ZZ, G)
F2 = GF(2)
U2, E8M = [2, 3], list(range(4, N))


def in_span(c, block):
    gens = [vector(ZZ, list(Mgram.column(j))) for j in range(N)]
    gens += [vector(ZZ, [1 if k == b else 0 for k in range(N)]) for b in block]
    return vector(ZZ, c) in (ZZ**N).submodule(gens)


def is_gent(g):
    """the summand test of coble_760-gent-membership.py: integral, form-preserving, summands preserved"""
    if g is None or not all(x in ZZ for x in g.list()):
        return False
    if matrix(QQ, N, N, list(g.transpose() * G * g)) != matrix(QQ, G):
        return False
    C = matrix(QQ, g.transpose())
    for block in (U2, E8M):
        for b in block:
            c = C * vector(QQ, [1 if k == b else 0 for k in range(N)])
            if not in_span(list(c), block):
                return False
    return True


def reflection(w):
    w = vector(ZZ, w)
    S = identity_matrix(QQ, N) - (QQ(2) / ip(w, w)) * matrix(QQ, N, 1, list(w)) * matrix(QQ, 1, N, list(G * w))
    return matrix(ZZ, S) if all(x in ZZ for x in S.list()) else None


print("the mod-2 orbit of the cusp-5 labels, under the Gent elements this record can build")
print("Sage %s; exact integer linear algebra over T_En = U + U(2) + E8(-2)" % SAGE_VERSION)
print("Gamma(2) = ker(O(T_En) -> O(T_En/2T_En)) is contained in ker rho, hence in Gent")
print()

gens, rejected = [], []
for lab in range(1, 15):
    r = reflection(R5[lab - 1])
    (gens if is_gent(r) else rejected).append(("s%d" % lab, r))
for i in range(8):
    w = vector(ZZ, [0] * N)
    w[4 + i] = 1
    r = reflection(w)
    (gens if is_gent(r) else rejected).append(("e8_%d" % i, r))
S = identity_matrix(ZZ, N)
S[2, 2], S[3, 3], S[3, 2], S[2, 3] = 0, 0, 1, 1
(gens if is_gent(S) else rejected).append(("swap_u2", S))
print("generators checked and accepted as Gent elements: %d" % len(gens))
print("   %s" % ", ".join(n for n, _ in gens))
print("reflections rejected by the summand test (not used): %s" % (", ".join(n for n, _ in rejected) or "none"))
print()

G2 = [matrix(F2, N, N, lambda i, j: int(g[i, j]) % 2) for _, g in gens]


def bits(v):
    return tuple(int(x) % 2 for x in v)


def act(M, b):
    return tuple(int(sum(M[i, j] * F2(b[j]) for j in range(N))) % 2 for i in range(N))


def orbit(start):
    seen, frontier = {start}, [start]
    while frontier:
        new = []
        for b in frontier:
            for M in G2:
                c = act(M, b)
                if c not in seen:
                    seen.add(c)
                    new.append(c)
        frontier = new
    return seen


