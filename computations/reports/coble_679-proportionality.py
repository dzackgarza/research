"""Are ABE22's divisor and the rational-curve divisor the same class? (research#679, A36)

    python3 computations/reports/coble_679-proportionality.py

No dependencies beyond the standard library: the whole question is exact
arithmetic in the rank-two lattice spanned by the section and the fibre.

The statement probed.  ABE22, Intro., write

    R = s + m sum_{i=1}^{24} f_i        (m >= 1, "any m >= 1 gives the same result")

and then compute, for the sum of the rational curves of |L|,

    R_rc == n_d ( s + (d+1)/24 sum_{i=1}^{24} f_i ),   "which is proportional to s + m sum f_i",

and name the compactification of the first divisor after the rational curves.
The withdrawn theorem of research#679 used that sentence to pass from the
compactification of (X, eps R_rc) to that of (X, eps(s + m sum f_i)).

The arithmetic.  All fibres of a morphism are algebraically equivalent, so the
24 singular fibres satisfy sum_{i=1}^{24} f_i == 24 f in the Neron-Severi
lattice, which is generated by s and f with s^2 = -2, f^2 = 0, s.f = 1 (an
elliptic K3 with a section, and L = s + (d+1) f, ABE22, Intro.).  Two classes
are proportional exactly when their coefficient vectors on (s, f) are.

What it establishes: the printed proportionality holds only at
m = (d+1)/24, which is not an integer, and at the integer m for which the two
divisors have equal degree the classes differ.  So no m >= 1 makes ABE22's
divisor and the rational-curve divisor the same class, and the sentence cannot
carry the identification.
"""

from fractions import Fraction

# Neron-Severi of the elliptic K3, in the basis (s, f).
GRAM = {"ss": Fraction(-2), "ff": Fraction(0), "sf": Fraction(1)}

FIBRES = 24            # the 24 singular fibres
YAU_ZASLOW = {1: 24}   # n_1, the number of rational curves in |L| for d = 1


def pairing(u, v):
    """The intersection number of two classes given in the (s, f) basis."""
    return GRAM["ss"] * u[0] * v[0] + GRAM["sf"] * (u[0] * v[1] + u[1] * v[0]) + GRAM["ff"] * u[1] * v[1]


def show(name, vector):
    print("  %-34s %s   degree against L: %s" % (name, format_vector(vector), pairing(vector, POLARIZATION)))


def format_vector(vector):
    return "(%s) s + (%s) f" % (vector[0], vector[1])


def proportional(u, v):
    """Return the scalar and True when u and v are proportional, else (None, False)."""
    if v[0] != 0:
        scale = Fraction(u[0], 1) / v[0]
        if u[1] == scale * v[1]:
            return scale, True
        return None, False
    if v[1] != 0:
        if u[0] == 0:
            return Fraction(u[1], 1) / v[1], True
        return None, False
    return None, False


for d in sorted(YAU_ZASLOW):
    print("d = %d, polarization L = s + %d f" % (d, d + 1))
    POLARIZATION = (Fraction(1), Fraction(d + 1))
    print("  L^2 = %s" % pairing(POLARIZATION, POLARIZATION))
    total_fibres = (Fraction(0), Fraction(FIBRES))
    print("  sum of the 24 singular fibres: %s" % format_vector(total_fibres))

    rational_curves = tuple(YAU_ZASLOW[d] * entry for entry in POLARIZATION)
    show("R_rc == n_d L", rational_curves)

    # ABE22's divisor s + m sum f_i, and the class their display calls proportional to it.
    print("  ABE22: s + m (sum f_i) = s + %d m f, against R_rc == n_d(s + (d+1)/24 sum f_i):" % FIBRES)
    reference = (Fraction(1), Fraction(d + 1))
    print("    coefficient of s: 1 in both, so any proportionality has scalar 1")
    needed = Fraction(d + 1, FIBRES)
    print("    coefficient of f: need %d m = %d, that is m = (d+1)/24 = %s" % (FIBRES, d + 1, needed))
    for m in (1, 2, 3):
        candidate = (Fraction(1), Fraction(FIBRES * m))
        scale, is_proportional = proportional(reference, candidate)
        print("    m = %d: divisor %s | proportional to s + (d+1) f: %s%s" % (
            m, format_vector(candidate), is_proportional,
            "" if is_proportional else "  (degrees: %s vs %s)" % (
                pairing(candidate, POLARIZATION), pairing(reference, POLARIZATION))))
    # the integer m at which the degrees agree
    equality = Fraction(pairing(rational_curves, POLARIZATION), FIBRES)
    at_equality = (Fraction(1), Fraction(FIBRES) * equality)
    print("    deg(R_rc) = %s and deg(s + m sum f_i) = %d m, so the degrees agree at m = %s;" % (
        pairing(rational_curves, POLARIZATION), FIBRES, equality))
    print("    there the classes are proportional: %s  (%s vs %s)" % (
        proportional(reference, at_equality)[1], format_vector(at_equality), format_vector(reference)))
    print()

print("Conclusion.  ABE22's divisor s + m sum f_i coincides with the rational-curve divisor's")
print("class only at m = (d+1)/24, which is not an integer; at the integer m that equalizes")
print("degrees the two classes are not proportional.  The printed 'proportional to' therefore")
print("cannot carry the identification of the two stable-pair compactifications, which is why")
print("thm:recognizable-fails-W was withdrawn (rmk:recognizable-gap).")
