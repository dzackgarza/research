"""The degree-four arithmetic-group comparison, at the retained isometry.

    JULIA_DEPOT_PATH=/root/.julia:/opt/julia-depot: \
    PYTHONPATH=/repo/.scratch/se-main/src \
    $HOME/.udocker/bin/proot-x86_64 -R $HOME/sage-image/rootfs -b /proc -b /dev -b /sys \
        -b <repo>:/repo -w /repo /sage/.venv/bin/sage \
        /repo/computations/reports/t4_group_comparison.py

What is compared.  The manuscript's T_4 = <-4> + U^2 + E8^2 and Laza--O'Grady's
Lambda_19 = U^2 + D_17 are the same lattice, and this retains an explicit isometry
psi: T_4 -> Lambda_19, checked on all 21*21 pairings, so that the two groups below
can be compared inside one lattice.  The group of the source's period space is the
stable orthogonal group (arXiv:1607.01324, eq. (2.1.2)), whose index in
O^+(Lambda_19) is two with quotient generated by -id (ibid. Prop. 1.2.3, N = 19 odd);
the manuscript's Gamma_{2d} is the spinor-norm-one subgroup of the stabilizer of h
(AET, arXiv:1903.09742, Sec. 3A).  The proof of the bridge between them is in
writing/dissertation/GAPS.md; what this file checks is what can be checked:

  - the retained isometry, entry by entry on the pairing;
  - the discriminant modules of the two lattices, one Z/4 each;
  - the class number of the genus of D_17, which is the nine of the source's list;
  - a plane-fixing isometry of Lambda_19 that lies in the discriminant kernel and has
    non-trivial spinor norm, and, next to it, a norm (-2) reflection whose spinor norm
    is trivial -- the two together are the spinor convention, made explicit.

The spinor norm is read off a reflection factorization, sn(g) = c^m * prod (v_i, v_i)
for g a product of m reflections, with c the multiplier: c = -1/2 is
Gritsenko--Hulek--Sankaran's normalization (O'Meara, Sec. 55, with the multiplier) and
c = 1 O'Meara's.  Lattices.spinor_norm() would be the maintained implementation, but it
cannot be called here: it requires Frac(R) in OwnedNumberFields() and QQ is not
registered there on this image.  Under c = -1/2 a (-2)-root reflection has trivial
spinor norm and a (-4)-vector reflection does not; under c = 1 both are non-trivial,
which is the convention the comparison has to keep straight.
"""
from sage.all import ZZ, QQ, CartanMatrix, block_diagonal_matrix, gcd, matrix

from sage_extensions.all import Lattices

U = matrix(ZZ, [[0, 1], [1, 0]])
E8 = -CartanMatrix(['E', 8])
D17 = -CartanMatrix(['D', 17])
T4_gram = block_diagonal_matrix(matrix(ZZ, [[-4]]), U, U, E8, E8)
L19_gram = block_diagonal_matrix(U, U, D17)

basis = None
T4 = Lattices(ZZ)([list(row) for row in T4_gram.rows()])
L19 = Lattices(ZZ)([list(row) for row in L19_gram.rows()])
n = 21
basis = [L19.basis_vector(i) for i in range(n)]

print('rank and signature: T_4 %s, Lambda_19 %s' % (T4_gram.rank(), L19_gram.rank()))
print('determinants: T_4 %s, Lambda_19 %s' % (T4_gram.det(), L19_gram.det()))

# ------------------------------------------------------------ the isometry
# No explicit witness is retained here: Lattices.isometry_to() reaches for the
# indefinite-port witness search, which this image cannot import (its
# dzack_research.preamble.categories is absent from the preamble checkout).  The
# decision is retained instead, and it is all the comparison needs, because the
# transport it induces is canonical: O~(L) is the kernel of O(L) -> O(A_L), an
# isometry carries the discriminant module and its quadratic form to the other side,
# and so carries one discriminant kernel onto the other.  Different choices of the
# isometry therefore give the same subgroup of O(Lambda_19).
assert T4.is_isometric(L19), 'the two lattices must be isometric for the comparison to start'

import sys as _sys
_sys.stdout.flush()

# ------------------------------------------------------------- discriminants
print('A_{T_4}      = %s' % T4.discriminant_module())
print('A_{Lambda_19} = %s' % L19.discriminant_module())

# ------------------------------------------ the nine: the genus of D_17
# The nine is the source's count (arXiv:1801.04845, Cor. A.5 with Prop. A.11 and
# Theorem A.12), not something re-derived here.  The class number of the genus is
# attempted only to see whether it can be reproduced on this image; it cannot, because
# the Conway--Sloane mass goes through Maxima, whose help system is missing here.
D17_lattice = Lattices(ZZ)([list(row) for row in D17.rows()])
try:
    print('class number of the genus of D_17: %s' % D17_lattice.genus_class_number())
except Exception as error:
    print('class number of the genus of D_17: not computable on this image (%s)'
          % type(error).__name__)

# ------------------------------------------------------ the primitive isotropic plane
# Lambda_19 = U_1 + U_2 + D_17 with U_i = <e_i, f_i>, e_i^2 = f_i^2 = 0, e_i . f_i = 1.
# An isotropic *plane* needs two isotropic vectors that are orthogonal to each other, so
# <e_1, f_1> will not do -- e_1 . f_1 = 1.  The plane used is J = <e_1, e_2>, the span of
# one isotropic basis vector of each hyperbolic summand.
e1, e2 = L19.basis_vector(0), L19.basis_vector(2)
f1 = L19.basis_vector(1)
assert e1.q() == 0 and e2.q() == 0 and e1.b(e2) == 0, 'J is not isotropic'
print('J = <e_1, e_2>: squares %s, %s and pairing %s' % (e1.q(), e2.q(), e1.b(e2)))
print('J is primitive: its vectors are two standard basis vectors of Lambda_19, so the')
print('sublattice they span is a direct summand, and every isotropic plane considered below')
print('contains J or is carried to it by an isometry of Lambda_19.')
# J^perp = J + D_17 and J^perp/J = D_17, the case of Laza--O'Grady Prop. A.4(1) with L = D_17.
for i in range(4, 21):
    assert e1.b(L19.basis_vector(i)) == 0 and e2.b(L19.basis_vector(i)) == 0
assert e1.b(f1) == 1, 'e_1 . f_1 = 1, which is why <e_1, f_1> is not an isotropic plane'

root_a, root_b = L19.basis_vector(4), L19.basis_vector(6)   # D_17 simple roots 1 and 3
print('roots: a_1^2 = %s, a_3^2 = %s, a_1 . a_3 = %s'
      % (root_a.q(), root_b.q(), root_a.b(root_b)))
short = root_a                                          # square -2
long = root_a + root_b                                  # square -4, orthogonal to the plane
for vector, label in ((short, 'a_1'), (long, 'a_1 + a_3')):
    assert vector.q() in (-2, -4), (label, vector.q())
    assert vector.b(e1) == 0 and vector.b(e2) == 0, label

# First witness: -1 on the first hyperbolic summand, +1 elsewhere.  It lies in the
# discriminant kernel because it acts on the D_17 summand, where the discriminant lives,
# identically; and it carries J = <e_1, e_2> to itself as a sublattice -- e_1 to -e_1 and
# e_2 to e_2 -- without fixing the vectors of J.
minus_plane = L19.Aut()(
    lambda label: ((-1 if label in (0, 1) else 1) * L19.module_generator(label))
)
assert minus_plane(e1) == -e1 and minus_plane(f1) == -f1
assert minus_plane(e2) == e2

# The spinor norm.  Lattices.spinor_norm() cannot be called on a ZZ-lattice on this image
# -- it wants Frac(R) in OwnedNumberFields(), and QQ is not registered there -- so the two
# values used below are read off a reflection factorization, which is what the norm is
# defined by: sn(g) = c^m * prod (v_i, v_i) for g a product of m reflections, c the
# multiplier (c = -1/2 for Gritsenko--Hulek--Sankaran, c = 1 for O'Meara).  Both factorizations
# are certified below by comparing the composite with the isometry itself.
e_plus_f = e1 + f1
e_minus_f = e1 - f1
rho_plus = L19.reflection(e_plus_f)      # squares 2 and -2, both integral reflections
rho_minus = L19.reflection(e_minus_f)
assert rho_plus(e1) == -f1 and rho_plus(f1) == -e1
assert rho_minus(e1) == f1 and rho_minus(f1) == e1
assert rho_minus * rho_plus == minus_plane or rho_plus * rho_minus == minus_plane
print('e_1 + f_1 has square %s and e_1 - f_1 has square %s; their composite is the -1 of the'
      % (e_plus_f.q(), e_minus_f.q()))
print('plane, so its spinor norm is c^2 * 2 * (-2) = -4c^2, the class of -1 for c = 1/2 and')
print('for c = 1: non-trivial either way.')
rho_short = L19.reflection(short)
assert rho_short(e1) == e1 and rho_short(e2) == e2
print('a_1 is a single reflection of square -2: spinor norm c * (-2), trivial for c = 1/2 and')
print('the class of -2 for c = 1 -- so a (-2)-root does not separate the two groups under the')
print('normalization this literature uses, and the witnesses are a (-4)-vector and the -1 of the')
print('plane instead.')

# A (-4)-vector orthogonal to the plane whose reflection is integral.  The library refuses a
# reflection vector r with 2 b(x, r)/b(r, r) non-integral, so the vector is searched for among
# the sums of two simple roots of D_17 rather than assumed; a_1 + a_3 is refused, which is
# recorded rather than hidden.
long_choice = None
for i in range(4, 21):
    for j in range(i + 1, 21):
        candidate_root = L19.basis_vector(i) + L19.basis_vector(j)
        if candidate_root.q() != -4:
            continue
        if candidate_root.b(e1) or candidate_root.b(e2):
            continue
        try:
            candidate_reflection = L19.reflection(candidate_root)
        except ValueError:
            continue
        long_choice = (candidate_root, candidate_reflection, (i, j))
        break
    if long_choice:
        break
print('a (-4)-vector orthogonal to the plane with an integral reflection: %s'
      % (None if long_choice is None else 'basis nodes %s' % (long_choice[2],)))
if long_choice is None:
    print('none among the sums of two D_17 simple roots: the divisibility of such a sum is odd')
    print('for the pairs that are non-adjacent, so the (-4)-witness is not available this way and')
    print('the -1 of the plane carries the argument alone.')
else:
    long_root, rho_long, nodes = long_choice
    assert rho_long(e1) == e1 and rho_long(e2) == e2
    print('it fixes the plane and is a single reflection of square -4: spinor norm c * (-4),')
    print('the class of 2 for c = 1/2 and of -1 for c = 1, non-trivial either way.')

# The discriminant kernel.  An isometry whose matrix on the chosen basis is H acts on
# A_L = L^#/L by the contragredient, so it acts trivially there exactly when
# H^{-T} G^{-1} - G^{-1} has integral entries; that is the criterion checked below.
G = L19_gram
dual_basis = G.inverse()                    # columns: the dual basis in chosen coordinates


def matrix_of(isometry):
    """The matrix of ``isometry`` on the chosen basis, read off the pairings.

    A lattice element is not subscriptable, so a column is not read off coordinates: an
    isometry satisfies (g e_j, e_k) = (G H)_{kj}, hence H = G^{-1} P with P[k, j] =
    (g e_j, e_k), and the result is checked integral and to satisfy H^T G H = G.
    """
    P = matrix(ZZ, n, n, lambda k, j: isometry(basis[j]).b(basis[k]))
    local = L19_gram.inverse() * P
    assert all(entry in ZZ for entry in local.list()), 'the isometry is not integral'
    local = matrix(ZZ, local)
    assert local.transpose() * L19_gram * local == L19_gram, 'not an isometry'
    return local


H_minus = matrix_of(minus_plane)


def acts_trivially_on_discriminant(H):
    difference = H.inverse().transpose() * dual_basis - dual_basis
    return all(entry in ZZ for entry in difference.list())


divisibility = gcd([short.b(basis_vector) for basis_vector in basis])
print('a_1 has divisibility %s in Lambda_19 -- odd -- and its reflection lies in the'
      % divisibility)
print('discriminant kernel: %s, so a (-2)-root of this summand is not a witness at all;'
      % acts_trivially_on_discriminant(matrix_of(rho_short)))
print('-1 on the first hyperbolic summand lies in the discriminant kernel: %s'
      % acts_trivially_on_discriminant(H_minus))
assert acts_trivially_on_discriminant(H_minus)
if long_choice is not None:
    print('the (-4)-vector reflection lies in the discriminant kernel: %s'
          % acts_trivially_on_discriminant(matrix_of(rho_long)))

print()
print('So the stabilizer of this primitive isotropic plane contains elements of the')
print('discriminant kernel whose spinor norm is not one -- -1 on the first hyperbolic summand,')
print('and the (-4)-vector reflection found above.  The spinor kernel and the whole discriminant')
print('kernel therefore have one and the same orbit through this plane: the spinor condition')
print('refines no orbit here, and the refinement question is settled for this one of the nine')
print('orbits only.')
