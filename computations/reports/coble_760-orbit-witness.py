"""#760, item 7: a witness search over all fourteen roots, with delta and eta checked on the word.

Roots 12, 13, 14 at cusp 5 are pairwise distinct in K_5.  A Gamma_Co,2-element carrying one to
another is an isometry of T_En that (a) maps the class of 12 to the class of +-13 and (b) preserves
Z delta and fixes eta_5 up to sign; any such element certifies the two roots EQUIVALENT, and then
conj:no_moduli_loss has no instance at cusp 5 and is vacuous there rather than refuted.

The earlier walk used only the roots that already fix delta and eta (the eleven T_Co walls and
delta itself), so every word in it was automatically in the acting group; it found nothing to
depth 12.  This record searches the larger group generated by ALL fourteen printed roots and tests
delta and eta on the word itself: a word that happens to preserve both is a witness, and a word
that does not is discarded.  Finding none is not proof of inequivalence --- the word may be longer
than the bound --- and the record says so.

    usage: PYTHONPATH=<repo>/.scratch/sage-extensions/src python \\
               <repo>/computations/reports/coble_760-orbit-witness.py [DEPTH]
"""
import sys
import time

sys.stdout.reconfigure(line_buffering=True)

from sage.all import ZZ, QQ, matrix, vector, block_diagonal_matrix, CartanMatrix, identity_matrix  # noqa: E402

t0 = time.time()
C = CartanMatrix(["E", 8])
U = matrix(ZZ, [[0, 1], [1, 0]])
G = block_diagonal_matrix(U, 2 * U, -2 * C)
N = 12
BAS = [vector(ZZ, [1 if k == i else 0 for k in range(N)]) for i in range(N)]
e, f, ep, fp = BAS[0], BAS[1], BAS[2], BAS[3]
alpha = [BAS[4 + i] for i in range(8)]
Cinv = C.inverse()
abar = [vector(ZZ, [int(c) for c in sum(QQ(-Cinv[k, i]) * alpha[k] for k in range(8))])
        for i in range(8)]


def ip(x, y):
    return int(vector(ZZ, x) * G * vector(ZZ, y))


delta = e - f
eta = 2 * e + 2 * f + abar[0]
et, ft = e + ep + fp - alpha[0], f + ep + fp - alpha[0]
at = [ep - fp, alpha[1], fp + alpha[2]] + list(alpha[3:8])
Gt = matrix(ZZ, 8, 8, lambda i, j: ip(at[i], at[j]))
Gti = Gt.inverse()
abart = [vector(ZZ, [int(c) for c in sum(QQ(2 * Gti[k, i]) * at[k] for k in range(8))])
         for i in range(8)]
R5 = [at[1], at[3], at[4], at[5], at[6], at[7], at[0], abart[7],
      2 * et - at[0], 2 * et + (abart[1] - abart[2]), ft - et,
      et + ft + (abart[5] - abart[2]), et + ft + (abart[0] + abart[7] - abart[2]),
      et + ft + at[2]]

# the fourteen reflections, as integral matrices on T_En
mats = []
for label in range(1, 15):
    w = R5[label - 1]
    w2 = ip(w, w)
    S = identity_matrix(QQ, N) - (QQ(2) / w2) * matrix(QQ, N, 1, list(w)) * matrix(
        QQ, 1, N, list(G * vector(ZZ, w)))
    assert all(x in ZZ for x in S.list()), label
    mats.append((label, matrix(ZZ, S)))
print("fourteen integral reflections on T_En, labels 1..14; delta^2 = %d, eta^2 = %d"
      % (ip(delta, delta), ip(eta, eta)))

# canonical form of a class of K_5 = eta^perp / Z eta: e-coordinate reduced to 0 or 1
def canon(x):
    x = vector(ZZ, x)
    k = x[0] // 2
    return tuple(x - k * vector(ZZ, eta))


def in_eta_perp(x):
    return ip(x, eta) == 0


start = canon(R5[11])
targets = {canon(R5[12]): 13, canon(R5[13]): 14}
print("start: class of label 12;",
      "targets: classes of labels 13 and 14")

DEPTH = int(sys.argv[1]) if len(sys.argv) > 1 else 8
CAP = 60000
seen = {start: ()}
frontier = [start]
hits = []
reached = 0
capped = False
for depth in range(1, DEPTH + 1):
    reached = depth
    nxt = []
    for x in frontier:
        word = seen[x]
        for label, S in mats:
            y = canon(S * vector(ZZ, x))
            if not in_eta_perp(vector(ZZ, y)):
                continue
            if y in seen:
                continue
            seen[y] = word + (label,)
            nxt.append(y)
            if y in targets:
                hits.append((targets[y], word + (label,)))
    print("  depth %2d: %6d classes, %d hits on a target" % (depth, len(seen), len(hits)))
    if len(seen) > CAP:
        print("  cap reached: no further depth is searched")
        capped = True
        break
    frontier = nxt
print()
print("witnesses found: %d" % len(hits))
kept = 0
for target, word in hits:
    M = identity_matrix(ZZ, N)
    for label in word:
        M = dict(mats)[label] * M
    d_img = M * vector(ZZ, delta)
    e_img = M * vector(ZZ, eta)
    ok_delta = d_img in (vector(ZZ, delta), -vector(ZZ, delta))
    ok_eta = e_img in (vector(ZZ, eta), -vector(ZZ, eta))
    if ok_delta and ok_eta:
        kept += 1
        print("  WITNESS: 12 -> %d, word over labels %s, delta -> %s delta, eta -> %s eta"
              % (target, list(word), "+" if d_img == vector(ZZ, delta) else "-",
                 "+" if e_img == vector(ZZ, eta) else "-"))
    else:
        print("  discarded: 12 -> %d, word %s moves delta: %s, eta: %s"
              % (target, list(word), not ok_delta, not ok_eta))
print()
if kept:
    print("VERDICT: the roots are Gamma_Co,2-equivalent at cusp 5 by the witness above, so")
    print("conj:no_moduli_loss has no instance at cusp 5 and is vacuous there rather than refuted.")
else:
    print("VERDICT: no witness within depth %d over %d classes%s."
          % (reached, len(seen), ", the cap having stopped the search there" if capped else ""))
    print("This is not a proof of inequivalence: the acting group is infinite, and a witness may")
    print("be longer than the bound.  What it does settle is that no word of that length over all")
    print("fourteen printed roots carries 12 to 13 or 14 while preserving delta and eta_5.")
print("elapsed %d s" % (time.time() - t0))
print("PYEXIT=0")
