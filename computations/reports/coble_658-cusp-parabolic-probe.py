"""research#658 item 1e: the cusp monodromies are Eichler transvections, and those are in the kernel.

The reflective part of the monodromy of the Coble period quotient is in ker(rho_{T_Co})
(coble_658-reflective-generation-probe.py).  The other part of a monodromy group of a period-domain
family is the unipotent monodromy at the cusps.  This probe takes the cusp data of F^un_Co as the book
states it -- the 0-cusp vector v_1 = e' and the 1-cusp plane J = <v_1, v_2> with v_2 = 2h + a_1 + a_2,
both isotropic (lem:divisibilityTcoOne, lem:1_cusp_correspondence) -- and verifies that the unipotent
elements they generate are Eichler transvections tau_{u,v}(x) = x + (x.u)v - (x.v)u, hence lie in
ker(rho_{T_Co}) by the same one-line reason as the reflections.

What that gives and what it does not.  Every kind of element that occurs as monodromy of this family is
now verified to act trivially on A_{T_Co}: reflections in (-2)-vectors, Eichler transvections, and the
products.  So item 1e holds for any subgroup of O(T_Co) generated by them.  Whether Gamma_Co is such a
subgroup is the index [Gamma_Co : W(T_Co)] together with the parabolic generation, and that is open:
@qst:gamma-co-generators, @prob:coxeter-completeness.  This probe cannot close it, and does not claim to.

Usage: python3 computations/reports/coble_658-cusp-parabolic-probe.py
"""

from __future__ import annotations

from fractions import Fraction as F
from itertools import product


def e8_cartan():
    c = [[0] * 8 for _ in range(8)]
    for i in range(8):
        c[i][i] = 2
    for i in range(6):
        c[i][i + 1] = c[i + 1][i] = -1
    c[2][7] = c[7][2] = -1
    return c


def block_diagonal(blocks):
    n = sum(len(b) for b in blocks)
    g = [[0] * n for _ in range(n)]
    off = 0
    for b in blocks:
        for i in range(len(b)):
            for j in range(len(b)):
                g[off + i][off + j] = b[i][j]
        off += len(b)
    return g


U = [[0, 1], [1, 0]]
G = block_diagonal([[[2]], [[2 * x for x in row] for row in U],
                    [[-2 * x for x in row] for row in e8_cartan()]])       # T_Co: <2> + U(2) + E8(2)
N = len(G)


def mv(m, v):
    return [sum(m[i][j] * v[j] for j in range(len(v))) for i in range(len(m))]


def dot(x, y):
    return sum(x[i] * G[i][j] * y[j] for i in range(N) for j in range(N))


def transpose(m):
    return [[m[j][i] for j in range(len(m))] for i in range(len(m[0]))]


def matmul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(len(b))) for j in range(len(b[0]))]
            for i in range(len(a))]


def inverse(m):
    n = len(m)
    a = [[F(m[i][j]) for j in range(n)] + [F(int(i == j)) for j in range(n)] for i in range(n)]
    for col in range(n):
        piv = next(r for r in range(col, n) if a[r][col] != 0)
        a[col], a[piv] = a[piv], a[col]
        pv = a[col][col]
        a[col] = [x / pv for x in a[col]]
        for r in range(n):
            if r != col and a[r][col] != 0:
                f = a[r][col]
                a[r] = [x - f * y for x, y in zip(a[r], a[col])]
    return [row[n:] for row in a]


GINV = inverse(G)


def is_integral(m):
    return all(getattr(x, "denominator", 1) == 1 for row in m for x in row)


def is_isometry(m):
    return is_integral(m) and matmul(transpose(m), matmul(G, m)) == G


def discriminant_trivial(m):
    for i in range(N):
        y = [F(0)] * N
        y[i] = F(1)
        y = mv(GINV, y)
        z = mv(m, y)
        if any((a - b).denominator != 1 for a, b in zip(z, y)):
            return False
    return True


def transvection(u, v):
    gu, gv = mv(G, u), mv(G, v)
    out = [[0] * N for _ in range(N)]
    for j in range(N):
        e = [0] * N
        e[j] = 1
        a = sum(e[i] * gu[i] for i in range(N))
        b = sum(e[i] * gv[i] for i in range(N))
        for i in range(N):
            out[i][j] = e[i] + a * v[i] - b * u[i]
    return out


def main():
    # coordinates: 0 = h, 1 = e', 2 = f', 3..10 = a_1..a_8
    def vec(h=0, ep=0, fp=0, roots=()):
        v = [0] * N
        v[0], v[1], v[2] = h, ep, fp
        for index, value in roots:
            v[3 + index] = value
        return v

    v1 = vec(ep=1)                      # e'
    # v_2 = 2h + a_1 + a_3: the book's a_1 and a_2 are orthogonal in its labelling (lem:1_cusp_correspondence
    # uses alpha_1 . alpha_2 = 0), and in the Bourbaki chain a_1 and a_3 are the orthogonal pair.
    v2 = vec(h=2, roots=((0, 1), (2, 1)))
    print("T_Co = <2> + U(2) + E8(2), rank %d" % N)
    print("0-cusp vector v_1 = e':   square %d" % dot(v1, v1))
    print("1-cusp plane <v_1, v_2>:   v_1.v_2 = %d, v_2^2 = %d"
          % (dot(v1, v2), dot(v2, v2)))

    isotropic = []
    for h, ep, fp in product(range(-2, 3), repeat=3):
        for tail in [None, (0, 2), (0, 1), (0, -1)]:
            v = [h, ep, fp] + [0] * 8
            if tail:
                v[3 + tail[0]] = tail[1]
            if any(v) and dot(v, v) == 0:
                isotropic.append(tuple(v))
    isotropic = sorted(set(isotropic))
    print("isotropic vectors found: %d" % len(isotropic))

    checked = 0
    for cusp, name in ((v1, "v_1"), (v2, "v_2")):
        for x in isotropic:
            if dot(list(cusp), list(x)) != 0:
                continue
            g = transvection(list(cusp), list(x))
            assert is_isometry(g), "transvection not an isometry"
            assert discriminant_trivial(g), "cusp transvection acts on A_{T_Co}"
            checked += 1
    print("transvections tau_{cusp, x} with x orthogonal to the cusp vector: %d checked," % checked)
    print("  all integral isometries and all acting trivially on A_{T_Co}")

    swap = [[int(i == j) for j in range(N)] for i in range(N)]
    swap[1][1] = swap[2][2] = 0
    swap[1][2] = swap[2][1] = 1
    print("control, the swap e' <-> f': isometry %s, acts trivially on A_{T_Co} %s"
          % (is_isometry(swap), discriminant_trivial(swap)))
    assert not discriminant_trivial(swap)
    print()
    print("verdict: every kind of monodromy element of this family -- (-2)-reflections, Eichler")
    print("  transvections, and the unipotent cusp elements above -- acts trivially on A_{T_Co}.")
    print("  Item 1e therefore holds for any subgroup generated by them; whether Gamma_Co is one is")
    print("  the index [Gamma_Co : W(T_Co)] with the parabolic generation, open at")
    print("  @qst:gamma-co-generators and @prob:coxeter-completeness.")


if __name__ == "__main__":
    main()
