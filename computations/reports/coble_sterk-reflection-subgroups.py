"""#654 (A11): the reflection subgroup of Stab_Gamma(eta_j) at each Sterk cusp.

What this decides
-----------------
For each of Sterk's five 0-cusps (Sterk 1991, Prop. 4.2.3) the quotient
K_j = eta_j^perp / Z eta_j is U(2)+E8(2) for j = 1 and U+E8(2) for j = 2..5, so the
quotients are mutually isometric and their full Vinberg reflection groups are
conjugate (10 walls each).  The published diagrams have 12, 10, 12, 11, 14 walls
(Figs 4, 6, 8, 10, 12), so the published chamber is not that of the full group.
Sterk (4.3.1) takes the subgroup G_v = rho(Stab_Gamma(v)) <= O(K_j), Gamma =
Gamma_En,2, and draws "the diagram of the reflection subgroup of G_v".  This
script computes that reflection subgroup and its Vinberg chamber for every cusp
and compares it with the published diagram.

The two inputs, both from the sources and not from this tree's prose
-------------------------------------------------------------------
* F = Gamma_En,2 as an isometry group of L^- = U(2)+E8(2): by Sterk's Prop. 2.7
  (p. 6) F is *exactly* the set of integral isometries of L^- whose induced map
  on L^-*/L^- = (1/2)U(2)/U(2) + (1/2)E8(-2)/E8(-2) respects the two summands.
  T_En = U + L^- with U unimodular, so A_{T_En} = L^-*/L^- and the same group is
  the summand-preserving subgroup M of O(A_{T_En}, q).  (The 9 generators of M in
  this tree's records are the 8 simple-root reflections of E8(2) and the
  reflection in e'-f' of U(2); the check |<they>| = 696729600 = |M| is quoted
  from coble_gammaEn2-* records, and their orbit partition on the 528 isotropic
  classes, [270,135,120,2,1], is recomputed here.)
* Which reflections of K_j lie in G_j.  Let r be a root of K_j (an integral
  reflection: r^2 in {-2,-4}) and r~ any lift in eta_j^perp subset T_En.  The
  isometries of T_En inducing s_r on K_j are s_{r~} * (unipotent shears
  x -> x + c(x,eta_j)eta_j).  Every such shear is an isometry of T_En whose
  discriminant image is trivial, because eta_j in L^- has class 0 in A_{T_En};
  shears are therefore in Gamma automatically and
        s_r in G_j   <=>   rho(s_{r~}) in M   <=>   rho(s_{r~}) respects both summands,
  independently of the lift.  So the reflection subgroup of G_j is generated by
  the roots of K_j whose reflection has a summand-preserving discriminant image.
  This is the criterion `in_Gamma` below; it is exact, in both directions.

Conventions fixed before any run (the page's warning, @sec-sterk-root-counts...)
-------------------------------------------------------------------------------
`vinal` is written for a Gram matrix of signature (n,1) with positive root
squares, while this tree's convention (and Sterk's) is (1,n) with roots of
negative square.  Every call below passes M = -G(K_j), so that M has signature
(9,1); the roots vinal returns are the images of the roots of K_j under the same
negation and are negated back (r = -v) before any Gram, norm or diagram is
formed.  Every returned root is checked against the original form: r^2 in
{-2,-4}, and the wall Gram is recomputed from G(K_j), not from M.

Run
---
  $HOME/.udocker/bin/proot-x86_64 -R $HOME/sage-image/rootfs -b /proc -b /dev -b /sys \\
      -b <repo>:/repo -w /repo /bin/sh -c \\
      'PATH=/sage/.venv/bin:$PATH /sage/.venv/bin/python \\
       /repo/computations/reports/coble_sterk-reflection-subgroups.py'

Transcript: `coble_sterk-reflection-subgroups-run.txt`.
"""
