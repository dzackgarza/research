# Per-cusp bound on the number of decompositions Vinberg's search may examine.  The bound is
# only reached by a search that does not close: a closed run returns before it, and prints its
# wall set; a run that reaches the bound prints the count and the elapsed time as the record of
# where it stopped.  Cusps 2, 3 and 5 close well inside it; the searches at cusps 4 and 1 run to
# the bound here and their chambers are therefore not claimed in this batch.
BOUNDS = {1: 20, 2: 4000, 3: 4000, 4: 20, 5: 4000}
