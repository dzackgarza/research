PUBLISHED = {1: (12, 9), 2: (10, 2), 3: (12, 4), 4: (11, 5), 5: (14, 13)}


def weights(roots, K=None):
    """Coxeter weight multiset; K=None uses the ambient form of T_En."""
    def pr(a, b):
        return ip(a, b) if K is None else int(a.dot_product(K*b))
    c = Counter()
    for i in range(len(roots)):
        for i2 in range(i+1, len(roots)):
            bb = pr(roots[i], roots[i2])
            if bb == 0:
                continue
            den = abs(pr(roots[i], roots[i])*pr(roots[i2], roots[i2]))
            ra = Fraction(bb*bb, den)       # cos^2(pi/m)
            c[{Fraction(1, 4): 3, Fraction(1, 2): 4, Fraction(3, 4): 6}.get(
                ra, 'inf' if ra == 1 else '?')] += 1
    return dict(sorted(c.items(), key=lambda kv: str(kv[0])))


def vertices(roots, K):
    """(finite, ideal) vertex counts of the chamber, from the rays of its dual cone.

    The chamber in the projective model is {x : b(x,r) <= 0 for all walls r}; its
    vertices are the extreme rays of that cone, a vertex is ideal when its ray is
    isotropic.  The Gram passed is -K (signature (9,1)) so that vinal's convention
    is kept throughout.
    """
    from sage.all import Cone
    M = -K
    rays = Cone([vector(ZZ, list(r)) for r in roots]).dual().rays()
    q = [matrix(M.inverse()*vector(ZZ, list(a))) for a in rays]
    return (sum(1 for x in q if x*M*x.transpose() < 0),
            sum(1 for x in q if x*M*x.transpose() == 0))


class SubVinAl(VinAl):
    """Vinberg's algorithm with the reflection set restricted to the subgroup."""

    def __init__(s, M, oracle, **kw):
        s.oracle = oracle
        s.nacc = s.nrej = s.ndup = 0
        super().__init__(M, **kw)

    def IsNewRoot(s, v):
        if not super().IsNewRoot(v):
            return False
        # vinal's own test compares only the first degree()-1 accepted roots, which lets a
        # repeated wall through once the accepted set is longer than the rank; reject a root
        # proportional to any accepted one.
        vv = list(v)
        for w in s.roots:
            ww = list(w)
            for i in range(len(vv)):
                if vv[i]:
                    lam = ww[i]/vv[i]
                    if all(ww[j] == lam*vv[j] for j in range(len(vv))):
                        s.ndup += 1
                        return False
                    break
        if not s.oracle(v):
            s.nrej += 1
            return False
        s.nacc += 1
        return True

    def NextRoot(s, max_decompositions=None, progress=None):
        # vinal yields every solution of one decomposition equation; two of them can be
        # proportional (v and a multiple), and vinal's own dependence test compares only the
        # first degree()-1 accepted roots, so a repeated wall can enter.  Dedupe the batch.
        def prop(a, b):
            aa, bb = list(a), list(b)
            for i in range(len(aa)):
                if aa[i]:
                    lam = bb[i]/aa[i]
                    return all(bb[j] == lam*aa[j] for j in range(len(aa)))
            return False
        examined = 0
        for a, k in s.IterateRootDecompositions():
            examined += 1
            if progress is not None:
                progress(examined, len(s.roots))
            if max_decompositions is not None and examined > max_decompositions:
                s.truncated = True
                return
            batch = []
            for v in s.Roots_decomposed_into(a, k):
                if not s.IsNewRoot(v):
                    continue
                if any(prop(v, w) for w in batch):
                    s.ndup += 1
                    continue
                batch.append(v)
            for root in batch:
                yield root

    def FundCone(s):
        V1 = [v for k in s.root_lengths for v in s.Roots_decomposed_into(s.V([0]*s.n), k)
              if s.IsRoot(v) and s.oracle(v)]
        from sage.all import Cone
        cone = Cone([[0]*s.n]).dual()
        for root in V1:
            hp = Cone([root]).dual()
            if cone.intersection(hp).dim() == s.n:
                cone = cone.intersection(hp)
            else:
                cone = cone.intersection(Cone([-root]).dual())
        return [s.V(r) for r in cone.dual().rays()]


