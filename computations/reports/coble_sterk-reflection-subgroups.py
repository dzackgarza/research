    fw = [-vector(ZZ, list(r)) for r in full.roots]
    print("    full group W(K): complete=%s, %d walls, norms %s  (%.1f s)"
          % (fullOK, len(fw), sorted(int(r.dot_product(K*r)) for r in fw), time.time() - t0))
    keep = [r for r in full.roots if oracle(r)]
    print("    of those, %d have their reflection in Gamma_En,2" % len(keep))
    t0 = time.time()
    alg = SubVinAl(-K, oracle, output=None)
    seen = {'n': 0, 't': time.time()}

