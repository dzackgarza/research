"""#654 (A11): the reflection subgroup of Stab_Gamma(eta_j) at each Sterk cusp.

What this decides, and what it does not
--------------------------------------
For Sterk's five 0-cusps (Sterk 1991, Prop. 4.2.3) the quotients K_j = eta_j^perp / Z eta_j are
U(2)+E8(2) for j = 1 and U+E8(2) for j = 2..5, so the full Vinberg groups are conjugate (10 walls
each) while the published diagrams have 12, 10, 12, 11, 14 walls.  Sterk (4.3.1) takes
G_v = rho(Stab_Gamma(v)) <= O(K_j) and draws "the diagram of the reflection subgroup of G_v".  For
each j this script works in Sterk's *own* representative and with *his own* printed roots, and
prints:

  * the M-orbit of the isotropic class [v/2] in A_{T_En} --- the five orbits, of sizes 1, 2, 120,
    270, 135, are the five cusps --- for his representative and for the page's, so that the cusp a
    representative belongs to is read off rather than assumed;
  * whether his printed roots are roots of K_j whose reflections lie in Gamma_En,2;
  * whether his walls bound a polytope of finite covolume (the closedness test: every vertex ray of
    the chamber lies in the closed light cone), with its finite and ideal vertex counts and its
    Coxeter weight multiset;
  * whether the reflection set restricted to the roots certified to be in Gamma_En,2 contains any
    further wall beyond his, by seeding Vinberg's search with his walls and continuing it.  This is
    the question "are his walls exactly the walls of W_j", and it is answered by the same restricted
    search, so it is only as sharp as the criterion below.

The criterion, and its one-sidedness
-----------------------------------
Let r be a root of K_j with a lift r~ in eta_j^perp, and let Gamma = Gamma_En,2 = rho^{-1}(M), M the
subgroup of O(A_{T_En}, q) preserving the two summands (Sterk Prop. 2.7, p. 6; A_{T_En} = L_-^*/L_-
because T_En = U + L^- with U unimodular).

  * If rho(s_{r~}) in M then s_{r~} in Gamma, it fixes eta_j, so it lies in Stab_Gamma(eta_j) and
    s_r in G_v.  This direction is unconditional: every root accepted below is certainly in G_v, so
    the group generated by the accepted roots is a subgroup of W_j.
  * The converse is NOT claimed here.  The kernel of Stab_{O(T_En)}(eta_j) -> O(K_j) consists of the
    shears x -> x + l(x) eta_j on eta_j^perp with l a homomorphism eta_j^perp/Z eta_j -> Z; the
    subfamily l = c (eta_j, .) has trivial discriminant image, but the kernel is larger (an isometry
    of T_En inducing one of its other elements also moves a complement of eta_j^perp), and such an
    element can carry rho out of M.  A reflection of G_v all of whose lifts miss M by one of those is
    invisible to this test.  So "no further wall found" below means "no further wall is certified",
    not "W_j has no further wall"; and where the certified chamber reproduces the published figure
    (j = 2 and j = 5 below) nothing is missing, because the two chambers are then equal.

Conventions fixed before any run (the page's warning)
----------------------------------------------------
vinal takes a Gram matrix of signature (n,1) with positive root squares; this tree and Sterk use
(1,n) with negative squares.  Every call passes M = -G(K_j), so M has signature (9,1); the roots
vinal returns are negated back (r = -v) and every one is re-checked against G(K_j): r^2 in {-2,-4},
and the wall Gram recomputed from G(K_j).

Run
---
  $HOME/.udocker/bin/proot-x86_64 -R $HOME/sage-image/rootfs -b /proc -b /dev -b /sys \\
      -b <repo>:/repo -w /repo /bin/sh -c \\
      'PATH=/sage/.venv/bin:$PATH /sage/.venv/bin/python \\
       /repo/computations/reports/coble_sterk-reflection-subgroups.py'

Transcript: `coble_sterk-reflection-subgroups-run.txt`.
"""
