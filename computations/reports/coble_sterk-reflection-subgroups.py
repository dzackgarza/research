# --------------------------------------------------------------- the lattice
C = CartanMatrix(['E', 8])
G = block_diagonal_matrix(matrix(ZZ, [[0, 1], [1, 0]]),      # U        slots 0,1
                         matrix(ZZ, [[0, 2], [2, 0]]),      # U(2)     slots 2,3
                         -2*C)                              # E8(2)    slots 4..11
N = 12
BAS = [vector(ZZ, [1 if k == i else 0 for k in range(N)]) for i in range(N)]
e, f, ep, fp = (BAS[i] for i in range(4))
alpha = [BAS[4+i] for i in range(8)]
Cinv = C.inverse()
abar = [vector(ZZ, sum(QQ(-Cinv[k, i])*alpha[k] for k in range(8))) for i in range(8)]
MASK_UP, MASK_E8 = 0b11, 0b1111111100


def ip(x, y):
    return int(vector(ZZ, x)*G*vector(ZZ, y))


# ------------------------------------------------ discriminant group A_{T_En}
def qval(m):
    s = 0
    for i in range(10):
        if (m >> i) & 1:
            for j in range(10):
                if (m >> j) & 1:
                    s += ip(BAS[2+i], BAS[2+j])
    assert s % 4 == 0
    return (s//4) % 2


QV = [qval(m) for m in range(1024)]
ISO = [m for m in range(1024) if QV[m] == 0]


def disc_cols(R):
    """columns = classes in A_{T_En} of R(b_{2+k});  R an involution preserving G."""
    cols = []
    for k in range(10):
        img = R*BAS[2+k]
        m = 0
        for kk in range(10):
            if int(img[2+kk]) % 2:
                m |= 1 << kk
        cols.append(m)
    return cols


def preserves_summands(cols):
    for k in range(10):
        img = cols[k]
        if (MASK_UP >> k) & 1:
            if img & MASK_E8:
                return False
        elif img & MASK_UP:
            return False
    return True


def refl(vec):
    """the integral reflection in vec, or None when its reflection is not integral."""
    vec = vector(ZZ, vec)
    sq = ip(vec, vec)
    if sq == 0:
        return None
    R = matrix(ZZ, N, N, 0)
    for i in range(N):
        for j in range(N):
            num = 2*ip(BAS[j], vec)
            if num % sq:
                return None
            R[i, j] = (1 if i == j else 0) - (num//sq)*int(vec[i])
    if R.transpose()*G*R != G:
        return None
    return R


def in_Gamma(vec):
    """rho(s_vec) in M: the reflection lies in Gamma_En,2."""
    R = refl(vec)
    return R is not None and preserves_summands(disc_cols(R))


# the nine recorded generators of M, and their orbit partition on the 528 classes
GENS = [disc_cols(refl(BAS[4+i])) for i in range(8)] + [disc_cols(refl(ep - fp))]


def apply_cols(cols, m):
    out, k = 0, 0
    while m:
        if m & 1:
            out ^= cols[k]
        m >>= 1
        k += 1
    return out


def orbit_partition(points, gens):
    seen, out = set(), []
    for p in points:
        if p in seen:
            continue
        orb, st = [], [p]
        seen.add(p)
        while st:
            x = st.pop()
            orb.append(x)
            for g in gens:
                y = apply_cols(g, x)
                if y not in seen:
                    seen.add(y)
                    st.append(y)
        out.append(sorted(orb))
    return out


# --------------------------------------------------------------- lattice code
def sat_kernel_rows(rowvec):
    n = len(rowvec)
    g = gcd(*[abs(int(x)) for x in rowvec])
    S, U, V = matrix(ZZ, [[int(x)//g for x in rowvec]]).smith_form()
    assert S[0, 0] == 1
    return matrix(ZZ, n-1, n, [[V[i, j] for i in range(n)] for j in range(1, n)])


def unimodular_completion(c):
    n = len(c)
    assert gcd(*[abs(int(x)) for x in c]) == 1
    S, U, V = matrix(ZZ, [list(c)]).smith_form()
    assert S[0, 0] == 1
    Q = V.inverse()
    Q = matrix(ZZ, [[int(Q[i, j]) for j in range(n)] for i in range(n)])
    if list(Q.row(0)) != list(c):
        Q = -Q
    assert list(Q.row(0)) == list(c) and abs(Q.det()) == 1
    return Q


def cusp_basis(v):
    """rows 0..9: a basis of eta^perp / Z eta for eta = v (row 0 of the completion is v)."""
    Wm = sat_kernel_rows([ip(BAS[i], v) for i in range(N)])
    sol = Wm.change_ring(QQ).transpose().solve_right(vector(QQ, v))
    assert all(x in ZZ for x in sol)
    Wp = unimodular_completion([int(x) for x in sol])*Wm
    assert vector(ZZ, list(Wp.row(0))) == v
    return Wp.submatrix(1, 0, 10, N)


