for j in (2, 3, 5, 4, 1):
    v = ETA[j]
    B = cusp_basis(v)
    K = matrix(ZZ, 10, 10, lambda a, b_: ip(B.row(a), B.row(b_)))
    Binv = B.change_ring(QQ)

    def lift(a, B=B):
        out = vector(ZZ, [0]*N)
        for i in range(10):
            if a[i]:
                out += int(a[i])*B.row(i)
        return out

    def oracle(a, lift=lift):
        return in_Gamma(lift(a))

    def stereo(r, Binv=Binv):
        sol = Binv.transpose().solve_right(vector(QQ, r))
        if all(x in ZZ for x in sol):
            return vector(ZZ, [int(x) for x in sol])
        return None

    print("=== cusp %d   v = %s   K = v^perp/Zv, det %s" % (j, list(v), K.det()))
