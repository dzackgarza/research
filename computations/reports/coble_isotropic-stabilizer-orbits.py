import os
import shutil
import sys
import time

sys.stdout.reconfigure(line_buffering=True)
os.environ["PATH"] = os.path.dirname(os.path.realpath("/sage/.venv/bin/sage")) + os.pathsep + os.environ.get("PATH", "")

from sage.all import CartanMatrix, ZZ, block_diagonal_matrix, matrix  # noqa: E402
from sage.version import version as SAGE_VERSION  # noqa: E402

from sage_extensions.all import Lattices  # noqa: E402

PIN = '15db925b0c92e525f769fcbf57135f1391263a9e'
CLAIMED_GROUP_ORDER = 46998591897600
CLAIMED_STABILIZER_ORDER = 94755225600

print('provenance')
print('  Sage: %s' % SAGE_VERSION)
print('  sage-extensions: .scratch/se-provider-15db925b/src, pin %s' % PIN[:12])
print('  gap on PATH: %s' % shutil.which('gap'))
print('')

U = matrix(ZZ, [[0, 1], [1, 0]])
E8 = -CartanMatrix(['E', 8])
T = Lattices(ZZ)([list(r) for r in
                  block_diagonal_matrix(matrix(ZZ, [[2]]), 2 * U, 2 * E8).rows()])
A = T.discriminant_quadratic_form()
zero_value = A.quadratic_value_module().zero()
isotropic = [x for x in A.elements() if A.q(x) == zero_value]
print('A = A_{T_Co}: %d classes, %d of them isotropic'
      % (int(A.cardinality()), len(isotropic)))
assert int(A.cardinality()) == 2048 and len(isotropic) == 528
print('')

start = time.time()
G = A.orthogonal_group()
print('|G| = |Orth(A, q)| = %d   (%.0f s)' % (int(G.order()), time.time() - start))
assert int(G.order()) == CLAIMED_GROUP_ORDER
print('')

c = None
for x in A.elements():
    if A.q(x) == A.q(x).parent()(1):
        c = x
        break
print('the polarization class c = %s, q(c) = %s' % (c, A.q(c)))
print('  the q = 1 fibre has %d classes; |G|/%d = %d'
      % (sum(1 for x in A.elements() if A.q(x) == A.q(c)), 496, CLAIMED_STABILIZER_ORDER))
print('')

print('H = G.stabilizer_of_element(c)   -- the expensive step')
start = time.time()
H = G.stabilizer_of_element(c)
print('  |H| = %d   (%.0f s)' % (int(H.order()), time.time() - start))
print('  check |H| = |G|/496: %d = %d   %s'
      % (int(H.order()), int(G.order()) // 496,
         'AGREE' if int(H.order()) == int(G.order()) // 496 else 'DISAGREE'))
assert int(H.order()) == CLAIMED_STABILIZER_ORDER
print('')

print("the orbits of H on the 528 isotropic classes")
print('  H\' = G.subgroup_on(H.group_generators()) -- same generators, so H\' <= H, and the')
print('  orders decide equality: a subgroup of H with H\'s order is H itself.')
start = time.time()
H_prime = G.subgroup_on(list(H.group_generators()))
print("  |H'| = %d   (%.0f s)" % (int(H_prime.order()), time.time() - start))
print("  |H|  = %d   equal: %s" % (int(H.order()), int(H_prime.order()) == int(H.order())))
assert int(H_prime.order()) == int(H.order()), "H' is not H"
print('')

from sage_extensions.categories.group.g_sets import FiniteGSets  # noqa: E402

print('  the restricted action of H on those 528 points, through H -> G')
start = time.time()
elements = G.element_action()
inclusion = H_prime.inclusion()
restricted_action = elements.restrict_action(inclusion)
h_set = FiniteGSets(H_prime)(isotropic, lambda h, x: restricted_action.act(h, x))
print('  the H-set built: %s' % type(h_set).__name__)
orbits = list(h_set.orbits())
sizes = sorted(len(list(orbit.points())) for orbit in orbits)
print('  %d orbits, sizes %s   (%.0f s)' % (len(orbits), sizes, time.time() - start))
print('  sum: %d, and the set has %d classes: %s'
      % (sum(sizes), len(isotropic), 'AGREE' if sum(sizes) == len(isotropic) else 'DISAGREE'))
assert sum(sizes) == len(isotropic)

isotropic_set = set(isotropic)
covered = set()
for orbit in orbits:
    covered |= set(orbit.points())
print('  the orbits cover the isotropic classes: %s' % (covered == isotropic_set))
assert covered == isotropic_set
zero_class = A.zero() if hasattr(A, 'zero') else c - c
singletons = [orbit for orbit in orbits if len(list(orbit.points())) == 1]
print('  exactly one singleton, and it is {0}: %s'
      % (len(singletons) == 1 and set(singletons[0].points()) == {zero_class}))
print('')
print('the stated list is [1, 255, 272]: %s'
      % ('AGREE' if sizes == [1, 255, 272] else 'DISAGREE'))
print('')
print('SUMMARY')
print('  |G| = 46998591897600, |H| = 94755225600 = |G|/496 AGREE, and the orbits of H on the')
print('  528 isotropic classes are %s, summing to 528 and covering them, so the stated list' % sizes)
print('  of B3 is %s.' % ('CONFIRMED' if sizes == [1, 255, 272] else 'REFUTED'))
