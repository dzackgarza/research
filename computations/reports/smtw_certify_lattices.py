def det(M):
    n = len(M)
    A = [[F(x) for x in row] for row in M]
    d = F(1)
    for k in range(n):
        p = next((i for i in range(k, n) if A[i][k] != 0), None)
        if p is None:
            return F(0)
        if p != k:
            A[k], A[p] = A[p], A[k]
            d = -d
        d *= A[k][k]
        inv = A[k][k]
        for i in range(k + 1, n):
            f = A[i][k] / inv
            if f != 0:
                for j in range(k, n):
                    A[i][j] -= f * A[k][j]
    return d


def signature(M):
    n = len(M)
    A = [[F(x) for x in row] for row in M]
    pos = neg = 0
    idx = list(range(n))
    while idx:
        piv = next((i for i in idx if A[i][i] != 0), None)
        if piv is None:
            pair = next(((i, j) for i in idx for j in idx if i != j and A[i][j] != 0), None)
            if pair is None:
                break
            i, j = pair
            for k in range(n):
                A[j][k] += A[i][k]
            for k in range(n):
                A[k][j] += A[k][i]
            continue
        a = A[piv][piv]
        if a > 0:
            pos += 1
        else:
            neg += 1
        idx.remove(piv)
        for i in idx:
            if A[i][piv] != 0:
                f = A[i][piv] / a
                for k in range(n):
                    A[i][k] -= f * A[piv][k]
                for k in range(n):
                    A[k][i] -= f * A[k][piv]
    return (pos, neg)


def sq(coords, M):
    n = len(coords)
    return sum(coords[i] * M[i][j] * coords[j] for i in range(n) for j in range(n))


def qval(coords, M):
    return F(sq(coords, M)) % 2


def integral(v):
    return all(F(x).denominator == 1 for x in v)


