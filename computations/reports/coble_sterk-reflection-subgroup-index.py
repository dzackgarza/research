chamber_of_the_subgroup = image.cusp_chamber()
assert chamber_of_the_subgroup.is_complete_wall_set() is True, (
    "cusp_chamber did not reach its own stop at cusp %d, so the wall set is a prefix" % j)
subgroup_vectors = tuple(chamber_of_the_subgroup.wall_roots())
subgroup_walls = tuple(coordinates(labels, reduction, w) for w in subgroup_vectors)
# `fundamental_chamber` and `cusp_chamber` state their chamber as `{x : b(r, x) >= 0 for every wall r}`
# and the walk below is written for the opposite inequality, so the normals are negated once, here, and
# everywhere.  Without this the polyhedron would be the antipode of the one the library returns: the
# same count, since `x |-> -x` preserves every mirror, but not the same chamber, and the transcript
# would be comparing Sterk's figure with a congruent copy rather than with the object the library built.
subgroup_walls = tuple(tuple(-c for c in wall) for wall in subgroup_walls)
stamp("cusp_chamber at Sterk_%d returned %d walls" % (j, len(subgroup_walls)))

full = HyperbolicLattices(SZZ)(reduction).fundamental_chamber()
assert full.is_complete_wall_set() is True, (
    "fundamental_chamber did not reach its own stop, so the wall set is a prefix")
full_vectors = tuple(full.wall_roots())
full_walls = tuple(coordinates(labels, reduction, w) for w in full_vectors)
full_walls = tuple(tuple(-c for c in wall) for wall in full_walls)  # the same one negation, see above
stamp("fundamental_chamber of W(K_j) returned %d walls" % len(full_walls))

print("")
print("Part B. P_j is Sterk's diagram, read as a chamber of the library")
print("  walls of the subgroup's chamber: %d;  Sterk prints %d for cusp %d"
      % (len(subgroup_walls), walls_published, j))
assert len(subgroup_walls) == walls_published, ("the wall count is not Sterk's", j)
squares = sorted(form(gram, w, w) for w in subgroup_walls)
print("  squares of the walls: %d x (-4), %d x (-2)" % (squares.count(-4), squares.count(-2)))
assert set(squares) <= {-2, -4}, ("a wall is not a root of K_j", squares)
assert all(image.admits_root(w) for w in subgroup_vectors), (
    "a wall of the returned chamber is not a root of K_j whose reflection lies in G_v")
print("  every wall is a root of K_j, and every wall's reflection lies in G_v: %d of %d"
      % (len(subgroup_vectors), len(subgroup_vectors)))
assert all(int(reduction.q(w)) == form(gram, coordinates(labels, reduction, w),
                                       coordinates(labels, reduction, w)) for w in subgroup_vectors)
print("  the coordinates read off the lattice vectors reproduce the pairings: checked")
print("")

print("Part C. P_j is a Coxeter polytope, and its polytope data against the published data")
# @def:bond-invariant reads a bond off the squares alone: t = 4 b^2/(q q') is 4 cos^2 of the dihedral
# angle, so t = 0, 1, 2, 3, 4 is the label 2, 3, 4, 6 or infinity.  The walls of a chamber of one of these
# lattices pair positively in the library's normalisation, so the label is taken from b^2.
bonds = {}
for a in range(len(subgroup_walls)):
    for b in range(a + 1, len(subgroup_walls)):
        entry = form(gram, subgroup_walls[a], subgroup_walls[b])
        product = (form(gram, subgroup_walls[a], subgroup_walls[a])
                   * form(gram, subgroup_walls[b], subgroup_walls[b]))
        square = entry * entry
        if entry == 0:
            label = 2
        elif 4 * square == product:
            label = 3
        elif 2 * square == product:
            label = 4
        elif 4 * square == 3 * product:
            label = 6
        elif square == product:
            label = "infinity"
        else:
            raise AssertionError(("two walls of the chamber are joined by no Coxeter bond",
                                  a, b, entry, product))
        bonds[label] = bonds.get(label, 0) + 1
print("  bonds: %s;  the diagram is Coxeter's, so @def:covolume applies"
      % sorted(bonds.items(), key=lambda item: str(item[0])))
polytope = facet_rays(subgroup_walls, gram)
assert polytope, "the walls bound no polytope: their cone has no extreme ray"
print("  the cone of P_j: dimension %d, pointed, of trivial lineality --- the assertions of "
      "`facet_rays`; so its extreme rays are the vertices of P_j and its interior is nonempty"
      % len(subgroup_walls[0]))

assert all(square >= 0 for square, _ray in polytope), (
    "an extreme ray of P_j is space-like, so P_j does not lie in the hyperbolic space")
ideal = [ray for square, ray in polytope if square == 0]
finite = [ray for square, ray in polytope if square != 0]
computed_f_vector = f_vector([ray for _square, ray in polytope], subgroup_walls, gram)
print("  extreme rays %d: %d finite, %d ideal;  Sterk's diagram has %d vertices at infinity"
      % (len(polytope), len(finite), len(ideal), ideal_published))
print("  f-vector %s" % (computed_f_vector,))
print("  CoxIter    %s" % (F_VECTOR[j],))
assert len(ideal) == ideal_published, ("the ideal-vertex count is not Sterk's", j)
assert len(polytope) == rays_published, ("the vertex count is not his f_0", j)
assert computed_f_vector == F_VECTOR[j], ("the f-vector is not CoxIter's", j)
print("")

print("Part D. The index [W(K_j) : W_j], as the number of W(K_j)-chambers inside P_j")
print("  the full chamber has %d walls, %d extreme rays, %d of them ideal"
      % (len(full_walls), len(chamber_rays(full_walls, gram)),
         sum(1 for ray in chamber_rays(full_walls, gram) if form(gram, ray, ray) == 0)))
anchor = interior_point(polytope, subgroup_walls, gram)
current, visited, flips = full_walls, set(), 0
while True:
    violated = [index for index in range(len(current)) if form(gram, anchor, current[index]) > 0]
    if not violated:
        break
    flips += 1
    assert flips < 4000, "the walk to the seed chamber does not stop"
    for index in sorted(violated, key=lambda i: -form(gram, anchor, current[i])):
        candidate = across(current, index, gram)
        if key_mirrors(candidate) not in visited:
            visited.add(key_mirrors(current))
            current = candidate
            break
    else:
        raise AssertionError("every violated wall leads back to a visited chamber")
seed_ok, seed_polar_ok, seed_rays = membership(current, subgroup_walls, gram)
assert seed_ok, "the chamber containing the point of P_j is not inside P_j"
assert seed_polar_ok, "the two membership tests disagree at the seed chamber"
stamp("the chamber containing an interior point of P_j reached in %d wall crossings" % flips)
chambers_in_p = {}
adjacency = {}
stack, enqueued, refused = [current], 0, 0
seen = {key_mirrors(current)}
while stack:
    chamber = stack.pop()
    enqueued += 1
    vertex_ok, polar_ok, rays = membership(chamber, subgroup_walls, gram)
    assert vertex_ok == polar_ok, ("the two membership tests disagree", key_mirrors(chamber))
    if not polar_ok:
        refused += 1
        continue
    here = key_mirrors(chamber)
    chambers_in_p[here] = (chamber, rays)
    # the facet across each wall of the chamber, keyed now: the closure below is then a dictionary
    # comparison and not a second walk over every facet of every chamber.
    links = []
    for index in range(len(chamber)):
        neighbour = across(chamber, index, gram)
        key = key_mirrors(neighbour)
        links.append((key, key_ray(chamber[index])))
        if key in seen:
            continue
        seen.add(key)
        stack.append(neighbour)
    adjacency[here] = links
index_of_the_subgroup = len(chambers_in_p)
stamp("the walk closed: %d chambers inside P_j, %d enqueued, %d refused"
      % (index_of_the_subgroup, enqueued, refused))
print("")
print("  index [W(K_j) : W_j] = %d" % index_of_the_subgroup)
if j == 2:
    assert index_of_the_subgroup == 1, (
        "Sterk 4.3.6 states O(H + E8(-2)) = {+-1} W_{e'}, so the index at cusp 2 is 1")

print("  the closure of the walk, facet by facet:")
mirrors = {key_ray(wall) for wall in subgroup_walls}
interior, boundary, per_mirror = 0, 0, {}
for key, links in adjacency.items():
    for neighbour_key, mirror in links:
        if neighbour_key in chambers_in_p:
            # the reverse link is checked as a pair and not by the chamber alone: the claim is about a
            # mirror, so a link back into this chamber across another of the neighbour's walls does
            # not test it.
            assert (key, mirror) in adjacency[neighbour_key], (
                "crossing a mirror twice does not return the chamber across that mirror",
                key, neighbour_key, mirror)
            interior += 1
            continue
        assert mirror in mirrors, (
            "a facet of a chamber inside P_j is not on the boundary of P_j", mirror)
        boundary += 1
        per_mirror[mirror] = per_mirror.get(mirror, 0) + 1
assert interior % 2 == 0
assert len(per_mirror) == len(mirrors), (
    "a wall of P_j carries no facet, so it was not needed")
assert index_of_the_subgroup * len(full_walls) == interior + boundary, (
    "the facets of the chambers do not distribute over P_j")
print("    %d chamber facets: %d shared between two chambers inside P_j, %d on the %d walls of P_j"
      % (index_of_the_subgroup * len(full_walls), interior, boundary, len(per_mirror)))
print("    chambers per wall of P_j: %s"
      % sorted(per_mirror.values()))
print("")

print("Part E. The ideal vertices of P_j (the columns of @thm:sterk-reflection-subgroup-index)")
ideal_keys = {key_ray(ray) for ray in ideal}
vertex_incidence = {}
elsewhere = {}
for key, (chamber, rays) in chambers_in_p.items():
    for ray in rays:
        if form(gram, ray, ray) != 0:
            continue
        ray_key = key_ray(ray)
        if ray_key in ideal_keys:
            vertex_incidence[ray_key] = vertex_incidence.get(ray_key, 0) + 1
            continue
        record = elsewhere.setdefault(ray_key, [0, face_dimension_of_a_ray(ray, subgroup_walls, gram)])
        record[0] += 1
print("  %d ideal vertices of P_j, each a vertex of some constituent chamber; chambers per vertex: %s"
      % (len(ideal_keys), sorted(vertex_incidence.values())))
assert set(vertex_incidence) == ideal_keys, "an ideal vertex of P_j is no vertex of a chamber"
assert all(record[0] >= 1 for record in elsewhere.values())
dimensions = {}
for record in elsewhere.values():
    dimensions[record[1]] = dimensions.get(record[1], 0) + 1
print("  ideal vertices of the chambers that are not vertices of P_j: %d distinct, %d incidences,"
      % (len(elsewhere), sum(record[0] for record in elsewhere.values())))
print("  lying in the relative interior of faces of P_j of dimensions %s"
      % sorted(dimensions.items()))
assert sum(vertex_incidence.values()) + sum(record[0] for record in elsewhere.values()) == (
    len(chambers_in_p) * sum(1 for ray in chamber_rays(full_walls, gram)
                             if form(gram, ray, ray) == 0))
print("")
print("cusp %d: [W(K_%d) : W_%d] = %d" % (j, j, j, index_of_the_subgroup))
print("Total run time: %.0f s" % (time.time() - T0))
