# ----------------------------------------------------------------- exact arithmetic on one lattice
def red(x):
    """Divide by the positive gcd of the coordinates; the sign is kept."""
    x = vector(ZZ, x)
    g = gcd(*[abs(int(c)) for c in x])
    return x if g in (0, 1) else vector(ZZ, [int(c) // g for c in x])


def key_ray(x):
    """The key of a ray: primitive, and the first nonzero coordinate positive."""
    x = red(x)
    for c in x:
        if c:
            return tuple(int(t) for t in (x if c > 0 else -x))
    raise ValueError("the zero vector is not a ray")


def key_mirrors(walls):
    return tuple(sorted(key_ray(w) for w in walls))


def form(gram, x, y):
    """The pairing `x^T G y`, with `G` held as its rows of Python integers.

    The walk asks this question a few hundred thousand times, so the arithmetic is plain integers
    rather than a Sage matrix product per call.
    """
    total = 0
    for i, coefficient in enumerate(x):
        if not coefficient:
            continue
        row = gram[i]
        total += int(coefficient) * sum(row[j] * int(y[j]) for j in range(len(row)))
    return total


def reflect(root, normal, gram):
    """The reflection in the mirror of `normal` applied to `root`."""
    square = form(gram, normal, normal)
    numerator = 2 * form(gram, root, normal)
    assert numerator % square == 0, ("a non-integral reflection", list(root), list(normal))
    return tuple(int(root[i]) - (numerator // square) * int(normal[i])
                 for i in range(len(root)))


def across(chamber, index, gram):
    """The chamber adjacent to `chamber` in its `index`-th wall."""
    normal = chamber[index]
    return tuple(reflect(root, normal, gram) for root in chamber)


def chamber_rays(chamber, gram):
    """The extreme rays of the simplicial cone `{x : b(x, w) <= 0 for w in chamber}`.

    The walls are a basis of the space of linear forms, so `A * (A^-1)_j = e_j` makes the `j`-th column of the
    inverse orthogonal to every wall but the `j`-th, and the sign is the one the `j`-th inequality picks.
    """
    walls = matrix(ZZ, [list(w) for w in chamber])
    # the rows of the matrix of linear forms are x |-> b(x, w), that is w G, not w.
    forms = walls * matrix(ZZ, gram)
    assert forms.rank() == forms.nrows(), "the chamber's walls are dependent"
    inverse = forms.change_ring(QQ).inverse()
    rays = []
    for index in range(walls.nrows()):
        column = vector(QQ, list(inverse.column(index)))
        scale = lcm([c.denominator() for c in column])
        ray = red(vector(ZZ, [int(c * scale) for c in column]))
        if form(gram, ray, chamber[index]) > 0:
            ray = -ray
        assert form(gram, ray, chamber[index]) < 0, "a wall of the chamber is not a facet"
        rays.append(ray)
    cone = Cone([list(ray) for ray in rays])
    assert cone.is_pointed(), ("the cone of a chamber contains a line", key_mirrors(chamber))
    assert int(cone.lineality()) == 0, ("the cone of a chamber has a lineality space",
                                        int(cone.lineality()))
    return rays


def facet_rays(walls, gram):
    """The extreme rays of `{x : b(x, w) <= 0 for w in walls}`, with more walls than the dimension.

    The inequalities are linear forms in the coordinates `y = G x`, where `b(x, w) = w . y`, so the cone
    is the polar of the cone the walls generate and Sage's cone arithmetic supplies its extreme rays.
    That is what these diagrams need: they are not simple --- the twelve walls of cusp 3 satisfy two
    linear relations --- so no `dim` many of the walls cut out a chamber vertex on their own.

    The cone is also asserted here to be pointed, of trivial lineality and of full dimension, which is
    not decoration: the extreme rays are the vertices of `P_j` only for a pointed cone, and a strictly
    interior point of the intersection of the half-spaces exists only if it is full-dimensional.
    """
    dimension = len(walls[0])
    polar = Cone([[-int(c) for c in w] for w in walls])
    cone = polar.dual()
    assert cone.is_pointed(), ("the cone of P_j contains a line, so P_j is not a polytope", walls)
    assert int(cone.lineality()) == 0, ("the cone of P_j has a lineality space", int(cone.lineality()))
    assert int(cone.dim()) == dimension, ("the half-spaces of P_j do not fill the space: the cone has "
                                          "dimension %d and not %d" % (int(cone.dim()), dimension))
    inverse = matrix(QQ, gram).inverse()
    found = {}
    for ray in cone.rays():
        x = inverse * vector(QQ, list(ray))
        scale = lcm([c.denominator() for c in x])
        x = red(vector(ZZ, [int(c * scale) for c in x]))
        # the *ray as computed*, not its sign-normalisation: `key_ray` flips a vector so that its first
        # nonzero coordinate is positive, and a flipped ray no longer satisfies the wall inequalities it
        # was computed from.  The key is still the normalised one, so the dict deduplicates.
        found[key_ray(x)] = (form(gram, x, x), x)
    return [(square, ray) for _key, (square, ray) in sorted(found.items())]


def interior_point(polytope, facets, gram):
    """A point strictly inside `P = {x : b(x, w) < 0 for every wall w}`, by the linear program below.

    The cone of `P` is generated by its extreme rays, so every point of it is a nonnegative combination
    of them, and demanding that the combination be a probability vector costs nothing, the cone being
    homogeneous.  So the program

        maximise t   subject to   sum_i lambda_i b(r_i, w) + t <= 0   (every wall w of P),
                                  sum_i lambda_i = 1,   lambda_i >= 0

    has optimum `t* > 0` exactly when a nonnegative combination of the rays is strictly inside every
    wall: a feasible `(lambda, t)` with `t > 0` is one, and a point strictly inside the walls, written
    as a combination and rescaled to `sum lambda = 1`, gives the feasible `t = min_w -b(x, w) > 0`.  The
    search is over the whole set of nonnegative combinations and not over a family of weights, so a
    valid chamber cannot be missed by a failed guess; and the solver is exact, the PPL backend working
    in rational arithmetic, so `t* > 0` is a proof and not an estimate.

    The maximiser is returned as an integral point, with every wall inequality and the square checked
    exactly: a nonempty finite intersection of open half-spaces containing `x` is a neighbourhood of
    `x` inside the cone, so strictness at the walls is what puts `x` in the interior, and a point
    strictly inside a cone on the space-like sheet has a positive square.
    """
    rays = [ray for _square, ray in polytope]
    program = MixedIntegerLinearProgram(solver="PPL", maximization=True)
    weight = program.new_variable(real=True, nonnegative=True)
    slack = program.new_variable(real=True)
    for wall in facets:
        program.add_constraint(slack[0] + sum(weight[index] * form(gram, ray, wall)
                                             for index, ray in enumerate(rays)) <= 0)
    program.add_constraint(sum(weight[index] for index in range(len(rays))) == 1)
    program.set_objective(slack[0])
    optimum = program.solve()
    assert optimum > 0, (
        "the program's optimum is %s and not positive, so no nonnegative combination of the %d extreme "
        "rays is strictly inside every wall of P_j: the rays are not the extreme rays of the cone the "
        "walls cut out" % (optimum, len(rays)))
    weights = program.get_values([weight[index] for index in range(len(rays))])
    point = sum((QQ(weights[index]) * vector(ZZ, ray) for index, ray in enumerate(rays)),
                vector(QQ, [0] * len(rays[0])))
    scale = lcm([c.denominator() for c in point])
    point = vector(ZZ, [int(c * scale) for c in point])
    assert all(form(gram, point, wall) < 0 for wall in facets), (
        "the program's point is not strictly inside every wall of P_j", list(point))
    assert form(gram, point, point) > 0, (
        "the point strictly inside P_j has square %d, so P_j is not on the space-like sheet"
        % form(gram, point, point))
    print("  the program over the %d extreme rays: optimum t* = %s, maximiser supported on %d rays "
          "with weights of denominator %d" % (len(rays), optimum,
                                              sum(1 for w in weights if w), scale))
    print("  the point %s, square %d, strictly inside all %d walls"
          % (list(point), form(gram, point, point), len(facets)))
    return point


def membership(chamber, facets, gram):
    """Both membership tests, from one inverse of the chamber's wall matrix.

    The vertex test asks whether every extreme ray of the chamber satisfies every wall inequality of
    `P`; the polar test asks whether every wall of `P` is a nonnegative combination of the chamber's
    walls.  They are written as one function because both are read off the same matrix: the inverse of
    `forms = W G` gives the rays, and `W^-1 = G (W G)^-1` gives the polar coordinates, so the walk
    inverts one 10 x 10 rational matrix per chamber instead of two.

    The chamber's cone --- the intersection of its own half-spaces --- is asserted pointed with trivial
    lineality here, for every chamber the walk visits: the rays of a pointed cone are its extreme rays,
    and those are what the vertex test tests.
    """
    walls = matrix(ZZ, [list(w) for w in chamber])
    gram_matrix = matrix(ZZ, gram)
    forms = walls * gram_matrix
    assert forms.rank() == forms.nrows(), "the chamber's walls are dependent"
    inverse = forms.change_ring(QQ).inverse()
    rays = []
    for index in range(walls.nrows()):
        column = vector(QQ, list(inverse.column(index)))
        scale = lcm([c.denominator() for c in column])
        ray = red(vector(ZZ, [int(c * scale) for c in column]))
        if form(gram, ray, chamber[index]) > 0:
            ray = -ray
        assert form(gram, ray, chamber[index]) < 0, "a wall of the chamber is not a facet"
        rays.append(ray)
    cone = Cone([list(ray) for ray in rays])
    assert cone.is_pointed(), ("the cone of a chamber contains a line", key_mirrors(chamber))
    assert int(cone.lineality()) == 0, ("the cone of a chamber has a lineality space",
                                        int(cone.lineality()))
    vertex_ok = all(form(gram, ray, wall) <= 0 for ray in rays for wall in facets)
    wall_inverse = gram_matrix * inverse
    coordinates = (wall_inverse.transpose()
                   * matrix(QQ, [list(p) for p in facets]).transpose())
    polar_ok = all(entry >= 0 for entry in coordinates.list())
    return vertex_ok, polar_ok, rays


def f_vector(rays, facets, gram):
    """The f-vector of `{x : b(x, p) <= 0, p in facets}` from its extreme rays, face by face."""
    dimension = len(facets[0]) - 1
    on_facet = [frozenset(index for index, ray in enumerate(rays) if form(gram, ray, facet) == 0)
                for facet in facets]
    universe = frozenset(range(len(rays)))
    faces = {}
    for size in range(len(facets) + 1):
        for subset in combinations(range(len(facets)), size):
            members = universe
            for index in subset:
                members = members & on_facet[index]
                if not members:
                    break
            if not members or members in faces:
                continue
            faces[members] = matrix(QQ, [list(rays[i]) for i in sorted(members)]).rank() - 1
    counts = [0] * (dimension + 1)
    for face_dimension in faces.values():
        assert 0 <= face_dimension <= dimension
        counts[face_dimension] += 1
    return tuple(counts)


def face_dimension_of_a_ray(ray, facets, gram):
    """The dimension of the smallest face of P whose relative interior contains the ray."""
    through = [wall for wall in facets if form(gram, ray, wall) == 0]
    assert through, "the ray is not on the boundary of P"
    # the face is P cut by the walls through the ray: its cone has dimension n - rank, and the
    # polytope one less, n being the number of coordinates of the lattice.
    return len(facets[0]) - 1 - matrix(QQ, [list(w) for w in through]).rank()


def coordinates(labels, lattice, lattice_vector):
    """The coordinates of a lattice vector in the lattice's own generating set."""
    given = lattice_vector.to_vector()
    return tuple(int(given(label)) for label in labels)


def gram_of(labels, lattice):
    """The Gram matrix of the lattice's own generating set, as rows of integers."""
    basis_elements = [lattice.module_generator(label) for label in labels]
    return [[int(lattice.b(basis_elements[a], basis_elements[b])) for b in range(len(labels))]
            for a in range(len(labels))]


