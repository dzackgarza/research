import time

sys.stdout.reconfigure(line_buffering=True)
os.environ["PATH"] = os.path.dirname(os.path.realpath("/sage/.venv/bin/sage")) + os.pathsep + os.environ.get("PATH", "")

from sage.all import CartanMatrix, QQ, ZZ, block_diagonal_matrix, matrix  # noqa: E402
from sage.version import version as SAGE_VERSION  # noqa: E402
from sage_extensions.all import Lattices  # noqa: E402

PIN = '15db925b0c92e525f769fcbf57135f1391263a9e'
print('provenance\n  Sage: %s\n  sage-extensions: .scratch/se-provider-15db925b/src, pin %s\n  gap: %s\n'
      % (SAGE_VERSION, PIN[:12], shutil.which('gap')))

U = matrix(ZZ, [[0, 1], [1, 0]])
E8 = -CartanMatrix(['E', 8])                      # negative definite, per @def:enriques-lattice
S = Lattices(ZZ)([list(r) for r in (2 * block_diagonal_matrix(U, E8)).rows()])       # S_En
T = Lattices(ZZ)([list(r) for r in block_diagonal_matrix(U, 2 * U, 2 * E8).rows()])  # T_En


def invariants(L, name):
    A = L.discriminant_quadratic_form()
    n = int(A.cardinality())
    a = n.bit_length() - 1
    values = {A.q(x) for x in A.elements()}
    integral = all(v in ZZ for v in values)
    print('  %-6s rank %2d, det %s, signature %s, |A| = %d = 2^%d, q takes %d values, delta = %d'
          % (name, L.rank(), L.determinant(), L.signature_pair(), n, a, len(values), 0 if integral else 1))
    return A


print('the lattices')
A_S = invariants(S, 'S_En')
A_T = invariants(T, 'T_En')
print('  (S_En is the invariant lattice, T_En the coinvariant and period lattice; T_dP = U + Delta^-(U)')
print('   + E8^2 of rank 18 is the invariant lattice of I_dP and appears in no count here.)')
print()

# the nine integral isometries of Stab_{O(S_En)}(h) and their discriminant images
basis = [S.basis_vector(i) for i in range(S.rank())]
u0, w0 = basis[0], basis[1]
h = u0 + w0
print('the polarization h = u_0 + w_0 in S_En: h^2 = %d' % h.q())
generators = [S.reflection(u0 - w0)] + [S.reflection(basis[2 + i]) for i in range(8)]
print('  nine integral isometries, each fixing h: %s' % all(g(h) == h for g in generators))
start = time.time()
rho = S.discriminant_representation()
images = tuple(rho(g) for g in generators)
print('  their nine discriminant images in O(A_{S_En}): built in %.0f s' % (time.time() - start))
start = time.time()
O = A_S.orthogonal_group()
G = O.subgroup(images)
print('  |O(A_{S_En}, q)| = %d   (%.0f s)' % (int(O.order()), time.time() - start))
print('  |G| = %d   (W(E8) = 696729600: %s)' % (int(G.order()), int(G.order()) == 696729600))
print()

# ---- the group the earlier record used, and why it is not this one
