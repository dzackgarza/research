# ---- coordinates on A_{S_En}, and the nine matrices
els = list(A_S.elements())
zero = els[0]
coord, cbasis = {zero: 0}, []
for e in els:
    if e in coord:
        continue
    shift = len(cbasis)
    coord.update({s + e: m | (1 << shift) for s, m in coord.items()})
    cbasis.append(e)
    if len(cbasis) == 10:
        break
assert len(coord) == 1024
mats = [tuple(coord[img(b)] for b in cbasis) for img in images]
sample = els[::53][:19]


def act(cols, x):
    out, i = 0, 0
    while x:
        if x & 1:
            out ^= cols[i]
        x >>= 1
        i += 1
    return out


bad = sum(1 for cols, img in zip(mats, images) for x in sample if coord[img(x)] != act(cols, coord[x]))
print('the nine matrices on a coordinate basis of A_{S_En}')
print('  they reproduce the provider action on %d classes x 9 images, mismatches: %d' % (len(sample), bad))
assert bad == 0
print()

# ---- vectors: the isotropic classes
iso_coord = {coord[x] for x in A_S.isotropic_elements()}
print('isotropic classes of A_{S_En}: %d' % len(iso_coord))


def walk(points, generators):
    seen, orbits = set(), []
    for seed in sorted(points):
        if seed in seen:
            continue
        orbit, frontier = {seed}, [seed]
        seen.add(seed)
        while frontier:
            x = frontier.pop()
            for cols in generators:
                y = act(cols, x)
                if y not in orbit:
                    orbit.add(y)
                    seen.add(y)
                    frontier.append(y)
        assert orbit <= points
        orbits.append(orbit)
    return orbits


start = time.time()
vector_orbits = walk(iso_coord, mats)
vsizes = sorted((len(o) for o in vector_orbits), reverse=True)
print('  G-orbits on them: %d, sizes %s   (%.0f s)' % (len(vector_orbits), vsizes, time.time() - start))
assert sum(vsizes) == len(iso_coord) == 528
nonzero = [o for o in vector_orbits if 0 not in o]
print('  the zero class is its own orbit: %s; the nonzero classes give %d orbits, sizes %s'
      % (any(0 in o for o in vector_orbits), len(nonzero), sorted((len(o) for o in nonzero), reverse=True)))
print()

# ---- planes: the totally singular 2-spaces
start = time.time()
planes = set()
for u, v in itertools.combinations(sorted(iso_coord - {0}), 2):
    w = u ^ v
    if w in iso_coord:
        planes.add(tuple(sorted((u, v, w))))
print('totally singular 2-spaces of A_{S_En}: %d   (%.0f s)' % (len(planes), time.time() - start))
start = time.time()
seen, plane_orbits = set(), []
for seed in sorted(planes):
    if seed in seen:
        continue
    orbit, frontier = {seed}, [seed]
    seen.add(seed)
    while frontier:
        a, b, _ = frontier.pop()
        for cols in mats:
            ia, ib = act(cols, a), act(cols, b)
            image = tuple(sorted((ia, ib, ia ^ ib)))
            if image not in orbit:
                orbit.add(image)
                seen.add(image)
                frontier.append(image)
    assert orbit <= planes, 'the walk left the totally singular 2-spaces'
    plane_orbits.append(orbit)
psizes = sorted((len(o) for o in plane_orbits), reverse=True)
print('  G-orbits on them: %d, sizes %s   (%.0f s)' % (len(plane_orbits), psizes, time.time() - start))
assert sum(psizes) == len(planes)
print()

