#!/usr/bin/env python3
"""Exact certificates for the Coble lattice table and its complementary lattices.

All arithmetic is exact (integers and rationals); no floating point and no genus
heuristics. For an integral Gram matrix B of a nondegenerate lattice L the script
computes

    rank, det, a(L) = dim_F2(A_L / 2A_L), delta(L) in {0,1},

where A_L = L*/L and delta = 1 iff the discriminant quadratic form takes a value
outside (1/2)Z. A_L is enumerated as the subgroup of (Z/|det|)^n generated by the
columns of the adjugate, which is at most a few thousand elements per block.
Signature is exact too: every block below is definite or a hyperbolic plane, and
signatures add over orthogonal sums.

Three further sections use the same arithmetic only:

  * the boundary lattice J^perp/J of one of Scattone's four 1-cusps at degree two,
    computed as the quotient of the orthogonal complement of an explicit isotropic
    plane J in T_2 = <-2> + U + U + E8 + E8, with the saturation of the 19 vectors
    checked by the gcd of their maximal minors;
  * the even overlattices of each of the four labels, from the isotropic subgroups
    of its discriminant group, which bound the index k = [J^perp/J : label];
  * the relation |det(J^perp/J)| = 2i^2 for i = [T_2 : J + J' + J^perp/J] over a
    complementary isotropic plane J', which with k^2 | det(label) leaves at most two
    values of k for each label.

Run: python3 two_elementary_checks.py
"""
from fractions import Fraction


def mat(n, f):
    return [[f(i, j) for j in range(n)] for i in range(n)]


def det(B):
    n = len(B)
    M = [[Fraction(x) for x in row] for row in B]
    d = Fraction(1)
    for c in range(n):
        p = next((r for r in range(c, n) if M[r][c] != 0), None)
        if p is None:
            return 0
        if p != c:
            M[c], M[p] = M[p], M[c]
            d = -d
        d *= M[c][c]
        inv = 1 / M[c][c]
        for r in range(c + 1, n):
            f = M[r][c] * inv
            for k in range(c, n):
                M[r][k] -= f * M[c][k]
    assert d.denominator == 1
    return int(d)


def adjugate(B):
    n = len(B)
    if n == 1:
        return [[1]]
    cof = []
    for i in range(n):
        row = []
        for j in range(n):
            minor = [[B[r][s] for s in range(n) if s != i] for r in range(n) if r != j]
            row.append(((-1) ** (i + j)) * det(minor))
        cof.append(row)
    return [[cof[j][i] for j in range(n)] for i in range(n)]


def diag_sum(*blocks):
    N = sum(len(X) for X in blocks)
    B = [[0] * N for _ in range(N)]
    off = 0
    for X in blocks:
        m = len(X)
        for i in range(m):
            for j in range(m):
                B[off + i][off + j] = X[i][j]
        off += m
    return B


def lattice_invariants(B):
    n = len(B)
    d = det(B)
    assert d != 0
    ad = adjugate(B)
    D = abs(d)
    gens = [[ad[i][j] % D for i in range(n)] for j in range(n)]
    zero = tuple([0] * n)
    seen, frontier = {zero}, [zero]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple((x[i] + g[i]) % D for i in range(n))
                if y not in seen:
                    seen.add(y)
                    nxt.append(y)
        frontier = nxt
    assert len(seen) == D, (len(seen), D)
    two_torsion = sum(1 for x in seen if all((2 * x[i]) % D == 0 for i in range(n)))
    a = two_torsion.bit_length() - 1
    delta = 0
    for x in seen:
        q = Fraction(0)
        for i in range(n):
            for j in range(n):
                q += Fraction(x[i] * B[i][j] * x[j], D * D)
        if (q % 2).denominator != 1:
            delta = 1
            break
    return dict(rank=n, det=d, a=a, delta=delta)


def chain(n, bonds):
    return mat(n, lambda i, j: -2 if i == j else (1 if (min(i, j), max(i, j)) in bonds else 0))


def A(n):
    return chain(n, {(i, i + 1) for i in range(n - 1)})


def D(n):
    return chain(n, {(i, i + 1) for i in range(n - 2)} | {(n - 3, n - 1)})


def E(n):
    return chain(n, {(i, i + 1) for i in range(n - 2)} | {(2, n - 1)})


U = [[0, 1], [1, 0]]
E8, E7, E6 = E(8), E(7), E(6)
E10 = diag_sum(U, E8)


def twist(B):
    return [[2 * x for x in row] for row in B]


def I2m(m):
    """I_{2,m} = diag(1,1,-1,...,-1), odd unimodular of signature (2,m)."""
    return mat(2 + m, lambda i, j: (1 if i == j and i < 2 else (-1 if i == j else 0)))


SIG = {'A(1)': (0, 1), 'A(17)': (0, 17), 'D(4)': (0, 4), 'D(6)': (0, 6), 'D(8)': (0, 8),
       'D(10)': (0, 10), 'D(16)': (0, 16), 'E(6)': (0, 6), 'E(7)': (0, 7), 'E(8)': (0, 8),
       'E(10)': (1, 9), 'U': (1, 1), 'U(2)': (1, 1), 'E8(2)': (0, 8), 'E10(2)': (1, 9)}


def block(name):
    table = {'A(1)': A(1), 'A(17)': A(17), 'D(4)': D(4), 'D(6)': D(6), 'D(8)': D(8),
             'D(10)': D(10), 'D(16)': D(16), 'E(6)': E6, 'E(7)': E7, 'E(8)': E8,
             'E(10)': E10, 'U': U, 'U(2)': twist(U), 'E8(2)': twist(E8),
             'E10(2)': twist(E10), '<2>': [[2]], '<4>': [[4]]}
    if name.startswith('I('):
        m = int(name[4:name.index(')')])
        return twist(I2m(m))
    return table[name]


def sig_of(name):
    if name.startswith('I('):
        m = int(name[4:name.index(')')])
        return (2, m)
    if name == '<2>':
        return (1, 0)
    if name == '<4>':
        return (1, 0)
    return SIG[name]


def describe(names):
    B = diag_sum(*[block(n) for n in names])
    inv = lattice_invariants(B)
    pos = sum(sig_of(n)[0] for n in names)
    neg = sum(sig_of(n)[1] for n in names)
    inv['sig'] = (pos, neg)
    return inv


def minors_index(rows, N):
    """Index of the lattice spanned by `rows` (k vectors in Z^N) inside its
    saturation, as the gcd of the maximal minors; 1 means the rows are primitive."""
    from itertools import combinations
    from math import gcd
    k = len(rows)
    g = 0
    for cols in combinations(range(N), k):
        M = [[rows[i][c] for c in cols] for i in range(k)]
        g = gcd(g, abs(det(M)))
        if g == 1:
            return 1
    return g


def disc_group(B):
    """A_L = L*/L as coefficient vectors mod |det L|, with the quadratic form q
    reduced mod 2, and the zero class."""
    n = len(B)
    D = abs(det(B))
    ad = adjugate(B)
    gens = [[ad[i][j] % D for i in range(n)] for j in range(n)]
    zero = tuple([0] * n)
    seen, frontier = {zero}, [zero]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple((x[i] + g[i]) % D for i in range(n))
                if y not in seen:
                    seen.add(y)
                    nxt.append(y)
        frontier = nxt
    assert len(seen) == D, (len(seen), D)
    q = {}
    for x in seen:
        v = Fraction(0)
        for i in range(n):
            for j in range(n):
                v += Fraction(x[i] * B[i][j] * x[j], D * D)
        q[x] = v % 2
    return D, sorted(seen), q, zero


def elem_order(x, D, zero):
    k, y = 1, x
    while y != zero:
        y = tuple((y[i] + x[i]) % D for i in range(len(x)))
        k += 1
    return k


FAIL = []


def check(label, inv, rank=None, a=None, sig=None, delta=None):
    ok = ((rank is None or inv['rank'] == rank) and (a is None or inv['a'] == a)
          and (sig is None or inv['sig'] == sig) and (delta is None or inv['delta'] == delta))
    if not ok:
        FAIL.append(label)
    print(f"  {label:38} rank={inv['rank']:2} det={inv['det']:>7} a={inv['a']:2} "
          f"delta={inv['delta']} sig={inv['sig']}  {'OK' if ok else 'MISMATCH'}")


